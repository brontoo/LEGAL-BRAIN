# ٣. تطبيع التاريخ والاسم — الموضع الواحد لكلٍّ منهما
# ==============================================================================

#: الأرقام العربية-الهندية (المشرقية والمغربية) إلى اللاتينية.
#:
#: ⚠️ **وتُنسخ هنا ولا تُستورد من `citations.py`** لأن المنطقين مختلفان لا
#: متشابهان: `citations.normalize` تطبيعٌ **لمطابقة نصّ عربي حرفي** (يطوي
#: الألف والهاء ويحذف الترقيم)، وهذا **تطبيع هويّة وتاريخ** يجب أن يبقي الحروف
#: كما هي ليُقرأ الاسم كما كُتب. ولو استُورد `normalize` هنا لطُويت «المادة»
#: إلى «الماده» في مفاتيح البحث — وهو أوّل ما يفترق به مفتاحان لسند واحد.
_DIGITS = str.maketrans("٠١٢٣٤٥٦٧٨٩۰۱۲۳۴۵۶۷۸۹", "01234567890123456789")

#: التشكيل والكشيدة — زخرفة لا تُفرّق سنداً عن سند.
_DIACRITICS = re.compile(r"[\u0610-\u061A\u064B-\u065F\u0670\u06D6-\u06ED]")
_TATWEEL = "\u0640"

#: كل ما ليس حرفاً عربياً ولا لاتينياً ولا رقماً يُستبدل بفراغ — في تطبيع الاسم.
_NOT_WORD = re.compile(r"[^\w\s]", re.UNICODE)
_WHITESPACE = re.compile(r"\s+")

#: بداية تاريخ ISO بصيغته الوحيدة المقبولة: أربع سنوات فشرطة فشهر.
_ISO_PREFIX = re.compile(r"^\d{4}-\d{2}(?:-\d{2})?$")


def _normalize_name(text: str) -> str:
    """
    يطبّع اسم تشريع أو رقم مادة **للمقارنة والبحث لا للعرض**.

    ⚠️ **ولا يطوي الحروف**: «أحمد» تبقى «أحمد»، و«المادة» تبقى «المادة».
    والفرق بين هذا التطبيع وتطبيع `citations.py` مقصود ومكتوب أعلاه: ذاك
    لمطابقة نصّ، وهذا لهويّة سند. وثمرته أن الاختلافات التي لا تُفرّق سنداً عن
    سند — الأرقام الهندية، والتشكيل، والكشيدة، والترقيم موضعاً — تُطوى وحدها.
    """
    if not text:
        return ""
    cleaned = _DIACRITICS.sub("", text).replace(_TATWEEL, "")
    cleaned = cleaned.translate(_DIGITS)
    cleaned = _NOT_WORD.sub(" ", cleaned)
    return _WHITESPACE.sub(" ", cleaned).strip()


def _instrument_article_key(instrument: str, article: str) -> str:
    """
    مفتاح السند من اسمه ورقمه — **مطبَّعاً فيُطابق ما كُتب برسمين**.

    >>> _instrument_article_key("المرسوم بقانون اتحادي رقم ٣٣ لسنة ٢٠٢١", "43")
    'المرسوم بقانون اتحادي رقم 33 لسنة 2021|43'
    """
    return f"{_normalize_name(instrument)}|{_normalize_name(article)}"


def parse_date(value: str) -> Optional[date]:
    """
    يقرأ تاريخاً ISO من نصّ **كما يكتبه المحامي**، أو ``None`` إن تعذّر.

    ⚠️ **و``None`` لا استثناء، وهذا اختيار مقصود في هذا الموضع:** الدالّة
    تُستدعى من دوالّ تُبثّ نتائجها إلى الواجهة، واستثناءٌ في مسار العرض يهدم
    الحصيلة كلها بسبب خانة تاريخ. أما من يحتاج التمييز بين «غير معلوم» و«مشوّه»
    فينادِي ``_require_date``، وهي التي ترفع.

    ⚠️ **ولا يُخمَّن ناقص**: «٢٠٢١-٠٦» بلا يوم **لا** يُقرأ أول الشهر ولا
    آخره — لأن الأول يُقدّم النفاذ يوماً، والثاني يؤخّره، وكلاهما اختراع لتاريخ
    لم يُدخله المحامي. ومن عنده الشهر وحده فليأتِ باليوم أو ليترك الخانة فارغة
    ويُعلَن الجهل.

    >>> parse_date("2021-09-20")
    datetime.date(2021, 9, 20)
    >>> parse_date("٢٠٢١-٠٩-٢٠")
    datetime.date(2021, 9, 20)
    >>> parse_date("2021-09") is None
    True
    >>> parse_date("") is None
    True
    """
    if not value:
        return None
    text = str(value).strip().translate(_DIGITS)
    if not _ISO_PREFIX.match(text):
        return None
    try:
        return date.fromisoformat(text)
    except ValueError:
        # تاريخ الشكل صحيح والمعنى مستحيل (شهر ١٣، أو ٣١ فبراير).
        return None


def _require_date(value: str, *, what: str) -> date:
    """
    تاريخٌ لا بدّ منه، أو استثناءٌ يسمّي الخانة المعطوبة.

    ⚠️ **والرفع هنا مقصود، لأن السكوت يُنتج حكماً عن تاريخ لم يُعطَ.**
    ولو رجعنا ``None`` لخرج الفحص ``not_in_force`` (وهو في `in_force_on`
    صحيح) — أما في **تاريخ الواقعة** فالفرق كبير: `check_application` بلا
    تاريخ ليس «مادة غير سارية»، بل **سؤال لم يُطرح**. فرفعُ الاستثناء يُظهر
    أن النداء ناقص، والسكوت عنه يُنتج حكماً مخترعاً في ثوب نتيجة.
    """
    parsed = parse_date(value)
    if parsed is None:
        raise ValueError(
            f"تاريخ غير صالح في «{what}»: {value!r}. والصيغة المقبولة ISO "
            f"(YYYY-MM-DD)، ولا يُخمَّن ناقصها — التاريخ المخترع يمضي إلى "
            f"المذكرة بلا أن يظهر سببه."
        )
    return parsed


# ==============================================================================
# ٤. الفحص الزمني — «أكانت المادة سارية يوم الواقعة؟»
# ==============================================================================
#
# ⚠️⚠️ **وهذا هو العيب الثاني الذي جاء الملف له، وهو أخفى الثلاثة.**
#
# المادة عُدّلت بين الواقعة والصياغة. الكاتب يفتح النصّ الساري **اليوم**،
# فيقرأ حكماً لم يكن قائماً وقت الواقعة، ويكتبه في مذكرة عن واقعة سابقة. والنصّ
# صحيح، والمصدر رسمي، والفحص في `citations.py` يمرّره كاملاً — **لأن النصّ
# موجود فعلاً في الأرشيف الحديث**. والعيب لا يظهر في أي موضع من المستند: لا في
# الاقتباس، ولا في النسبة، **بل في الزمن وحده**.
#
# فالفحص هنا **مقارنة تاريخين لا أكثر**، وهو لذلك حتمي بلا مجال: إمّا كانت
# المادة نافذة يوم الواقعة أو لم تكن.


def in_force_on(authority: Authority, date: str) -> bool:
    """
    هل كان السند سارياً في هذا التاريخ؟ — **الفحص الزمني، وهو حكم ثنائي**.

    القاعدة، وهي كلّها:

    1. **تاريخ النفاذ غير معلوم (`""`) ⇒ ليس سارياً.** والجهل **لا يُقرأ**
       سرياناً. وهذا موضع خطأ يقع كثيراً: يُترك الحقل فارغاً فيُظنّ معناه
       «سارية دائماً»، والصحيح أنه **لم يُثبَت أنها كانت نافذة** — وهو ما لا
       يقوم عليه استشهاد. ومن عرف أنها سارية بلا تاريخ انتهاء فليكتب تاريخ
       نفاذها وليترك `in_force_to` فارغاً؛ **والفرق بين الفراغين فرقُ معنى**.
    2. **قبل النفاذ ⇒ ليس سارياً.** (``date < in_force_from``)
    3. **بعد الانتهاء ⇒ ليس سارياً.** (``in_force_to`` معلوم و``date >
       in_force_to``) ⚠️ **ويوم الانتهاء نفسه سارٍ**، لأن `in_force_to` تاريخ
       **آخر يوم نفاذ** لا أول يوم بعد النفاذ. ولو أُقصي يومه لنُسب نقصُ يومٍ
       إلى نصّ سارٍ في يومه — والحدّ مكتوب هنا وفي الاختبار لأن لبسه قائم.
    4. وما عدا ذلك: سارٍ.

    ⚠️ **والتاريخ المشوّه يُرجع ``False`` ولا يرفع.** لأن هذه دالّة تُستدعى في
    مسار عرض الحصيلة، والفرق بين «المادة غير نافذة» و«التاريخ لا يُقرأ» **لا
    يضيع**: كلاهما يُعالَج في `check_application`، وهي التي ترفع على تاريخ
    الواقعة المشوّه (انظر ``_require_date``) وتُصرّح بالسبب في ``reason`` عند
    فساد تاريخ النفاذ.

    ⚠️ **ولماذا ``date`` نصٌّ لا `datetime.date`؟** لأن التواريخ في هذا الملف
    **بيانات المحامي كما كتبها**، تمرّ من ملفٍ أو من خانة إدخال. ولو طالبنا
    بكائن `date` لوجب تحويلها في موضع سابع لا يعرفه الاختبار، ولو لم يُحوَّل
    لأخطأ النداء — والتحويل هنا موضع واحد.

    >>> in_force_on(Authority(key="k", instrument="مثال تشريع", article="1", kind=SourceKind.FEDERAL_LAW, official_source="جهة رسمية", in_force_from="2020-01-01"), "2022-01-01")
    True
    >>> in_force_on(Authority(key="k", instrument="مثال تشريع", article="1", kind=SourceKind.FEDERAL_LAW, official_source="جهة رسمية", in_force_from="2020-01-01"), "2019-01-01")
    False
    """
    moment = parse_date(date)
    if moment is None:
        return False

    start = parse_date(authority.in_force_from)
    if start is None:
        # جهل أو تشويه — وكلاهما لا يُثبت سرياناً.
        return False
    if moment < start:
        return False

    end = parse_date(authority.in_force_to)
    if end is not None and moment > end:
        return False

    return True


def _latest_amendment_before(authority: Authority, date: str) -> str:
    """
    أحدث تعديل مُعلَن وقع **قبل** هذا التاريخ — أو ``""``.

    ⚠️ **والتعديلات تُرتَّب هنا ولا تفترض مرتّبة**: المحامي يكتبها كما تأتيه،
    وافتراضُ ترتيبها عيبٌ صامت (**العيب نفسه في ثوب آخر**: يُقرأ أول تعديل
    فيُظنّ آخرها). والتواريخ غير المقروءة **تُسقَط ولا تُخمَّن**.

    ⚠️ **والتعديل الواقع في يوم الواقعة نفسه لا يُعدّ سابقاً لها**: «جرى في
    يوم كذا» واقعةٌ يجب أن تُقرأ لا أن تُقدَّر، فاليوم نفسه يبقى محكوماً بالنصّ
    الأصلي حتى يُثبَت غيره — والإعلان أهون من الافتراض.

    >>> _latest_amendment_before(Authority(key="k", instrument="مثال تشريع", article="1", kind=SourceKind.FEDERAL_LAW, official_source="جهة رسمية", in_force_from="2020-01-01", amended_by=("2021-01-01",)), "2022-06-01")
    '2021-01-01'
    >>> _latest_amendment_before(Authority(key="k", instrument="مثال تشريع", article="1", kind=SourceKind.FEDERAL_LAW, official_source="جهة رسمية", in_force_from="2020-01-01", amended_by=("2021-01-01",)), "2020-06-01")
    ''
    """
    moment = parse_date(date)
    if moment is None:
        return ""
    candidates = [
        amendment
        for amendment in authority.amended_by
        if (parsed := parse_date(amendment)) is not None and parsed < moment
    ]
    if not candidates:
        return ""
    # الترتيب بالمفتاح المطبَّع لا بالمكتوب، فلا يتغيّر الناتج بتغيّر رسم التاريخ.
    return max(candidates, key=lambda amendment: parse_date(amendment) or date.min)


def transitional_note(authority: Authority, date: str) -> str:
    """
    إعلانٌ عربي بأن **القاعدة الانتقالية لم تُفحَص ولم تُقرأ** — ولا يقول ماذا
    تقول. وهذا كلّ ما تستطيع هذه الدالّة أن تقوله، وهذا مقصود.

    ⚠️⚠️ **ولماذا لا تقول الدالّة ماذا تنصّ القاعدة الانتقالية؟** لأنها **لا
    تعرفها، ولا يجوز أن تعرفها**. ولو كُتبت في الكود «يُطبَّق النصّ الجديد على
    الوقائع اللاحقة» لصار هذا الملف رأياً في القانون **يتقادم بصمت** في اللحظة
    التي يُعدَّل فيها المُعدِّل نفسه — بلا أن يُبلّغ شيء. ثم إن القاعدة
    الانتقالية تُكتب في المُعدِّل أو في قرار خاصّ، وموضعها **نصُّ المُعدِّل
    لا جدول التواريخ**. فالواجب هنا: أن يُقال للمحامي **إنّ هنا موضع نظر**،
    وأن يُسمّى المُعدِّل وتاريخه، **وأن تُترك القراءة له**.

    ⚠️ **ومتى تُطلَق؟** حين تتقاطع الواقعة مع تعديل: أي أن للسند تاريخ نفاذ
    معلوم ومعروف، وأن تعديلاً مُعلَناً وقع **قبل تاريخ الواقعة** وداخل مدّة
    السريان. فإن كان كل التعديلات بعد الواقعة فلا تقاطع (الواقعة محكومة بالنصّ
    الأصلي)، وإن كان تاريخ النفاذ مجهولاً فلا يُعرَف تقاطع أصلاً، **ويُقال
    ذلك**: الجهل بالسريان ليس «لا تعديل».

    ⚠️ **والإرجاع ``""`` حين لا تقاطع، لا نصّ يقول «لا شيء».** والفراغ هنا
    معناه «لم يُطلب إعلان»، ويُقابله في `check_application` حالةُ سندٍ سارٍ
    بماضيه. وأما إذا **وُجد** تقاطع فرجع الفراغ لكان أثرُه أن يمرّ تعديل صامتاً
    — وهو العيب الذي جاءت الدالّة لمنعه.

    >>> transitional_note(Authority(key="k", instrument="مثال تشريع", article="1", kind=SourceKind.FEDERAL_LAW, official_source="جهة رسمية", in_force_from="2020-01-01", amended_by=("2021-01-01",)), "2022-06-01") != ""
    True
    >>> transitional_note(Authority(key="k", instrument="مثال تشريع", article="1", kind=SourceKind.FEDERAL_LAW, official_source="جهة رسمية", in_force_from="2020-01-01", amended_by=("2021-01-01",)), "2020-06-01")
    ''
    >>> transitional_note(Authority(key="k", instrument="مثال تشريع", article="1", kind=SourceKind.FEDERAL_LAW, official_source="جهة رسمية", in_force_from="2020-01-01"), "2022-06-01")
    ''
    """
    if not authority.amended_by:
        return ""

    start = parse_date(authority.in_force_from)
    moment = parse_date(date)
    if start is None or moment is None:
        return ""
    if moment < start:
        # قبل النفاذ: لا سريان يُعدَّل أصلاً.
        return ""

    end = parse_date(authority.in_force_to)
    if end is not None and moment > end:
        # خارج مدّة السريان: التعديل لا يمسّ واقعةً لا تحكمها هذه المادة.
        return ""

    amendment = _latest_amendment_before(authority, date)
    if not amendment:
        return ""

    amendment_date = parse_date(amendment)
    assert amendment_date is not None  # مضمون بـ`_latest_amendment_before`
    if amendment_date <= start:
        # التعديل ليس بين طرفي السريان: هو إمّا سابق للنفاذ (وصفه لا تعديلاً
        # داخلها) أو مقارن له. وحدُّ التقاطع: **داخل** المدّة بعد نفاذها.
        return ""

    return (
        f"تعديل سابق لتاريخ الواقعة: أُدرج على هذا السند تعديلٌ مؤرَّخ "
        f"{amendment}، والواقعة مؤرَّخة {date}. "
        f"فالقاعدة الانتقالية لم تُفحَص هنا، ولا يقرّرها هذا الملف: "
        f"**وعلى المحامي أن يقرأ نصّ المُعدِّل أو قرار النفاذ**، "
        f"وأن يُثبت في المذكرة ما نصّ عليه من أثر على الوقائع السابقة. "
        f"وهذا الملف لا يحمل نصّاً ولا قاعدة انتقالية، ولا يقول ماذا تنصّ."
    )


# ==============================================================================
# ٥. مطابقة الشروط بالوقائع — **لفظية ومعلَنة الحدود**
# ==============================================================================
#
# ⚠️⚠️ **هذا أدقّ موضع في الملف، وحدّه يجب أن يُقرأ قبل الثقة بنتيجته.**
#
# الملف لا يفهم المعنى، ولا يجوز أن يدّعي ذلك: لو «فهم» لصار رأياً في القانون.
# فهو يقابل **كلمات الشرط** بـ**كلمات الوقائع**، ويستنتج اثنتين لا ثالثة:
#
#   * **متناقض** — دخلت واقعةٌ نافية على كلمات الشرط، أو نفت الوقائعُ كلماتِ
#     الشرط الموجبة.
#   * **غير متحقَّق منه** — الوقائع لا تتكلّم عن الشرط أصلاً. وهذا **ليس**
#     تحقّقاً ولا انتفاءً، بل سؤالٌ يُطرح على المحامي.
#
# ولا يوجد استنتاج ثالث: «متحقّق» **لا يُستنتج من غياب النفي**. لو قلنا
# «متحقّق» لأن الوقائع سكتت لصار السكوتُ إثباتاً — وهو أخطر من العيب الذي جاء
# الملف لمنعه، لأن المذكرة تُبنى على شرط لم يُثبته أحد.
#
# ⚠️ **ونصوص النفي والإثبات مُدرَجة هنا كأدوات لغوية، لا كقانون.** ولا تُعدّ
# «محتوى قانونياً»: هي كلمات وظيفية في العربية، لا حكم ولا مادّة.

#: أدوات النفي — وجودها في الواقعة مع كلمات الشرط = **تناقض مُعلَن**.
_NEGATIVE: frozenset[str] = frozenset(
    {
        "لم", "لن", "لا", "ما", "ليس", "ليست", "غير", "دون", "بلا", "بدون",
        "انعدم", "انعدام", "انتفى", "انتفاء", "عدم", "نفي", "نفى", "امتنع",
        "امتناع", "رفض", "خلت", "خلا", "بغير",
    }
)

#: كلمات الإثبات في الوقائع — نفيُها في الشرط = **تناقض مُعلَن**.
_POSITIVE: frozenset[str] = frozenset(
    {
        "صدر", "صدرت", "صدرا", "قام", "قامت", "أبرم", "ابرام", "وقع", "وقعت",
        "حصل", "حصلت", "تم", "تمت", "ثبت", "ثبتت", "سلّم", "سلم",
        "أخطار", "إخطار", "اخطار", "أشعر", "اشعر", "إشعار", "اشعار",
        "استلم", "تسلّم", "تسلم", "أدّى", "أدى", "سدد", "سدّد",
    }
)

#: أقلّ نسبة تطابق تُعدّ بها كلماتُ الشرط **متكلَّماً عنها**.
#:
#: ⚠️ **والنسبة معلَنة ولا تُخمَّن:** التطابق التامّ يمنع أن يُكتشف تناقض في شرط
#: طويل صيغت واقعتُه بغير ترتيبه؛ والنقصُ الشديد يحوّل السكوتَ إلى اتهام.
_MATCH_RATIO = 0.6

#: أقصر كلمة تُعدّ «مميّزة» في الشرط — وهي التي يُبنى التطابق عليها.
_DISTINCTIVE_LEN = 3

#: أقصى عدد كلمات يُعرض للقارئ في سياق العبارة — فلا يُغرق السطر.
_CONTEXT_WORDS = 6

#: الفراغات التي يُبحث عنها قبل «ل» الملتصقة.
_WHITESPACE_CHARS = " \t\n\r\f\v\u00a0"

#: حرف الجرّ «ل» (U+0644) — يُجرَّد **من المقارنة وحدها**.
_DANGLING_LAM = "\u0644"

#: «لما» — لامُها **ليست جارًّا**، فلا تُجرّد.
_LAM_MA = "\u0644\u0645\u0627"

#: الفراغ الذي يُطوى في المقارنة.
_SPACE_BEFORE_WORD = re.compile(r"\s+")


def _tokens(text: str) -> list[str]:
    """
    كلمات النصّ مطبَّعةً — **والتطبيع يحفظ الحروف ويطوي الزخرفة**.

    ⚠️ **ولا تُحذف الأرقام**: شرطٌ قد يكون «إخطار خلال ٧ أيام»، والواقعة قد
    تقول «٧ أيام». وطيّ الرقم كان يجعل الشرط والواقعة يتّفقان على الفراغ.
    """
    normalized = _normalize_name(text).lower()
    return normalized.split()


def _stems(tokens: Sequence[str]) -> set[str]:
    """
    جذوع الكلمات — تُزاد عليها صورةٌ مقلَّمة من بادئات شائعة.

    ⚠️ **والغرض عملي لا نحويّ:** الواقعة تكتب «بإخطار» والشرط يكتب «إخطار»،
    و«الوزارة» تُكتب «وزارة». فلولا التقليم لما التقت الكلمتان، ولَما اكتُشف
    تناقضٌ ظاهر للقارئ في ثانية.
    """
    stems: set[str] = set()
    for token in tokens:
        stems.add(token)
        if len(token) <= _DISTINCTIVE_LEN:
            continue
        for prefix in ("بال", "وال", "فال", "ال", "ب", "و", "ف", "ل"):
            if token.startswith(prefix) and len(token) - len(prefix) >= 2:
                stems.add(token[len(prefix) :])
    return stems


def _distinctive(condition: str) -> set[str]:
    """الكلمات **المميّزة** في الشرط — هي التي يُبنى عليها التطابق."""
    return {
        stem for stem in _stems(_tokens(condition)) if len(stem) >= _DISTINCTIVE_LEN
    }


def _condition_stems(condition: str) -> tuple[set[str], set[str]]:
    """(كل جذوع الشرط، الكلمات المميّزة فيه) — في نداء واحد يُقرأ بلا لبس."""
    return _stems(_tokens(condition)), _distinctive(condition)


def _contradicted_by_negation(condition: str, fact: str) -> bool:
    """
    هل **تناقض** الواقعةُ الشرطَ تناقضاً لفظياً مُعلَناً؟

    ⚠️⚠️ **والمنطق هنا يجب أن يُقرأ قبل الاعتماد عليه، وهو أوسع مما يبدو:**
    الشرط «صدور قرار من الوزارة» والواقعة «لم يصدر قرار من الوزارة»: الكلمات
    تتفق ومعناها متناقض. فالفحص **لا يقف عند تطابق الكلمات**، بل يسأل: هل تحمل
    الواقعة أداةَ نفي **مع** تطابقٍ كافٍ في الكلمات؟

    ⚠️ **وأداة النفي تُبحث في الواقعة كلها لا في جوار الكلمة وحدها**، لأن صيغة
    النفي في العربية تتقدّم الفعل وتفصله عنه («لم يصدر قرار…»)، والنافذة
    الضيّقة كانت تُسقِط الحالة التي جاءت الدالّة لها. **وثمنُ ذلك حدٌّ معلَن**:
    واقعةٌ تنفي فعلَ الخصم تُقرأ تنفيذاً من الكاتب — والخطأ في اتجاه التشكّي لا
    في اتجاه التسليم.

    ⚠️ **ولا يُعلَن التناقض بلا تطابق كافٍ**: فذكرُ النفي في واقعة لا تتكلّم عن
    الشرط أصلاً **ليس** تناقضاً بل سكوت.

    >>> _contradicted_by_negation("صدور قرار من الوزارة", "لم يصدر قرار من الوزارة")
    True
    >>> _contradicted_by_negation("صدور قرار من الوزارة", "صدر قرار من الوزارة في 2022")
    False
    """
    condition_stems, distinctive = _condition_stems(condition)
    if not condition_stems:
        return False

    fact_stems = _stems(_tokens(fact))
    if not fact_stems:
        return False

    overlap = condition_stems & fact_stems
    if not overlap:
        return False

    if not distinctive:
        return False

    ratio = len(overlap & distinctive) / len(distinctive)
    if ratio < _MATCH_RATIO:
        return False

    fact_tokens = set(_tokens(fact))
    if fact_tokens & _NEGATIVE:
        return True

    # والعكس أيضاً: الشرط منفيٌّ والواقعة تثبته («عدم الإخطار» مقابل «قام
    # بالإخطار»). ولو أُسقط لمرّ التعدّي في اتجاهه.
    if set(_tokens(condition)) & _NEGATIVE and fact_tokens & _POSITIVE:
        return any(stem in condition_stems for stem in _stems(fact_tokens & _POSITIVE))

    return False


def _verified_by_facts(condition: str, facts: Sequence[str]) -> bool:
    """
    هل **تتكلّم** الوقائع عن الشرط بكلماتٍ يتّفق عليها الاثنان؟

    ⚠️ **ووجود التطابق لا يعني «الشرط متحقّق»** — وهو سبب وجود الدالّة بمفردها:
    التطابق **يرفع السكوت** فيصير السؤال قابلاً للفحص، ولا يثبت التحقّق. ولذلك
    لا يوجد في الملف استنتاج اسمه «متحقّق».
    """
    condition_stems, _distinctive_stems = _condition_stems(condition)
    if not condition_stems:
        return False
    for fact in facts:
        if condition_stems & _stems(_tokens(fact)):
            return True
    return False


