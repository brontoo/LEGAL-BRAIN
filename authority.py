def summarize(
    checks: Sequence[ApplicationCheck],
    *,
    findings: Sequence[Finding] = (),
    unsourced_authorities: Sequence[Authority] = (),
) -> dict:
    """
    يحوّل الحصيلة إلى قاموس **صالح للبثّ كـ JSON** إلى الواجهة.

    ⚠️⚠️ **و``not_in_force`` خطأ، و``secondary_as_primary`` خطأ — وكلاهما
    قولٌ كاذب عن القانون، لا نقصاً في التغطية:**

    * **``not_in_force``** يقول للقارئ إن نصّاً يحكم واقعةً لا يحكمها: إمّا
      لأنه لم يكن نافذاً بعد، وإمّا لأنه أُلغي وحلّ غيره. **والكذب هنا في
      الزمن**، ولهذا لا يكشفه ما عداه.
    * **``secondary_as_primary``** يقدّم ملخّصاً مقام النصّ: قولٌ عن القانون لا
      يقول القانون، ويُقرأ في المستند كأنه النصّ.

    ⚠️ **و``conditions_unverified`` و``unsourced`` ملاحظات — والسبب أن كلاًّ
    منهما ثغرة في المُدخَل لا كذباً في القول:** شرطٌ لا تتكلّم عنه الوقائع
    **سؤال يُطرح على المحامي**، وسندٌ بلا مصدر رسمي **خانة تُملأ**. ومن جعل
    هذين خطأً منع تسليم مذكرة سليمة لمجرد سؤال لم يُسأل.

    ⚠️ **والسجلّ الفارغ سليم ويقول ذلك بالعربية** (`CLEAN_EMPTY_NOTE`).

    >>> payload = summarize(())
    >>> payload["clean"], payload["error_count"], payload["total"]
    (True, 0, 0)
    >>> "لا أسانيد" in summarize(()).get("note", "")
    True
    """
    ordered = tuple(checks or ())
    findings = tuple(findings or ())
    unsourced_authorities = tuple(unsourced_authorities or ())

    error_checks = tuple(check for check in ordered if check.is_error)
    notice_checks = tuple(
        check for check in ordered if check.status == STATUS_CONDITIONS_UNVERIFIED
    )
    error_findings = tuple(finding for finding in findings if finding.is_error)
    notice_findings = tuple(finding for finding in findings if not finding.is_error)

    payload: dict = {
        "summary": _summary_line(ordered, findings, unsourced_authorities),
        "clean": not error_checks and not error_findings,
        "error_count": len(error_checks) + len(error_findings),
        "notice_count": len(notice_checks)
        + len(notice_findings)
        + len(unsourced_authorities),
        "total": len(ordered),
        "applies": sum(1 for check in ordered if check.status == STATUS_APPLIES),
        "not_in_force": sum(
            1 for check in ordered if check.status == STATUS_NOT_IN_FORCE
        ),
        "conditions_unmet": sum(
            1 for check in ordered if check.status == STATUS_CONDITIONS_UNMET
        ),
        "conditions_unverified": len(notice_checks),
        "secondary_as_primary": len(error_findings),
        "unsourced": len(unsourced_authorities),
        "checks": [
            {
                "key": check.key,
                "instrument": check.instrument,
                "article": check.article,
                "status": check.status,
                "label": LABELS.get(check.status, check.status),
                "reason": check.reason,
                "conditions": list(check.conditions),
                "unmet": list(check.unmet),
                "unverified": list(check.unverified),
                "exceptions": list(check.exceptions),
            }
            for check in ordered
        ],
        "findings": [
            {
                "kind": finding.kind,
                "label": LABELS.get(finding.kind, finding.kind),
                "key": finding.key,
                "instrument": finding.instrument,
                "article": finding.article,
                "source": finding.source,
                "reason": finding.reason,
                "detail": finding.detail,
                "is_error": finding.is_error,
            }
            for finding in findings
        ],
    }

    if unsourced_authorities:
        # ⚠️ **و``unsourced`` لا تُدرَج فارغةً في الحصيلة**، لأن صفاً فارغاً
        # يُقرأ «فحص لم يُشغَّل» بدل «لا يوجد» — والفرق بين «لا أعرف» و«لا يوجد»
        # فرقٌ لا يُطوى.
        payload["findings"].append(
            {
                "kind": "unsourced",
                "label": LABELS.get("unsourced", "unsourced"),
                "key": "",
                "instrument": "",
                "article": "",
                "source": "register",
                "reason": (
                    "أسانيد في السجلّ بلا مصدر رسمي مُدرَج — فالمصدر غير "
                    "متحقَّق، والمستند لا يُعرض عليها كأنها محقَّقة."
                ),
                "detail": " · ".join(
                    f"{entry.key}: {entry.instrument} / {entry.article}"
                    for entry in unsourced_authorities
                ),
                "is_error": False,
            }
        )

    if not ordered and not payload["findings"]:
        payload["note"] = CLEAN_EMPTY_NOTE

    return payload


def _summary_line(
    checks: Sequence[ApplicationCheck],
    findings: Sequence[Finding],
    unsourced_authorities: Sequence[Authority],
) -> str:
    """
    سطر عربي واحد يصلح للعرض في الواجهة أو السجلّ — **ولا يفترق عن الحصيلة**.

    ⚠️ **وذكر الملاحظات في السطر ليس تفصيلاً:** حصيلةٌ تخرج ``clean`` وفيها
    شرطٌ لم تتكلّم عنه الوقائع **ليست** كحصيلة فُحصت كلها.
    """
    if not checks and not findings and not unsourced_authorities:
        return CLEAN_EMPTY_NOTE

    parts: list[str] = []
    applies = sum(1 for check in checks if check.status == STATUS_APPLIES)
    if applies:
        parts.append(f"تنطبق: {applies}")
    not_in_force = sum(1 for check in checks if check.is_error)
    if not_in_force:
        parts.append(f"غير سارية: {not_in_force}")
    unmet = sum(1 for check in checks if check.status == STATUS_CONDITIONS_UNMET)
    if unmet:
        parts.append(f"شرط غير متحقّق: {unmet}")
    unverified = sum(
        1 for check in checks if check.status == STATUS_CONDITIONS_UNVERIFIED
    )
    if unverified:
        parts.append(f"شرط غير متحقَّق منه: {unverified}")

    secondary = sum(1 for finding in findings if finding.kind == "secondary_as_primary")
    if secondary:
        parts.append(f"مصدر ثانوي مقام النصّ: {secondary}")
    if unsourced_authorities:
        parts.append(f"بلا مصدر رسمي: {len(unsourced_authorities)}")

    if not parts:
        return CLEAN_EMPTY_NOTE
    return " · ".join(parts) + f" من {len(checks)} سنداً مفحوصاً."
