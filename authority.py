"""
سجلّ الأسانيد — هل تحكم هذه المادة هذه الواقعة، **ثم**؟
=============================================================================

⚠️⚠️ **لا حكم في هذا الملف، ولا نصّ مادة واحدة، ولا رقم تشريع واحد، ولا مدّة
نفاذ واحدة، ولا قاعدة انتقالية واحدة.**

هذا الملف **حساب ومحاسبة على جدول يملؤه المحامي**: تواريخ تُقارَن، وشروط
تُطابَق بوقائع مُورَّدة، وأسماء مصادر تُعدّ فارغةً أو مملوءة. ولماذا هذا الحدّ
مكتوب في أوّل سطر؟ لأن **القاعدة المكتوبة في الكود تصير خطأً في اللحظة التي
يتغيّر فيها النصّ، ولا شيء في المنظومة يُبلّغ بذلك**: تُعدَّل مادة، ويبقى
الملف يحكم بالقديم **بثقة** — والثقة تمضي بالمذكرة إلى المحكمة، والجهل يوقف
الكاتب. وعلى قاعدة `labour_rules.py` و`deadlines.py`: **الجدول للمحامي أن
يتحقّقه، والمصدر يُذكر ولا يُخمَّن.**

وعملياً: كل مُدخَل في هذا الملف **يحمل مصدره** (`official_source`)، ومن لم
يحمل **يُعلَن** (`unsourced`) ولا يُمرَّر كأنه محقَّق.

المشكلة التي يحلّها
------------------
رصدت ثلاث مراجعات قانونية مستقلّة لمذكرات هذا المشروع ثلاثة عيوب، وكلّها من
جنس واحد: **السند صحيح، والاستعمال خاطئ.**

١. **مادة صحيحة في موضع لا تنطبق فيه.** اعتمدت مذكرة على المادة ٥٤ من قانون
   العمل، ونصّها في التقاضي بعد قرار الوزارة، **ولا قرار وزارة في الواقعة**
   والمبالغ تجاوزت نطاق ذلك المسار. والنصّ حقيقي، والاستعمال خاطئ، ومادة
   أخرى من القانون نفسه كانت تحكم. **وقال المراجع الجملة الفاصلة: نسبة نصّ
   إلى مادة ليست له أخطر من عدم ذكر المادة أصلاً.** لأن الغياب يُسأل عنه،
   أما النسبة الكاذبة فتُسلَّم لأنها تحمل شكل التوثيق.

٢. **استُعمل النصّ الساري اليوم، لا النصّ الساري وقت الواقعة.** مادة عُدّلت
   بين الواقعة والصياغة يجب أن تُطبَّق **كما كانت وقتها**، ويُنظر في القاعدة
   الانتقالية. ومذكرة كُتبت بالنصّ الجديد عن واقعة قديمة تقول عن القانون ما
   لم يقله عنها.

٣. **عُومل المصدر الثانوي معاملة النصّ.** ملخّص نتائج بحث قام مقام قراءة
   النصّ الذي سيُقتبس. والتعليق **ليس** النصّ، ولا يُنقل عنه بحال.

فالملف هو الموضع الذي تُلتقط فيه الثلاثة **حتمياً** قبل أن تخرج المذكرة.

والفرق بينه وبين `attribution.py` — وهما متجاوران لا متكرّران
--------------------------------------------------------------
* `attribution.py` يسأل: **«أهذا النصّ نصُّ المادة التي نُسب إليها؟»** — أي
  **نسبة النصّ إلى صاحبه**، بالطبع الاقتباس بالمقطع المسترجَع.
* وهذا الملف يسأل سؤالاً آخر تماماً: **«أهذه المادة تحكم هذه الواقعة، في هذا
  التاريخ؟»** — أي **الانطباق الزمني والموضوعي**، بمقارنة تواريخ وشروط
  بوقائع.

فليس في هذا الملف مطابقة نصّ عربي ولا اقتباس ولا عتبة محارف. نصّ المادة إن
احتاجه القارئ فموضعه `citations.py` و`attribution.py`. وحين يعمل الثلاثة معاً
تُغطّى ثلاثة أسئلة لا واحد: **هل النصّ موجود؟ لمن هو؟ أيحكم هذه الواقعة الآن؟**

المبدأ التصميمي — على نمط `citations.py` و`attribution.py`
-----------------------------------------------------------
> **النموذج يروي، والخادم يُقرّر.**

والملف:
* **بلا تبعية خارجية** — مكتبة بايثون القياسية وحدها.
* **بلا حالة وبلا إدخال/إخراج وبلا شبكة وبلا طبع** — دوالّ نقية ونماذج مجمّدة
  (`Authority` و`ApplicationCheck`)، فالمدخل نفسه يُعطي الحكم نفسه دائماً.
* **وبلا حكم قانوني واحد** — الجدول والشروط والاستثناءات **بيانات** في
  `Authority`، ومصدرها حقلٌ يملؤه المحامي.

الحالات الأربع — ولماذا أربع لا اثنتان
--------------------------------------
* ``applies``               — سارية في التاريخ، ولا شرط معلَن تناقضه الواقعة.
* ``not_in_force``          — **الفحص الزمني رسب**: إمّا لم تكن المادة سارية
  بعد، أو انتهت سريانها، أو تاريخ نفاذها غير مُدخَل. **وهذا خطأ (`error`).**
* ``conditions_unmet``      — شرط معلَن **تناقضه** الواقعة المُعطاة.
* ``conditions_unverified`` — شروط معلَنة **لا تتكلّم عنها** الوقائع المُعطاة.

⚠️ **و``conditions_unverified`` ملاحظة لا خطأ، والفرق ليس تنظيمياً:** الشرط
الذي لا تتكلّم عنه الوقائع **ثغرة في المُدخَل تُعرَض على المحامي ليُكمِلها أو
ليُصرّح بأنها غير محقَّقة**. أما ``not_in_force`` و``secondary_as_primary``
فهما **قولٌ كاذب عن القانون**: الأول يستشهد بنصّ مُلغى أو غير نافذ، والثاني
يقدّم ملخّصاً مقام النصّ. **والكاذب يمنع التسليم، والثغرة تُذكر ولا تمنعه** —
فمن جعل الثغرة خطأً منع تسليم مذكرة سليمة، ومن جعل الكذب ملاحظةً سلّم مذكرة
تقول عن القانون ما لم يقله.

⚠️ **والسجلّ الفارغ سليم، ويقول ذلك بالعربية.** ليس فشلاً ولا نقصاً: مذكرة لا
تعتمد على مادة **جواب صحيح**، وقد صار في المشروع عرفٌ أن يُقال صراحةً بدل أن
يُترك فراغاً يُقرأ خطأً.

حدود معلنة — تُقرأ مع النتيجة لا بعدها
--------------------------------------
1. **الفحص الموضوعي على مستوى الشرط لا على مستوى المادة.** لا يعرف هذا الملف
   نطاق المادة ولا موضوعها (ولا يجوز أن يعرفه: ذلك نصّ قانون محفوظ). فهو يفحص
   **الشروط التي أدرجها المحامي** في `Authority.conditions`. فمادة أُدرجت
   **بلا شروط** تخرج ``applies`` إن كانت سارية — **و``applies`` هنا معناها
   «لم يُعترض عليها من داخل الجدول»، لا «ثبت انطباقها»**. ومن أراد الحكم
   الثاني فليُدرج شرطه.
2. **``conditions_unmet`` يقوم على تناقض لفظي مُعلَن، لا على فهم.** الشرط
   يُعدّ متناقضاً إذا دخلت واقعةٌ **نافية** على كلمات الشرط نفسها (``_NEGATIVE``:
   لم، لا، بلا، غير، دون، انعدم، انتفى …) أو إذا نفت الواقعة كلمات الشرط
   الموجبة (``_POSITIVE``: صدر، قام، أبرم …). وهذا **فحص لفظي** يمكن أن يُخطئ
   في الاتجاهين، وأشهر خطئه أن واقعةً تصف نزاعاً **تنفي فيه الخصمَ** شرطاً
   («ولم يقم المدعى عليه بالإخطار») تُقرأ تنفيذًا من الكاتب. وقد اختير أن يكون
   الخطأ **في اتجاه التشكّي لا في اتجاه التسليم** — على قاعدة `attribution.py`:
   **قد يُتَّهم بريء، ولا يُبرَّأ متّهم**. والعلاج الأمثل أن تُكتب الوقائع في
   صيغة موجبة مُجرَّدة عن الخصومة.
3. **``in_force_on`` على التواريخ المعلَنة في السجلّ وحده.** لا يعرف الملف
   تاريخ صدور في الجريدة الرسمية ولا مدّة النفاذ ولا الوقف، حتى لو حُفظ في
   `in_force_from`. فمن أدرج تاريخاً خاطئاً حصل على حكم خاطئ **بثقة** — وهذا
   سبب وجود `unsourced` إلى جانبه.
4. **``asserted_without_source`` لا يقرأ المعنى، بل يطابق عبارات مُدرَجة.**
   فهو **لا يفهم** النصّ: عبارة تُكتب في سياق النقد («ولا يصحّ القول بأن من
   المقرر قانوناً …») أو في سياق نقل عن الغير بلا علامة تنصيص **تُعلَن** وهي
   بريئة. ولذلك تُعرَض **بموضعها وسياقها** ليقرأها المحامي في ثانية، ولا
   تُمنع بها مذكرة. وتفصيل هذا الحدّ في موضع الدالّة.
5. **المصادر الثانوية تُعرَف بالتصنيف لا بالاسم.** ``secondary_as_primary``
   يعتمد على أن المحامي صنّف المُدخَل `SECONDARY`؛ ومصدرٌ ثانوي صُنّف
   `SECONDARY` لكنه لم يُذكر في المتن **لا يُعلَن** (لا موضع له). فالفحص
   **إعلانٌ لما وقع في هذه المسودّة**، لا شهادة على كلّ ما فيها.
"""

