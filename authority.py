def check_application(
    authority: Authority,
    facts: Sequence[str],
    date: str,
) -> ApplicationCheck:
    """
    يفحص سنداً واحداً على واقعة: **أيحكم هذه الواقعة، في هذا التاريخ؟**

    ⚠️⚠️ **وترتيب الفحوص ليس تفصيلاً، بل هو المنطق كله:**

    1. **الزمن أوّلاً** — فإن لم تكن المادة نافذة يوم الواقعة **فلا معنى لفحص
       شروطها**: لا يُقال «انطبق شرطها» عن نصّ لا يحكم الواقعة، ولا يُقال «لم
       تتكلّم الوقائع عن شرطها» لأن السؤال سقط قبل أن يُطرح. وهذا **بالضبط
       العيب الأول**: مادة صحيحة في موضع لا تنطبق فيه.
    2. **الشروط بعدها** — «غير متحقَّق» ثم «غير متحقَّق منه» ثم «تنطبق».

    ⚠️ **و``conditions_unmet`` تُقدَّم على ``conditions_unverified``** لأن
    الأشدّ يُذكر أوّلاً: تقريرٌ يقول «ثمّة شرط لم تتكلّم عنه الوقائع» بينما شرطٌ
    آخر **تناقضه الوقائع صراحةً** يُخفي الأخطر بالأخفّ.

    ⚠️ **و``facts`` تُقبل تسلسلاً لا نصّاً واحداً**، لأن الوقائع تُروى بنوداً،
    والشرط قد يُستوفى في بند غير الذي فيه نقيضه.
    """
    moment = _require_date(date, what=f"تاريخ الواقعة ({authority.key})")
    facts = tuple(facts or ())
    conditions = tuple(authority.conditions)
    exceptions = tuple(authority.exceptions)

    def verdict(
        status: str,
        reason: str,
        *,
        unmet: tuple[str, ...] = (),
        unverified: tuple[str, ...] = (),
    ) -> ApplicationCheck:
        """يبني الحكم **بشروطه واستثناءاته محمولةً معه** — فلا تُفتح البطاقة."""
        return ApplicationCheck(
            key=authority.key,
            instrument=authority.instrument,
            article=authority.article,
            status=status,
            reason=reason,
            conditions=conditions,
            unmet=unmet,
            unverified=unverified,
            exceptions=exceptions,
        )

    if not in_force_on(authority, date):
        return verdict(STATUS_NOT_IN_FORCE, _not_in_force_reason(authority, moment))

    unmet = tuple(
        condition
        for condition in conditions
        if any(_contradicted_by_negation(condition, fact) for fact in facts)
    )
    if unmet:
        return verdict(
            STATUS_CONDITIONS_UNMET,
            "شرط معلَن في السند تناقضه الوقائع المُعطاة: "
            + " · ".join(unmet)
            + " — وهذا تناقض لفظي مُعلَن (نفيٌ في الواقعة على كلمات الشرط)، "
            "فعلى المحامي مراجعته: إمّا الشرط لا ينطبق، وإمّا صيغة الواقعة "
            "تحمل نفي الخصم لا نفي الكاتب.",
            unmet=unmet,
        )

    unverified = tuple(
        condition for condition in conditions if not _verified_by_facts(condition, facts)
    )
    if unverified:
        return verdict(
            STATUS_CONDITIONS_UNVERIFIED,
            "شروط معلَنة لا تتكلّم عنها الوقائع المُعطاة: "
            + " · ".join(unverified)
            + " — وهذا سكوت في المُدخَل لا نفي: **لم يُثبَت تحقّق الشرط، ولم "
            "يُثبَت انتفاؤه**. فيُكمَل المُدخَل أو يُصرَّح في المذكرة بأنه غير "
            "محقَّق.",
            unverified=unverified,
        )

    note = transitional_note(authority, date)
    base = (
        f"سارية في {date} ولا شرط معلَناً تناقضه الوقائع المُعطاة "
        f"({len(conditions)} شرطاً)."
    )
    if exceptions:
        base += " ⚠️ وللسند استثناءات معلَنة لم تُفحص هنا: " + " · ".join(exceptions)
    if note:
        base += " ⚠️ " + note
    return verdict(STATUS_APPLIES, base)


def _not_in_force_reason(authority: Authority, moment: date) -> str:
    """
    سبب رسب الفحص الزمني — **مسمّى لا مُجمَل**.

    ⚠️ **والتفصيل مقصود:** «غير سارية» وحدها لا تكفي ليتصرّف المحامي. فسندٌ لم
    يكن نافذاً بعد يُنتظر نصّه الساري، وسندٌ انتهى سريانه يُبحث عن بديله، وسندٌ
    تاريخ نفاذه غير مُدخَل **يسأل عن تاريخه ولا يسأل عن بديله**.
    """
    start = parse_date(authority.in_force_from)
    if start is None:
        return (
            f"تاريخ النفاذ غير معلوم أو غير مقروء «{authority.in_force_from}»، "
            f"والجهل بالسريان لا يُقرأ سرياناً — فلزم إدراج تاريخ النفاذ من "
            f"مصدره الرسمي قبل الاعتماد على السند."
        )
    if moment < start:
        return (
            f"الواقعة مؤرَّخة {moment} قبل نفاذ السند في {start} — "
            f"فالسند لا يحكمها."
        )
    end = parse_date(authority.in_force_to)
    if end is not None and moment > end:
        return (
            f"الواقعة مؤرَّخة {moment} بعد انتهاء سريان السند في {end} — "
            f"فالسند لا يحكمها، ويلزم البحث عن النصّ الذي حلّ محلّه."
        )
    return (
        f"تعذّر إثبات السريان في {moment} بالتواريخ المُدخَلة "
        f"(من «{authority.in_force_from}» إلى «{authority.in_force_to}»)."
    )


