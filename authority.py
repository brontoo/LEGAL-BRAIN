def _drop_dangling_lam(normalized_text: str) -> str:
    """
    يجرد «ل» الجارّ **والفراغين المحيطين بها** — فلا تبقى كلمة «ل» وحدها.

    ⚠️⚠️ **وهذا الموضع أُصلح ثلاث مرّات، والأخطاء من جنس واحد: حذف نصف ما يجب
    حذفه، أو حذف ما لا يجب.**

    ١. أُسقِطت «ل» وحدها، فبقيت **كلمة «ل» منفصلة**: «وفقا ل»، فصار آخر الكلمات
       «ل» لا «وفقا» — **فوقع التمهيد من الفحص كله**.
    ٢. ثم أُسقِطت «ل» **والحرف الذي يليها**، فأُكِل **أوّل حرف من اسم المصدر**
       («وفقا لتعليق» ← «وفقاعليق») — وهو أسوأ: الاسم نفسه يُمسّ.
    ٣. والصواب أن يُسقَط **الفراغان و«ل»**، ويبقى ما بعدها كما هو.

    >>> _drop_dangling_lam("وفقا لتعليق")
    'وفقاتعليق'
    >>> _drop_dangling_lam("وفقا لما ورد في")
    'وفقاما ورد في'
    >>> _drop_dangling_lam("كما ورد في")
    'كما ورد في'
    """
    if len(normalized_text) < 3:
        return normalized_text
    parts: list[str] = []
    index = 0
    while index < len(normalized_text):
        char = normalized_text[index]
        if (
            char == _DANGLING_LAM
            and index > 0
            and normalized_text[index - 1] in _WHITESPACE_CHARS
            and normalized_text[index : index + 2] != _LAM_MA
        ):
            # ⚠️ **ولا يُتخطّى الحرف الذي بعد «ل»** — فتخطّيه كان يأكل أوّل حرف
            # من اسم المصدر. يُسقَط الفراغان و«ل» فقط.
            if parts:
                parts.pop()
            index += 1
            if index < len(normalized_text) and normalized_text[index] in _WHITESPACE_CHARS:
                index += 1
            continue
        parts.append(char)
        index += 1
    return "".join(parts)


def _ends_with_citation_lead(pre_text: str) -> bool:
    """
    هل ينتهي **ما قبل اسم المصدر** بتمهيد استشهاد؟ — بحدود الكلمات.

    ⚠️ **والمفحوص هو ما قبل الاسم لا النصّ كلّه:** بعد التمهيد يأتي اسم المصدر
    ثم بقيّة الجملة، فالسؤال عن **الكلمات التي تسبق الاسم مباشرةً**.

    ⚠️ **ولا يُجرَّد إلا «ل» وحدها** (``_drop_dangling_lam``)، فلا يُمسّ «في»
    ولا «من».

    >>> _ends_with_citation_lead("وفقا ل")
    True
    >>> _ends_with_citation_lead("كما ورد في")
    True
    >>> _ends_with_citation_lead("راجع اللغة")
    False
    """
    words = _SPACE_BEFORE_WORD.sub(" ", _drop_dangling_lam(pre_text.lower())).split()
    if not words:
        return False
    # ⚠️ **وتُجاز بادئة «و»/«ف» على الصيغة**: العربية تقول
    # «**و**يقول تعليق فلان إن الإخطار واجب»، فيقع أوّل المقطع في
    # وسط الكلمة ويُرفض التطابق. فيُقارن المقطع مرّة بحاله، ومرّة
    # بعد استبعاد حرف العطف الأوّل إن كان واحداً منهما.
    tail = words[-max(len(lead.split()) for lead in _CITATION_LEADS) :]
    candidates = [tail]
    if tail and len(tail[0]) > 1 and tail[0][0] in ("\u0648", "\u0641"):
        candidates.append([tail[0][1:]] + tail[1:])
    return any(
        candidate[-len(lead_words) :] == lead_words
        for candidate in candidates
        for lead_words in (lead.split() for lead in _CITATION_LEADS)
        if lead_words and len(lead_words) <= len(candidate)
    )


def _raw_span_of_name(draft: str, normalized_name: str) -> Optional[tuple[int, int]]:
    """
    مدى اسم المصدر **في النصّ الخام** — بناءً على مسار مطبَّع للمحارف.

    ⚠️ **ولماذا مسار، ولا بحثٌ مباشر في الخام؟** لأن الاسم يُكتب برسوم مختلفة
    (تشكيل، وأرقام هندية، وترقيم زائد)، والبحث الحرفي يُسقِط الإعلان عند أول
    اختلاف رسم. والمسار يحفظ **موضع كل محرف في الخام**، **ويبقى الفحص على
    الترقيم الخام** — وهي مواضع النقطتين وعلامات التنصيص.
    """
    pieces: list[tuple[str, int]] = []
    for index, char in enumerate(draft):
        mapped = _DIACRITICS.sub("", char).replace(_TATWEEL, "").translate(_DIGITS)
        if not mapped or _NOT_WORD.sub("", mapped) == "":
            continue
        if mapped.isspace():
            pieces.append((" ", index))
            continue
        for shifted in mapped:
            pieces.append((shifted, index))

    stream = _WHITESPACE.sub(" ", "".join(char for char, _position in pieces)).strip()
    if not stream:
        return None

    trimmed: list[int] = []
    previous_space = True
    for char, position in pieces:
        if char == " ":
            if previous_space:
                continue
            previous_space = True
            trimmed.append(position)
            continue
        previous_space = False
        trimmed.append(position)
    while trimmed and len(trimmed) > len(stream):
        trimmed.pop()
    if len(trimmed) < len(stream):
        return None

    offset = stream.find(normalized_name)
    if offset == -1:
        return None
    start = trimmed[offset]
    last = trimmed[offset + len(normalized_name) - 1]
    return start, last + 1


def _context(text: str, start: int, end: int) -> str:
    """
    الشاهد: العبارة ومحيطها المحدود **بكلمات لا بمحارف**.

    ⚠️ **والحدّ بالكلمات لا بالمحارف مقصود:** المحارف تُقطع الكلمة العربية في
    نصفها، والكلمة المقطوعة لا تُقرأ ولا تُبحث، **وإعلانٌ بموضع خاطئ أسوأ من
    غياب الموضع**.
    """
    sliced = text[start:end].strip()
    words = sliced.split()
    if len(words) > _CONTEXT_WORDS:
        sliced = " ".join(words[:_CONTEXT_WORDS])
    return sliced


#: صيغ الاستشهاد التي تجعل ما بعدها **سنداً** — ومعها لا يكون التعليق تعليقاً.
#:
#: ⚠️ **والصيغ مكتوبة مطبَّعةً للبحث** (`_normalize_name` يحذف التنوين ويردّ
#: «وفقا» لا «وفقاً»)، فلا تُكتب الصيغتان لكل عبارة.
_CITATION_LEADS: tuple[str, ...] = (
    "وفقا", "طبقا", "استنادا", "بحسب", "بموجب",
    "كما ورد في", "كما جاء في", "ورد في",
    "وفقا لما ورد في", "طبقا لما ورد في",
    "راجع", "انظر", "المشار اليه في", "وفق", "طبق",
    # ⚠️ **وأفعال القول**: «يقول تعليق فلان إن الإخطار واجب» نقلٌ عن التعليق,
    # ولو لم تُدرج لمرّ كذلك — **وهو العيب الثالث**. والقائمة تُزاد بلا حدّ.
    "يقول", "تقول", "يرى", "ترى",
    "ذهب", "ذهبت", "يذهب",
    "يرجح", "يستخلص", "يعلق",
)

#: رقم تشريع بصيغته المعتادة — علامةً على أن التعليق صار موضع الإحالة.
_DOCUMENT_NUMBER = re.compile(r"^\s*(?:ال)?(?:رقم|قانون|مرسوم|قرار)\s*[\d\u0660-\u0669]")

#: عدد المحارف التي يُبحث فيها عن التمهيد قبل اسم المصدر (وما بعده).
_LEAD_WINDOW = 60

#: ما يفصل التمهيد عن المنقول.
_QUOTE_MARKS = ("«", '"', "“", "'", "‘")


def _introduces_a_quotation(before: str, after: str) -> bool:
    """
    هل يقدّم ما قبل الاسم **ومنه** الاسمَ لمنقولٍ بين علامتَي تنصيص؟

    ⚠️⚠️ **وهذا أخطر وجوه العيب الثالث**: التعليق **يُصدّر جملةً تُنقل حرفياً**،
    فيُقرأ في المذكرة كأنه نصّ المادة. والعلامة قرينتان معاً: تمهيدٌ ينتهي
    بنقطتين، وعلامة تنصيص تفتح المنقول.

    ⚠️ **والنقطتان تُقبلان على أيّ من جانبَي الاسم**، لأن العربية تكتب الوجهين:
    «يقول تعليق فلان: «…»» (بعد الاسم) و«وفقاً لتعليق فلان: «…»» — وفي الاثنين
    النقطتان **بعد** الاسم لا قبله. وكان الشرط يطلبها قبله، **فلا تُطابق الصيغة
    المكتوبة في التوثيق نفسه**.
    """
    if not any(mark in after for mark in _QUOTE_MARKS):
        return False
    head = after
    for mark in _QUOTE_MARKS:
        cut = head.find(mark)
        if cut != -1:
            head = head[:cut]
            break
    return head.rstrip().endswith(":") or ":" in before


def _secondary_marker_at(
    text: str,
    position: int,
    length: int,
    *,
    raw: str = "",
) -> Optional[str]:
    """
    العلامة عند موضع معروف في النصّ الخام — منطق واحد لا اثنان.
    """
    before = text[max(0, position - _LEAD_WINDOW) : position]
    after = text[position + length : position + length + _LEAD_WINDOW]
    shown = raw or text

    # ⚠️ **والمقارنة بالصيغ تقتضي تطبيع ما قبل الاسم**، لأن النصّ خامّ والصيغ
    # مطبَّعة؛ ولولا ذلك لسقط التمهيد المنوَّن («وفقاً ل») — وهو أشيع ما يُكتب.
    if _ends_with_citation_lead(_normalize_name(before)):
        return _context(shown, position, position + length)
    if _introduces_a_quotation(before, after):
        return _context(shown, position, position + length)
    if _DOCUMENT_NUMBER.search(after):
        return _context(shown, position, position + length)

    return None


def _secondary_use_marker(instrument: str, draft: str) -> Optional[str]:
    """
    العلامة التي بها عُومل المصدر الثانوي معاملة النصّ — أو ``None``.

    ⚠️ **والبحث على النصّ الخام** لأن العلامات علامات ترقيم ووصل، والتطبيع
    يحذف الترقيم الذي يُبنى عليه الفحص. **والاسم يُطابَق بعد التطبيع** فيُوجد
    بأي رسم، **والشاهد من النصّ الخام** فيجده المحامي في مسودّته.
    """
    normalized_name = _normalize_name(instrument).lower()
    if not normalized_name:
        # اسم لا يُطبَّع إلى شيء: ولا يُبنى على فراغ تطابقٌ — «الفراغ يطابق كل
        # شيء» أشهر خطأ في مثل هذا الفحص.
        return None

    span = _raw_span_of_name(draft, normalized_name)
    if span is None:
        return None
    start, end = span

    return _secondary_marker_at(draft, start, end - start, raw=draft)


def secondary_as_primary(
    authorities: Sequence[Authority],
    draft: str,
) -> tuple[Finding, ...]:
    """
    يعلن كل **مصدر ثانوي عُومل معاملة النصّ** في المسودّة — **العيب الثالث**.

    ⚠️⚠️ **ولماذا هذا خطأ لا ملاحظة؟** لأن الفرق ليس في درجة الثقة، بل في
    **هويّة ما يُقتبس**. التعليق يقول «يُفهم من المادة كذا»، والنصّ يقول
    «يُحكم بكذا». فمن كتب «تنص المادة …» ونصُّ ما بين يديه ملخّصُ معلّق **لم
    يقتبس بتخمين، بل نسب إلى المادة ما لم تُرد به**.

    ⚠️ **والعلامات أربع، وكلّها معلَنة:** تمهيد استشهاد مركّب («وفقاً لتعليق
    …»)، وتمهيد بنقطتين قبل منقول («يقول تعليق فلان: «…»»)، ورقم تشريع بعد
    الاسم (صار التعليق موضع الإحالة)، وما بينهما من صيغ `_CITATION_LEADS`.

    ⚠️ **ولماذا لا يُفحص المصدر الثانوي الذي لم يُذكر في المتن؟** لأن الإعلان
    بلا موضع لا يُصلَح: المحامي لا يجد ما يُغيّر.

    >>> secondary_as_primary((Authority(key="s", instrument="تعليق على قانون مثال", article="1", kind=SourceKind.SECONDARY, official_source="", in_force_from="2019-01-01"),), "وفقا لتعليق على قانون مثال يُفهم أن الإخطار واجب")[0].kind
    'secondary_as_primary'
    >>> secondary_as_primary((Authority(key="s", instrument="تعليق على قانون مثال", article="1", kind=SourceKind.SECONDARY, official_source="", in_force_from="2019-01-01"),), "لم نقف في هذا الموضع على نصّ يحكم الواقعة.")
    ()
    """
    if not draft:
        return ()

    findings: list[Finding] = []
    for authority in authorities:
        if authority.kind is not SourceKind.SECONDARY:
            continue
        marker = _secondary_use_marker(authority.instrument, draft)
        if marker is None:
            continue

        findings.append(
            Finding(
                kind="secondary_as_primary",
                key=authority.key,
                instrument=authority.instrument,
                article=authority.article,
                source="draft",
                reason=(
                    "مصدر ثانوي (تعليق أو ملخّص) عُومل في المسودّة معاملة النصّ "
                    "الذي يُقتبس. والتعليق ليس نصّ المادة، ولا يُنقل عنه نصٌّ "
                    "يُنسب إلى مادة: يُقرأ النصّ من مصدره الرسمي، ويُذكر "
                    "التعليق — إن ذُكر — تعليقاً لا سنداً."
                ),
                detail=marker,
            )
        )

    return tuple(findings)


def unsourced(authorities: Sequence[Authority]) -> tuple[Authority, ...]:
    """
    الأسانيد التي **لا مصدر رسمي لها** — تُعلَن ولا تُعرض كأنها محقَّقة.

    ⚠️⚠️ **وهذا الموضع هو الذي يفرض المصدر — لا المُنشئ (`__post_init__`).**
    والتقسيم بينهما غير ظاهر من الخارج، فيُقال صراحةً:

    * **المُنشئ يفرض التأريخ والتصنيف**: مفتاحٌ لا يكون فارغاً، ونوعٌ من المغلقة
      — لأن حكماً بلا مفتاح أو بتصنيف نصّيّ حرّ لا يُقابَل بشيء.
    * **والمراجعة تفرض التنصيص على المصدر**: هذه الدالّة تُعلن ما لا مصدر له،
      و`summarize` يُبطل ``clean`` لأجله (وهو **ملاحظة** لا خطأ). ولو رفع
      المُنشئ استثناءً على سندٍ بلا مصدر، لَما أمكن إدراج سند لم يُتحقَّق بعد
      — **وقد يكون مفيداً في الفحص الزمني وفحص الشروط، وهما لا يحتاجان رابطاً.**

    ⚠️ **و``official_source`` الفارغ معناه «لم يُتحقَّق»، لا «لا مصدر له»** —
    وهذا فرقٌ في التصرّف. ولهذا يُعلَن ولا يُرفض السند.

    ⚠️ **والفراغ بمسافاتٍ فراغ**: ``"  "`` لا يُعدّ مصدراً.

    >>> unsourced(())
    ()
    """
    return tuple(
        authority
        for authority in authorities
        if not authority.official_source.strip()
    )


