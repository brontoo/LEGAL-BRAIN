#: عبارات **الإقرار بقاعدة مستقرّة بلا سند**.
#:
#: ⚠️⚠️ **وسبب وجودها أن هذه العبارات تعمل عمل السند — وهي أخطر من الغياب.**
#: المذكرة التي تكتب «استقر القضاء على كذا» بلا حكم ولا مادة **تقول للقارئ إنّ
#: وراءها سنداً مستقرّاً**، فلا يسأل. وليست العبارة كذباً بالضرورة — قد تكون
#: صحيحة تماماً — **بل سنداً غير قابل للفحص**، وهو ما يجب أن يراه المحامي.
#:
#: ⚠️ **وهي قائمة يُقاس عليها، لا استقصاء**، **وتُقاس بالاختبار**: كل صيغة
#: مذكورة هنا لها مثالٌ يثبت أنها تعمل — وقد رُصد أن **صيغتين مكتوبتين في
#: التعليق لا تعملان**، وهو أسوأ من غيابهما.
#:
#: ⚠️ **ولا حدودَ كلمةٍ داخل الأنماط، والحكم فيها فحصٌ صريح في الكود**
#: (``_is_word_bounded``): لأن النظر الخلفي المنفي في هذا الإصدار من بايثون
#: **يمنع المطابقة حين يليه اختبارٌ اختياري أو مجموعةُ بدائل** — وقد رُصد ذلك
#: عملياً: «وفاستقرت المحكمة…» **في أوّل النصّ لا يُطابق**.
#:
#: ⚠️ **وترتيب البدائل مقصود**: الأطول أوّلاً («استقرت» قبل «استقر»)، فلو جاء
#: الأقصر أوّلاً لَطابق جزءاً من «استقرت» ولَرفضه حدُّ النهاية بعده.
_ASSERTION_PATTERNS: tuple[re.Pattern[str], ...] = (
    # «استقر القضاء» · «استقرت المحكمة» · «واستقرت» · «فاستقرت» · «وفاستقرت».
    #
    # ⚠️ **والبادئة حرفان لا حرف**: العربية تقدّم «و» و«ف» معاً («وفاستقرت»)،
    # والاختياريّ المفرد `(?:و|ف)?` كان يُسقط هذه الصيغة — **وهي أوّل ما رُصد**.
    re.compile(
        r"(?:\u0648|\u0641)?(?:\u0648|\u0641)?"
        r"(?:\u0627\u0633\u062a\u0642\u0631\u062a|\u0627\u0633\u062a\u0642\u0631|\u064a\u0633\u062a\u0642\u0631)"
        r"\s+(?:\u0639\u0644\u064a|\u0627\u0644\u0642\u0636\u0627\u0621|\u0642\u0636\u0627\u0621"
        r"|\u0627\u0644\u0645\u062d\u0643\u0645\u0629|\u0645\u0642\u0631)"
    ),
    # «قضاء مستقر».
    re.compile(r"(?:\u0648|\u0641)?\u0642\u0636\u0627\u0621\s+\u0645\u0633\u062a\u0642\u0631"),
    # «من المقرر قانوناً» · «المقرر في قضاء» · «فمن المقرر».
    re.compile(
        r"(?:\u0648|\u0641)?(?:\u0645\u0646\s+)?(?:\u0627\u0644\u0645\u0642\u0631\u0631|\u0645\u0642\u0631\u0631)"
        r"\s+(?:\u0642\u0627\u0646\u0648\u0646\u0627|\u0642\u0627\u0646\u0648\u0646\u0627\u064b"
        r"|\u0641\u064a\s+\u0642\u0636\u0627\u0621|\u0641\u0642\u0647|\u0627\u0644\u0642\u0636\u0627\u0621)"
    ),
    # «بصفتها قاعدة مستقرة» · «قاعدة مستقرة» · «مبدأ مستقر».
    re.compile(
        r"(?:\u0648|\u0641)?(?:\u0628\u0635\u0641\u062a\u0647\u0627|\u0628\u0635\u0641\u062a\u0647)?\s*"
        r"(?:\u0642\u0627\u0639\u062f\u0629|\u0642\u0627\u0639\u062f\u0647|\u0645\u0628\u062f\u0623"
        r"|\u0645\u0628\u062f\u0627|\u0645\u0628\u0627\u062f\u0626)"
        r"\s+(?:\u0645\u0633\u062a\u0642\u0631\u0629|\u0645\u0633\u062a\u0642\u0631\u0647|\u0645\u0633\u062a\u0642\u0631)"
    ),
    # «من الثابت قانوناً» · «الثابت في القانون».
    re.compile(
        r"(?:\u0648|\u0641)?(?:\u0645\u0646\s+)?\u0627\u0644\u062b\u0627\u0628\u062a"
        r"\s+(?:\u0642\u0627\u0646\u0648\u0646\u0627|\u0642\u0627\u0646\u0648\u0646\u0627\u064b"
        r"|\u0641\u064a\s+\u0627\u0644\u0642\u0627\u0646\u0648\u0646)"
    ),
    # «لا خلاف على أن» · «لا جدال في أن» · «لا نزاع في أن».
    #
    # ⚠️ **و`(?:على|عليه|عليها|في)` لا `علي[هه]`**: الأخيرة تعني
    # «عليه/عليها» **فلا تُطابق «على» المجرّدة** — وهي الصيغة المكتوبة في هذا
    # التعليق نفسه. وقد رُصد أن «لا خلاف في أن…» تُعلَن و«لا خلاف على أن…» لا
    # تُعلَن: **تعليقٌ يَعِد بما لا يفعله النمط.**
    re.compile(
        r"(?:\u0648|\u0641)?\u0644\u0627\s+(?:\u062e\u0644\u0627\u0641|\u062c\u062f\u0627\u0644|\u0646\u0632\u0627\u0639)\s+"
        r"(?:\u0639\u0644\u0649|\u0639\u0644\u064a\u0647|\u0639\u0644\u064a\u0647\u0627|\u0641\u064a)\s+"
        r"[\u0627\u0623\u0625\u0622]\u0646"
    ),
    # «مما لا شك فيه» · «مما لا جدال فيه».
    re.compile(
        r"(?:\u0648|\u0641)?\u0645\u0645\u0627\s+\u0644\u0627\s+"
        r"(?:\u0634\u0643|\u0631\u064a\u0628\u0629|\u0631\u064a\u0628\u0647|\u062c\u062f\u0627\u0644)\s+\u0641\u064a\u0647"
    ),
    # الصيغ اللاتينية — تُقابَل بعد التطبيع (حروف صغيرة).
    re.compile(r"settled[\s\-]+law"),
    re.compile(r"it\s+is\s+settled"),
    re.compile(r"well[\s\-]+established\s+(?:law|principle|rule)"),
    re.compile(r"established\s+principle"),
)


#: سياق سابق يُبطل الإعلان: العبارة موجودة لكن **الكاتب يردّها أو ينقلها**.
#:
#: ⚠️ **وهذا هو الموضع الذي يُتَّهم فيه بريء**، ولهذا يُفحص قبل الإعلان: مذكرة
#: تقول «ولا يصحّ القول بأن من المقرر قانوناً …» **تنفي** القاعدة، وإعلانُها
#: تناقضٌ صريح مع معناها.
_REJECTION_CUES: tuple[str, ...] = (
    "\u0644\u0627 \u064a\u0635\u062d", "\u0644\u0627\u064a\u0635\u062d",
    "\u0644\u0627 \u064a\u0633\u062a\u0642\u064a\u0645", "\u0644\u0627\u064a\u0633\u062a\u0642\u064a\u0645",
    "\u0628\u0627\u0637\u0644", "\u0639\u0627\u0631 \u0639\u0646 \u0627\u0644\u0635\u062d\u0629",
    "\u0644\u0627 \u064a\u0633\u0644\u0645", "\u0644\u0627\u064a\u0633\u0644\u0645",
    "\u064a\u062f\u0651\u0639\u064a", "\u064a\u064f\u062f\u0651\u0639\u064a",
    "\u0632\u0639\u0645", "\u064a\u0632\u0639\u0645", "\u0627\u062f\u0639\u0649", "\u0623\u062f\u0651\u0639\u0649",
    "\u0639\u0644\u0649 \u063a\u064a\u0631 \u0623\u0633\u0627\u0633",
    "\u0628\u0644\u0627 \u0633\u0646\u062f", "\u062f\u0648\u0646 \u0633\u0646\u062f",
    "\u0644\u0645 \u064a\u0639\u062f", "\u0644\u0645 \u064a\u0628\u0642",
)

#: مدى النافذة السابقة التي يُبحث فيها عن سياق الردّ — بالمحارف.
_REJECTION_WINDOW = 40


@dataclass(frozen=True)
class Assertion:
    """
    عبارة تقرّر القانون بلا سند، **بموضعها وسياقها**.

    ⚠️ **والموضع يُحفظ لأن الإعلان بلا موضع لا يُصلَح**، والقارئ الذي يُقال له
    «في مذكورتك عبارة مستقرّة» وليس عنده موضعها يعيد قراءة المستند كله.
    """

    phrase: str
    start: int
    end: int
    context: str


def _strip_quotes(text: str) -> str:
    """
    يستبدل محتوى كل ما بين علامتَي تنصيص بفراغ — **لا يحذفه بل يفرّغه**.

    ⚠️⚠️ **والاستبدال بالفراغ لا بالحذف مقصود:** لو حذفنا المُقتبَس لتغيّرت
    مواضع العبارات بعده، فصار الموضع المُعلَن لا يُوافق موضعاً في المستند الذي
    فتحه المحامي — **وإعلانٌ بموضع خاطئ أسوأ من غياب الموضع**. والاستبدال بفراغ
    يحفظ الطول والمواضع.

    ⚠️ **ولا يُسأل: هل المُقتبَس منسوب إلى مصدر؟** الفرق بين هذا الملف
    و`attribution.py` هو هذا بالضبط: **هنا لا يُحاكم النقل، بل يُحاكَم القرار
    الذي قرّره الكاتب بلفظه.**
    """
    return _QUOTED.sub(lambda match: " " * len(match.group(0)), text)


#: كل ما بين علامتَي تنصيص — يُفرَّغ قبل البحث عن العبارات.
_QUOTED = re.compile(r"«[^»]*»|\"[^\"]*\"|“[^”]*”|'[^']*'|‘[^’]*’", re.DOTALL)


def _is_letter(char: str) -> bool:
    """هل المحرف حرفٌ في كلمة — عربيّاً أو لاتينيّاً أو رقمًا؟"""
    return char.isalpha() or char.isdigit()


def _is_word_bounded(text: str, start: int, end: int) -> bool:
    """
    هل العبارة واقعة على **حدّ كلمة** في النصّ؟

    ⚠️⚠️ **وهذه الدالّة وُجدت لأن الحدّ في النمط نفسه لا يعمل في هذا الإصدار من
    بايثون:** النظر الخلفي المنفي يمنع المطابقة حين يليه اختبارٌ اختياريّ أو
    مجموعةُ بدائل — وقد رُصد ذلك عملياً («وفاستقرت المحكمة…» في أوّل النصّ **لا
    يُطابق**). **فالحدّ صار فحصاً صريحاً يُقرأ ويُقاس في الاختبار.**
    """
    if start > 0 and _is_letter(text[start - 1]):
        return False
    if end < len(text) and _is_letter(text[end]):
        return False
    return True


def asserted_without_source(text: str) -> tuple[Assertion, ...]:
    """
    يعلن العبارات التي **تُقرّر قاعدة مستقرّة بلا سند** — مطابقةً حتميةً بلا نموذج.

    ⚠️⚠️ **وهذا فحصٌ يقع على القرار لا على النقل.** فالمذكرة التي تنقل حكماً
    بين علامتَي تنصيص **لا تُعلَن** هنا، لأن ما نقلته موضعه `attribution.py`،
    ولأن النقل لا يدّعي الاستقرار من عند الكاتب.

    ⚠️ **ومتى لا تُعلَن عبارة؟ في ثلاثة مواضع:**
    ١. **داخل تنصيص** — النقل لا يُحاكم هنا، **والمواضع محفوظة** فتُطابق ما في
       المستند.
    ٢. **عبارة عادية لا تسند قاعدة** — «الاستقرار» في غير القضاء، و«المقرر»
       بمعنى المُعتمَد إدارياً. ولهذا بُنيت الأنماط على **تركيب** لا على كلمة.
    ٣. **في سياق ردّ أو نقل عن الغير** — «ولا يصحّ القول بأن من المقرر قانوناً…».
       والفحص لفظي ومحدود بنافذة، **وهو أشهر موضع لخطأ إعلانٍ كاذب**.

    ⚠️ **والنتيجة بتسلسل النصّ لا بترتيب الأنماط**، والعبارة **لا تُعلَن مرّتين**
    ولو طابقها نمطان (يُطوى التداخل).

    >>> [found.phrase for found in asserted_without_source("ومن المقرر قانوناً أن الإخطار واجب.")]
    ['ومن المقرر قانونا']
    >>> asserted_without_source("ويقول المدعي «استقر القضاء على ذلك» في مذكورته.")
    ()
    """
    if not text:
        return ()

    haystack = _strip_quotes(str(text))
    matches: list[tuple[int, int, str]] = []
    for pattern in _ASSERTION_PATTERNS:
        for match in pattern.finditer(haystack):
            phrase = match.group(0).strip()
            if not phrase:
                continue
            start, end = match.start(), match.start() + len(match.group(0).rstrip())
            if not _is_word_bounded(haystack, start, end):
                # جزءٌ من كلمة أطول — ليست عبارةً قائمة.
                continue
            if any(
                start < seen_end and seen_start < end
                for seen_start, seen_end, _ in matches
            ):
                continue
            matches.append((start, end, phrase))

    found: list[Assertion] = []
    for start, end, phrase in sorted(matches):
        if _in_rejection_context(haystack, start):
            continue
        found.append(
            Assertion(
                phrase=_normalize_name(phrase),
                start=start,
                end=end,
                context=_context(haystack, start, end),
            )
        )
    return tuple(found)


def _in_rejection_context(text: str, start: int) -> bool:
    """
    هل العبارة واقعة في سياق **ردٍّ أو نقلٍ عن الغير**؟ — حدّ الإعلان الكاذب.

    ⚠️ **والفحص لفظي ومحدود بنافذة**، ولا يدّعي شيئاً أكثر: من كتب العبارة في
    سياق النقد لم يُقرّر قاعدة، ومن كتبها في سياق التقرير قرّرها. والتمييز بين
    السياقين **قراءةٌ لا مطابقة**، وهذا الملف لا يقرأ — فيُعلَن المشكوك فيه
    **ليقرأه من يقرأ**.
    """
    window = text[max(0, start - _REJECTION_WINDOW) : start]
    normalized = _normalize_name(window)
    return any(cue in normalized for cue in _REJECTION_CUES)


