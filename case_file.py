def _is_absent(case: CaseFile, name: str) -> bool:
    """
    هل الحقل **لم يُثبَت**؟ — التعريف الواحد لـ«الناقص» في هذا الملف.

    ⚠️ ولماذا «لم يُثبَت» لا «فارغ»؟ لأن الحقل قد يكون قائمةً أو زوجاً ولا
    يكون فارغاً. فالتعريف: النصّ الفارغ (أو الفراغات وحدها) ناقص، والقائمة
    الفارغة (أو التي لا عنصر ذا معنى فيها) ناقصة. والقاعدة **في موضع واحد**
    حتى لا يفترق `missing` عن `confirmed` — وهو التناقض الذي وقع في
    `labour_rules.py` حين صار لشيء واحد معياران.
    """
    value = getattr(case, name, None)
    if value is None:
        return True
    if isinstance(value, str):
        return not value.strip()
    if isinstance(value, (tuple, list)):
        if not value:
            return True
        for item in value:
            if isinstance(item, str):
                if item.strip():
                    return False
            elif isinstance(item, (tuple, list)):
                if any(isinstance(part, str) and part.strip() for part in item):
                    return False
            else:
                return False
        return True
    return False


