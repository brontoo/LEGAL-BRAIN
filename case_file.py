def questions_for(missing: object) -> tuple[Question, ...]:
    """
    الأسئلة الواجب طرحها عن الحقول الناقصة، **بترتيب الأولوية، المانع أولاً**.

    Args:
        missing: أسماء الحقول الناقصة (أيّ مجموعة تُقبل عليها العضوية).

    ولماذا لا يُفرز الناتج فرزه ثانية؟ لأن ترتيب ``QUESTIONS`` **هو** ترتيب
    الأولوية، والفرز على ``BLOCKING_FIELDS`` مرة أخرى يجعل للترتيب مصدرين
    يفترقان عند أول تعديل.

    ⚠️ **ولا يُولَّد سؤال لحقل غير مسجَّل.** الحقل المجهول يُهمَل ولا يُخترع له
    سؤال: سؤال مخترع يُجاب، وجوابٌ لسؤال لم يُقصد يُكتب في القالب فيصير افتراضاً
    صامتاً — وهو العيب نفسه.

    >>> [q.field for q in questions_for({"claims", "emirate"})]
    ['emirate', 'claims']
    """
    known = set(missing)  # type: ignore[arg-type]
    return tuple(question for question in QUESTIONS if question.field in known)


