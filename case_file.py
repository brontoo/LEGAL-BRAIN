@dataclass(frozen=True)
class _Keys:
    """
    المفاتيح المجموعة التي تُقرأ منها الشروط — **لا الحقول الخام**.

    ⚠️ ووُجد هذا الصنف لمنع أن يقرأ شرطٌ نصّاً حرّاً: كل شرط يستلم ``_Keys``،
    وفيه مفاتيح فقط (``emirate``، ``forum``، ``free_zone``، ``dispute_type``،
    ``choice_of_law``، ``arbitration_clause``). فلو حاول أحدهم كتابة
    ``keys.forum_text == "دبي"`` لم يوجد الحقل أصلاً — **المنع بنيوي لا
    مكتوب**، وهو أبقى من تعليق.
    """

    emirate: str
    forum: str
    free_zone: bool
    dispute_type: str
    choice_of_law: bool | None
    arbitration_clause: bool | None


def regime_notes(
    case: CaseFile,
    *,
    application: str = "",
) -> tuple[RegimeNote, ...]:
    """
    الملاحظات التي تخصّ هذه القضية — **بشروطها المسمّاة، لا بالتشابه النصّي**.

    Args:
        case: ملف القضية.
        application: نصّ يُطبَّق معه صراحةً (كسند عقد أو بند)، فيُقرأ منه **شرط
            التحكيم** وحده (``ARBITRATION_CLAUSE_MARKERS``). ⚠️ وهو **لا
            يُفتح به شيء آخر**: الحقوق الأخرى تُقرأ من حقول الملف، فلا يفتح
            نصٌّ عابر ملاحظةً عن نظام قضائي.

    ⚠️ **والشروط تقرأ المفاتيح:**
      * ``free_zone`` على ``forum_key`` — مركز مالي، لا إمارة.
      * ``onshore_emirate`` على ``emirate_key`` **مع نفي** المركز المالي.
      * ``other_emirates`` على ``emirate_key`` للإمارات الخمس.
      * ``onshore_labour`` على ``dispute_type`` **مع نفي** المركز المالي.
      * ``choice_of_law`` و``arbitration_clause`` على حقول العقد الصريحة.

    ⚠️ **وقياسٌ على القضية لا استنتاجٌ لها:** الدالّة **لا تقول** إن نظاماً
    ينطبق، ولا تُرجّح بين نظامين، ولا تُسقط ملاحظةً لأنها «غير محتملة». هي
    تُرجع ملاحظات الجدول التي انطبق شرطها — والشرط اسمه مكتوب في الجدول،
    فيُقرأ ويُفحَص.

    >>> ["free_zone" if n.area is RegimeArea.FREE_ZONE else n.area.value
    ...  for n in regime_notes(_difc_case())]
    ['free_zone']
    >>> [n.area.value for n in regime_notes(_abudhabi_labour_case())]
    ['employment', 'emirate']
    >>> [n.area.value for n in regime_notes(_sharjah_lease_case())]
    ['emirate']
    """
    keys = _Keys(
        emirate=case.emirate_key,
        forum=case.forum_key,
        free_zone=case.is_free_zone,
        dispute_type=case.dispute_type.value,
        choice_of_law=case.has_choice_of_law,
        arbitration_clause=(
            True
            if case.has_arbitration_clause
            else _mentions_arbitration_clause(application)
        ),
    )

    found: list[RegimeNote] = []
    for note in REGIME_NOTES:
        condition = _TRIGGERS.get(note.trigger)
        # ملاحظة بشرط غير مسجَّل تُسقَط ولا تُفتح: الفتح بلا شرط معروف يعني
        # عرض ملاحظة على كل قضية، وهو أسوأ من غيابها. والاختبار يمنع وجودها.
        if condition is None:
            continue
        if condition(keys):  # type: ignore[operator]
            found.append(note)

    # الترتيب ترتيب الجدول — وقد وُضع بأولويته المعروضة على المحامي لا أبجدياً.
    # والاختبار يثبّته.
    return tuple(found)


def notes_summary(notes: tuple[RegimeNote, ...]) -> list[dict]:
    """
    قائمة الملاحظات في صورة **صالحة للبثّ كـ JSON**.

    ووُجدت منفصلة عن `regime_notes` على نمط ``summarize`` في `review.py`: البحث
    حكمٌ، والعرض تحويل — فلا يختلطان ببعضهما في دالّة واحدة.

    >>> notes_summary(regime_notes(_difc_case()))[0]["area"]
    'free_zone'
    """
    return [
        {
            "area": note.area.value,
            "trigger": note.trigger,
            "note": note.note,
            "source": note.source,
            "limit": note.limit,
        }
        for note in notes
    ]


# ==============================================================================
# ٦. الاشتقاق — الموضع الوحيد الذي يُشتقّ فيه مفتاح من نصّ
# ==============================================================================


def _fold(text: str) -> str:
    """
    يطوي النصّ للمطابقة: بلا تشكيل، وبأرقام لاتينية، وبلا علامات اتجاه.

    ⚠️ **وطيّ الألف والهمزة والتاء المربوطة مقصود هنا** خلافاً لِما قيل في
    ``facts._content_tokens``: ذاك يطابق **نصّ نقلٍ** فيخشى طيّ كلمتين
    مختلفتين، وهذا يطابق **اسم إمارة أو جهة** من مجموعة مغلقة، فالطيّ فيه
    يزيد الاحتمال ولا يُنقص الدقّة — «أبوظبي» و«أبو ظبي» و«ابوظبي» واحدة.

    ⚠️ **ولا يُطبَّع بحذف الفراغات**، لأن الصور المعلنة قد تحوي فراغاً
    («ابو ظبي»)، والمطابقة تجري على النصّ كما هو بعد الطيّ.
    """
    if not text:
        return ""
    folded = unicodedata.normalize("NFKC", text)
    folded = re.sub(r"[\u200b-\u200f\u202a-\u202e\u2066-\u2069\ufeff]", "", folded)
    folded = re.sub(r"[\u0610-\u061a\u064b-\u065f\u0670\u06d6-\u06ed]", "", folded)
    folded = folded.replace("\u0640", "")
    folded = folded.translate(
        str.maketrans("٠١٢٣٤٥٦٧٨٩۰۱۲۳۴۵۶۷۸۹", "01234567890123456789")
    )
    folded = folded.translate(str.maketrans({"أ": "ا", "إ": "ا", "آ": "ا", "ة": "ه"}))
    folded = re.sub(r"[^\w\s]", " ", folded, flags=re.UNICODE)
    return re.sub(r"\s+", " ", folded).strip().lower()


def _without_article(word: str) -> str:
    """يحذف أداة التعريف من صورة الإمارة — «إمارة دبي» و«دبي» سواء."""
    for article in _DEFINITE_ARTICLES:
        if word.startswith(article) and len(word) - len(article) >= 3:
            return word[len(article) :]
    return word


def derive_emirate_key(emirate: str) -> str | None:
    """
    مفتاح الإمارة من نصّها، أو ``None`` إن لم تُعرف صورته.

    ⚠️ **و``None`` هنا إعلانُ جهل لا فشل**، على قاعدة ``rule_for`` في
    `labour_rules.py`: هو ما يرفع الاستثناء في ``CaseFile.__post_init__``
    فيمنع تقريراً فارغاً كاذباً.

    والمطابقة تبدأ بالصورة المنقوصة (بلا أداة تعريف)، ثم بالنصّ كما هو، ثم
    بأول رمز فيه — فتُدرك «إمارة دبي» و«دبي» و«DUBAI» و«أبو ظبي» معاً.

    >>> derive_emirate_key("أبوظبي")
    'abu_dhabi'
    >>> derive_emirate_key("إمارة دبي") 
    'dubai'
    >>> derive_emirate_key("دولة قطر") is None
    True
    """
    folded = _fold(emirate)
    if not folded:
        return None
    candidates = [folded]
    candidates.extend(_without_article(word) for word in folded.split())
    for candidate in candidates:
        if candidate in EMIRATE_ALIASES:
            return EMIRATE_ALIASES[candidate]
    # وبعد الصور المعلنة: **أضعف مطابقة** — رمز الإمارة داخل نصّ أطول مثل
    # «محكمة دبي الابتدائية» حين يُكتب في حقل الإمارة خطأً.
    for word in folded.split():
        stripped = _without_article(word)
        if stripped in EMIRATE_ALIASES:
            return EMIRATE_ALIASES[stripped]
    return None


def derive_forum_key(forum: str) -> str | None:
    """
    مفتاح الجهة من نصّها، أو ``None`` إن لم تُعرف صورتها.

    ⚠️ **والترتيب في ``_FORUM_ALIASES`` هو الحكم:** التحكيم يُقدَّم على
    غيره، لأن «مركز دبي للتحكيم» فيه «دبي» وفيه «تحكيم»، والاختصاص يتبعه
    الشرط لا محلّ الانعقاد.

    >>> derive_forum_key("محاكم مركز دبي المالي العالمي (DIFC Courts)")
    'difc'
    >>> derive_forum_key("هيئة التحكيم الدولية")
    'arbitration'
    >>> derive_forum_key("محكمة الشارقة الابتدائية")
    'onshore'
    """
    folded = _fold(forum)
    if not folded:
        return None
    for needle, key in _FORUM_ALIASES:
        if needle in folded:
            return key
    return None


def _mentions_arbitration_clause(application: str) -> bool:
    """
    هل في النصّ الممرَّر ما يفصح عن شرط تحكيم؟ — **ولا يُفتح به غيره**.

    >>> _mentions_arbitration_clause("البند ١٢: يُحال أي نزاع إلى التحكيم")
    True
    >>> _mentions_arbitration_clause("عقد إيجار وحدة سكنية")
    False
    """
    folded = _fold(application)
    if not folded:
        return False
    return any(_fold(marker) in folded for marker in ARBITRATION_CLAUSE_MARKERS)


