# ٥.١ الشروط — كل شرط في دالّة واحدة مسمّاة، بلا مغالطات منطقية مخفيّة
# ==============================================================================
# ⚠️ **ودالّة لكل شرط لا ``lambda`` في الجدول**، وسببان:
#
# ١. اسم الشرط يُكتب في ``RegimeNote.trigger`` **ويُفحَص**: يمكن إثبات أن كل
#    شرط مذكور في الجدول موجود في ``_TRIGGERS``، وأن كل شرط في ``_TRIGGERS``
#    يُفتح به ملاحظة — فلا يبقى شرط ميت ولا ملاحظة لا تُبلَغ.
# ٢. والمغالطة المنطقية في ``lambda`` لا تُقرأ: `a and not b or c` تُحتمل
#    معنيين، وشرط الاختصاص **ليس موضعاً للاحتمال**. أما `if` فتُقرأ سطراً
#    سطراً، والاختبار يُثبّت كل فرع منها.


def _trigger_free_zone(keys: _Keys) -> bool:
    """
    مركز مالي — ``DIFC`` و``ADGM`` وحدَهما.

    ⚠️ **والشرط على ``forum_key`` لا على ``emirate_key``.** قضية في دبي
    مفتاح إمارتها ``dubai`` ولا يجوز أن تجرّ ملاحظة مركز مالي، ولو كان
    الطرفان مسجَّلين فيه: العبرة بمحكمة النظر (أو بالعقد) لا بمحلّ التسجيل.
    """
    return keys.forum in (ForumKey.DIFC.value, ForumKey.ADGM.value)


def _trigger_onshore_emirate(keys: _Keys) -> bool:
    """
    النظام القضائي المحلّي **المحرَّر** — أبوظبي ودبي وحدهما، وعلى البرّ.

    ⚠️ **و``not keys.free_zone`` شرطٌ لا احتياط:** قضية أمام محاكم مركز دبي
    المالي إمارتها ``dubai``، فلو لم يُستثنَ المركز لظهرت لها ملاحظة «لدبي
    نظامها القضائي المحلي ومركز فضّ المنازعات الإيجارية» — وهي **صحيحة في
    دبي وخاطئة في هذه القضية**، وهذا هو العيب الذي جاء الجدول لمنعه.

    ⚠️ **والحصر في ``_EMIRATES_WITH_FORUM_NOTES`` ليس تضييقاً بل منع
    تكرار:** كان الشرط ``keys.emirate in EMIRATES`` فانطبقت **هذه الملاحظة
    وملاحظة الإمارات الخمس معاً** على قضية في الشارقة، فظهرت للمحامي
    ملاحظتان عن «نظام الإمارة القضائي» في تقرير واحد — إحداهما تصف نظاماً
    محرَّراً والأخرى تقول إنه غير محرَّر. والتكرار هنا **ليس ضجيجاً فقط**:
    هو **تناقض ظاهر** يُفقد التقرير كلّه الثقة، وهو العيب نفسه الذي وُسم به
    تقرير `language_audit.py` (أحد عشر سلوكاً صحيحاً كأخطاء). فالشرط الآن
    يقرأ الثابت نفسه الذي يقرأه شرط الإمارات الأخرى، فلا يفترقان.
    """
    return keys.emirate in _EMIRATES_WITH_FORUM_NOTES and not keys.free_zone


def _trigger_other_emirates(keys: _Keys) -> bool:
    """
    الإمارات الخمس التي لم تُحرَّر أنظمتها في هذا المشروع.

    ⚠️ وشرطها ``emirate`` بلا ``free_zone`` لأن السوق والمركز لا يقومان في
    هذه الإمارات — فإن وُجد مستقبلاً مركزٌ مالي فيها وجب تعديل الشرط هنا،
    لا في الجدول.
    """
    return keys.emirate in _EMIRATES_WITHOUT_NOTES and not keys.free_zone


def _trigger_onshore_labour(keys: _Keys) -> bool:
    """
    دعوى عمالية أمام قضاء الدولة — ويُحتمل أن يلزمها مسار الوزارة.

    ⚠️ **والشرط على ``dispute_type == LABOUR``، وهي قيمة مغلقة** — لا على
    كلمة «عمالي» في نصّ: «دعوى عمالية» و«نزاع عمل» و«مطالبة عمالية» ثلاث
    صيغ، والمطابقة على النصّ تُخطئ في اثنتين منها. وهذا هو الدرس نفسه الذي
    أُصلح في مطابقة الجهة.

    ⚠️ **و``not keys.free_zone`` جوهري:** نظام ``DIFC`` و``ADGM`` العمالي
    خاصّ بهما، ومسار الوزارة يخصّ من يخضع للقانون الاتحادي. فلو دخلت ملاحظة
    المسار على قضية في المركز لكانت **النصّ الصحيح في الموضع الخاطئ**.
    """
    return keys.dispute_type == DisputeType.LABOUR.value and not keys.free_zone


def _trigger_choice_of_law(keys: _Keys) -> bool:
    """
    اتّفاق الطرفين على قانون يحكم العقد — يُملأ من **حقل صريح**.

    ⚠️ **ولا يُستنبط من ``likely_law``**: ذاك ترجيح المحامي لا اتّفاق
    الطرفين، والخلط بينهما يجعل ملاحظةً عن «القانون المختار» تظهر في ملفٍ
    لم يُختَر فيه قانون أصلاً. ولذلك ``keys.choice_of_law is True`` لا
    ``is not None``.
    """
    return keys.choice_of_law is True


def _trigger_arbitration_clause(keys: _Keys) -> bool:
    """وجود شرط تحكيم — من الحقل الصريح، أو من مفتاح الجهة إن كانت هيئة تحكيم."""
    return keys.arbitration_clause is True or keys.forum == ForumKey.ARBITRATION.value


