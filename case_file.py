"""
ملف القضية — الحقول التي لا يُصاغ مستند قبل أن تُعرَف.
=============================================================================

المشكلة التي يحلّها
------------------
الصياغة كانت تبدأ من **الوقائع السائبة**: نصّ يكتبه المحامي، ثم نموذج يقرأه
ويكتب المذكرة. ولا يُسأل في أيّ إمارة القضية، ولا أمام أيّ جهة، ولا في أيّ
مرحلة، ولا لصالح مَن. فالمسودّة تُبنى على افتراضات **لم يكتبها أحد** — وهي
أخطر من الخطأ الصريح، لأن الخطأ الصريح يُرى ولا يُسلَّم، والافتراض الصامت
يمضي.

ثلاث مراجعات قانونية مستقلّة رصدت هذا في صورته العملية:

١. **نصّ قانون صحيح في موضع لا ينطبق.** مادة ذُكرت في موضع لا تنطبق عليه،
   لأن المسار لم يسأل: **أيّ نظام يحكم هذه القضية؟** والنصّ الذي يصلح في
   قضاء الإمارة لا يصلح في مركز مالي له محكمته ونظامه.

٢. **مبلغ منقول عن تسوية سابقة كأنه احتساب.** والجواب ليس حساباً جديداً، بل
   أن يُعرَف **ما هو محلّ النزاع أصلاً** (الطلبات) وما مصدر الرقم.

٣. **مدّة محسوبة على أساس خاطئ** (١٢٧٨ يوماً والصحيح ١٣٠٧) — والعدّ نفسه
   يتغيّر بتغيّر **تاريخ انتهاء العلاقة**، وهو حقلٌ في هذا الملف لا في المذكرة.

فالملف هو **مِلء استمارة قبل الكتابة**: يُجيب عن الأسئلة التي يتفرّع عليها
القانون قبل أن تُكتب كلمة واحدة.

المبدأ التصميمي — على نمط `citations.py` و`labour_rules.py`
-----------------------------------------------------------
> **النموذج يروي، والخادم يُقرّر.**

فالملف **بلا حالة وبلا إدخال/إخراج وبلا شبكة**: مكتبة بايثون القياسية وحدها
(``dataclasses``، ``enum``، ``json``، ``re``)، ودوالّه نقية فتُختبر مباشرة.

⚠️ **وما ليس هذا الملف**
------------------------
هو **ليس رَأياً قانونياً**، ولا يقول للمحامي أيّ نظام ينطبق. هو:
الأماكن التي **يفترق فيها** الجواب، و**مصدر** كل افتراق، و**ما يُسأل عنه
المحامي** قبل الكتابة. والجواب نفسه يبقى للمحامي — وهذا صريح في موضعه أدناه.

⚠️ **وأهمّ ما في الملف: لا يُفترض نظام واحد للإمارات**
-----------------------------------------------------
«القانون الإماراتي» ليس كتلة واحدة. دولة الإمارات **اتّحاد**، وفيه نظامان
قضائيان محلّيان (أبوظبي ودبي)، ومراكز مالية لها محاكمها ونظامها العمالي
الخاصّ (مركز دبي المالي العالمي، وسوق أبوظبي العالمي)، وجهات إدارية تسبق
القضاء في بعض الدعاوى (وزارة الموارد البشرية والتوطين في دعاوى العمل).
فالمسودّة التي تفترض نظاماً واحداً تُنتج نصّاً صحيحاً في نظامٍ وخاطئاً في
الذي ينطبق. و`REGIME_NOTES` أدناه هو جواب ذلك: **جدول أماكن الافتراق**، لا
جدول قانون.

⚠️ **ودرسٌ دُفع ثمنه في هذا الملف نفسه — فاقرأه قبل أن تُعدّل المطابقة**
-----------------------------------------------------------------------
أول نسخة من `regime_notes` طابقت **رموز الجدول الآلية** (``difc``،
``dubai``، ``abu_dhabi``...) على **نصّ الحقل العربي** (``"دبي"``،
``"أبوظبي"``). والنتيجة أن المطابقة **لم تُرجع ملاحظة واحدة أبداً**، ولا في
قضية عمالية في أبوظبي: مفتاحٌ لاتيني لا يساوي نصّاً عربياً، فالتقاطع فراغٌ
دائماً.

⚠️ **وخطورة العيب ليست في فراغ الجواب، بل في أن الفراغ كان صامتاً:**
المحامي يقرأ تقريراً فارغاً فيظنّ أن قضيتَه لا موضع افتراق فيها، فيتوقّف عن
السؤال — **وهو نقيض ما وُجد الجدول له**. وأداةٌ تُنذر دائماً لا تُنذر أبداً،
وأداةٌ **تصمت دائماً** أسوأ منهما.

فالمطابقة الآن **لا تقع على نصّ حرّ**:
* الإمارة **مفتاح آلي** يُشتقّ من نصّ الحقل عبر جدول صور معلن
  (`EMIRATE_ALIASES`)، **ويُشتقّ مرة واحدة** فتُبنى عليه كل المطابقات.
* الجهة كذلك (`forum_key`)، لأن ``difc`` و``adgm`` **وصفٌ للجهة لا للإمارة**:
  قضية تجارية في دبي على البرّ لا يجوز أن تجرّ ملاحظة مركز دبي المالي.
* ونوع النزاع ووجود شرط التحكيم **قيمٌ صريحة** لا تُستنبط من نصّ: انظر
  ``DisputeType`` و``has_arbitration_clause``.
* ⚠️ **والنصّ الذي لا يُعرف مفتاحه يرفع استثناءً ولا يمرّ صامتاً.** هذا هو
  الدرس: العيب الذي لا يُرى يُعاد، والذي يوقف المسار يُصلَح.

الملف لا يُغلق نقصاً ولا يُخمّن: ما لم يُعرَف يبقى فارغاً ويرتفع إلى المحامي
(`missing` و`questions_for`)، وحقل **مانع** ناقص يوقف الصياغة بدل أن يُكمَل
من عنده (`BLOCKING_FIELDS`).
"""

