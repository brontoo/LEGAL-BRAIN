# ٥. أماكن افتراق الأنظمة — ⚠️ هذه **قائمة تحقّق للمحامي، لا رأي قانوني**
# ==============================================================================
#
# ⚠️⚠️ **اقرأ هذا قبل أن تعتمد الجدول أو تنقل منه إلى مسودّة.**
#
# الجدول أدناه **ليس بياناً بالقانون**، ولا يزعم أنه استقصى أنظمة الإمارات.
# هو **قائمة تحقّق تبدأ بها**: يسمّي الأماكن التي **يفترق فيها** الجواب في
# الدولة، ويذكر لكل افتراق **مصدراً** يُراجَع. والجواب نفسه — أيّ هذه الأماكن
# ينطبق على القضية، وما حكمه — **للمحامي**، ولا يُبنى عليه في هذا الملف.
#
# ولماذا وُجد أصلاً؟ لأن ثلاث مراجعات قانونية رصدت **النصّ الصحيح في الموضع
# الخاطئ**، وأصل العيب أن المسار لم يسأل «أيّ نظام يحكم هذه القضية؟». فسؤالٌ
# واحد يُطرح قبل الكتابة يكفي لمنع تكراره، وهذا الجدول هو ذلك السؤال في صورة
# بيانات.
#
# **وحدود الجدول — مكتوبة كما في `RULES` في `labour_rules.py`:**
#
# ١. **كل ملاحظة تحمل `source`.** ولا تُقبل ملاحظة بلا مصدر، ولو كانت صحيحة في
#    الظاهر: بلا مصدر لا يستطيع المحامي أن يتحقّق، فتصير الملاحظة **رأياً
#    يتنكّر في هيئة مرجع**.
# ٢. **وما لم يُتيقَّن من تفصيله حُذف ولم يُخترع.** فلا أرقام قوانين مخمَّنة،
#    ولا تواريخ مخمَّنة: رقم قانون مخمَّن **يمضي إلى المسودّة** ويصطدم بفحص
#    `citations.py` الذي يرفض ما لا سند له في الأرشيف. ومن احتاج التفصيل
#    فليأتِ بمصدره، وليُضِف الملاحظة بمصدرها — تعديلاً في موضع واحد.
# ٣. **ولا يُقال في الجدول إنّ حكماً «مستقرّ».** الصيغة المعتمدة فيه: «هذا
#    موضع افتراق، تحقّق منه». والعبارة التي تقول «القانون يقضي كذا» تُقرأ
#    نتيجةً لا سؤالاً، وهذا ما يُريد الملف منعه.
#
# **وما حُذف صراحةً لنقص في التيقّن، ولماذا كلٌّ حُذف — حتى لا يُظنّ سهواً:**
#
#   • **أرقام قوانين المناطق الحرّة ونظامها العمالي.** لا تُكتب أرقام قوانين
#     مركز دبي المالي العالمي وسوق أبوظبي العالمي العمالية هنا لأن التيقّن من
#     أرقامها ونسخها السارية لم يحصل في هذا المشروع. فيُقال **إنّ للنظامين
#     نظاماً عمالياً خاصاً** — وهي الحقيقة التي تمنع الخطأ — ويُترك الرقم
#     للمحامي. وهذا صريح في كل ملاحظة تحتها.
#   • **ميعاد دعوى العمل أمام النظامين الخاصين (المناطق الحرّة)، ومدّة
#     إسقاط الدعوى العمالية أمام قضاء الدولة.** لم يُتيقَّن من أرقام المواد
#     التي تقرّرها، فالمادة التي لا يُتيقّن من رقمها **تُحذف قاعدتها بالكامل**
#     ولا تُكتب بتخمين — وهو الحدّ نفسه المكتوب فوق `RULES` في `labour_rules.py`.
#     ⚠️ وخطره حقيقي: مدّة التقادم التي تُخطئ فيها **تُسقط الحقّ**، لا تُنقص
#     رقماً.
#   • **أرقام موادّ مراكز فضّ المنازعات الإيجارية ولوائحها.** كذلك: يُذكر أن
#     للمسار لائحة وإجراءً خاصّين، ولا يُخمَّن رقم.
#   • **تفاصيل التوزيع القضائي داخل أبوظبي** (أيّ دائرة تختصّ بأيّ نزاع). يُذكر
#     أن لأبوظبي نظاماً قضائياً محلياً مستقلاً عن النظام الاتحادي في جانب
#     النظر، ولا يُخمَّن تفصيل الدوائر.


@dataclass(frozen=True)
class RegimeNote:
    """
    ملاحظة **موضع افتراق** واحد، بمصدرها وحدّها.

    Attributes:
        area:    باب الافتراق من ``RegimeArea``.
        trigger: **اسم الشرط** الذي تُفتح به الملاحظة — اسمٌ من ``_TRIGGERS``
                 **لا دالّة ولا نصّ**. ولماذا اسم لا دالّة؟ لأن الجدول يجب أن
                 يبقى **بيانات قابلة للقراءة والفحص**: اختبارٌ يستطيع أن يعدّ
                 الشروط ويُثبت أن **كل ملاحظة يمكن بلوغها**، بينما دالّةٌ في
                 الحقل تُخفي الشرط فلا يُفحَص إلا بالتنفيذ.
        applies_to: **الحقول التي يقرأها الشرط** — توثيقٌ يُفحَص آلياً (انظر
                 ``test_every_note_names_the_fields_it_reads``)، فتُكتشف
                 الملاحظة التي تقول إنها تقرأ حقلاً ثم تقرأ غيره.
        note:    الملاحظة بالعربية — **صيغتها «تحقّق من»** لا «القانون يقضي»،
                 لأنها سؤال على المحامي لا نتيجة له.
        source:  ما يُراجَع لهذه الملاحظة. وإلزاميّ كما في ``Rule.article``.
        limit:   **حدّ الملاحظة** — ما لا تقوله. وحقل الحدّ ليس ترفاً:
                 الملاحظة التي تُقرأ أوسع مما هي عليه تُنتج **النصّ الصحيح
                 في الموضع الخاطئ**، وهو العيب الذي جاء الجدول لمنعه.

    ⚠️ **ولماذا لا يبقى حقل ``placement`` كما كان؟** كان يقصد «أين تُبحث
    الملاحظة: في الإمارة أم في الجهة»، وهو **بديل عن الشرط لا شرط**: قضية
    في دبي على البرّ تجرّ ملاحظة الدفاع الإيجاري، وقضية في مركز دبي المالي
    تُسقطها — وهذا لا يُعبَّر عنه بمكان البحث بل بشرط صريح على **المفاتيح**
    (`emirate_key` و`forum_key`). فاستُبدل المكان بالشرط، وصار كل شرط مقروءاً
    مسمّى.
    """

    area: RegimeArea
    trigger: str
    applies_to: tuple[str, ...]
    note: str
    source: str
    limit: str


