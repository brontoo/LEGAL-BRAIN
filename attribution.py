"""
سند المادة — هل النصّ المقتبس نصُّ المادة التي نُسب إليها؟
=============================================================================

المشكلة التي يحلّها
------------------
`citations.py` يجيب سؤالاً واحداً: **«هل هذا الاقتباس موجود حرفياً في مقطع
استرجعناه؟»**. وهذا يمنع **التأليف**، ولا يمنع ما هو أخطر منه:

    اقتباسٌ حقيقي — منسوبٌ إلى المادة الخطأ.

وقد وقع ذلك في مسودّة حقيقية: كُتب فيها «المادة ٤٣/٢ تنص على: …» ونُقل بعدها نصٌّ
عن العقد محدد المدة **لا تحويه المادة ٤٣**، بل هو نصّ مادة أخرى. والاقتباس موجود
في الأرشيف فعلاً، والمرجع يشير إلى مقطع حقيقي، فيمرّ من كل فحص قائم — ويصل إلى
المحكمة **نصٌّ صحيح منسوباً إلى مادة بريئة**.

وكلام المحامي فيه فصل: **نسبة نصّ إلى مادة ليست له أخطر من عدم ذكر المادة
أصلاً.** لأن الغياب يُسأل عنه فيُجاب، أما النسبة الكاذبة فتُسلَّم لأنها تحمل
شكل التوثيق: مرجعٌ مكتوب، ونصٌّ موجود في الأرشيف، وفحصٌ يجتاز. فالعيب لا يظهر
في أي موضع من المستند.

فهذا فحص **ثانٍ فوق** `citations.py` لا بديلاً عنه. الأول يسأل: «هل النصّ موجود
فيما أُعطي؟». وهذا يسأل: «**أهو نصّ المادة التي نُسب إليها؟**».

المبدأ التصميمي — كـ `citations.py` و`review.py`
-------------------------------------------------
> **النموذج يروي، والخادم يُقرّر.**

ولا يُحفظ في هذا الملف **نصّ مادة واحدة**. لو كتبنا في الكود «المادة ٤٣ تتكلّم عن
العقد محدد المدة» لصار الملف رأياً في القانون يتقادم بصمت، **ولما اختبر شيئاً**:
المقارنة تكون بين **ما كتبه النموذج** و**ما استُرجِع من أرشيفك**. فالحكم مبنيّ
على ما أُعطي، لا على معرفة محفوظة هنا. (وهو حدّ `labour_rules.py` نفسه: الجدول
للمحامي أن يتحقّقه، ولا يُغني عنه.)

الحالات الثلاث — ولماذا ثلاث لا اثنتان
--------------------------------------
* ``matched``    — المقطع الذي **يحمل المادة** يحمل النصّ أيضاً.
* ``mismatched`` — المقطع الذي يحمل المادة **لا** يحمل النصّ. **وهذا العيب الذي
  جاء الملف له**، وهو **خطأ** (`error`) لأنه **قولٌ كاذب عن القانون** بنصّه.
* ``absent``     — لا مقطع في المسترجَع **يذكر المادة أصلاً**. وهذه **ملاحظة**
  (`notice`) لا خطأ: **المسودّة ذكرت مادة لم يُنتجها الاسترجاع**، وقد يكون
  الأرشيف ناقصاً لا الكاتب مخطئاً. ولو صارت خطأً لمنعنا التسليم بسب عيبٍ في
  التغطية لا في المسودّة — وهو ما يجعل الأداة تُنذر دائماً فلا تُقرأ.

⚠️ **و``absent`` ليست سلامة.** هي «لم يُفحص»، لا «صحّ». ولهذا تُعرَض على
المحامي في ``summarize`` بدل أن تُطوى: الفرق بين «نسب نصّاً إلى المادة الخطأ»
و«نسب نصّاً إلى مادة لا نعرفها» فرقٌ يُبنى عليه تصرّف مختلف.

حدود معلنة — كلّها في اتجاه واحد: **قد يُتَّهم بريء، ولا يُبرَّأ متّهم**
----------------------------------------------------------------------
1. **الاقتباس يُقتطع من موضع المرجع إلى نهاية المقطع.** فإن لم تكن علامتا تنصيص
   (``«…»``) تحيط بالنصّ، دخل في المقتطع **كلام الكاتب عن المادة** («وتنص على
   أنه…»). ولذلك يُقلَّم التمهيد قبل الحكم (انظر ``_FRAMING``)، ويُقدَّم
   الاقتباس الصريح بين علامتيه إن وُجد. ومع ذلك يبقى ما لا يُقلَّم — كتعليق
   للكاتب بعد نصّ المادة — **سبباً لـ``mismatched`` كاذب**. والعلاج الأمثل أن
   يُلزم الموجّه النموذج **بعلامتي تنصيص** حول كل نصّ ينسبه إلى مادة.
2. **التقليم من أول النصّ ولا من آخره.** الأول آمن (الباقي جزءٌ من النصّ فيبقى
   انطواؤه صحيحاً)، والثاني غير آمن (لا يُعرف أين ينتهي نصّ المادة وأين يبدأ
   كلام الكاتب).
3. **الفحص على مستوى المادة لا البند.** فـ«المادة ٤٣/٢» يُفتش عن «٤٣»: مقطع
   يحمل «المادة ٤٣» يُعدّ حاملاً للنصّ. فإن كان في الأرشيف بنودٌ متعدّدة للمادة
   نفسها وكان النصّ في بند غيرها، **مرّ الإسناد** — أي الخطأ هنا في اتّجاه
   التسامح لا في اتّجاه الاتّهام، وهو الموضع المقبول.
4. **الذكر العابر للمادة يُعدّ حملها.** مقطع يقول «كما ورد في المادة ٤٣» ويحمل
   نصاً آخر يُعدّ حاملاً للمادة. فإن كان نصّ المادة نفسها **لم يُسترجَع أصلاً**
   ووُجد مجرّد ذكره، خرج اقتباسٌ صحيح ``mismatched`` وكان الأحقّ ``absent``.
5. **الاقتباس الأقصر من ``MIN_QUOTE_CHARS`` لا يُحاكم.** ما دون حدّ الدليل ليس
   اقتباساً بل ذكرٌ للمادة في نثر، وإصدار حكم «منسوب إلى غير مادّته» عليه اتهامٌ
   لا يقوم عليه دليل. والمرجع نفسه يبقى مفحوصاً في `citations.py`
   (``unbacked_article_refs``). فالثمن **تغطية ناقصة**، لا اتهام كاذب.

الملف بلا تبعية خارجية وبلا حالة وبلا إدخال/إخراج وبلا شبكة: مكتبة بايثون
القياسية وحدها مع ما يُستورد من `citations.py`، فيعمل اختباره بلا أرشيف وبلا
مفتاح API وبلا نموذج.
"""

