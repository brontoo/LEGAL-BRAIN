STATUS_ABSENT = "absent"
STATUS_MISMATCHED = "mismatched"

#: الحالة التي تمنع التسليم، والحالة التي تُعرَض ولا تمنع.
#:
#: ⚠️ **والفرق بينهما هو الفرق بين قولٍ كاذب عن القانون ونقصٍ في الأرشيف:**
