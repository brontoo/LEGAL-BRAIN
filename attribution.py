def _article_number(reference: str) -> str:
    """
    رقم المادة من مرجع مكتوب — **مطبَّعاً**، لأن الفحص كلّه على المطبَّع.

    والتحويل يمرّ بـ``normalize`` ولا يُكتب هنا جدول أرقام ثانٍ: نسخُ جدول
    الأرقام يعني جدولين يفترقان عند أول تعديل، فيُبحث عن «٤٣» باللاتينية في
    نصّ لم يُطبَّع. وهذا بعينه ما يُنتج ``absent`` كاذباً.

    >>> _article_number("المادة ٤٣/٢")
    '43'
    >>> _article_number("م 15")
    '15'
    """
    if not reference:
        return ""
    match = _REFERENCE.search(reference)
    if match is None:
        return ""
    return normalize(match.group("num"))


def _article_marker(number: str) -> re.Pattern[str]:
    """
    نمط «المادة ٤٣» في مقطع — أي أن المقطع **يحمل المادة** لا يذكر رقمها عارضاً.

    وحدّه ``(?<!\\d)``/``(?!\\d)`` كما في `citations.py`: الرقم «٤٣» لا يُطابق
    «٤٣٠» ولا «١٤٣». وهذا الحدّ هو الذي يمنع أن يُقرأ «المادة ٤٣٠» حاملاً
    للمادة ٤٣.
    """
    return re.compile(
        r"(?:^|(?<![\w]))(?:و|ف)?(?:ال)?"
        r"(?:ماده|مادتان|مادتي|مادتين|مواد|م)"
        rf"\s*(?<!\d){re.escape(number)}(?!\d)"
    )


def _carries_article(item: Evidence, number: str, text_of: Callable[[Evidence], str]) -> bool:
    """
    هل يحمل هذا المقطع المادةَ المطلوبة؟

    والعبارة «يحمل» أدقّ من «يذكر»: المقطع الذي نصّه نصُّ المادة **يحملها**،
    والمقطع الذي يقول «كما ورد في المادة ٤٣» **يذكرها**. والاثنان يُعدّان
    حاملين هنا لأن الفحص على الرقم، وهو حدّ معلن في صدر الملف (الحدّ الرابع).
    """
    return bool(_article_marker(number).search(normalize(text_of(item))))


def _carries_quote(item: Evidence, quote: str, text_of: Callable[[Evidence], str]) -> bool:
    """
    هل يحمل هذا المقطع النصَّ المنسوب؟

    والحكم ليس هنا: هو ``quote_in_text`` في `citations.py` — ومنها تأتي عتبة
    ``MIN_QUOTE_CHARS`` أيضاً. فلو حكم هذا الملف على النصّ العربي بنفسه لصار في
    المشروع حكمان يفترقان عند أول تعديل.
    """
    return quote_in_text(quote, text_of(item))


def verify_attribution(
    reference: str,
    quote: str,
    evidence: Sequence[Evidence],
    text_of: Callable[[Evidence], str],
) -> Attribution:
    """
    يفحص إسناداً واحداً: أهذا النصّ نصُّ المادة المذكورة؟

    والخطوات ثلاث، بترتيبها في المنطق:

    1. **رقم المادة** — مطبَّعاً. فإن لم يُقرأ الرقم فالمرجع غير مقروء، والجواب
       ``absent`` (ملاحظة لا خطأ): **المرجع الذي لا يُقرأ لا يُتَّهم نصُّه**،
       والإصلاح في الصياغة لا في المسودّة.
    2. **المقطع الحامل للمادة** — من يحمل رقمها. فإن لم يوجد: ``absent``.
       الاسترجاع لم يُنتج هذه المادة، فلا يُقال عن المسودّة إنها نسبت نصّاً إلى
       مادة خطأ؛ يُقال إن المادة غير متوفّرة. والفرق بين الاتّهام والنقص هو
       الفرق بين ``error`` و``notice``.
    3. **النصّ في المقطع الحامل** — فإن وُجد، ``matched``. وإن لم يوجد:
       ``mismatched``، ويُبحث عن النصّ في **سائر المقاطع** ليُسجَّل في
       ``found_in``: النصّ حقيقي لكنه في مادة أخرى، وهذه هي المعلومة التي
       يحتاجها المحامي ليُصلح النسبة بدل أن يحذف الاقتباس.

    ⚠️ **والفحص على المادة لا على البند، وهو حدّ مقصود** (الثالث في صدر
    الملف): يُفتَّش عن «٤٣» في «المادة ٤٣/٢»، فمقطع «المادة ٤٣» يُعدّ حاملاً.
    والخطأ في هذا الاتّجاه **تسامح** لا اتّهام، وهو الاتّجاه المقبول: الأول
    يُبقي نصاً صحيحاً في المسودّة، والثاني يتّهم بريئاً.

    ⚠️ **ومن نادى هذه الدالّة مباشرةً بنصّ أقصر من ``MIN_QUOTE_CHARS`` حصل على
    ``mismatched``**، لأن ``quote_in_text`` ترفض ما دون العتبة فلا تثبت شيئاً.
    وهذا **لا يقع في المسار المعتاد**: ``extract_attributions`` لا تُخرج زوجاً
    دون العتبة أصلاً (الحدّ الخامس في صدر الملف)، فالنتيجة الكاذبة محصورة في
    نداءٍ مباشر يتجاوز المستخرج.

    >>> evidence = [Evidence("L2", "9", "قانون العمل", "المادة 43: لا يجوز إنهاء عقد العمل إلا بإخطار كتابي")]
    >>> check = verify_attribution("المادة 43", "لا يجوز إنهاء عقد العمل إلا بإخطار كتابي", evidence, lambda item: item.text)
    >>> check.status, check.evidence_ref
    ('matched', 'L2')
    """
    empty = Attribution(reference=reference, quote=quote, status=STATUS_ABSENT, evidence_ref="")

    number = _article_number(reference)
    if not number:
        return empty

    owners = [item for item in evidence if _carries_article(item, number, text_of)]
    if not owners:
        return empty

    for owner in owners:
        if _carries_quote(owner, quote, text_of):
            return Attribution(
                reference=reference,
                quote=quote,
                status=STATUS_MATCHED,
                evidence_ref=owner.ref,
                found_in=owner.ref,
            )

    # النصّ غير موجود في مادّته. وحيث وُجد فعلاً يُسجَّل — لأن الفرق بين «نصّ
    # مؤلَّف» و«نصّ صحيح في مادة أخرى» فرقٌ في التصرّح لا في التصحيح: الأول
    # يُحذف، والثاني يُنقل إلى مادّته.
    elsewhere = ""
    for item in evidence:
        if _carries_quote(item, quote, text_of):
            elsewhere = item.ref
            break

    return Attribution(
        reference=reference,
        quote=quote,
        status=STATUS_MISMATCHED,
        evidence_ref=owners[0].ref,
        found_in=elsewhere,
    )


def verify_attributions(
    draft: str,
    evidence: Sequence[Evidence],
    text_of: Callable[[Evidence], str],
) -> AttributionOutcome:
    """
    يفحص كل إسناد في المسودّة، ويعيد الحصيلة كاملة.

    و``text_of`` يُمرَّر ولا يُقرأ ``Evidence.text`` مباشرةً: فالنصّ الذي يجب أن
    يُفحص هو **ما رآه النموذج**، وقد يعرض المستدعي منه جزءاً محدوداً (نافذة
    سياق، أو مقاطعاً مقتطعة). ولو قرأ هذا الملف ``item.text`` بنفسه لفحص نصاً
    غير الذي بُني عليه الاقتباس — وهو الخطأ نفسه الذي يحذّر منه `citations.py`.

    والنتيجة **كاملة** في ``AttributionOutcome`` بلا حالة على مستوى الوحدة: لو
    خُزّن «آخر حصيلة» في حالةٍ لقرأها مستدعٍ ثانٍ فيكون جوابه عن مسودّة غيره.

    >>> evidence = [Evidence("L2", "9", "قانون العمل", "المادة 43: لا يجوز إنهاء عقد العمل إلا بإخطار كتابي")]
    >>> verify_attributions("وتنص المادة 43 على: «لا يجوز إنهاء عقد العمل إلا بإخطار كتابي»", evidence, lambda item: item.text).clean
    True
    """
    return AttributionOutcome(
        checks=[
            verify_attribution(reference, quote, evidence, text_of)
            for reference, quote in extract_attributions(draft)
        ]
    )


