# ٢. الأنماط — على الرسم الخام للمسودّة، والتطبيع يجري عند المقارنة
# ==============================================================================

#: الأرقام العربية-الهندية واللاتينية معاً. والصورتان مكتوبتان هنا لأن
#: **المطابقة تجري على رسم المسودّة** قبل تطبيعه؛ أما تحويلهما إلى اللاتينية
#: فيجري في `normalize` ولا يجري هنا (انظر `_article_number`)، لأن نسخ جدول
#: الأرقام في ملف ثانٍ يُنتج جدولين يفترقان.
_DIGITS = "٠-٩0-9"

#: الإشارة إلى مادة في **متن المسودّة** — على رسمها الخام لا على المطبَّع.
#:
#: والسبب أن ``Attribution.reference`` يُعرَض على المحامي ليبحث به في مسودّته،
#: فيجب أن يكون **كما كُتب فيها** («المادة ٤٣/٢») لا كما صار بعد التطبيع
#: («الماده 43 2»). ولهذا يقبل النمط ``[ةه]`` في «المادة»، والأرقام بالصورتين،
#: وقوسين حول الرقم، وشرطة بين الرقم والبند.
#:
#: ⚠️ **وحدّ ``(?<![\w])`` في أوّله مقصود:** بدونه يطابق النمط ``م`` في آخر
#: كلمة مثل «ثم» فيقرأ «ثم ٤٣» مادةً ٤٣. واستثناء ``و``/``ف`` قبله مقصود أيضاً:
#: «والمادة ٤٣» إشارةٌ إلى المادة، ولو منعنا ما قبلها لسقطت من الاستخراج.
_REFERENCE = re.compile(
    rf"(?:^|(?<![\w]))(?:و|ف)?(?:ال)?"
    rf"(?:ماد[ةه]|مادتان|مادتي|مادتين|مواد|م)"
    rf"\s*[\(\[]?\s*(?P<num>[{_DIGITS}]{{1,4}})"
    rf"(?:\s*/\s*(?P<clause>[{_DIGITS}]{{1,4}}))?"
    rf"\s*[\)\]]?"
)

#: مقاطع المسودّة التي يُبحث فيها عن الإسنادات — تُفصل عند نهاية الجملة.
#:
#: ⚠️ **ولا يُفصل عند النقطتين (:)، وهذا مقصود:** الصيغة الشائعة «المادة ٤٣/٢:
#: نصّ المادة» لو فُصلت عنده لوقع الاقتباس في مقطع آخر غير الذي فيه المرجع،
#: فيُقرأ «مرجع بلا نصّ» ويُسقَط الفحص — وهو أسوأ خطأ يمكن أن يقع هنا: **يُسقط
#: الفحص بدل أن يُنذر**.
#:
#: والفواصل التي تُقطع عندها هي نهايات الجمل وحدها، لأن المراد نصٌّ يلي المرجع
#: في **الجملة نفسها**؛ وما بعد نهاية الجملة كلامٌ آخر لا يُنسب إليه.
_SEGMENT = re.compile(r"[^\n\r.؟!?؛;]+")

#: الاقتباس الصريح بين علامتي تنصيص — وهو **الأرجح أن يكون المنسوب**: الاقتباس
#: الصريح نصُّ المادة، وما قبله كلام الكاتب عنها. فإذا وُجدت علامتان أُخذ ما
#: بينهما وحده، ولم يدخل التمهيد ولا التعليق.
_QUOTED_SPAN = re.compile(r"[«\"“'‘](?P<inner>[^»\"”'’\n]{1,})[»\"”'’]")

#: صيغ التمهيد التي يكتبها الكاتب قبل نصّ المادة — **بعد التطبيع** (وفيه «علي»
#: لا «على»، لأن ``normalize`` يطوي الألف المقصورة).
#:
#: ⚠️ **ولماذا يُقلَّم أول النصّ ولا يُترك؟** لأن السؤال المطروح على
#: ``quote_in_text`` هو: «هل هذا النصّ موجود في مقطع المادة؟». وكلام الكاتب عن
#: المادة («وتنص على أنه…») **ليس في المادة**، فبقاؤه في الاقتباس يُسقط اقتباساً
#: بريئاً — أي يُنتج ``mismatched`` كاذباً، وهو أسوأ ما في هذا الملف.
#:
#: ⚠️ **والتقليم آمن في هذا الاتجاه وحده:** ما بقي بعد حذف أول النصّ **جزءٌ من
#: نصّ المادة**، فيبقى انطواؤه صحيحاً. أما التقليم من **آخره** فغير آمن: لا
#: يُعرف أين ينتهي نصّ المادة وأين يبدأ تعليق الكاتب. ولهذا لا يُقلَّم الآخر.
_FRAMING = re.compile(
    r"^(?:و\s+)?(?:"
    r"تنص|ينص|تقضي|يقضي|تقول|يقول|تقرر|يقرر|ورد|وردت|جاء|جاءت|نصها|نصه|نص"
    r"|علي\s+ان(?:ه|ها)?|بان(?:ه|ها)?|ان(?:ه|ها)?|وفقا|طبقا|كما|وهي|وهو"
    r")\s*"
)

#: حدّ تكرار التقليم — الصيغة المركّبة («وتنص على أنه…») تحتاج مرّتين، والحدّ
#: يمنع حلقة لا تنتهي لو أُضيفت صيغة تُطابق الفراغ.
_FRAMING_PASSES = 8


