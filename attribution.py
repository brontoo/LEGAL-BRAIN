def _quote_from_tail(tail: str) -> str:
    """
    الاقتباس من النصّ الذي يلي المرجع: الصريح بين علامتيه، وإلا الباقي مقلَّماً.

    والخطوتان مرتّبتان لأن ترتيبهما هو الترتيب الصحيح: **الاقتباس الصريح مقدَّم
    على غيره** لأنه نصٌّ وضع الكاتبُ عليه علامة النقل، فليس فيه تمهيد ولا تعليق.
    ولا يُقلَّم ما بين العلامتين، لأن ما بينهما **قاله الكاتب نفسُه**.

    ⚠️ **والمُعاد مطبَّع**، وهذا قرار له سبب: الحكم في هذا الملف كلّه يجري على
    النصّ المطبَّع، فلو عرضنا على المحامي رسمَ الاقتباس الخام لكان ما يراه غيرَ
    ما فُحص — وهذا الفرق نفسه الذي يشرحه صدْر `citations.py`. وثمرته العملية أن
    الترقيم وعلامات التنصيص لا تُحسب من الطول ولا من المطابقة.
    """
    span = _QUOTED_SPAN.search(tail)
    if span is not None:
        return normalize(span.group("inner"))

    cleaned = normalize(tail)
    for _pass in range(_FRAMING_PASSES):
        stripped = _FRAMING.sub("", cleaned).strip()
        if stripped == cleaned:
            break
        cleaned = stripped
    return cleaned


def extract_attributions(draft: str) -> list[tuple[str, str]]:
    """
    يستخرج من المسودّة أزواج (المرجع، النصّ المنسوب إليه).

    الطريقة: تُقسَّم المسودّة إلى جمل ومقاطع، ويُبحث في كل مقطع عن إشارات
    المواد، ويُقرن كل مرجع بما يليه **في المقطع نفسه** إلى أن يُلقى مرجع آخر أو
    ينتهي المقطع. فالمرجع الأخير يُقرن ببقيّة مقطعه، ولا يُقرن بجملة تالية —
    لأن ما بعد نهاية الجملة كلامٌ جديد لا يُنسب إليه.

    ⚠️ **وثلاثة أشياء لا تُخرِج زوجاً، وكلّها مقصودة:**

    1. **مرجع بلا نصّ يليه** — «وردت المادة ٤٣ في الفصل الثاني» ليست إسناداً،
       بل ذكرٌ للمادة. ولا يُنسب إلى المادة نصٌّ لم يُذكر.
    2. **نصّ أقصر من ``MIN_QUOTE_CHARS`` بعد التطبيع** — ما دون حدّ الدليل ليس
       اقتباساً بل نثراً، وإصدار حكم «منسوب إلى غير مادّته» عليه اتهامٌ بلا
       دليل. والثمن تغطية ناقصة معلنة، لا اتهام كاذب (الحدّ الخامس في صدر
       الملف).
    3. **الزوج المكرّر** — المسودّة قد تُعيد الإسناد نفسه في موضعين، وإعادة
       الفحص نفسه مرّتين تُضخّم العدّاد المعروض على المحامي بلا معلومة جديدة.
       والتكرار **بعد التطبيع** يُطوى، على قاعدة `review.py` نفسها: الصيغة
       الإملائية الثانية هي الإسناد الأول.

    >>> extract_attributions("وتنص المادة ٤٣/٢ على: «العقد المحدد المدة ينتهي بمضي مدته»")
    [('المادة ٤٣/٢', 'العقد المحدد المده ينتهي بمضي مدته')]
    """
    if not draft:
        return []

    pairs: list[tuple[str, str]] = []
    seen: set[tuple[str, str]] = set()

    for segment in _SEGMENT.finditer(draft):
        text = segment.group(0)
        matches = list(_REFERENCE.finditer(text))
        for index, match in enumerate(matches):
            # الاقتباس يمتدّ إلى المرجع التالي **في المقطع نفسه**، وإلا إلى آخر
            # المقطع: المرجعان في جملة واحدة يفصل بينهما نصّان، فلا يُنسب إلى
            # الأول نصّ الثاني.
            end = matches[index + 1].start() if index + 1 < len(matches) else len(text)
            quote = _quote_from_tail(text[match.end() : end])
            if len(quote) < MIN_QUOTE_CHARS:
                continue
            reference = match.group(0).strip()
            key = (normalize(reference), quote)
            if key in seen:
                continue
            seen.add(key)
            pairs.append((reference, quote))

    return pairs


