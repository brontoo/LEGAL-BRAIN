@dataclass(frozen=True)
class Attribution:
    """
    إسناد نصٍّ إلى مادة: الحكم فيه، ومن يحمله من المقاطع.

    Attributes:
        reference:   المرجع **كما كُتب في المسودّة** («المادة ٤٣/٢»)، فيبحث به
                     المحامي في مسودّته ويجده. ولو حُفظ مطبَّعاً («الماده 43 2»)
                     لصار البحث عنه في المستند عملاً زائداً على القارئ.
        quote:       النصّ المنسوب إلى المادة. وهو **مطبَّع** (انظر
                     ``_quote_from_tail``): الحكم كلّه يجري على المطبَّع، فلو
                     عُرض على المحامي رسمٌ خام لكان ما يراه غيرَ ما فُحص.
        status:      ``matched`` أو ``absent`` أو ``mismatched`` — والمعاني
                     الثلاثة مشروحة في صدر الملف، وكلٌّ منها تصرّفٌ مختلف.
        evidence_ref: مرجع المقطع الذي **يحمل المادة**، أو ``""`` إن لم يوجد
                     مقطع يذكرها (حالة ``absent``).
        found_in:    مرجع المقطع الذي **وُجد فيه النصّ فعلاً**، أو ``""``.
                     وهو الفرق بين «النصّ مؤلَّف» و«النصّ صحيح لكنه في مادة
                     أخرى» — وهذا الفرق هو كل ما يحتاجه المحامي ليُصلح النسبة:
                     ينقل الاقتباس إلى مادّته بدل أن يحذفه.
    """

    reference: str
    quote: str
    status: str
    evidence_ref: str
    found_in: str = ""


@dataclass
class AttributionOutcome:
    """
    حصيلة فحص إسنادات مسودّة واحدة — على نمط ``VerificationOutcome``.

    Attributes:
        checks: الفحوص **بترتيب ورودها في المسودّة**. والترتيب مقصود لا عرضي:
                    المحامي يقرأ المسودّة من أولها، فيقرأ الاعتراضات بترتيب
                    مواضعها فيها لا بترتيب عشوائي.
    """

    checks: list[Attribution] = field(default_factory=list)

    @property
    def matched(self) -> list[Attribution]:
        """الإسنادات التي ثبت أن النصّ فيها نصُّ المادة المذكورة."""
        return [check for check in self.checks if check.status == STATUS_MATCHED]

    @property
    def mismatched(self) -> list[Attribution]:
        """
        إسنادات إلى مادة **لا تحمل** النصّ المنسوب إليها — وهي الأخطاء.

        وهذه هي الحصيلة التي يمنع وجودها التسليم، لأنها قولٌ كاذب عن القانون
        بنصّه، لا نقصاً في التغطية.
        """
        return [check for check in self.checks if check.status == STATUS_MISMATCHED]

    @property
    def absent(self) -> list[Attribution]:
        """إسنادات إلى موادّ **لا يذكرها أيّ مقطع مسترجَع** — وهي الملاحظات."""
        return [check for check in self.checks if check.status == STATUS_ABSENT]

    @property
    def clean(self) -> bool:
        """
        هل خرجت المسودّة بلا نسبة كاذبة؟

        ⚠️ **و``absent`` لا تمنع**: هي «لم تُفحص هذه المادة» لا «كُذب فيها»،
        ومنع التسليم بسبب نقص التغطية يُعاقب المسودّة على عيب في الأرشيف — وهو
        الطريق إلى أداة تُنذر دائماً فلا تُقرأ.
        """
        return not self.mismatched

    def summary(self) -> str:
        """سطر عربي موجز — يُبنى من نفس دالّة ``_summary_line`` فلا يفترقان."""
        return _summary_line(self.checks)


