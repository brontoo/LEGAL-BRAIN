def _summary_line(checks: Sequence[Attribution]) -> str:
    """
    سطر عربي واحد يصلح للعرض في الواجهة أو السجل.

    ⚠️ **وذكر الغائب في السطر ليس تفصيلاً:** مسودّة نسبَت نصّاً إلى مادة لم
    يُنتجها الاسترجاع تخرج ``clean`` — وهذا صحيح، إذ لم يثبت فيها كذب. لكنها
    ليست كمسودّة **فُحصت كلها**: المحامي يستحقّ أن يعرف الفرق بين «كل إسناد
    مطابق» و«إسناد لم يُفحص لأن المادة ليست في الأرشيف».
    """
    matched = [check for check in checks if check.status == STATUS_MATCHED]
    mismatched = [check for check in checks if check.status == STATUS_MISMATCHED]
    absent = [check for check in checks if check.status == STATUS_ABSENT]

    if not checks:
        return "لا إسناد نصٍّ إلى مادة في المسودّة."

    if not mismatched and not absent:
        return f"كل الإسنادات مطابقة لنصّ موادّها ({len(matched)})."

    parts = [f"مطابق: {len(matched)}"]
    if mismatched:
        parts.append(f"منسوب إلى غير مادّته: {len(mismatched)}")
    if absent:
        parts.append(f"مادة لم تُسترجَع: {len(absent)}")
    return " · ".join(parts) + f" من {len(checks)}."


def summarize(outcome: AttributionOutcome | Sequence[Attribution]) -> dict:
    """
    يحوّل الحصيلة إلى قاموس صالح للبثّ كـ JSON إلى الواجهة.

    ``clean`` تُحسب من المخالفات وحدها، على قاعدة `review.py` نفسها: ما لا يمنع
    التسليم لا يجوز أن يمنعه. و``absent`` تُعرَض في العدّاد ولا تُسقط النتيجة،
    لأنها عيب تغطية يُعرض على المحامي ليُقرّر.

    وتُقبل الحصيلة أو قائمة الفحوص، لأن مستدعياً قد يبني الفحوص بنفسه ثم يريد
    العرض بالشكل نفسه — ولا يُعاد ترتيب شيء: ``checks`` تُبثّ بترتيب ورودها.

    >>> payload = summarize(AttributionOutcome())
    >>> payload["clean"], payload["error_count"], payload["total"]
    (True, 0, 0)
    """
    checks = outcome.checks if isinstance(outcome, AttributionOutcome) else list(outcome)

    return {
        "summary": _summary_line(checks),
        "clean": not any(check.status in ERROR_STATUSES for check in checks),
        "error_count": sum(1 for check in checks if check.status in ERROR_STATUSES),
        "notice_count": sum(1 for check in checks if check.status == STATUS_ABSENT),
        "total": len(checks),
        "checks": [
            {
                "reference": check.reference,
                "quote": check.quote,
                "status": check.status,
                "evidence_ref": check.evidence_ref,
                "found_in": check.found_in,
            }
            for check in checks
        ],
    }
