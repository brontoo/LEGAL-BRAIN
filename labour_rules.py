#: **أساس الاحتساب** — الحقل الذي يقوم عليه الجدول كله.
#:
#: ولماذا نصّان لا درجة؟ لأن العيب الذي وقع فعلاً كان **اختيار نصّ في موضع
#: نصّ**: حسب الكاتب على الأجر الشامل، والقاعدة تطلب الأساسي. فلو كان الأساس
#: وصفاً حرّاً (`"الأجر الأساسي"` مكتوباً في كل سطر) لما أمكن فحصه، ولا اكتشف
#: أحد أن اختياراً خاطئاً وقع. أما كونه قيمةً من ثوابت مغلقة فيصير الخطأ
#: **قابلاً للكشف في الاختبار** لا في عين المراجع وحده.
WAGE_BASIS_BASIC = "basic"
WAGE_BASIS_GROSS = "gross"

#: أسماء الأساس بالعربية — تُستعمل في النصوص المعروضة على المحامي.
#: الجدول نصّ عربي والمفتاح لاتيني: الفصل بين ما يُحسب به وما يُقرأ.
WAGE_BASIS_LABELS: dict[str, str] = {
    WAGE_BASIS_BASIC: "الأجر الأساسي",
    WAGE_BASIS_GROSS: "الأجر الشامل",
}

#: **أمر التقريب** — يُصرَّح به هنا مرة واحدة ولا يُترك لقاعدة عائمة.
#:
#: وقراران في هذا السطر، وكلاهما مقصود:
#:
#: ١. **منزلتان** لأنهما منزلة الدرهم في هذه المستندات. والحساب الداخلي يجري
#:    بدقّة كاملة، والتقريب **عند الإخراج وحده**.
#: ٢. **``ROUND_HALF_UP``** لا التقريب المصرفي، لأن هذا هو العرف في
#:    المستندات المالية العربية: نصف الدرهم يُرفع. أما ``Decimal`` الافتراضي
#:    (``ROUND_HALF_EVEN``) فيُخفض النصف — فيخالف العرف المالي بلا سبب.
#:
#: ⚠️ **وحدث التقريب مقصود أيضاً:** يُقرَّب المبلغ النهائي، **لا** الأجر
#: اليومي قبله. ولو قرّبنا اليومي أولاً (٥٠٠٠ ÷ ٣٠ = ١٦٦٫٦٧) ثم ضربناه في
#: الأيام، لظهر فرق سنتات في المذكرة لا يُفسّره محامٍ. فالسلسلة كلها جبرٌ دقيق،
#: والقلم يُرفع عند النتيجة.
_MONEY_QUANTUM = Decimal("0.01")

#: **عدد أيام الشهر المعتمد** في تحويل الأجر الشهري إلى يومي.
#:
#: وهو **٣٠ يوماً ثابتاً** لا عدد أيام الشهر الميلادي. والسبب أن هذا هو العرف
#: الحسابي في قانون العمل الإماراتي وفي المذكرات المرفوعة، وله فائدة عملية:
#: أجرُ يومٍ واحد لا يتغيّر لأن الإجازة وقعت في فبراير أو في أغسطس. ولو
#: اعتبرنا الشهر الميلادي لتغيّر أجر اليوم الواحد بتغيّر الشهر — وهو ما لا
#: يُفسَّر لعامل، ولا يُطلب من نموذج أن يتذكّره.
#:
#: والدالّة `daily_rate` هي الموضع **الوحيد** في الملف الذي يستعمل هذا الثابت،
#: فتبديله (إلى ٣٠٫٤ أو إلى عدد أيام الشهر الفعلي) تبديلٌ في مكان واحد.
DAYS_PER_MONTH = Decimal("30")

#: ⚠️ **مبلغ المكافأة — المادة ٥١ من المرسوم بقانون اتحادي ٣٣ لسنة ٢٠٢١.**
#:
#: ٢١ يوماً من الأجر **الأساسي** عن كل سنة من السنوات الخمس الأولى، و٣٠ يوماً
#: عن كل سنة تالية.
#:
#: ⚠️ **وكان في هذا الملف «نصف شهر» الخاطئة (١٥ يوماً) — وهي صيغة القانون الاتحادي
#: رقم ٨ لسنة ١٩٨٠ الملغى.** والفرق نحو ٢٨٪ من المكافأة.
#:
#: ⚠️ **وهما مكتوبان هنا لا داخل الدالّة**، ليقابلهما القارئ بالمادة مباشرةً،
#: **ولأن اختباراً يثبّتهما صار ممكناً** — وهو ما لم يكن ممكناً وهما حرفان في
#: سطر حساب.
GRATUITY_DAYS_FIRST_TIER = Decimal("21")
GRATUITY_DAYS_SECOND_TIER = Decimal("30")

#: **مقام كسر السنة** في مكافأة نهاية الخدمة — ٣٦٥ يوماً.
#:
#: والمدّة تُقاس بالأيام (وهو الرقم الموثوق)، ثم تُحوّل إلى سنوات بهذا المقام
#: المعلن. ورقم مكتوب هنا مرةً واحدة لأن كل من خالفه يخالف في موضع واحد، لا في
#: كل مذكرة. وحدّ الأثر: السنة الكبيسة تُنتج يوماً زائداً في المدّة فترتفع
#: المكافأة بنسبة ١/٣٦٥ — وهو أثر المدّة الفعلية لا خطأ في العدّ.
DAYS_PER_YEAR = Decimal("365")


# ==============================================================================
# ٢. جدول القواعد — وهو أهمّ سطر في هذا الملف، فاقرأه قبل أن تعتمد الجدول
# ==============================================================================
#
# ⚠️⚠️ **هذا الجدول للمحامي أن يتحقّقه، لا أن يعتمده كما هو.**
#
# الجدول **ليس بياناً بالقانون**، ولا يزعم أنه استقصى أحكام قانون العمل
# الإماراتي. هو **مجموعة صغيرة من القواعد القابلة للتحقّق**، ضُمّت هنا لأن
# تشغيلاً حقيقياً أنتج مذكرة خالفتها — فصارت في المنظومة بدل أن تبقى في محادثة.
#
# وكل سطر فيه يجب أن يُقرأ على أنه: «هذه قاعدتنا في الاحتساب حتى يقول المحامي
# غير ذلك». ولذلك كل قاعدة تحمل **مادّتها** صريحة، فلا يُنسب إلى الجدول ما لم
# يُنسب إلى المادة.
#
# **وحدّ المرجع:** لا يُزاد في الجدول رقم مادة لم يثبت في المشروع أو في مصدر
# يتحقّق منه المحامي. **والمادة التي لا يُتيقّن من رقمها تُحذف قاعدتها
# بالكامل** — ولا تُكتب بتخمين، ولا يُترك رقمها فارغاً. والسبب أن رقم مادة
# مخمَّن **أسوأ من غياب القاعدة**: الغياب يوقف الكاتب، والرقم المخمَّن يمضي به
# إلى المذكرة. ثم إن `citations.py` يرفض رقم مادة لم يظهر في المقاطع المسترجعة
# — فالتخمين هنا يصطدم بالفحص هناك، ويضيع وقت المحامي في تناقض لا في دعوى.
#
# **وصراحة مطلوبة عن ما لم يُدرَج:** لم تُدرَج قاعدة الأجر عن الإجازة المرضية،
# ولا أجر العمل الإضافي، ولا الحدّ الأدنى لبدل الإجازة، لأن أرقام موادّها لم
# تثبت في هذا المشروع. فغيابها **قرار موثَّق** لا سهو، ومن احتاجها فليأتِ
# بمرجعها أولاً.


@dataclass(frozen=True)
class Rule:
    """
    قاعدة احتساب واحدة: استحقاق، وأساسه، ومادّته، وقاعدته في سطر.

    Attributes:
        entitlement: اسم الاستحقاق بالعربية كما يُكتب في المذكرة.
        basis:       وعاء الاحتساب — قيمة من ``WAGE_BASIS_*``.
        article:     رقم المادة التي تُسند القاعدة، بصيغة «٢٩/٩» أي المادة ٢٩
                     البند ٩. ووجوده إلزامي: قاعدة بلا مادة **رأيٌ لا قاعدة**.
        statement:   القاعدة في سطر عربي واحد — هذا الحقل هو الذي يُعرض على
                     النموذج في الموجّه، وعلى المحامي في التقرير.
    """

    entitlement: str
    basis: str
    article: str
    statement: str

    @property
    def basis_label(self) -> str:
        """اسم الأساس بالعربية — للعرض، ويُستعمل في `rules_block`."""
        return WAGE_BASIS_LABELS.get(self.basis, self.basis)


#: الجدول، **بترتيبه المقصود** لا أبجدياً: يبدأ بالاستحقاقين الأكثر وقوعاً في
#: المذكرات (الإجازة، ثم نهاية الخدمة)، ثم بالاستحقاق الذي أُنكر ظلماً في
#: التشغيل الذي كشف العيب (أجر الإشعار)، ثم بالاستحقاق الذي يحتاج تحقّقاً
#: وقائعياً قبل الحساب (الأجر خلال الإجازة).
#:
#: وترتيب العرض ليس تفصيلاً: هو الترتيب نفسه الذي يقرأه النموذج في الموجّه،
#: وهو ترتيب مطالبات المذكرة العمالية المعتاد. فالقاعدة الأسبق تُقرأ أولاً.
RULES: tuple[Rule, ...] = (
    Rule(
        entitlement="بدل الإجازة السنوية",
        basis=WAGE_BASIS_BASIC,
        article="٢٩/٩",
        statement=(
            "يُحسب بدل الإجازة السنوية على الأجر الأساسي وحده، لا على الأجر "
            "الشامل؛ ولا يُزاد عليه إلا إذا منح اتفاقٌ العاملَ ميزةً أفضل."
        ),
    ),
    Rule(
        entitlement="مكافأة نهاية الخدمة",
        basis=WAGE_BASIS_BASIC,
        article="٥١",
        statement=(
            "تُحسب مكافأة نهاية الخدمة على الأجر الأساسي وحده، ويُبنى عليها "
            "احتسابٌ واحد لا يتناقض مع نفسه في المذكرة نفسها."
        ),
    ),
    Rule(
        entitlement="أجر مدة الإشعار",
        basis=WAGE_BASIS_GROSS,
        article="٤٣/٢",
        statement=(
            "أجر مدة الإشعار واجبٌ كاملاً لأن العقد يبقى قائماً خلالها؛ "
            "وإعفاء العامل من الحضور فيها ليس بذاته سبباً لحرمانه منه."
        ),
    ),
    Rule(
        entitlement="الأجر خلال الإجازة",
        basis=WAGE_BASIS_GROSS,
        article="٢٩/٩",
        statement=(
            "لا يستحقّ العامل أجر الإجازة إلا إذا كان في إجازة فعلاً؛ ومجرّد "
            "وجود موافقة مسجَّلة على الإجازة لا يحسم وحده ما إذا كان قد أدّى "
            "عملاً خلالها."
        ),
    ),
)


def rule_for(entitlement: str) -> Optional[Rule]:
    """
    يعيد قاعدة استحقاق باسمه، أو ``None`` إن لم يكن في الجدول.

    و``None`` هنا **جواب مقصود لا فشل**: معناه أن أساس هذا الاستحقاق غير
    محقَّق، وهو ما يجب أن يُقال للمحامي صراحةً بدل أن يختار الكاتب أساساً من
    عنده. ومن هنا جاءت عبارة «الأساس غير محقَّق» في `rules_block`.

    >>> rule_for("بدل الإجازة السنوية").basis
    'basic'
    >>> rule_for("بدل السكن") is None
    True
    """
    for rule in RULES:
        if rule.entitlement == entitlement:
            return rule
    return None


def wage_basis_for(entitlement: str) -> Optional[str]:
    """
    يعيد أساس الاحتساب لاستحقاق، أو ``None`` إن لم يكن في الجدول.

    وُجدت هذه الدالّة منفصلةً لأنها هي السؤال الذي وقع فيه الخطأ: «على أيّ
    أجرٍ يُحسب هذا؟». فجعلها سؤالاً واحداً له جواب واحد يمنع أن يُجاب عنه في
    موضع بالشامل وفي موضع بالأساسي — وهو التناقض الداخلي نفسه الذي رُصد في
    احتساب المكافأة.

    >>> wage_basis_for("مكافأة نهاية الخدمة")
    'basic'
    """
    rule = rule_for(entitlement)
    return rule.basis if rule else None


