"""
قواعد العمال — أساس الاحتساب، لأن الخطأ ليس في المعرفة بل في المكان.
=============================================================================

المشكلة التي يحلّها
------------------
أُنتجت مذكرة عمالية أمام المحكمة، ومراجع قانوني مستقلّ رصد فيها أربعة عيوب:

١) **بدل الإجازة السنوية حُسب على الأجر الشامل (٨٠٠٠) بدل الأجر الأساسي
   (٥٠٠٠).** والمادة ٢٩/٩ تجعل الأساسي هو الأساس إلا إذا منح اتفاقٌ العامل
   ميزةً أفضل. والصحيح ١١ يوماً = ١٨٣٣٫٣٣ لا ٢٩٣٣٫٣٧.

٢) **حُرم العامل أجر مدة الإشعار بحجّة أنه أُعفي من الحضور.** والمادة ٤٣/٢
   تُبقي العقد قائماً طوال مدة الإشعار والأجر واجبٌ كاملاً؛ والإعفاء من الحضور
   ليس بذاته مسقطاً للاستحقاق.

٣) **مادة صحيحة ذُكرت في موضع خاطئ:** مسار المادة ٥٤ السابق للتقاضي استُعمل
   حيث تنطبق إحالة المادة ٥٤/٤.

٤) واحتساب مكافأة نهاية الخدمة كان متناقضاً مع نفسه.

وأصل العيب ليس في معرفة النموذج
-------------------------------
هذا هو موضع العبرة، وهو سبب وجود هذا الملف:

**المراجع القانوني كان قد أبلغ النموذج بالعيب الأول بلغة صريحة، فعاد الخطأ
نفسه في التشغيل التالي.** والسبب أن **التصحيح الذي يعيش في محادثة لا يصل إلى
المسار**: المحادثة تنسى، والموجّه لا ينسى. فالقاعدة يجب أن تكون **في المنظومة
لا في الحوار** — تُكتب مرة واحدة في الموجّه، فيراها كل تشغيل لا تشغيلاً دون
تشغيل.

المبدأ التصميمي — على نمط `citations.py` و`language_audit.py`
--------------------------------------------------------------
> **النموذج يروي، والخادم يُقرّر.** وكل ما يمكن حسابه بقاعدة ثابتة لا
> يُترَك لنموذج يحسب.

فالملف يؤدّي عملين لا يفترقان:

١. **جدول قواعد** (`RULES`) — لكل استحقاق: أساسُه، ومادّته، وقاعدته في سطر.
   يُصاغ منه `rules_block()` الذي يُلحق بالموجّه، فتصير القاعدة **في المنظومة**.
٢. **حاسبة حتمية** (`service_period` وما بعدها) — فلا يبقى في المسار حسابُ
   تاريخ ولا مدّة ولا مبلغ يجتهد فيه نموذج. ودالّة `leave_pay` تعرض **الأساس
   الصحيح والخاطئ معاً** والفرق بينهما، لأن الخطأ الذي يُرى يُصحَّح، والخطأ
   الصامت يُسلَّم.

⚠️ وحدّان صريحان
----------------
**الأول: الجدول ليس بياناً بالقانون.** هو مجموعة صغيرة من القواعد **قابلة
للتحقّق**، وُضعت لتُعرض على المحامي لا لتُغني عنه. وتفصيل هذا الحدّ في التصريح
المكتوب فوق الجدول نفسه — فهو أهمّ ما في الملف.

**والثاني: الحاسبة تحسب، ولا تُطبّق.** هي تحسب الأجر على الأساسين وتقول أيّهما
تطلبه القاعدة؛ أما هل تنطبق المادة على الواقعة، وهل يوجد اتفاق يمنح العامل
ميزةً أفضل (وهو ما تُجيزه المادة ٢٩/٩)، فحكمٌ قانوني لا يحسمه كود. ولذلك
الحصيلة تحمل أساسها ومادّتها وسطر قاعدتها، ليقرأها المحامي لا ليأخذها مسلَّمة.

الملف بلا تبعية خارجية وبلا حالة وبلا إدخال/إخراج وبلا شبكة: مكتبة بايثون
القياسية وحدها (``datetime``، ``decimal``، ``dataclasses``، ``typing``)، فيعمل
اختباره بلا مفتاح API وبلا نموذج.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import date, timedelta
from decimal import Decimal, ROUND_HALF_UP
from typing import Optional

