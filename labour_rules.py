def _money(value: Decimal) -> Decimal:
    """يُقرّب مبلغاً إلى منزلتين — الموضع الوحيد الذي يُقرَّب فيه مبلغ."""
    return value.quantize(_MONEY_QUANTUM, rounding=ROUND_HALF_UP)


def daily_rate(monthly_wage: Decimal) -> Decimal:
    """
    الأجر اليومي من الأجر الشهري — بقسمة على ٣٠ يوماً، **بلا تقريب**.

    وترك التقريب هنا مقصود: التقريب يُؤخَّر إلى النتيجة النهائية، لأن تقريب
    الأجر اليومي أولاً يُنتج فرق سنتات في المذكرة لا يُفسّره محامٍ (انظر شرح
    ``_MONEY_QUANTUM``).

    >>> daily_rate(Decimal("5000"))
    Decimal('166.6666666666666666666666667')
    """
    return Decimal(monthly_wage) / DAYS_PER_MONTH


def _to_decimal(value: object) -> Decimal:
    """
    يحوّل مدخلاً رقمياً إلى ``Decimal`` من **نصّه** لا من عائمة.

    و``Decimal(str(value))`` لا ``Decimal(value)``: تمرير عائمة إلى ``Decimal``
    مباشرةً ينسخ خطأها الثنائي إلى الحساب (``Decimal(0.1)`` ليست عُشراً)، وهو
    خطأ لا يظهر في الأرقام الصحيحة فيمرّ صامتاً. والتحويل من النصّ يجعل من
    كتب ``8000`` في الكود يحصل على ٨٠٠٠ بالضبط.
    """
    if isinstance(value, Decimal):
        return value
    if isinstance(value, int):
        return Decimal(value)
    if isinstance(value, float):
        return Decimal(str(value))
    return Decimal(str(value))


def _decompose(
    start: date,
    end: date,
    *,
    exclusive: bool,
) -> tuple[int, int, int]:
    """
    يفكّ المدّة إلى سنوات كاملة، ثم أشهر كاملة، ثم أيام باقية — بعدّ تقويمي.

    الطريقة: نتقدّم شهراً شهراً ما دام الشهر التالي لا يتجاوز **آخر يوم
    محسوب**. فالشهر يُعَدّ كاملاً بعدّ **التقويم** (من ١ فبراير إلى ١ أغسطس =
    ستة أشهر تامة) لا بعدّ ثلاثين يوماً. والفرق بين الطريقتين هو نفسه الفرق
    الذي أنتج «١٢٧٨» في المذكرة تحت المراجعة.

    والتفكيك **تقسيم تقويمي للمدّة، لا جمعٌ يُعاد**: السنوات والأشهر تقاس من
    الطرف الأول وتتقدّم بالتقويم، والباقي هو ما تبقّى من الأيام. فلا يصحّ أن
    يُقال «مجموع الأجزاء = عدد الأيام» بأي ضرب ثابت (لا ٣٦٥ ولا ٣٠)، لأن
    الأشهر الميلادية متفاوتة: مدّة ستة أشهر من ١ فبراير إلى ١ أغسطس هي ١٨١
    يوماً، ومن ١ مارس إلى ١ سبتمبر ١٨٤ يوماً. والاختبار يثبّت التفكيك على
    وقائع محدّدة (`test_the_memorandum_period_decomposes`)، لا على معادلة
    تُدّعى.

    ⚠️ **وحدّ التقويم — وهو موضع خطأ وقع أثناء كتابة هذا الملف نفسه:** التقويم
    يُقاس إلى **آخر يوم محسوب**، وهو ``end`` إن كان محسوباً و``end`` ناقص يوم
    إن لم يكن. وأول نسخة قاست إلى النهاية ثم زادت يوماً، فأنتجت **١٣٠٨** أيام
    في الواقعة تحت المراجعة بدل ١٣٠٧ — أي أن العيب الذي جاء هذا الملف لمنعه
    كاد يُنتَج في السطر الذي يمنعه. والقاعدة: **عدّ واحد لا عدّان.**

    ⚠️ ولا نطرح الأيام هكذا: ``(end - start).days - years * 365``. فالطرح يظنّ
    كل سنة ٣٦٥ يوماً، فيخطئ في السنوات الكبيسة ويُنتج «٣ سنوات و١٨١ يوماً» بدل
    «٣ سنوات و٦ أشهر». والتقدّم بالتقويم لا يعرف الخطأ أصلاً.

    ``_step_month`` يعالج حالة الشهر الذي لا يوجد فيه اليوم نفسه (٢٩ فبراير
    مثلاً) بإرجاع آخر يوم من الشهر الهدف، فلا تفشل الدالّة على مدّة تقع في سنة
    كبيسة.

    **والطريقة تقويمية لا حسابية — وهذا مقصود، وهو الفرق الذي أنتج «١٢٧٨»:**
    تُعدّ السنوات والأشهر بعدّ التقويم، لا بضرب السنوات في ٣٦٥ ولا بقسمة
    الأيام على ٣٠.

    ⚠️ **وحدّ هذه الطريقة، وهو حدّ حقيقي يجب أن يعرفه المحامي:** المدّة التي
    تساوي سنة كاملة وتنتهي عشيّة يوم الذكرى تُعرض «١١ شهراً و٣٠ يوماً» لا
    «سنة» — لأن عدّ التقويم لا يبلغ الذكرى إلا في يومها. فمدّة من ٢٠٢٣-٠٢-٠١
    إلى ٢٠٢٤-٠١-٣١ هي ٣٦٥ يوماً بالضبط، ويُعرض فكّها «١١ شهراً و٣٠ يوماً».
    والرقمان **لا يتناقضان**: الأول عدّ أيام، والثاني رحلة تقويمية انتهت قبل
    الذكرى بيوم واحد. ومدّة من ٢٠٢٣-٠٢-٠١ إلى ٢٠٢٦-٠٢-٠١ (أي ١٠٩٧ يوماً)
    تُعرض «٣ سنوات» بالضبط، لأن الطرف وقع على الذكرى. ولذلك يُقدَّم في المذكرة
    **عدد الأيام** لأنه لا يحتمل هذا الخلاف، و`describe` للعرض وللتقريب
    البشري، و`days` هي الحجّة.
    """
    span_end = end if not exclusive else end - timedelta(days=1)
    if span_end < start:
        # مدّة من يوم واحد في وضع «اليوم الأخير غير محسوب»: لا تقويم يُقاس.
        return 0, 0, 0

    years = months = 0
    cursor = start

    while True:
        candidate = _step_month(cursor, 12)
        if candidate is None or candidate > span_end:
            break
        cursor = candidate
        years += 1

    while True:
        candidate = _step_month(cursor, 1)
        if candidate is None or candidate > span_end:
            break
        cursor = candidate
        months += 1

    # ⚠️ والباقي يُقاس من **الموضع الذي بلغه التقويم** إلى **آخر يوم في المدّة**
    # — لا بطرح ما استُهلك من المدّة الكلّية.
    #
    # وهذا موضع خطأ ثالث وقع هنا، وهو من جنس العيب الذي جاء الملف لمنعه:
    # الطرح (`period_days - _days_in_span`) جمع عدّين مختلفي الحدّ، فأنتج باقياً
    # ينقص يوماً في كل مدّة. والقياس المباشر لا يعرف هذا الخلاف أصلاً، لأن
    # طرفيه من التقويم نفسه.
    #
    # ⚠️ و`cursor` هنا قد يكون **بعد** آخر يوم في المدّة: مدّة من ٢٦ يوماً لا
    # تبلغ شهراً تقويمياً، فلا يتقدّم التقويم ولا تبقى إلا الحالة الأولى. أما
    # مدّة بلغت شهراً ثم لم تُكمل الذي بعده، فيقف التقويم عند أول الشهر،
    # والباقي محسوبٌ إلى آخر يوم.
    span_last = start if span_end < start else span_end
    if cursor > span_last:
        # لم يُكمل التقويم شهراً ولا سنة: المدّة كلها أيام.
        return 0, 0, (span_last - start).days + 1

    # ولا حرس على السالب: حدّ `span_end` هو الذي أوقف التقويم، فالتقويم لم يبلغ
    # النهاية، وما بقي موجبٌ بالضرورة. والحرس هنا كان سيُخفي خطأً في مكان آخر.
    return years, months, (span_last - cursor).days


def period_days(start: date, end: date, *, exclusive: bool = True) -> int:
    """
    عدد أيام المدّة — الموضع **الوحيد** الذي يُعدّ فيه اليوم، فيُستدعى ولا يُعاد.

    وُجدت هذه الدالّة بعد أن أنتجت نسختان من العدّ رقمين مختلفين لمدّة واحدة
    (١٣٠٧ و١٣٠٨). فصار للعدّ موضع واحد، ومن أراد عدّ الأيام نادى هذا الموضع ولا
    يعدّ بنفسه.

    ⚠️ **واتجاه الافتراضي معلن: ``exclusive=True``، أي النهاية حدٌّ لا تُحسب.**
    وهذا هو العدّ المعتمد في `service_period`، فلا يفترق الافتراضيان: من نادى
    الدالّتين بلا وسيط حصل على الرقم نفسه. والوسيطان يُمرَّران من موضع واحد
    (`exclusive=not inclusive_end`) حتى لا يُقلب أحدهما وحده — وهو ما أنتج
    يوماً زائداً في أول نسخة.

    >>> period_days(date(2023, 2, 1), date(2026, 8, 31))
    1307
    >>> period_days(date(2023, 2, 1), date(2026, 8, 31), exclusive=False)
    1308
    """
    return (end - start).days + (0 if exclusive else 1)


def _step_month(anchor: date, months: int) -> Optional[date]:
    """
    يتقدّم ``months`` شهراً من ``anchor``، مع تصحيح يوم الشهر إن لم يوجد.

    >>> _step_month(date(2023, 2, 1), 6)
    datetime.date(2023, 8, 1)
    >>> _step_month(date(2024, 2, 29), 12)
    datetime.date(2025, 2, 28)
    """
    total = anchor.month - 1 + months
    year = anchor.year + total // 12
    month = total % 12 + 1
    if year < 1 or year > 9999:
        return None
    day = min(anchor.day, _days_in_month(year, month))
    return date(year, month, day)


def _days_in_month(year: int, month: int) -> int:
    """عدد أيام الشهر — بحساب التقويم لا بجدول محفوظ."""
    if month == 12:
        return 31
    return (date(year, month + 1, 1) - date(year, month, 1)).days


def service_period(
    start: date,
    end: date,
    inclusive_end: bool = False,
) -> ServicePeriod:
    """
    مدّة الخدمة بين تاريخين — محسوبةً بالضبط، بلا تقدير.

    ⚠️ **قرار يوم النهاية — وهو قرار اتُّخذ على دليل رقمي، لا على ذوق:**

    ``end`` **حدٌّ لا يُحسب** (وهو الافتراضي ``inclusive_end=False``)، أي أن
    المدّة من ``start`` إلى ما قبل ``end``. والدليل هو الرقم الذي طلبه المحامي
    في الواقعة تحت المراجعة: من ٢٠٢٣-٠٢-٠١ إلى ٢٠٢٦-٠٨-٣١ **١٣٠٧ أيام** — وهذا
    هو بالضبط ``(end - start).days`` = ١٣٠٧، ولا يصحّ إلا بهذا القرار. ولو
    حُسب يوم النهاية لصار ١٣٠٨ وهو الرقم الذي رصده المراجع بديلاً.

    ولذلك ``inclusive_end=True`` هو **العدّ الآخر المعلن**: يوم النهاية محسوب،
    فتصير الواقعة ١٣٠٨. ومن استعمله فليعلم أنه يخالف الرقم المقصود، وليكن
    استعماله صريحاً لا ضمنياً.

    وحدّ هذا القرار يُقال: النهاية هنا **حدّ** («انتهت العلاقة في ٣١ أغسطس»)
    لا **يوم عمل** («عمل يوم ٣١ أغسطس»). والذي يحتاج الثاني — كاحتساب أيام
    إشعار أو أجر يوم عمل فعلي — يمرّر ``inclusive_end=True`` صريحاً.

    >>> service_period(date(2023, 2, 1), date(2026, 8, 31)).days
    1307
    >>> service_period(date(2023, 2, 1), date(2026, 8, 31), inclusive_end=True).days
    1308
    """
    if end < start:
        # المدّة معكوسة: خطأ مدخل لا مدّة سالبة. ورفع استثناء هنا مقصود —
        # إرجاع صفر كان سيُنقص استحقاقاً بصمت، وهو أسوأ من التوقّف.
        raise ValueError(
            f"تاريخ النهاية ({end}) قبل تاريخ البداية ({start}) — راجع المدخل."
        )

    # ⚠️ **والوسيط يُمرَّر ``not inclusive_end``، وهي بالضبط الصيغة التي أخطأت
    # فيها أول نسخة خطأً.** والسبب أن ``_decompose`` يسأل سؤالاً واحداً: «هل
    # ``end`` الذي أُعطيتُه **آخر يوم في المدّة**، أم حدّ لا يُحسب؟» فإذا كان
    # يوم النهاية محسوباً هنا، فالنهاية التي أُمرّرها هي آخر يوم — أي
    # ``exclusive=False``. وأول نسخة مرّرت ``inclusive_end`` نفسه، فقُرئ
    # «استبعد النهاية» حيث أُريد «اعتمدها»، فنقص يوم من كل مدّة. واسم المُعامل
    # يصف **طبيعة الطرف**، لا **حال المدّة** — والخلط بينهما هو الخطأ كله.
    years, months, remainder = _decompose(start, end, exclusive=not inclusive_end)

    return ServicePeriod(
        # والعدّ يُنادى من موضعه الواحد، وباتجاه واحد مع `_decompose` أعلاه —
        # فلا يُقلب أحدهما وحده، وهو ما أنتج يوماً زائداً في أول نسخة.
        days=period_days(start, end, exclusive=not inclusive_end),
        years=years,
        months=months,
        remainder_days=remainder,
        inclusive_end=inclusive_end,
        start=start,
        end=end,
    )


def end_of_service_gratuity(
    basic_wage: Decimal,
    period: ServicePeriod,
) -> Decimal:
    """
    مكافأة نهاية الخدمة على **الأجر الأساسي** — مبلغاً واحداً بلا تناقض.

    ⚠️ **وهذه الدالّة تحسب على الأساسي وحده، ولا تعرض أساساً آخر.** والفرق بين
    حالتها وحالة `leave_pay` مقصود: العيب الذي وقع في الإجازة كان **اختيار
    أساس خاطئ**، فأُظهر الأساسان ليُرى الفرق. أما العيب الذي وقع في المكافأة
    فكان **تناقضاً داخلياً** — رقمان لمدّة واحدة في المذكرة نفسها. وعلاج
    التناقض أن يكون للمكافأة **رقم واحد لا رقمين**، فلو عرضنا هنا أساسين
    لأعدنا إنتاج التناقض نفسه بثوب آخر.

    **وقاعدة الاحتساب المفروضة في هذا السطر — للمحامي أن يتحقّقها:**
    أجر ٢١ يوماً عن كل سنة من السنوات الخمس الأولى، وأجر ٣٠ يوماً عن كل سنة تالية،
    ويُحتسب كسر السنة **بالنسبة** لا بالتقريب إلى سنة كاملة.

    ⚠️ **والاحتساب كله يجري على ``period.days`` — وهو قرار مقصود، وهو علاج
    التناقض بعينه:**

    عدد الأيام هو **الرقم الوحيد الموثوق** في المدّة (وهو ١٣٠٧ في الواقعة تحت
    المراجعة)، وفكّها إلى سنوات وأشهر وأيام **للعرض** لا للحساب. ولو حُسبت
    المكافأة من الفكّ التقويمي لصار في الملف معياران: الأشهر أثلاثاً من سنة
    تقويمية، والأيام نسبةً من ٣٦٥ — فيخرج مبلغان لمدّة واحدة، وهو **العيب
    الرابع** الذي رصده المراجع. وقد وقع ذلك فعلاً أثناء كتابة هذا الملف: مدّة
    سنتين بالضبط (٧٣١ يوماً لأن ٢٠٢٤ كبيسة) أنتجت **٤٩٩٧٫١٥** بدل ٥٠٠٠ — رقم
    ينقص ثلاثة دراهم بلا سبب يُفسَّر، ولو وصل المحامي لكان سؤالاً لا جواب له.

    فالقاعدة الآن **جملة واحدة بلا معيارين**:

        كسر السنوات = عدد الأيام المحسوب ÷ ٣٦٥

    و«٣٦٥» مقام **معلن مكتوب** لا مفترضاً، ويُغيّر في مكان واحد. وحدّ هذه
    القاعدة يُقال صراحةً: السنة الكبيسة تُنتج يوماً زائداً في المدّة (٧٣١
    يوماً في سنتين)، فتزيد المكافأة بنسبة ١/٣٦٥ — وهو أثر **مقصود ومعلن**،
    لأنه ناتج عن المدّة الفعلية لا عن خطأ في العدّ.

    وحدّها الثاني: لا تُطبّق هنا سقفاً ولا حدّاً أدنى ولا شرط مدّة خدمة، لأن
    أرقام موادّها لم تثبت في هذا المشروع. فمن احتاجها فليأتِ بمرجعها، وليكن
    التعديل تعديلاً واحداً في هذا الموضع لا في كل مذكرة.

    >>> gratuity_basis = service_period(date(2023, 2, 1), date(2026, 8, 31))
    >>> end_of_service_gratuity(Decimal("5000"), gratuity_basis) > 0
    True
    >>> two_years = service_period(date(2023, 1, 1), date(2025, 1, 1))
    >>> str(end_of_service_gratuity(Decimal("5000"), two_years))
    '5006.85'
    """
    if period.days <= 0:
        return _money(Decimal("0"))

    base = _to_decimal(basic_wage)

    # **المعيار الواحد: الأشهر والساعات لا تدخل هنا — الأيام وحدها.**
    #
    # ⚠️ ولا يُستعمل `period.years` ولا `period.months` في هذا الحساب، وهذا
    # **مقصود ومكتوب** حتى لا يُعاد إليهما ظنّاً أنهما أدقّ. الفكّ التقويمي
    # للعرض، والعدّ بالأيام للحساب.
    years_of_service = Decimal(period.days) / DAYS_PER_YEAR

    # ⚠️⚠️ **وهذا الموضع كان خطأً قانونياً حقيقياً، فأُصلح.**
    #
    # كان مكتوباً `Decimal("0.5")` — **«نصف شهر» لكل سنة من الخمس الأولى**.
    # **وهي صيغة القانون الاتحادي رقم ٨ لسنة ١٩٨٠ — الملغى.** وقد حلّ محله
    # المرسوم بقانون اتحادي ٣٣ لسنة ٢٠٢١، **والمادة ٥١ منه تجعلها ٢١ يوماً**
    # عن كل سنة من الخمس الأولى، و**٣٠ يوماً** عن كل سنة تالية.
    #
    # ⚠️ **والفرق ليس شكلياً:** ١٥ يوماً بدل ٢١ **تُنقص نحو ٢٨٪ من المكافأة**،
    # **وهي حقّ مالي للعامل** — والخطأ في حقّه أخطر من الخطأ في حقّ الشركة،
    # لأن المستشار يكتب للشركة فيُخشى أن يُغفل حقّ الخصم.
    #
    # ⚠️ **والأرقام مكتوبة صريحة لا كنسبة** (`21` و`30`)، ليقابلها القارئ
    # بالمادة **بلا حساب ذهني**: `0.5` لا يقول ١٥ ولا يُنبّه أحداً، و`21` تقول
    # نفسها. والقسمة على `DAYS_PER_MONTH` هي تحويل الأيام إلى أجر، لا قاعدة.
    first_tier = min(years_of_service, Decimal("5"))
    second_tier = max(years_of_service - Decimal("5"), Decimal("0"))

    days_owed = (
        first_tier * GRATUITY_DAYS_FIRST_TIER
        + second_tier * GRATUITY_DAYS_SECOND_TIER
    )
    return _money(base / DAYS_PER_MONTH * days_owed)


def leave_pay(
    days: int,
    basic_wage: Decimal,
    gross_wage: Optional[Decimal] = None,
) -> LeavePay:
    """
    بدل الإجازة السنوية — ويُعرض على **الأساسين معاً**، وأحدهما هو المطلوب.

    والأساس المطلوب لا يُختار هنا: يُقرأ من **الجدول** (`wage_basis_for`)، فلا
    يصير للحاسبة رأيٌ يخالف الجدول، ولا يفترق الموجّه عن الحساب. فإن كان
    الاستحقاق غير مدرج في الجدول، افترضت الدالّة الأساسي — وهو **الأقلّ**
    للمستحقّ، فيكون الخطأ في أضيق حدّه ولا يُنشئ استحقاقاً من لا شيء.

    >>> pay = leave_pay(11, Decimal("5000"), Decimal("8000"))
    >>> str(pay.on_basic), str(pay.on_gross), str(pay.difference)
    ('1833.33', '2933.33', '1100.00')
    """
    if days < 0:
        raise ValueError(f"عدد الأيام سالب ({days}) — راجع المدخل.")

    base = _to_decimal(basic_wage)
    gross = _to_decimal(gross_wage) if gross_wage is not None else None

    rate_basic = daily_rate(base)
    on_basic = _money(rate_basic * Decimal(days))
    on_gross = _money(daily_rate(gross) * Decimal(days)) if gross is not None else None

    rule = rule_for("بدل الإجازة السنوية")
    required_basis = rule.basis if rule else WAGE_BASIS_BASIC
    required_amount = on_basic if required_basis == WAGE_BASIS_BASIC else (on_gross or on_basic)

    difference: Optional[Decimal] = None
    if on_gross is not None:
        # الفرق **بالقيمة المطلقة**: المطلوب أن يرى القارئ حجم الأثر، لا
        # اتّجاهه. واتّجاهه مقروء من الأساسين المعروضين في الحصيلة.
        difference = _money(abs(on_gross - on_basic))

    return LeavePay(
        days=days,
        basic_wage=base,
        gross_wage=gross,
        on_basic=on_basic,
        on_gross=on_gross,
        required_basis=required_basis,
        required_amount=required_amount,
        difference=difference,
        article=rule.article if rule else "",
        rule_statement=rule.statement if rule else "",
    )


def notice_pay(
    days: int,
    basic_wage: Decimal,
    gross_wage: Optional[Decimal] = None,
    *,
    attendance_excused: bool = False,
) -> NoticePay:
    """
    أجر مدة الإشعار — والمبلغ كامل، والإعفاء من الحضور لا يُنقصه.

    ⚠️ **وهذا هو جواب العيب الثاني بعينه.** مُنع العامل أجرَ مدة الإشعار لأن
    إعفاءه من الحضور عُدّ سبباً كافياً للحرمان. والقاعدة (المادة ٤٣/٢) أن العقد
    **يبقى قائماً** خلال المدة وأن الأجر واجبٌ فيها؛ فالإعفاء من **الحضور** لا
    يمسّ قيام **العقد**، والأجر مقابل العقد لا مقابل الحضور. والحقل
    ``excusal_defeats_claim`` ثابتٌ على ``False`` فلا يُعاد بناء هذا الاستدلال
    في كل مسودّة، و``attendance_excused`` يُسجَّل ليُكتب في المذكرة صريحاً.

    والأساس هنا هو **الأجر الشامل** — خلافاً للإجازة والمكافأة — لسبب مفهوم:
    الأجر خلال مدة الإشعار أجرٌ عن مدّة **لم تُعمل**، فيُقاس بما كان العامل
    يتقاضاه لولا الإنهاء، لا بالأساسي وحده. وهو الأساس الذي يقرؤه المحامي في
    الحصيلة ليقرّره.

    >>> pay = notice_pay(30, Decimal("5000"), Decimal("8000"), attendance_excused=True)
    >>> str(pay.required_amount), pay.excusal_defeats_claim
    ('8000.00', False)
    """
    if days < 0:
        raise ValueError(f"عدد الأيام سالب ({days}) — راجع المدخل.")

    base = _to_decimal(basic_wage)
    gross = _to_decimal(gross_wage) if gross_wage is not None else None

    on_basic = _money(daily_rate(base) * Decimal(days))
    on_gross = _money(daily_rate(gross) * Decimal(days)) if gross is not None else None

    rule = rule_for("أجر مدة الإشعار")
    required_basis = rule.basis if rule else WAGE_BASIS_GROSS
    # غياب الأجر الشامل لا يُسقط الاستحقاق: يُحتسب على الأساسي المتاح، والأساس
    # المطلوب يبقى مذكوراً في الحصيلة حتى يعرف المحامي أن الرقم ناقص لأن
    # مدخلاً ناقص، لا لأن القاعدة نقصت.
    required_amount = on_gross if (required_basis == WAGE_BASIS_GROSS and on_gross is not None) else on_basic

    return NoticePay(
        days=days,
        basic_wage=base,
        gross_wage=gross,
        on_basic=on_basic,
        on_gross=on_gross,
        required_basis=required_basis,
        required_amount=required_amount,
        article=rule.article if rule else "",
        attendance_excused=attendance_excused,
        rule_statement=rule.statement if rule else "",
    )


# ==============================================================================
# ٥. كتلة الموجّه — القاعدة في المنظومة لا في الحوار
# ==============================================================================
# هذه هي الوصلة التي كانت مفقودة: المراجع أبلغ النموذج بالعيب في محادثة، وعاد
# العيب في التشغيل التالي. فالكلام هنا **آمر** لا واعظ: يمنع الحساب من أصله،
# ويسمّي الأساس لكل استحقاق، ويلزم النموذج بأن يقول «الأساس غير محقَّق» بدل أن
# يختار أساساً من عنده.
#
# ⚠️ وموضع عبارة «الأساس غير محقَّق» هو أهمّ سطر في الكتلة. النموذج مُدرَّب على
# أن يكمل الناقص، ولو تركناه يكمله لاختار أساساً — وهو **العيب نفسه** الذي جاء
# هذا الملف لمنعه. فالبديل يجب أن يكون معلَناً ومأموراً به، لا متروكاً للحدس.


def rules_block() -> str:
    """
    يبني كتلة عربية تُلحق بموجّه الصياغة، فتصير القاعدة في المنظومة.

    والكتلة تفعل ثلاثة أشياء، وكلّها ردّ على عيب وقع:

    ١. **تمنع الحساب أصلاً** («لا تحسب») — لأن الحساب في النصّ المولَّد لا
       يُتحقَّق منه أحد، وقد ظهر فيه ١٢٧٨ يوماً بدل ١٣٠٧.
    ٢. **تسمّي الأساس لكل استحقاق** من الجدول — لأن العيب الأول كان اختيار
       أساس في صمت: حساب على ٨٠٠٠ حيث القاعدة تطلب ٥٠٠٠.
    ٣. **تأمر بالنصّ على «الأساس غير محقَّق»** — وهذا هو صمّام الأمان: حيث لا
       قاعدة، لا يُخترع أساس.

    ولا تُبنى من نصّ ثابت محفوظ بل من `RULES` مباشرةً، فلا يفترق الموجّه عن
    الجدول: من عدّل قاعدة في الجدول عدّلها في الموجّه بلا أن يتذكّر.

    Returns:
        كتلة نصّية عربية تنتهي بسطر فارغ، تُلحق بالموجّه.

    >>> "لا تحسب" in rules_block()
    True
    >>> "٢٩/٩" in rules_block()
    True
    """
    lines = [
        "قواعد احتساب المستحقات العمالية (إلزامية):",
        "1. **لا تحسب أنت** أيّ تاريخ ولا مدّة ولا مبلغاً ولا نسبة: لا جمع ولا "
        "طرح ولا قسمة ولا ضرب. استعمل أرقام المدّة والمبلغ كما تصل إليك، وإن "
        "لم تصل إليك فاطلبها ولا تُقدّرها.",
        "2. والأساس الذي يُحسب عليه كل استحقاق هو الآتي — ولا تُخالفه، ولا "
        "تُخترع له أساساً آخر:",
    ]
    for rule in RULES:
        lines.append(
            f"   • {rule.entitlement} — الأساس: {rule.basis_label} "
            f"(المادة {rule.article}). {rule.statement}"
        )
    lines.extend(
        (
            "3. وحيث لا تغطّي القواعد أعلاه استحقاقاً في المسألة، **قل صراحةً "
            "إن أساس الاحتساب غير محقَّق** واذكر الأرقام كما وردت. ولا تختر "
            "أساساً من عندك، ولا تُجرِ الحساب على أساس ترجّحه أنت: الأساس غير "
            "المحقَّق يُقال، ولا يُخمَّن.",
            "4. ولا تذكر رقم مادة لم ترد في المقاطع المسترجعة؛ وقواعد توثيق "
            "الأسانيد أعلاه تبقى سارية كما هي.",
            "",
        )
    )
    return "\n".join(lines)


#: الكتلة محسوبةً مرة واحدة عند الاستيراد — للاستعمال في تركيب الموجّه.
#:
#: ⚠️ **ولا تُستعمل `rules_block()` في تركيب ثابت على مستوى الوحدة**، لأن
#: الاستيراد في اثنين من الوحدات يقع في دورة (``labour_rules`` ←
#: ``legal_agent``) فيسقط الاستيراد عند الإقلاع. ولذلك بنية الموجّه في
#: ``legal_agent`` تستورد **الدالّة** لا هذا الثابت، وتستدعيها في سطر واحد بعد
#: تعريف كل الموجّهات. والثابت هنا للتشخيص والعرض لا للتركيب.
LABOUR_RULES = rules_block()
