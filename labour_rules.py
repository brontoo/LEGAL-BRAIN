@dataclass(frozen=True)
class ServicePeriod:
    """
    مدّة الخدمة محسوبةً **بالضبط** لا تقديراً.

    Attributes:
        days:           عدد أيام المدّة الفعلية، بعدد أيام التقويم الحقيقي —
                        لا بضرب السنوات في ٣٦٥. وهذا هو الفرق الذي وقع في
                        المذكرة تحت المراجعة: قيل ١٢٧٨ يوماً، والصحيح ١٣٠٧.
        years/months:   السنوات والأشهر الكاملة.
        remainder_days: الأيام الباقية بعد السنوات والأشهر الكاملة.
        inclusive_end:  هل عُدّ يوم النهاية محسوباً في المدّة؟
        start, end:     الطرفان كما أُعطيا — يُحفظان لأن الحصيلة بلا طرفيها
                        لا تُتحقَّق: «١٣٠٧» وحدها لا تُراجَع، و«من ٢٠٢٣-٠٢-٠١
                        إلى ٢٠٢٦-٠٨-٣١ = ١٣٠٧» تُراجَع.
    """

    days: int
    years: int
    months: int
    remainder_days: int
    inclusive_end: bool
    start: date
    end: date

    def describe(self) -> str:
        """
        سطر عربي موجز يُكتب في المذكرة — بالسنوات والأشهر والأيام.

        >>> service_period(date(2023, 2, 1), date(2026, 8, 31)).describe()
        '3 سنة و6 شهر و29 يوم (1307 يوماً)'
        """
        return (
            f"{self.years} سنة و{self.months} شهر و{self.remainder_days} يوم "
            f"({self.days} يوماً)"
        )


@dataclass(frozen=True)
class LeavePay:
    """
    بدل الإجازة على **الأساسين معاً** — وهذا هو جوهر الملف.

    Attributes:
        days:             عدد أيام الإجازة المحتسبة.
        basic_wage:       الأجر الأساسي الشهري.
        gross_wage:       الأجر الشامل الشهري، أو ``None`` إن لم يُعطَ.
        on_basic:         المبلغ على الأجر الأساسي.
        on_gross:         المبلغ على الأجر الشامل، أو ``None``.
        required_basis:   الأساس الذي **تطلبه القاعدة** — من الجدول لا من هنا.
        required_amount:  المبلغ على الأساس المطلوب.
        difference:       الفرق بين الأساسين، أو ``None``.

    ولماذا يُعرض الأساس الخاطئ وقد عرفنا الصواب؟ لأن العيب الذي وقع لم يكن
    جهلَ الكاتب بالرقم، بل **اختيارَه أساساً في صمت**. فإظهار المبلغين معاً،
    مع الأساس المطلوب والفرق بينهما، يجعل الخطأ **ظاهراً في المستند** بدل أن
    يكون رقماً واحداً يبدو سليماً ولا يُراجَع. والفرق ليس تفصيلاً: ١١٠٠ درهم
    في أحد عشر يوماً.
    """

    days: int
    basic_wage: Decimal
    gross_wage: Optional[Decimal]
    on_basic: Decimal
    on_gross: Optional[Decimal]
    required_basis: str
    required_amount: Decimal
    difference: Optional[Decimal]
    article: str
    rule_statement: str

    @property
    def required_basis_label(self) -> str:
        """اسم الأساس المطلوب بالعربية — يُكتب في المذكرة وفي التقرير."""
        return WAGE_BASIS_LABELS.get(self.required_basis, self.required_basis)

    def describe(self) -> str:
        """
        سطر عربي يصلح للعرض: الأساس المطلوب ومبلغه، ثم الأساس الآخر والفرق.

        >>> leave_pay(11, Decimal("5000"), Decimal("8000")).describe()
        'بدل الإجازة السنوية (11 يوماً): الأجر الأساسي 1833.33 درهم؛ ويخالفه الأجر الشامل بـ 1100.00 درهم'
        """
        line = (
            f"بدل الإجازة السنوية ({self.days} يوماً): {self.required_basis_label} "
            f"{self.required_amount} درهم"
        )
        if self.difference is not None:
            other = (
                WAGE_BASIS_GROSS
                if self.required_basis == WAGE_BASIS_BASIC
                else WAGE_BASIS_BASIC
            )
            line += (
                f"؛ ويخالفه {WAGE_BASIS_LABELS.get(other, other)} بـ "
                f"{self.difference} درهم"
            )
        return line


