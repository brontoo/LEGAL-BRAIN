# ٦. نزع التكرار والترتيب
# ==============================================================================

_SEVERITY_RANK = {severity: index for index, severity in enumerate(_SEVERITIES)}
_INJECTION_KIND_RANK = {kind: index for index, kind in enumerate(_INJECTION_KINDS)}


def _dedupe(findings: list) -> list:
    """
    يطوي التكرار ويُرتّب: الأخطاء أولاً، ثم الأنواع بترتيب ``_INJECTION_KINDS``.

    والمفتاح ``(kind, excerpt)`` كما طُلب، **ولكنّ الطيّ يحتفظ بالأشدّ**: لو
    ورد العثور نفسه مرّة ``notice`` (من فحص عام) ومرّة ``error`` (من مادة على
    وشك السياج) ثم طُوي الأول، لصار الخطأ ملاحظة — أي أن الطيّ يُخفي أخطر ما
    وُجد. وهذا هو الدرس نفسه الذي دفع `review.py` إلى التفريق بين الطيّ
    والإسقاط: **التكرار ضجيج، وإسقاط الخطأ تزوير.**

    والفرز في بايثون مستقرّ: ما تساوت رتبته يبقى بترتيب الورود، فيُقرأ العثور
    بترتيب ظهوره في النصّ قدر الإمكان.
    """
    best: dict[tuple[str, str], object] = {}
    for finding in findings:
        key = (finding.kind, finding.excerpt)
        current = best.get(key)
        if current is None:
            best[key] = finding
            continue
        # الاحتفاظ بالأشدّ: error تتقدّم على notice.
        if _SEVERITY_RANK[finding.severity] < _SEVERITY_RANK[current.severity]:
            best[key] = finding

    ordered = sorted(
        best.values(),
        key=lambda item: (
            _SEVERITY_RANK[item.severity],
            _INJECTION_KIND_RANK.get(item.kind, len(_INJECTION_KINDS)),
        ),
    )
    return ordered


