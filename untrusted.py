# ٢. السياج — الدالّة
# ==============================================================================


def fence(text: Optional[str], locus: str = "") -> str:
    """
    يضع نصّ المستند داخل سياج، ويسبقه بسطر يعلن أنه **مقتبس يُستشهد به ولا
    يُطاع**.

    Args:
        text:  نصّ المستند غير الموثوق. و``None`` و``""`` يعودان ``""``.
        locus: من أين جاء النصّ (اسم المقطع أو المستند). يُطبع سطراً داخل
               السياج، ليعرف القارئ **مرجع ما يقرأ**، فيصير الاقتباس منه
               ممكناً منسوباً إلى أصله.

    Returns:
        النصّ ملفوفاً. ونصّ فارغ يعود فارغاً: سياج بلا محتوى ليس سياجاً، بل
        سطران يوهمان بأن ثمّة مادة.

    ⚠️ العلامتان **تُفكَّكان من النصّ قبل اللفّ**. وهذا ليس تحسيناً بل شرط
    سلامة: المستند الذي فيه ``FENCE_CLOSE`` يغلق السياج قبل آخره، فيخرج ما
    بعده بلا سياج، وتصير الحماية نفسها هي الثغرة.

    >>> output = fence("البند الأول: يلتزم الطرف الثاني بالسداد.", "C1")
    >>> output.startswith(FENCE_RULE)
    True
    >>> body = output.split(FENCE_OPEN, 1)[1]
    >>> FENCE_CLOSE in body[: body.rfind(FENCE_CLOSE)]
    False
    """
    body = (text or "").strip()
    if not body:
        return ""

    body = _neutralise_markers(body)

    origin = (locus or "").strip()
    # السطر المرجعي **قبل** النصّ أيضاً، ولا يُخلط بالنصّ: لو أُلحق به لكان
    # جزءاً من المقتبس، فيقتبس النموذج من كلامنا لا من المستند.
    header = f"[{origin}]\n" if origin else ""
    return f"{FENCE_RULE}\n{FENCE_OPEN}\n{header}{body}\n{FENCE_CLOSE}"


