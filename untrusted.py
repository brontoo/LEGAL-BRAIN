def _injection_summary_line(findings: Sequence[InjectionFinding]) -> str:
    """سطر عربي واحد يصلح للعرض في الواجهة أو السجلّ."""
    errors = [item for item in findings if item.severity == "error"]
    notices = [item for item in findings if item.severity == "notice"]

    if not errors and not notices:
        return "لا أثر لمحاولة حقن في النصّ المفحوص."
    if not errors:
        return (
            f"لا محاولة حقن · {len(notices)} إشارة للعلم — "
            "قد تكون ذكراً عابراً لا هجوماً."
        )
    return (
        f"{len(errors)} محاولة حقن تمنع الاعتماد على النصّ"
        + (f" · {len(notices)} إشارة للعلم" if notices else "")
        + "."
    )


def summarize_injection(findings: Sequence[InjectionFinding]) -> dict:
    """
    يحوّل عثور الحقن إلى قاموس صالح للبثّ كـ JSON.

    ``clean`` تُحسب من الأخطاء وحدها، كـ `language_audit.summarize`: الملاحظة
    لا تمنع، ووسمُ الملاحظة خطأً هو ما يُفقد التقرير كلّه.

    >>> payload = summarize_injection([])
    >>> payload["clean"], payload["error_count"]
    (True, 0)
    """
    items = list(findings)
    errors = [item for item in items if item.severity == "error"]
    notices = [item for item in items if item.severity == "notice"]

    return {
        "summary": _injection_summary_line(items),
        "clean": not errors,
        "error_count": len(errors),
        "notice_count": len(notices),
        "findings": [
            {
                "kind": item.kind,
                "severity": item.severity,
                "message": item.message,
                "excerpt": item.excerpt,
                "locus": item.locus,
            }
            for item in items
        ],
    }


def summarize_sensitive(hits: Sequence[SensitiveHit]) -> dict:
    """
    يحوّل عثور البيانات الشخصية إلى قاموس صالح للبثّ كـ JSON.

    ⚠️ والقيم **لا تخرج** من هذا القاموس: ``sample`` محجوب في ``SensitiveHit``
    نفسه قبل أن يصل إلى هنا. فالتقرير الذي يُبَثّ إلى الواجهة أو يُكتَب في
    السجلّ لا يحمل رقماً واحداً ممّا وُجد — وهذا هو الغرض من الوحدة كلها.

    >>> payload = summarize_sensitive(scan_sensitive("b@x.ae"))
    >>> payload["clean"], payload["kinds"], payload["notice_count"]
    (False, {'email': 1}, 1)
    """
    items = list(hits)
    errors = [item for item in items if item.severity == "error"]
    notices = [item for item in items if item.severity == "notice"]

    kinds: dict[str, int] = {}
    for item in items:
        kinds[item.kind] = kinds.get(item.kind, 0) + 1

    return {
        "summary": _sensitive_summary_line(items),
        # ولا عثور = لا بيانات شخصية. ولو كانت هناك ملاحظة اتصال لبقي `clean`
        # صحيحاً، على قاعدة أن الملاحظة لا تمنع. ولذلك يُعرَض العدد إلى جانبها.
        "clean": not items,
        "error_count": len(errors),
        "notice_count": len(notices),
        "kinds": kinds,
        "hits": [
            {
                "kind": item.kind,
                "severity": item.severity,
                "locus": item.locus,
                "sample": item.sample,
            }
            for item in items
        ],
    }


def _sensitive_summary_line(hits: Sequence[SensitiveHit]) -> str:
    """سطر عربي واحد: ماذا وُجد، وبأي درجة، **وبلا قيمة واحدة**."""
    if not hits:
        return "لا بيانات شخصية في النصّ المفحوص."
    errors = [item for item in hits if item.severity == "error"]
    notices = [item for item in hits if item.severity == "notice"]
    if errors:
        line = f"{len(errors)} معرّفاً حسّاساً يجب حجبه قبل الإرسال"
        if notices:
            line += f" · {len(notices)} بيان اتّصال"
        return line + "."
    return f"{len(notices)} بيان اتّصال شخصي في النصّ — يُحجَب في السجلّ."
