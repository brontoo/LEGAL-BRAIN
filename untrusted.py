@dataclass(frozen=True)
class InjectionFinding:
    """
    محاولة حقن واحدة، مرصودة في نصّ غير موثوق.

    Attributes:
        kind:     ``instruction`` | ``role_play`` | ``exfiltration`` | ``delimiter``.
        severity: ``error`` يمنع الاعتماد على المقطع بلا نظر، أو ``notice`` للعلم.
        message:  ما رُصد بالعربية.
        excerpt:  النصّ المخالف **حرفياً من المصدر**، بلا تطبيع ولا حجب: هو
                  المدَّعى عليه، ولا يُحكَم على محاولة حقن بنصّ محجوب.
        locus:    من أين جاء: اسم المقطع أو المستند أو «الموجز».
    """

    kind: str
    severity: str
    message: str
    excerpt: str
    locus: str = ""


#: أنواع العثور ورتبها كما تُعرَض. الحدود أولاً لأنها تلغِي البنية، ثم الأمر
#: الصريح، ثم إعادة الأدوار، ثم محاولة استخراج الداخل.
_INJECTION_KINDS: tuple[str, ...] = (
    "instruction",
    "role_play",
    "exfiltration",
    "delimiter",
)

#: درجتا الخطورة — كـ `language_audit.py` و`review.py`.
_SEVERITIES: tuple[str, ...] = ("error", "notice")


# ==============================================================================
# ٤. كشف الحقن — الأنماط
# ==============================================================================
# ⚠️ القاعدة التي تحكم هذا القسم كلّه، وهي التي يتعلّمها هذا المشروع من
#    `language_audit.py`: **الكاشف الذي يوسم كل أمر عربي أسوأ من كاشف معدوم،
#    لأنه يُفقد الثقة فيُتجاهَل معه العثور الحقيقي.**
#
#    والنثر القانوني العربي **مبنيّ على الأمر**: «يجب على صاحب العمل»،
#    «يلتزم الطرف الثاني»، «لا يجوز للعامل»، «يُرسل الإخطار»، «يحق للدائن».
#    ولو وسَمنا صيغة الأمر لصار كل مستند في الأرشيف محاولة حقن. فليست
#    الصيغة إذن هي العلامة، بل **الموضوع**: أن يوجَّه الكلام إلى **النظام**
#    ليغيّر قواعده. ولذلك لا نمط في هذا القسم يقبل «يجب» أو «يلتزم» أو
#    «لا يجوز» وحدها، بل تشترط كلّها مفعولاً به من عالم الحديث: تعليمات،
#    أوامر، ما سبق، النظام، النموذج، دوراً.
#
#    والاختبار `test_ordinary_legal_arabic_is_not_an_attack` يُثبّت هذا الحدّ.

#: أنماط **تجاوز الأمر**: أن يُطلب من النظام أن يُلغي قواعده أو يُقدّم عليها.
#: درجة ``error``: هذا هو الحقن نفسه، لا ذكر له.
