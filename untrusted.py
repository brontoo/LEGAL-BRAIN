def _is_ascii_upper(char: str) -> bool:
    """
    هل المحرف حرف لاتيني كبير (``A``–``Z``)؟

    ⚠️ ولا تُستعمل ``str.isupper()`` هنا، وهي مفاجأة سجّلها هذا الملف: هي
    تعيد ``True`` للحرف **العربي** أيضاً (فالعربية لا حال لها، والحرف يُعدّ
    كبيراً). فلو فُحصت بها الحروف لَجُمعت كلمة «IBAN» العربية المجاورة إلى
    المقطع، فصار ``IBANAE070331234567890123456`` — فعلاً بصنف ``IBANAE`` لا
    ``AE``، **فسقط الـIBAN من الكشف كله**. ولا يكشف ذلك إلا اختبار يجمع
    الأصناف في سطر واحد.

    والأسماء والقيم كلها لاتينية في هذا الملف (``AE``)، فالفحص على المدى
    الصريح لا على خاصية اللغة.
    """
    return "A" <= char <= "Z"


def _digit_runs(text: str) -> list[tuple[int, int, str, str, bool]]:
    """
    المقاطع المرشّحة للأرقام: ``(البداية، النهاية، الحروف، الأرقام، مفصول)``.

    والمقطع = محرف لاتيني كبير أو رقم، وما يتّصل به من حروف وأرقام ومحارف
    ``_SEPARATORS``. فالمسافة والشرطة تدخلان في المقطع (فهما بنيته المرئية،
    ويجب أن يشملها الحجب)، ولا يدخل فيه غيرهما — فحرف عربي أو فاصلة أو نقطة
    تقطع المقطع، وهذا ما يمنع أن يُقرأ «المادة 43. 2026» رقماً واحداً.

    والعلم الأخير ``مفصول`` = هل بين أرقام المقطع فاصل؟ وهو لازم لتمييز
    الأرضي: تسعة أرقام متّصلة تبدأ بالصفر لا تُفرَّق عن رقم قضية قصير، بخلاف
    ``02 123 4567`` فالفاصل نفسه دليل أنه رقم هاتف.

    ⚠️ والتعريف **متعمَّد الإفراط**: قد يجمع المقطع أرقاماً لا علاقة بينها.
    والحكم لا يقع هنا بل في ``_classify_digits``، فيُطرح الزائد. والاحتياط في
    الفحص لا في القطع: القطع الضيّق يُسقط قيماً حقيقية، والاحتياط لا يُسقط
    إلا ما يرفضه الحكم بعده.
    """
    runs: list[tuple[int, int, str, str, bool]] = []
    index = 0
    length = len(text)

    while index < length:
        plus = text[index] == "+"
        if not (text[index].isdigit() or _is_ascii_upper(text[index]) or plus):
            index += 1
            continue

        value_start = index + 1 if plus else index
        cursor = value_start
        letters: list[str] = []
        digits: list[str] = []
        seen_digit = False
        #: آخر موضع بعد قيمة حقيقية — هو نهاية المقطع التي تُعاد، لا نهاية
        #: الفواصل. وبدونه يُحجَب «0501234567.» بالقوس **و**النقطة.
        value_end = value_start
        #: هل مرّ فاصل بعد آخر قيمة؟ يُستعمل للفصل عند بدء حروف جديدة.
        pending_separator = False

        while cursor < length:
            char = text[cursor]
            if char.isdigit():
                digits.append(char)
                seen_digit = True
                value_end = cursor + 1
                pending_separator = False
            elif _is_ascii_upper(char) and not seen_digit:
                # ⚠️ **والفصل هنا لازم**، وهو العيب الذي كشفه هذا الملف: الفاصل
                # داخل المقطع يمرّ (فالمسافة والشرطة بنية الرقم المرئية)، فإذا
                # جاء **فاصل ثم حرف لاتيني جديد** فذلك بدء قيمة أخرى لا امتداد
                # لهذه. ولولاه لصار ``IBAN AE07 …`` قيمةً واحدة اسمها ``IBANAE``
                # — فيسقط الـIBAN من الكشف كله، وهو ما وقع فعلاً.
                if pending_separator and letters:
                    break
                letters.append(char)
                value_end = cursor + 1
                pending_separator = False
            elif char in _SEPARATORS:
                pending_separator = True
            else:
                break
            cursor += 1

        if digits or letters:
            # ``separated`` من **داخل** القيمة لا من أطرافها: فاصل في الطرف
            # دليل على نهاية الكلمة لا على أن الرقم مكتوب مفصولاً.
            separated = plus or value_end - value_start > len(digits) + len(letters)
            runs.append((value_start, value_end, "".join(letters), "".join(digits), separated))

        index = max(cursor, value_start + 1)

    return runs


def _phone_digits(digits: str, plus_ok: bool = False, separated: bool = False) -> bool:
    """
    هل هذا التسلسل الرقمي هاتف إماراتي؟

    والحكم على **أرقامه** لا على رسمه، فالفاصل لا أثر له هنا — وهذا جوهر
    الفرق بين هذا الماسح والأنماط التي كانت تشترط فاصلاً بعينه.

    والصور المقبولة:

    * **الجوال بعشرة أرقام** يبدأ بـ``05``: ``0501234567`` · ``050 123 4567``
      · ``050-123-4567``.
    * **الجوال بصيغة الدولة**: بعد ``971`` تسعة أرقام تبدأ بـ5
      (``+971 50 123 4567``)، أو ثمانية تبدأ بـ5 (``971501234567`` المضغوط).
    * **الأرضي بتسعة أرقام** يبدأ بـ``0`` ورمز منطقة من ٢ إلى ٩:
      ``02 123 4567`` · ``04-123-4567`` — ورمز المنطقة رقم واحد لأنه رمز منطقة.
    * **الأرضي بصيغة الدولة**: بعد ``971`` ثمانية أرقام تبدأ برمز منطقة
      (``+971 2 123 4567``).

    ⚠️ وحدّ مسجَّل: الأرضي بعشرة أرقام ببادئة محلية (``02 1234 5678``) **لا
    يُقبل**، لأنه لا يُفرَّق عن أرقام القضايا والفواتير: عشرة أرقام متّصلة تبدأ
    بالصفر ترد في المستندات القانونية بكثرة، ووسمها هاتفاً هو الوسم الخطأ الذي
    يُفقد الثقة.

    Args:
        plus_ok: هل سبق الرقم ``+``؟ فإن سبقه صارت ``971`` بادئة دولة بلا شكّ،
                 لأن ``+`` لا يُكتب قبل رقم محلّي.
    """
    for prefix in _COUNTRY_PREFIXES:
        if not digits.startswith(prefix):
            continue
        rest = digits[len(prefix) :]
        if len(rest) == 9 and rest.startswith("5"):
            return True
        if len(rest) == 8 and rest.startswith("5"):
            return True
        if len(rest) == 8 and rest[0] in "2345679":
            return True
        return False

    # البادئة المحلية: جوال بعشرة أرقام يبدأ بـ``05``.
    if len(digits) == 10:
        return digits.startswith("05")

    # الأرضي بتسعة أرقام: ``0`` ثم رمز المنطقة (٢–٩) ثم سبعة أرقام. ورمز
    # المنطقة لا يبدأ بـ٠ ولا بـ١، فبذلك لا يُقرأ الرقم المضغوط ``971…`` هاتفاً
    # محلياً.
    #
    # ⚠️ **ويُشترط فاصل** في الأرضي بلا بادئة دولة: ``021234567`` تسعة أرقام
    # متّصلة تبدأ بالصفر، وهي لا تُفرَّق عن رقم قضية أو فاتورة أو رمز. أما
    # ``02 123 4567`` فالفاصل نفسه دليل على أنها رقم هاتف مكتوب. والقاعدة:
    # **لا وسم بلا دليل** — والوسم الخطأ يُفقد الثقة في الأداة كلها.
    if len(digits) == 9 and digits[0] == "0" and separated:
        return digits[1] in "2345679"

    return False


def _in_passport_context(match: re.Match[str]) -> bool:
    """
    هل الرقم الصريح قريب من كلمة «جواز»؟

    ⚠️ وهذا تضييق مقصود. الصيغة ``A12345678`` ترد في أرقام العقود والفواتير
    وأكواد المخزون أيضاً. فبدل أن نوسم كل تسلسل «جوازاً» — وهو وسم خطأ يُفقد
    الثقة — **نطلب السياق**، ولا نُعلن الكشف إلا حيث تدلّ الكلمة على المستند.
    والثمن معروف ومسجَّل: رقم جواز في نصّ لا ترد فيه كلمة «جواز» يفوته الكشف.
    ويُغلب هذا الثمن بأن الكشف يجري على مستند كامل، وفيه عادةً اسم الوثيقة.

    والفحص هنا **لا يوسّع المدى** — يُقرِّر فقط أيُعرَض العثور أم يُسقَط.
    """
    window_start = max(0, match.start() - _PASSPORT_CONTEXT_WINDOW)
    window_end = min(len(match.string), match.end() + _PASSPORT_CONTEXT_WINDOW)
    return bool(_PASSPORT_CONTEXT.search(match.string[window_start:window_end]))


def _classify_digits(
    letters: str,
    digits: str,
    plus_ok: bool = False,
    separated: bool = False,
) -> Optional[str]:
    """
    صنف القيمة بحسب **حروفها وأرقامها وحدها** — أو ``None`` إن لم تُعرف.

    والترتيب أخصّ أولاً: الهوية (١٥ رقماً تبدأ بـ784) ثم الهاتف ثم الـIBAN ثم
    البطاقة. والهوية قبل الهاتف مقصودة: رقم الهوية يحمل اثني عشر رقماً متّصلاً
    قد يشبه هاتفاً مضغوطاً، فالحكم بالطول والبادئة يسبق حكم الهاتف — وبذلك لا
    يُبلَّغ رقم الهوية هاتفاً أيضاً.

    ووجود حروف يمنع الهوية والهاتف والبطاقة كلها: لا واحد منها يحمل حرفاً.
    """
    if (
        not letters
        and len(digits) == _EMIRATES_ID_DIGITS
        and digits.startswith(_EMIRATES_ID_PREFIX)
    ):
        return "emirates_id"
    if not letters and _phone_digits(digits, plus_ok, separated):
        return "phone"
    if letters == _IBAN_LETTERS and len(digits) == _IBAN_DIGITS:
        return "iban"
    # البطاقة: ١٣–١٩ رقماً بشرط لون. ولا تُحسب الهوية بطاقةً بطولها، فقد صُنّفت
    # قبل هذا السطر.
    if not letters and 13 <= len(digits) <= 19 and luhn_ok(digits):
        return "card"
    return None


def _sensitive_matches(
    text: str,
) -> list[tuple[int, int, str]]:
    """
    المحرّك الوحيد للكشف والحجب معاً: ``(البداية، النهاية، الصنف)``.

    ويعمل على مرحلتين:

    ١. **ماسح الأرقام** (``_digit_runs``): الهوية والهاتف والـIBAN المفصول
       والبطاقة — كلها تُحكَم بعدّ أرقامها وبادئتها. وهو ماسح يدويّ لا تعبير
       نمطي، لأن التعبير النمطي في هذا المفسّر يفشل في الأنماط التي تحتاج
       فاصلاً بعد حرفيات (انظر التعليق المطوَّل في صدر هذا القسم) — والفشل صامت.
    ٢. **التعبير النمطي** (``_IBAN_COMPACT`` · ``_EMAIL`` · ``_PASSPORT``):
       صيغها محارف لا يلتقطها الماسح بهذا الإحكام.

    ويُمنع التراكب بين المرحلتين: ما التقطه أحدهما لا يُلتقط بعده، فيبقى ترتيب
    الأسبقية حتمياً بنيويّاً لا حظّياً.
    """
    found: list[tuple[int, int, str]] = []
    taken: list[tuple[int, int]] = []

    def blocked(start: int, end: int) -> bool:
        return any(start < other_end and other_start < end for other_start, other_end in taken)

    # (١) الأرقام: الهوية والهاتف والـIBAN المفصول والبطاقة.
    for start, end, letters, digits, separated in _digit_runs(text):
        if blocked(start, end):
            continue
        plus_ok = start > 0 and text[start - 1] == "+"
        kind = _classify_digits(letters, digits, plus_ok, separated)
        if kind is not None:
            taken.append((start, end))
            found.append((start, end, kind))

    # (٢) النمطية: IBAN المضغوط، والبريد، ثم الجواز — ويُشترط للجواز السياق
    #     لئلا يُوسَم كل كود عقد جوازاً.
    for kind, pattern in (
        ("iban", _IBAN_COMPACT),
        ("email", _EMAIL),
        ("passport", _PASSPORT),
    ):
        for match in pattern.finditer(text):
            if kind == "passport" and not _in_passport_context(match):
                continue
            start, end = match.span()
            if blocked(start, end):
                continue
            taken.append((start, end))
            found.append((start, end, kind))

    return sorted(found)

#: رقم جواز السفر — بصيغة **صريحة**: حرف لاتيني ثم ثمانية أرقام.
#:
#: ⚠️ ولماذا الصراحة؟ لأن أرقام الجوازات لا صيغة عامّة تُعرف بها: لكل دولة
#: صيغتها. والقاعدة الحاكمة هنا أن **الوسم الخطأ يُفقد الثقة**: لو وسَمنا كل
#: تسلسل من خمسة إلى تسعة محارف «جوازاً» لصارت أرقام العقود والفواتير
#: جوازات، ولَضاع العثور الحقيقي. فحيث لا يُعرف الشكل، يُعلَن الحدّ ولا
#: يُدّعى الكشف. والصيغة أعلاه هي الشكل الشائع في الجوازات العربية.
_PASSPORT = re.compile(r"(?<![A-Za-z0-9])[A-Z][0-9]{8}(?![0-9])")

#: سياق يدلّ على أن الرقم الصريح جواز سفر لا رقم عقد.
_PASSPORT_CONTEXT = re.compile(r"جواز|باسبور|passport", re.IGNORECASE)

#: مدى السياق الذي يُبحث فيه عن كلمة «جواز» حول الرقم.
_PASSPORT_CONTEXT_WINDOW = 60

#: درجات الخطورة: الهوية والمال خطأ، والاتّصال ملاحظة.
#:
#: ⚠️ ورقم الجواز ``error`` وإن لم يُسمَّ في الحدّ الأدنى: هو **معرّف حكومي**
#: كالهوية الإماراتية، وهو وثيقة سفر تُنتحل. وحصره في ``notice`` كان يجعل
#: أخطر ما في الملف يمرّ بلا منع. وتصنيفه معلوم ومُختبَر، لا متروك للحدس.
_SEVERITY_BY_KIND = {
    "emirates_id": "error",
    "iban": "error",
    "card": "error",
    "passport": "error",
    "phone": "notice",
    "email": "notice",
}


def luhn_ok(digits: str) -> bool:
    """
    تحقّق خوارزمية لون (Luhn) — يفصل رقم البطاقة عن أي ستة عشر رقماً.

    ⚠️ ولماذا لون وليس عدد الأرقام؟ لأن عدد الأرقام وحده يوسم **كل** تسلسل من
    ستة عشر رقماً بطاقةً: رقم عقد، رقم صك، رقم فاتورة، رقم هوية أجنبية. وأداة
    تُنذر دائماً لا تُقرأ، ومعها يضيع الرقم الحقيقي حين يظهر. ولون تضيّق
    الكشف إلى ما صُمِّم ليصطاده، وثمنها الوحيد أن بطاقة **مغلوطة** (رقم واحد
    مقلوب) تفوت — وهي بطاقة لا تعمل أصلاً.

    >>> luhn_ok("4111111111111111")
    True
    >>> luhn_ok("1234567890123456")
    False
    """
    digits = re.sub(r"\D", "", digits)
    if not digits:
        return False

    total = 0
    # المضاعفة تبدأ من الرقم **قبل الأخير** وتنتقل يساراً خطوة بعد خطوة: هذا
    # هو ترتيب لون، ومخالفته تعطي نتائج صحيحة بالغلط على أرقام قليلة.
    for index, char in enumerate(reversed(digits)):
        value = int(char)
        if index % 2 == 1:
            value *= 2
            if value > 9:
                value -= 9
        total += value
    return total % 10 == 0


def _hit(kind: str, locus: str) -> SensitiveHit:
    """يبني عثوراً بقيمته المحجوبة — ولا يمرّ ولا محرف واحد من القيمة الأصلية."""
    return SensitiveHit(
        kind=kind,
        severity=_SEVERITY_BY_KIND[kind],
        locus=locus,
        sample=_SAMPLE_MASK[kind],
    )


def scan_sensitive(text: Optional[str], locus: str = "") -> list[SensitiveHit]:
    """
    يكشف البيانات الشخصية في نصّ **قبل أن يخرج من المبنى**.

    Args:
        text:  النصّ المفحوص — موجز أو مقطع مسترجع أو سطر سجلّ.
        locus: من أين جاء.

    Returns:
        العثور مرتّباً: الأخطاء (هوية، IBAN، بطاقة، جواز) قبل الملاحظات
        (هاتف، بريد)، ثم بترتيب الأصناف، ثم بترتيب الظهور في النصّ.

    ⚠️ هذا الكشف و``redact`` **يمرّان على محرّك واحد** (``_sensitive_matches``)،
    فلا يمكن أن يرى أحدهما ما لا يراه الآخر. والاختبار
    ``test_scan_and_redact_never_disagree`` يحرس هذه الخصيصة على مدخلات كثيرة
    — وهي التي كانت منقوصة حين كانت لكل دالّة قائمة أنماط مكتوبة بيدها.

    ⚠️ وحدّ معروف: هذا فحص **بالصور المعروفة**، لا فهم. نصّ يذكر رقم إماراتي
    مكتوباً بالأرقام الهندية، أو بأرقام متباعدة لا فاصل بينها، قد يفوته. ولذلك
    ``redact`` يُستدعى **قبل** الكتابة في السجلّ ولا يُعتمد عليه بعدها.

    >>> [hit.kind for hit in scan_sensitive("رقمه 784-1985-1234567-1")]
    ['emirates_id']
    >>> scan_sensitive("البند الأول: يلتزم الطرف الثاني بالسداد.")
    []
    """
    body = text or ""
    if not body.strip():
        return []

    hits = [_hit(kind, locus) for _start, _end, kind in _sensitive_matches(body)]

    # ترتيب العرض: الأخطاء أولاً، ثم الأصناف، ثم ترتيب الظهور — والفرز مستقرّ،
    # فما تساوت رتبته بقي بترتيب المواضع في النصّ.
    return sorted(
        hits,
        key=lambda item: (
            _SEVERITY_RANK[item.severity],
            _SENSITIVE_KINDS.index(item.kind),
        ),
    )


