def redact(text: Optional[str]) -> str:
    """
    يستبدل كل قيمة شخصية في النصّ بقوسين مربّعين فارغين، فيصير النصّ آمناً
    للكتابة في طرفية أو ملف سجلّ أو لقطة شاشة.

    ⚠️ ولماذا لا يُذكر الصنف داخل النصّ المحجوب (``[هوية]`` بدل ``[]``)؟ لأن
    النصّ المحجوب قد يُنسخ إلى مسودّة أو يُلصق في محادثة، فيُفشي **ما نوع**
    البيانات التي كانت فيه. والقوس الفارغ يقول «هنا كان شيء لا يُكتب» بلا
    إفشاء. أما ``SensitiveHit.sample`` فيذكر الصنف لأن التقرير لا يُنسخ إلى
    المستند، ولأن المحامي يحتاج أن يعرف ماذا أُخفي عنه.

    ⚠️ ومواضع الحجب تأتي من ``_sensitive_matches`` — **المحرّك نفسه** الذي
    يُغذّي ``scan_sensitive``. فلا يستطيع أحدهما أن يرى ما لا يراه الآخر، وهو
    الخلل الذي وقع فعلاً حين كانت لكل دالّة قائمة أنماط مكتوبة بيدها: أُنذر
    بالهاتف ولم يُحجَب، فصار الرقم يُبلَّغ عنه ويخرج في الوقت نفسه.

    Returns:
        النصّ نفسه إن لم يحوِ شيئاً — **حرفاً بحرف**. وهذا مهمّ: ``redact``
        تُستدعى في كل سطر سجلّ، ولو غيّرت النصّ السليم لكانت هي نفسها عيباً.

    >>> redact("هاتف الموكل 0501234567 وبريده client@example.ae")
    'هاتف الموكل [] وبريده []'
    >>> redact("البند الأول: يلتزم الطرف الثاني بالسداد.")
    'البند الأول: يلتزم الطرف الثاني بالسداد.'
    """
    if not text:
        return text or ""

    # المدى يعود إلى **النصّ الأصلي** لا إلى النسخة الموحَّدة الفواصل: التبديل
    # يوازي الطول محرفاً بمحرف، فالمواضع صالحة في الأصل — ويُحجَب من الأصل،
    # فتبقى المسافة غير الفاصلة على حالها بعد الحجب.
    spans = [(start, end) for start, end, _kind in _sensitive_matches(text)]
    if not spans:
        return text

    # الماسح يمنع التراكب أصلاً، والفرز والدمج هنا **حزام ثانٍ**: لو أُضيف نمط
    # غداً بغير مراجعة الترتيب، لَما نتج عن التراكب حجبٌ مزدوج يُفسد النصّ.
    spans.sort()
    merged: list[tuple[int, int]] = []
    for start, end in spans:
        if merged and start <= merged[-1][1]:
            previous_start, previous_end = merged[-1]
            merged[-1] = (previous_start, max(previous_end, end))
        else:
            merged.append((start, end))

    parts: list[str] = []
    cursor = 0
    for start, end in merged:
        parts.append(text[cursor:start])
        parts.append("[]")
        cursor = end
    parts.append(text[cursor:])
    return "".join(parts)


