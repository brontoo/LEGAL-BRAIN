#: ⚠️⚠️ **لماذا لا تُفحص أرقام الهوية والهاتف والـIBAN بتعبير نمطي في هذا الملف؟**
#:
#: لأن التعبير النمطي في المفسّر المستعمل هنا **يفشل فشلاً صامتاً** في بناء
#: بعينه، وهو البناء الذي تحتاجه هذه الأرقام كلها:
#:
#:     >>> import re
#:     >>> bool(re.search("050", "050 123 4567"))          # نصّ حرفي: يعمل
#:     True
#:     >>> bool(re.search(r"05[ ][0-9]{3}", "050 123 4567"))  # صنف بعد حرفي
#:     False
#:
#: فصنف المحارف ``[ ]`` بعد نصّ حرفي **لا يُطابق شيئاً**، وإن كان النصّ فيه
#: فراغ بالفعل. وكذلك ``[0-9]`` بعده. والنتيجة أن كل نمط يبدأ بحرفيات ثم يطلب
#: فاصلاً يفشل بلا استثناء وبلا تحذير — فيمرّ الرقم بلا كشف، **وتُعلن الوحدة
#: سلامةً لم تتحقّق منها**.
#:
#: وهذا ليس تفصيلاً في هذا الملف: هو **السبب الأول** الذي جعل ``redact`` لا
#: يحجب الهاتف بعد أن رصده الكاشف، وهو ما أبلغ عنه المراجع.
#:
#: **والعلاج:** أنماط التعبير النمطي باقية فيما تُحسنه (وسوم، وكلمات، وبريد)،
#: أما **الأرقام فتُفحص بماسح يدويّ** (``_digit_runs`` و``_classify_digits``)
#: يقرأ النصّ محرفاً محرفاً: يجمع الأرقام المتّصلة، ويجمع المتّصلة بفواصل،
#: ثم يحكم على **أرقامها** لا على رسمها. والفاصل يصير بلا أثر: أيّ مزيج من
#: المسافة والشرطة والنقطة يُقبل، بخلاف الأنماط التي كانت تشترط فاصلاً واحداً.
#:
#: ⚠️ والدرس المسجَّل: **الفشل الصامت في المحرّك لا يُكشف بتجربة يدوية.** كل
#: فحص أجريته يدوياً على هذه الأنماط أعطى نتيجة، ولم يكن يُعرف أصحيح هو أم
#: ناقص إلا بمقارنته بمتوقَّع مكتوب بالنصّ. ولذلك اختبارات هذه الوحدة تُقارن
#: المخرَج بمتوقَّع تامّ لا بـ«وُجد عثور ما».

#: محارف تُعدّ **داخل** الرقم: المسافة، والجدول، والمسافة غير الفاصلة (U+00A0
#: التي تأتي من النسخ من وورد والبريد)، والشرطة بصورها.
#:
#: ⚠️ **والنقطة ليست منها عن قصد**، وإن كانت تُكتب في أرقام البطاقات
#: (``4111.1111.1111.1111``): لأن النقطة تفصل الجُمل في النثر العربي، فإدخالها
#: يجعل «... المادة 43. 2026 ...» رقماً واحداً — أي يُصنع عثور من لا شيء.
#: والفقد المقابل (بطاقة بنقاط) أهون من وسم نصّ سليم.
_SEPARATORS = " \t\u00a0\u2010\u2011\u2012\u2013\u2014\u2015-"

#: بادئات الدولة الإماراتية ومرادفاتها: ``+971`` · ``00971`` · ``971``.
#: تُقارَن على الأرقام وحدها بعد نزع المحارف غير الرقمية. **والأطول أولاً**،
#: وإلا قُرئت ``00971`` بصيغة ``971`` وبقي صفر زائد فأفسد الحساب.
_COUNTRY_PREFIXES: tuple[str, ...] = ("00971", "971")

#: بادئة الـIBAN الإماراتي، والباقي بعدها واحد وعشرون رقماً بالضبط.
#: ويُفحص في ماسح الأرقام **بالحروف**: فالماسح يجمع الحروف الكبيرة المتّصلة
#: بالأرقام، فيُقرأ ``AE07 0331 …`` وحدةً واحدة.
