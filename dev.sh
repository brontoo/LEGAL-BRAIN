#!/usr/bin/env bash
# ==============================================================================
# LEGAL-BRAIN — تشغيل الخادم الخلفي والواجهة الأمامية معاً
# ==============================================================================
#     ./dev.sh
#
# يشغّل الاثنين، ويعرض عنوانيهما، ويوقف **كليهما** عند Ctrl+C.
# بديل عن فتح طرفيتين وتشغيل uvicorn ثم npm run dev يدوياً في كل مرة.
#
# متغيّرات اختيارية:
#     BACKEND_PORT=8000    FRONTEND_PORT=3000    ./dev.sh
# ==============================================================================

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$ROOT"

BACKEND_PORT="${BACKEND_PORT:-8000}"
FRONTEND_PORT="${FRONTEND_PORT:-3000}"

# ------------------------------------------------------------------------------
# فحوص سريعة قبل التشغيل — رسالة واضحة أفضل من فشل غامض لاحقاً
# ------------------------------------------------------------------------------
if [[ ! -f .env ]]; then
  echo "❌ ملف .env غير موجود في: $ROOT"
  echo "   أنشئه أولاً:  cp .env.example .env   ثم املأ المفاتيح."
  exit 1
fi

if [[ ! -d frontend/node_modules ]]; then
  echo "❌ frontend/node_modules غير موجود."
  echo "   شغّل أولاً:  cd frontend && npm install"
  exit 1
fi

command -v uvicorn >/dev/null 2>&1 || {
  echo "❌ الأمر uvicorn غير موجود."
  echo "   شغّل أولاً:  pip install -r requirements.txt"
  exit 1
}

# ------------------------------------------------------------------------------
# فحص المساحة قبل التشغيل — يُصلح عطباً وقع فعلاً
# ------------------------------------------------------------------------------
# ⚠️ لماذا هذا الفحص موجود؟
#
# لأن مخزون Turbopack في `.next/dev/cache` **ينمو بلا سقف**، وقد امتلأ القرص
# في منتصف جلسة تطوير على Codespaces:
#
#     No space left on device (os error 28)
#     FATAL: An unexpected Turbopack error occurred.
#
# فتوقّف البناء ولم تُفتح الصفحة، والسبب **لا علاقة له بالكود** — بل بمخزون
# كان يمكن حذفه في ثانية. وهذا الفحص يحذفه **قبل** أن يصل الأمر إلى هناك.
#
# ⚠️ والعتبة ٢ غ.ب: أعلى من حجم إعادة بناء كاملة، وأدنى من أن تسبق الامتلاء.
# ⚠️ وما يُحذف هنا **يُبنى من جديد فوراً** — لا نموذج مُنزَّل ولا node_modules.
# ⚠️ وقد أُعطّل مخزون التطوير أصلاً في `frontend/next.config.ts`، وهذا الفحص
#    يبقى حزاماً ثانياً: لبيانات قديمة، ولبناء الإنتاج، ولكل ما لم نتوقّعه.
# ------------------------------------------------------------------------------
MIN_FREE_MB="${MIN_FREE_MB:-2048}"
free_mb() { df -Pm "$ROOT" 2>/dev/null | awk 'NR==2 {print $4}'; }

FREE_MB="$(free_mb)"
if [[ -n "${FREE_MB:-}" && "$FREE_MB" -lt "$MIN_FREE_MB" ]]; then
  echo "⚠️  المساحة الحرة ${FREE_MB} م.ب — أقلّ من ${MIN_FREE_MB} م.ب."
  echo "   تنظيف المخزونات القابلة لإعادة البناء..."
  rm -rf "$ROOT/frontend/.next/dev/cache" "$ROOT/frontend/.next/cache" 2>/dev/null || true
  find "$ROOT" -type d -name "__pycache__" -prune -exec rm -rf {} + 2>/dev/null || true
  rm -f /tmp/next-panic-*.log 2>/dev/null || true
  NEW_FREE_MB="$(free_mb)"
  echo "✅ صارت المساحة الحرة ${NEW_FREE_MB:-?} م.ب"
  if [[ -n "${NEW_FREE_MB:-}" && "$NEW_FREE_MB" -lt "$MIN_FREE_MB" ]]; then
    echo "⚠️  وما زالت ضيّقة — للمزيد:  ./scripts/reclaim-space.sh --deep"
  fi
  echo ""
fi

# ------------------------------------------------------------------------------
# إيقاف نظيف: أي خروج (Ctrl+C أو انهيار أحدهما) يوقف الآخر
# ------------------------------------------------------------------------------
PIDS=()

cleanup() {
  echo ""
  echo "⏹  إيقاف الخادمين..."
  for pid in "${PIDS[@]:-}"; do
    # kill على مجموعة العمليات ليشمل العمليات الابنة (next dev يفرّخ عمليات)
    kill -- "-$pid" 2>/dev/null || kill "$pid" 2>/dev/null || true
  done
  wait 2>/dev/null || true
  echo "✅ تم الإيقاف."
}
trap cleanup EXIT INT TERM

echo "⚖️  العقل القانوني — تشغيل الخادم والواجهة"
echo "────────────────────────────────────────────"

# set -m يجعل كل عملية في مجموعة خاصة، فيسهل إيقاف شجرتها كاملة
set -m

# ------------------------------------------------------------------------------
# ⚠️ `--reload` ليس ترفاً — وهو أُضيف بعد عطب حقيقي.
#
# كان السطر بلا `--reload`، فـ`uvicorn` لا يراقب الملفات: بعد `git pull` يبقى
# الخادم يعمل بالشيفرة **القديمة** المحمّلة في الذاكرة. والنتيجة أن كل مسار
# جديد يعيد `404 Not Found` — وهي رسالة **لا تشير إلى السبب إطلاقاً**: تبحث
# عن خطأ في المسار أو الوكيل، والعلّة أن الخادم لم يُعَد تشغيله.
#
# وقد وقع هذا فعلاً: لوحتا القيادة والأرشيف أعادتا `404` على `/archive/*`
# بعد إضافة المسارين، بينما `/health` و`/revisions/stats` يعملان — لأن
# الأولين جديدان والآخرين قائمان. ولم يُكشف السبب إلا بمقارنة ما يعمل بما لا
# يعمل.
#
# و`--reload` يراقب ملفات `.py` وحدها (السلوك الافتراضي لـwatchfiles)، فلا
# يثقل بـ`frontend/node_modules`.
# ------------------------------------------------------------------------------
uvicorn main:app --host 0.0.0.0 --port "$BACKEND_PORT" --reload &
PIDS+=($!)

( cd frontend && npm run dev -- --port "$FRONTEND_PORT" ) &
PIDS+=($!)

echo "🔧 الخادم   : http://localhost:${BACKEND_PORT}  (يُعيد التحميل تلقائياً)"
echo "🖥️  الواجهة  : http://localhost:${FRONTEND_PORT}"
echo ""
echo "في Codespaces: اجعل المنفذين عامّين من تبويب PORTS."
echo "اضغط Ctrl+C لإيقاف الاثنين معاً."
echo ""

# ننتظر أول عملية تنتهي — ثم يُشغّل trap cleanup الباقي
wait -n || true
