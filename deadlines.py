@dataclass(frozen=True)
class Period:
    """
    مدّة محسوبةً **بالضبط** لا تقديراً — ومعها العدّ الذي حُسبت به.

    Attributes:
        days:          عدد أيام المدّة بالعدّ الذي طلبته الاتفاقية: بالتقويم
                       أو بأيام العمل. **وهو الرقم الذي يُكتب في المذكرة.**
        working_days:  عدد أيام العمل في المدّة — يُملأ **فقط** إذا وُرِّد
                       ``HolidaySet``، وإلا بقي ``None``. و``None`` مقصود:
                       صفرٌ كان سيوهم بأن المدّة لا أيام عمل فيها، والفرق بين
                       «لا أعرف» و«لا يوجد» فرقٌ لا يُطوى.
        whole_years:   السنوات الكاملة — **بالعدّ التقويمي** لا بقسمة الأيام.
        whole_months:  الأشهر الكاملة بعدها.
        remainder_days: الأيام الباقية بعد السنوات والأشهر.
        convention_key: الاتفاقية التي حُسبت بها المدّة — **تُذكر ولا تُفترض**،
                       فعلى قارئ الرقم أن يعرف بأيّ حدٍّ عُدّ.
        start, end:    الطرفان كما أُعطيا. يُحفظان لأن الحصيلة بلا طرفيها لا
                       تُتحقَّق: «١٣٠٧» وحدها لا تُراجَع، و«من ٢٠٢٣-٠٢-٠١ إلى
                       ٢٠٢٦-٠٨-٣١ = ١٣٠٧» تُراجَع.

    ⚠️ **والفكّ تقويميٌّ دائماً (سنوات وأشهر)، وعدد الأيام وحده يتبع الاتفاقية.**
    والسبب أن الشهر تقويميّ بحكم تعريفه لا بحكم العدّ. ولا يُقال إنّ
    ``days`` = مجموع الأجزاء بأي ضرب ثابت (لا ٣٠ ولا ٣٦٥) — فالأشهر الميلادية
    متفاوتة، والتفكيك **وصفٌ تقويمي للمدّة** لا جمعٌ يُعاد.
    """

    days: int
    working_days: Optional[int]
    whole_years: int
    whole_months: int
    remainder_days: int
    convention_key: str
    start: date
    end: date

    def describe(self) -> str:
        """
        سطر عربي موجز — على الصيغة المعتمدة في المذكرات.

        ⚠️ والأرقام العربية-الهندية للسنوات والأشهر والأيام، و**عدد الأيام
        الكلّي بالأرقام اللاتينية** بين قوسين: لأنه الرقم الذي يُقابَل بالملف
        ويُبحث عنه في المذكرة، فيبقى قابلاً للفحص بأداة.

        >>> period = period_between(
        ...     date(2023, 2, 1), date(2026, 8, 31), CALENDAR_EXCLUSIVE
        ... )
        >>> period.describe()
        '٣ سنة و٦ شهر و٢٩ يوماً (1307 يوماً)'
        """
        return (
            f"{_arabic(self.whole_years)} سنة و{_arabic(self.whole_months)} شهر "
            f"و{_arabic(self.remainder_days)} يوماً ({self.days} يوماً)"
        )

    def __str__(self) -> str:
        """والطباعة العادية تُعطي السطر العربي نفسه — فلا صيغتان للعرض."""
        return self.describe()

    def describe_working_days(self) -> Optional[str]:
        """
        سطر عدد أيام العمل، أو ``None`` إن لم يُورَّد تقويم.

        ⚠️ وُجدت منفصلة عن ``describe`` لأن ``describe`` بصيغتها المعتمدة في
        المذكرات، **ولا تُغيّر صيغتها بحسب المدخل** — فالسطر الذي يتغيّر شكله
        بحسب ما وُرِّد يُقرأ خطأً. وأما عدد أيام العمل فيُعرض في سطر مستقلّ
        حين يوجد، وحين لا يوجد **لا سطر** — والغياب يُرى.

        >>> holidays = HolidaySet(frozenset(), label="تقويم اختبار")
        >>> period = period_between(
        ...     date(2026, 6, 1), date(2026, 6, 7), WORKING_DAYS, holidays
        ... )
        >>> period.describe_working_days()
        'أيام العمل في المدّة: 5'
        """
        if self.working_days is None:
            return None
        return f"أيام العمل في المدّة: {self.working_days}"


