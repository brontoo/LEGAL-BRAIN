def _check_order(start: date, end: date) -> None:
    """
    المدّة المعكوسة **خطأ مدخل**، وترفع استثناءً ولا تُرجع صفراً.

    ⚠️ ورفع الاستثناء مقصود، على قاعدة `labour_rules.service_period`: إرجاع
    صفر كان سيُنقص مدّةً بصمت — والمذكرة تُسلَّم وفيها مدّة صفر بلا سبب ظاهر.
    """
    if end < start:
        raise ValueError(
            f"تاريخ النهاية ({end}) قبل تاريخ البداية ({start}) — راجع المدخل."
        )


def counted_days(
    start: date,
    end: date,
    convention: Convention,
) -> tuple[date, ...]:
    """
    **الأيام التي تُحسب في المدّة** — العدّ معلَن في موضع واحد فلا يُخمَّن.

    وهذه هي الإجابة المكتوبة على سؤال المكلَّف بهذا الملف: «كيف يُحسب يوم
    البداية ويوم النهاية؟». فالأيام المحسوبة هي:

        من ``start`` إلى ما قبل ``end`` — أي ``(end - start).days`` يوماً —
        ويُضاف إليها ``end`` نفسه إذا نصّت الاتفاقية على أن يوم النهاية محسوب.

    ⚠️ **ويوم البداية أوّل هذه الأيام دائماً**، فحقل ``include_start`` يُعلن
    القرار ولا يزيد العدد: من ٢٠٢٣-٠٢-٠١ إلى ٢٠٢٦-٠٨-٣١ = ١٣٠٧ أيام، **وفيها
    يوم البداية**. ومن استبعد يوم البداية أيضاً أنتج ١٣٠٦ — وهو رقم لا يوافق
    العدّ المعتمد في `labour_rules` ولا الرقم الذي طلبه المحامي. فالفرق بين
    «لا يُضاف» و«لا يُحسب» يومٌ واحد، وهو بعينه الفرق بين ١٣٠٧ و١٣٠٦.

    ⚠️ ووُجدت هذه الدالّة **عامّة** لا خاصّة: لأن المدّة سؤال يُسأل عنه،
    والعدّ الذي لا يُرى لا يُراجَع. ومن أراد أن يفحص حصيلةً فليعدّ أيامها هنا
    لا في ورقة.

    >>> counted_days(date(2026, 1, 1), date(2026, 1, 4), CALENDAR_EXCLUSIVE)
    (datetime.date(2026, 1, 1), datetime.date(2026, 1, 2), datetime.date(2026, 1, 3))
    >>> len(counted_days(date(2026, 1, 1), date(2026, 1, 4), CALENDAR_INCLUSIVE_END))
    4
    """
    # ⚠️ والحرس هنا **داخل الدالّة لا في ناديها**: الدالّة عامّة، ومن ناداها
    # مباشرةً على طرفين معكوسين كان سيحصل على **مجموعة فارغة** لا على خطأ —
    # أي مدّة صفرية بدل مدّة معكوسة، وهو نقصٌ صامت.
    _check_order(start, end)
    span = (end - start).days
    days = tuple(start + timedelta(days=offset) for offset in range(span))
    if convention.include_end:
        days = days + (end,)
    return days


def _calendar_count(start: date, end: date, convention: Convention) -> int:
    """
    عدد الأيام بالعدّ التقويمي — ``(end - start).days`` مضافاً إليه يوم النهاية.

    ⚠️ والصيغة **واحدة في موضع واحد**، وهي التي يثبتها
    `labour_rules.period_days(..., exclusive=not include_end)`. ولا تُحسب هنا
    بجمع الأشهر ولا بضربها في ثلاثين ولا بضرب السنوات في ٣٦٥ — فذلك هو العدّ
    الذي أنتج «١٢٧٨» في المذكرة.
    """
    return (end - start).days + (1 if convention.include_end else 0)


def _working_count(
    start: date,
    end: date,
    convention: Convention,
    holidays: HolidaySet,
) -> int:
    """
    عدد أيام العمل في المدّة — بالمرور على أيامها المحسوبة وترشيحها.

    ⚠️ و**لا تُطرح** من العدّ التقويمي نسبةٌ ولا تُضرب فيه: عدد أيام العمل
    يُعدّ عدّاً مستقلاً، لأن العطلات تتوزّع على التقويم بلا نسبة ثابتة. فمن
    «قدّر» أن الشهر خمس وعشرون يوم عمل أنتج موعداً مخترعاً.
    """
    return sum(
        1 for day in counted_days(start, end, convention)
        if holidays.is_working_day(day)
    )


def _calendar_parts(
    start: date,
    end: date,
    convention: Convention,
) -> tuple[int, int, int]:
    """
    الفكّ التقويمي (سنوات، أشهر، أيام) — **من موضعه الواحد في `labour_rules`**.

    ⚠️ **وهذه إعادة استعمال لا إعادة كتابة:** `labour_rules` ثبّتت التفكيك
    التقويمي بعد ثلاثة أخطاء وقعت فيه (انظر شرح ``_decompose`` هناك)، ونسخة
    ثانية هنا **تخالفها بصمت** في أوّل حالة حدّية. فلا يُنشأ تفكيك ثانٍ،
    والاتفاقية تُترجم إلى السؤال الواحد الذي تسأله `_decompose`: «هل ``end``
    آخر يوم في المدّة أم حدٌّ لا يُحسب؟» — وهو ``include_end`` بعينه.
    """
    parts = labour_rules.service_period(start, end, inclusive_end=convention.include_end)
    return parts.years, parts.months, parts.remainder_days


def period_between(
    start: date,
    end: date,
    convention: Convention,
    holidays: Optional[HolidaySet] = None,
) -> Period:
    """
    المدّة بين تاريخين — **بالاتفاقية التي تُقال لها** لا باتفاقية لها رأي فيها.

    ⚠️ **وهذا هو موضع الدرس:** الدالّة لا تختار العدّ. فإن كانت القاعدة تعدّ
    بالأيام تقول لها ذلك، وإن كانت تعدّ بأيام العمل مرّرت لها التقويم — وإن
    لم تمرّره **رفضت** (انظر `_require_holidays`) بدل أن تجرّب عدّاً.

    >>> period_between(date(2023, 2, 1), date(2026, 8, 31), CALENDAR_EXCLUSIVE).days
    1307
    >>> period_between(
    ...     date(2023, 2, 1), date(2026, 8, 31), CALENDAR_INCLUSIVE_END
    ... ).days
    1308
    >>> period_between(
    ...     date(2024, 2, 28), date(2024, 3, 1), CALENDAR_EXCLUSIVE
    ... ).days
    2
    """
    _check_order(start, end)

    if convention.unit_basis is DayCount.WORKING:
        supplied = _require_holidays(convention, holidays)
        working = _working_count(start, end, convention, supplied)
        # والعدّ بأيام العمل: **عدد أيام العمل هو عدد المدّة**، فالحقلان
        # يتّفقان بالضرورة. ولو اختلفا لكان في الحصيلة معياران لشيء واحد.
        days = working
    else:
        working = (
            _working_count(start, end, convention, holidays)
            if holidays is not None
            else None
        )
        days = _calendar_count(start, end, convention)

    years, months, remainder = _calendar_parts(start, end, convention)

    return Period(
        days=days,
        working_days=working,
        whole_years=years,
        whole_months=months,
        remainder_days=remainder,
        convention_key=convention.key,
        start=start,
        end=end,
    )


def _days_in_month(year: int, month: int) -> int:
    """عدد أيام الشهر — بجمع التقويم لا بجدول محفوظ ولا بقاعدة كبيسة مكتوبة."""
    if month == 12:
        return 31
    return (date(year, month + 1, 1) - date(year, month, 1)).days


def _shift_months(anchor: date, months: int) -> date:
    """
    يتقدّم ``months`` شهراً تقويمياً من ``anchor``، **ويقصر اليوم إن لم يوجد**.

    ⚠️ **وهذا هو التقييد (clamping) الذي لا يصحّ غيره:** ٣١ يناير + شهر =
    **٢٨ فبراير** (أو ٢٩ في السنة الكبيسة)، لا ٣ مارس. والسبب أن الشهر وحدة
    تقويمية لا ثلاثون يوماً، فمن فاض يومُه على الشهر الهدف **يقف عند آخر يوم
    منه** ولا يقفز إلى الشهر التالي. ولو قفز لكان الموعد بعد الحدّ بيومين أو
    ثلاثة ولا يظهر السبب في الورقة.

    ⚠️ **ولا يُصلح ``min`` الحالة الكبيسة وحدها:** هو نفسه الذي يُصلح كلّ شهر
    أقصر من شهر البداية (٣١ → ٣٠، و٣١ → ٢٨)، فالقاعدة الواحدة تكفي.

    >>> _shift_months(date(2026, 1, 31), 1)
    datetime.date(2026, 2, 28)
    >>> _shift_months(date(2024, 1, 31), 1)
    datetime.date(2024, 2, 29)
    >>> _shift_months(date(2024, 2, 29), 12)
    datetime.date(2025, 2, 28)
    """
    total = anchor.month - 1 + months
    year = anchor.year + total // 12
    month = total % 12 + 1
    if not 1 <= year <= 9999:
        raise ValueError(f"التاريخ الناتج خارج المدى المسموح: {year}-{month}.")
    day = min(anchor.day, _days_in_month(year, month))
    return date(year, month, day)


def _add_working_days(
    start: date,
    amount: int,
    convention: Convention,
    holidays: HolidaySet,
) -> date:
    """
    يتقدّم ``amount`` يوم عمل من ``start`` — مروراً على التقويم لا بضربٍ فيه.

    ⚠️ **ولا حلقة لا تنتهي:** `HolidaySet` ترفض تقويماً كلّه عطل، والعطلات
    المورَّدة مجموعة منتهية، فيبقى في الأسبوع يوم عمل يتكرّر.
    """
    day = start
    counted = 0
    while True:
        # وإن كانت النهاية حدّاً لا يُحسب، فالمدّة تنتهي **بعد** آخر يوم عمل
        # محسوب — وهذا هو العدّ نفسه الذي تعرضه `counted_days`.
        if counted == amount and not convention.include_end:
            return day
        if holidays.is_working_day(day):
            counted += 1
        if counted == amount and convention.include_end:
            return day
        day += timedelta(days=1)


def add_period(
    start: date,
    amount: int,
    unit: Unit,
    convention: Convention,
    holidays: Optional[HolidaySet] = None,
) -> date:
    """
    يُضيف مدّةً إلى تاريخ — **وبالعكس من `period_between` بالاتفاقية نفسها**.

    ⚠️ **والضمان المكتوب:** المدّة بين ``start`` وما تُرجعه هذه الدالّة تساوي
    ``amount`` بالاتفاقية المعطاة — أي أن الدالّتين **متعاكستان**، فالموعد
    المحسوب هنا إذا أُعيد إلى `period_between` أعطى المدّة التي أُمر بها. وهذا
    الضمان هو الذي يمنع يوماً زائداً أو ناقصاً في الموعد من حيث لا يُرى.

    ⚠️ **وقواعد التقدّم بحسب الوحدة، وكلّها معلنة:**

    * **الأيام (``Unit.DAYS``):** تُعدّ بالتقويم أو بأيام العمل بحسب
      ``unit_basis``. وفي العدّ التقويمي ينقل ``include_end`` الموعد يوماً
      واحداً: فمدّة «٣٠ يوماً» تنتهي في اليوم الـ٣٠ من العدّ، فإن كان يوم
      النهاية محسوباً كان الموعد عند اليوم الـ٢٩ (لأن العدّ يشمل الطرفين).
    * **الأسابيع (``Unit.WEEKS``):** سبعة أيام تقويمية دائماً. **ولا تُحوّل إلى
      أيام عمل**: فـ«أسبوع عمل» ليس سبعة أيام عمل، ولا يجوز أن نفترض له عدداً
      لم تنصّ عليه القاعدة. ومن عنده أسبوع بأيام العمل فليحوّله إلى أيام عمل
      صريحة، أو فليكتب اتفاقيته هو.
    * **الأشهر والسنوات:** أشهر تقويمية بتقييد اليوم (٣١ يناير + شهر = ٢٨
      فبراير)، والسنة اثنا عشر شهراً. **ولا يتغيّر التقدّم بالأشهر بحسب
      الاتفاقية**، لأن الشهر تقويميّ بحكم تعريفه؛ وأما «أين ينتهي الشهر» —
      في يومه الأخير أو في أوّل الشهر التالي — فمسألة القاعدة لا التقويم.

    >>> add_period(date(2026, 1, 31), 1, Unit.MONTHS, MONTHS_WHOLE)
    datetime.date(2026, 2, 28)
    >>> add_period(date(2024, 2, 29), 12, Unit.MONTHS, MONTHS_WHOLE)
    datetime.date(2025, 2, 28)
    """
    if amount < 0:
        raise ValueError(
            f"المدّة سالبة ({amount}) — والرجوع إلى الوراء سؤال آخر، "
            f"ولا يُخترع له عدٌّ من عندنا."
        )
    unit = Unit(unit)
    if amount == 0:
        # المدّة الصفرية تعيد البداية نفسها: لا مدّة بلا أيام، ولا تاريخ
        # «قبل البداية بيوم» بحجّة أن يوم النهاية محسوب.
        return start

    if unit is Unit.MONTHS:
        return _shift_months(start, amount)
    if unit is Unit.YEARS:
        return _shift_months(start, 12 * amount)
    if unit is Unit.WEEKS:
        return start + timedelta(days=7 * amount)

    # Unit.DAYS
    if convention.unit_basis is DayCount.WORKING:
        supplied = _require_holidays(convention, holidays)
        return _add_working_days(start, amount, convention, supplied)
    return start + timedelta(days=amount - (1 if convention.include_end else 0))


def is_expired(
    deadline: date,
    as_of: date,
    convention: Convention,
    holidays: Optional[HolidaySet] = None,
) -> bool:
    """
    هل فات الموعد بتاريخ ``as_of``؟ — **والجواب يتغيّر بحقلٍ واحد في الاتفاقية.**

    ⚠️ **وهذا موضع يُسأل عنه كثيراً، والجواب ليس عرفاً عاماً:**

    * إن كان **يوم النهاية محسوباً** في الاتفاقية، فالموعد نفسه **آخر أيام
      المدّة**، فلا يكون فائتاً فيه — ويفوت في اليوم التالي.
    * وإن كان **يوم النهاية حدّاً لا يُحسب**، فالمدّة انتهت في اليوم السابق
      للموعد، فالموعد **فائتٌ في يومه**. والفرق يومٌ واحد، وهو نفسه الفرق بين
      ١٣٠٧ و١٣٠٨.

    ⚠️ **ولا يمتدّ الموعد إلى يوم العمل التالي إذا وقع على عطلة.** فالمدّة
    المعدودة بأيام العمل لا تنتهي في يوم عطلة، وإن وقع ``deadline`` على يوم
    غير يوم عمل فالسؤال صار **حكماً في القاعدة** (أيمتدّ الموعد؟) لا حساباً —
    فترفض الدالّة ولا تختار. والامتناع هنا هو الفرق بين حاسبة ومستشار.

    >>> deadline = date(2026, 6, 10)
    >>> is_expired(deadline, date(2026, 6, 10), CALENDAR_EXCLUSIVE)
    True
    >>> is_expired(deadline, date(2026, 6, 10), CALENDAR_INCLUSIVE_END)
    False
    """
    if convention.unit_basis is DayCount.WORKING:
        supplied = _require_holidays(convention, holidays)
        if not supplied.is_working_day(deadline):
            raise ValueError(
                f"الموعد ({deadline}) ليس يوم عمل بهذا التقويم، والمدّة معدودة "
                f"بأيام العمل. ومدّ الموعد إلى يوم العمل التالي — أو عدم مدّه — "
                f"حكمٌ في القاعدة لا في الحاسبة: سمِّ الحكم ثم أعد النداء."
            )
    if convention.include_end:
        # يوم الموعد آخر أيام المدّة: يفوت بعد انتهائه.
        return as_of > deadline
    # يوم الموعد حدٌّ: المدّة انتهت قبله، فهو فائت في يومه.
    return as_of >= deadline


def service_period(start: date, end: date) -> Period:
    """
    مدّة الخدمة — **إعادة توجيه إلى العدّ الواحد في `labour_rules`، لا نسخة ثانية.**

    ⚠️⚠️ **واقرأ هذا قبل أن تكتب هنا عدّاً:** `labour_rules.py` فيها
    ``service_period`` وقد ثُبِّتت بعد أن أنتجت نسختان من العدّ رقمين لمدّة
    واحدة (١٣٠٧ و١٣٠٨)، ثم عاد الخطأ في موضع ثالث فكاد يُنتج ١٣٠٨ مكان ١٣٠٧.
    **فنسخةٌ ثانية هنا تخالف بصمت، وهي أسوأ من غياب الدالّة.** ولهذا لا يوجد
    في هذا الملف عدُّ مدّة خدمة ثانٍ: هذه الدالّة **تنادي** العدّ القائم
    وتُعيده في حصيلة ``Period`` تحمل أساس العدّ ومفتاح الاتفاقية وعدد أيام
    العمل — وهي الأشياء الثلاثة التي لا تحملها `ServicePeriod` هناك.

    ⚠️ **والعدّ هو العدّ نفسه:** ``calendar_exclusive`` — أي ``end`` حدٌّ لا
    يُحسب، و``(end - start).days``. والتفكيك التقويمي (السنوات والأشهر
    والأيام) يأتي من `labour_rules` مباشرةً (انظر `_calendar_parts`). فالدالّتان
    **لا تفترقان إلا في الشكل**: من نادى إحداهما أو الأخرى على المدخل نفسه
    حصل على ١٣٠٧ نفسها، و(٣، ٦، ٢٩) نفسها. واختبار في
    `tests/test_deadlines.py` يثبّت هذا الاتفاق على مدى تواريخ، لا على واقعة
    واحدة.

    >>> service_period(date(2023, 2, 1), date(2026, 8, 31)).days
    1307
    >>> service_period(date(2023, 2, 1), date(2026, 8, 31)).describe()
    '٣ سنة و٦ شهر و٢٩ يوماً (1307 يوماً)'
    """
    return period_between(start, end, CALENDAR_EXCLUSIVE)


# ==============================================================================
# ٦. جدول المدد — **الشكل بلا قانون**
# ==============================================================================
#
# ⚠️⚠️ **هذا القسم يعرّف شكل السطر، ولا يحمل سطراً واحداً.**
#
# ولا توجد هنا — ولا تُضاف — مدّةٌ محفوظة: لا «ثلاثون يوماً» ولا «سبعة أيام»
# ولا «ستون يوماً». والسبب مكتوب في ترويسة الملف ومُعادٌ هنا لأنه أهمّ ما في
# القسم: **المدّة المحفوظة في الكود تصير خطأً صامتاً في اللحظة التي يتغيّر
# فيها النصّ**، ولا شيء في المنظومة يُبلّغ بذلك. تُعدَّل المادة، ويبقى الجدول
# على القديم، فيُحسب الموعد على قاعدة ملغاة **بثقة** — وهو أسوأ من الجهل.
#
# والحدّ بين العملين:
#
#   * **المحامي** يأتي بالمدّة وبمصدرها (المادة أو البند أو العقد).
#   * **هذا الملف** يأتي بالحساب: العدّ، والتقويم، والتقييد، والسنة الكبيسة.
#
# ⚠️ **و``source`` يبقى فارغاً حتى يملأه المحامي، ولا يُخمَّن.** وسطرٌ بلا
# مصدر **يُعرض بأنه بلا مصدر** (انظر `describe_rule`) ولا يُمرَّر صامتاً —
# وحدُّه كحدّ الجدول في `labour_rules.py`: **المدّة التي لا يُتيقّن من مصدرها
# تُترك خارج الجدول، ولا تُكتب بتخمين.**


@dataclass(frozen=True)
class DeadlineRule:
    """
    قاعدة مدّة واحدة: **مقدارها ووحدتها واتفاقية عدّها ومصدرها**.

    Attributes:
        key:            معرّف آلي — يُسأل به في `rule_for`.
        label:          الاسم بالعربية كما يُكتب في المذكرة.
        amount:         مقدار المدّة — **يملؤه المحامي من النصّ**.
        unit:           وحدة المدّة: أيام أو أسابيع أو أشهر أو سنوات.
        convention_key: مفتاح الاتفاقية التي تُعدّ بها المدّة. **وهو القرار
                        القانوني في السطر**: أيوم البداية يُحسب؟ أيوم النهاية؟
                        أبالتقويم أم بأيام العمل؟ ويُتحقَّق منه بـ
                        `convention_for`، فإن كان غير معرَّف **قيل ذلك** ولم
                        يُطبَّق عدٌّ افتراضي.
        source:         **المصدر** — المادة أو البند أو العقد. يملؤه المحامي،
                        وقد يكون فارغاً؛ وحين يكون فارغاً يُعرض كذلك صريحاً.
        note:           ملاحظة المحامي على القاعدة، أو فراغ.

    ⚠️ **والقاعدة لا تحسب شيئاً بنفسها**، ولا تحمل تاريخاً ولا موعداً: هي
    **وصف** لمَدّة. والحساب في `add_period` و`period_between` بالاتفاقية
    المسماة فيها.
    """

    key: str
    label: str
    amount: int
    unit: Unit
    convention_key: str
    source: str
    note: str


def rule_for(
    key: str,
    rules: Sequence[DeadlineRule],
) -> Optional[DeadlineRule]:
    """
    يعيد قاعدة المدّة بمفتاحها، أو ``None`` إن لم تكن في الجدول.

    ⚠️ **والجدول يُمرَّر ولا يُقرأ من الملف** — وهذا مقصود: لا جدول مدد محفوظ
    في هذا الملف، فلا يمكن أن يُحسب موعد من قاعدة لم يأتِ بها المحامي في هذا
    التشغيل. و``None`` هنا **جواب مقصود لا فشل**: معناه أن المدّة غير محقَّقة،
    وهو ما يجب أن يُقال صراحةً بدل أن يُخمَّن مقدارٌ من عند الحاسبة — لأن
    المدّة المخترعة **تمضي إلى المذكرة**، والجهل يوقف الكاتب.

    >>> rule = DeadlineRule(
    ...     key="example", label="مهلة اختبار", amount=30, unit=Unit.DAYS,
    ...     convention_key="calendar_inclusive_end", source="", note="",
    ... )
    >>> rule_for("example", (rule,)).amount
    30
    >>> rule_for("لا-وجود", (rule,)) is None
    True
    >>> rule_for("لا-وجود", ()) is None
    True
    """
    for rule in rules:
        if rule.key == key:
            return rule
    return None


def describe_rule(rule: DeadlineRule) -> str:
    """
    سطر عربي يعرض القاعدة **كما هي** — بلا استكمال ناقص ولا اختراع مصدر.

    ⚠️ **وثلاثة مواضع في هذا السطر لا تُجمل على المحامي:**

    ١. **المصدر الفارغ يُقال**: «بلا مصدر مُدرَج» — ولا يُطبع السطر كأن له
       سنداً. فالمدّة بلا مصدر **رأيٌ لا قاعدة**، وعلى قاعدة `labour_rules.py`
       يُقال ذلك ولا يُخفى.
    ٢. **والاتفاقية غير المعرَّفة تُقال**: «اتفاقية غير معرَّفة» — ولا يُطبَّق
       عدٌّ افتراضي لها. فسكوتُ الحاسبة عن اتفاقية مجهولة يجعله عدّاً بلا قاعدة
       وهو لا يظهر.
    ٣. **ولا يُذكر مقدار لم يُعطَ**: السطر لا يحمل إلا ما في القاعدة.

    >>> rule = DeadlineRule(
    ...     key="example", label="مهلة اختبار", amount=30, unit=Unit.DAYS,
    ...     convention_key="calendar_inclusive_end", source="", note="",
    ... )
    >>> "بلا مصدر مُدرَج" in describe_rule(rule)
    True
    >>> "اتفاقية غير معرَّفة" in describe_rule(
    ...     DeadlineRule(
    ...         key="x", label="م", amount=1, unit=Unit.DAYS,
    ...         convention_key="لا-وجود", source="المادة ١", note="",
    ...     )
    ... )
    True
    """
    convention = convention_for(rule.convention_key)
    if convention is None:
        convention_part = f"اتفاقية غير معرَّفة: {rule.convention_key}"
    else:
        convention_part = convention.label

    source = rule.source.strip()
    source_part = source if source else "بلا مصدر مُدرَج"

    parts = [
        f"{rule.label}: {_arabic(rule.amount)} {UNIT_LABELS.get(rule.unit, rule.unit.value)}",
        f"العدّ: {convention_part}",
        f"المصدر: {source_part}",
    ]
    note = rule.note.strip()
    if note:
        parts.append(f"ملاحظة: {note}")
    return "؛ ".join(parts)
