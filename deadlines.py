"""
مواعيد الإجراءات — العدّ الذي لا يُخترع، والقاعدة التي لا يكتبها الكود.
=======================================================================

المشكلة التي يحلّها
------------------
طُلب لهذا الملف، في معناه: **بيّن كيف يُحسب يوم البداية ويوم النهاية، والسنة
الكبيسة، وأيام العمل والعطلات، عند احتساب مدّة — بحسب القاعدة التي تنطبق، ولا
تُطبّق قاعدة واحدة على كلّ مدّة.**

وفي الخلف ثلاثة عيوب وقعت فعلاً:

١. **مدّة خدمة من ٢٠٢٣-٠٢-٠١ إلى ٢٠٢٦-٠٨-٣١ كُتبت في مذكرة «١٢٧٨ يوماً»،
   والصحيح ١٣٠٧ — أو ١٣٠٨ لو حُسب يوم النهاية.** والعيب من **العدّ اليدوي**،
   وموضعه الحاسبة لا المحامي: الرقم لم يُخطئ في المعرفة، بل في العدّ.

٢. **والمدد لا تُعدّ عدّاً واحداً:** المدّة بالأيام التقويمية ليست المدّة
   بأيام العمل، وهل يُحسب يوم البداية **خاصيةٌ في القاعدة** لا عرفٌ عام. فمن
   طبّق عدّاً واحداً على كلّ مدّة أنتج موعداً صحيحاً في موضع وخاطئاً في آخر
   بلا أن يظهر له فرق.

٣. **والسنة الكبيسة تُغيّر العدّ:** ٢٠٢٤ كبيسة، والمدّة أعلاه تحتوي ٢٩
   فبراير ٢٠٢٤ — فيومٌ واحد فرقٌ في العدّ، وهو نفسه الفرق في كلّ نسبة سنوية
   تُبنى على المدّة.

المبدأ التصميمي — على نمط `citations.py` و`labour_rules.py`
------------------------------------------------------------
> **النموذج يروي، والخادم يُقرّر.** وكل ما يمكن حسابه بقاعدة ثابتة لا
> يُترَك لنموذج يحسب.

فالملف **بيانات وحساب**، لا حكم:

* **الاتفاقية بيانات** (`Convention`): لا أعراف مكتوبة داخل الشروط. من أراد
  عدّاً نادى الاتفاقية باسمها، وظهر اسمها في كلّ حصيلة (`convention_key`).
* **العطلات بيانات مورَّدة** (`HolidaySet`): ولا تقويم عطلات في هذا الملف —
  ولا تاريخ عطلة واحد، لأن التقويم يُعلَن كلّ سنة ويُعدَّل.
* **الحساب دوالّ نقية** (`period_between`، `add_period`، `is_expired`): بلا
  حالة، وبلا إدخال/إخراج، وبلا شبكة، وبلا طبع.
* **جدول المدد شكلٌ بلا قانون** (`DeadlineRule`): الحقل `source` يملؤه
  المحامي، ولا مدّة واحدة في هذا الملف.

⚠️ **وحدّان صريحان، وهما أهمّ ما في الملف**
------------------------------------------
**الأول: اختيار الاتفاقية قانونٌ لا حساب.** القاعدة هي التي تقول: هل يُحسب
يوم التبليغ؟ وهل تُعدّ العطلة الرسمية؟ وهذا الملف **لا يقرّر ذلك، ولا يُدخل
على أيّ مدّة أيّ اتفاقية من عنده**. هو يُطبّق الاتفاقية التي تُقال له، ويُظهر
**أيّ اتفاقية طُبّقت** في الحصيلة — حتى يراها المحامي لا ليأخذها مسلَّمة.
**ولهذا لا يوجد في الملف ربطٌ بين مدّة واتفاقية**: جدولٌ يقول «مهلة كذا =
اتفاقية كذا» هو الحكم القانوني نفسه، وموضعه القاعدة أو المحامي، لا الحاسبة.

**والثاني: الحاسبة تحسب ولا تُطبّق.** تحسب المدّة بين تاريخين، وتُضيف مدّة
إلى تاريخ، وتقول هل فات الموعد — ولا تقول **هل انطبقت المادة** على الواقعة.
ومن نادى `period_between` وأخذ الرقم بلا سؤال «بأيّ حدٍّ عُدّ؟» فقد أخذ حساباً
بلا قاعدة، وهو بعينه العيب الذي جاء هذا الملف لمنعه.

⚠️ **ولماذا لا تُحفظ مدّة واحدة في الجدول؟**
--------------------------------------------
لأن المدّة المحفوظة في الكود **تصير خطأً في اللحظة التي يتغيّر فيها النصّ،
ولا شيء في المنظومة يُبلّغ بذلك**: تُعدَّل المادة من ثلاثين يوماً إلى ستين،
ويبقى الجدول يقول ثلاثين، فيُحسب الموعد على قاعدة ملغاة **بثقة** — وهو أسوأ
من الجهل، لأن الجهل يوقف الكاتب والثقة تمضي به إلى المذكرة. فالمدّة تُملأ من
مصدرها في كلّ تشغيل، أو تُترك غير محقَّقة ويُقال ذلك صراحةً — على قاعدة
`labour_rules.py`: **القاعدة في المنظومة لا في الحوار، والمصدر يُذكر ولا
يُخمَّن.**

⚠️ **ودقّة في العدّ لا بدّ من كتابتها، لأنها موضع لبس:**
-------------------------------------------------------
العدّ المعتمد في هذا الملف هو **الفراغ التقويمي بين الطرفين،
``(end - start).days``**، وهو نفسه العدّ الذي يثبته
`labour_rules.period_days(..., exclusive=True)`: من ٢٠٢٣-٠٢-٠١ إلى
٢٠٢٦-٠٨-٣١ = **١٣٠٧** أيام، ويوم النهاية **حدٌّ لا يُحسب**. فإذا نصّت
الاتفاقية على أن **يوم النهاية محسوب** زاد يوماً واحداً فصار **١٣٠٨**.
ويوم البداية **أوّل أيام هذا الفراغ**، فحقل ``include_start`` يُعلن القرار ولا
يزيد العدد — ولو أُخرج يوم البداية من العدد أيضاً لصار ١٣٠٦، وهو رقم **لا
يوافق** العدّ المعتمد ولا الرقم الذي طلبه المحامي. فالفرق بين «لا يُضاف» و«لا
يُحسب» يومٌ واحد، ولذلك يُعلن الحقل ولا يُترك للافتراض، والاختبار يثبّته.

الملف بلا تبعية خارجية: مكتبة بايثون القياسية وحدها (`datetime`، `enum`،
`dataclasses`، `typing`)، ومعها وحدتان من هذا المشروع: `labour_rules`
**لأنها الموضع الواحد لعدّ المدّة** (انظر `service_period` أدناه). فيعمل
اختباره بلا شبكة وبلا مفتاح API وبلا نموذج.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import date, timedelta
from enum import Enum
from typing import Optional, Sequence

# ⚠️ **والاستيراد مقصود، وليس تبعية**: `labour_rules` هي الموضع الذي ثُبّت فيه
# العدّ الواحد (`period_days`) والتفكيك التقويمي (`_decompose`) ومدّة الخدمة
# (`service_period`) بعد أن أنتجت نسختان من العدّ رقمين لمدّة واحدة (١٣٠٧
# و١٣٠٨). فمن نادى العدّ هنا نادى الموضع نفسه، ولا يُنشأ عدّ ثانٍ — لأن نسخة
# ثانية **تخالف بصمت** أسوأ من غياب الدالّة كلها.
import labour_rules

# ==============================================================================
# ١. الوحدات وأساس العدّ — قيمتان مغلقتان لا نصّان حرّان
# ==============================================================================
# ولماذا `Enum` لا نصّ؟ لأن العيب الذي جاء هذا الملف لمنعه كان **اختيار عدّ في
# صمت**: عُدّت مدّة بالتقويم حيث تلزم أيام العمل، أو حُسب يوم النهاية حيث هو
# حدّ. ولو كان الأساس نصّاً حرّاً لما أمكن فحصه، ولا اكتشف أحد أنّ اختياراً
# خاطئاً وقع. أما كونه قيمةً من مغلقتين فيصير الخطأ **قابلاً للكشف في
# الاختبار** لا في عين المراجع وحده — وهو نفس ما فُعل بـ `WAGE_BASIS_*` في
# `labour_rules.py`.


class Unit(str, Enum):
    """
    وحدة المدّة — وهي سؤال القاعدة: «ثلاثون **يوماً**» أو «**شهر**»؟

    ⚠️ والفرق ليس لفظياً: الشهر تقويمي (٢٨ إلى ٣١ يوماً)، والثلاثون يوماً عدّ
    ثابت. فمن حوّل أحدهما إلى الآخر بضربٍ ثابت أنتج موعداً يخالف النصّ وهو
    يظنّ أنه طبّقه.
    """

    DAYS = "days"
    WEEKS = "weeks"
    MONTHS = "months"
    YEARS = "years"


class DayCount(str, Enum):
    """
    أساس العدّ — **بأيّ الأيام تُقاس المدّة؟**

    وهو جوهر المسألة التي جاء هذا الملف لها: مدّة معدودة بالأيام التقويمية
    ليست مدّة معدودة بأيام العمل، والرقمان لا يتساويان إلا مصادفةً.
    """

    CALENDAR = "calendar"  # كل الأيام
    WORKING = "working"  # بلا عطلات نهاية الأسبوع والعطلات الرسمية


#: الأرقام العربية-الهندية للعرض — على عرف المستندات في هذا المشروع.
#:
#: ⚠️ **وعدد الأيام الكلّي يبقى بالأرقام اللاتينية** في `Period.describe`:
#: لأنه الرقم الذي يُقابَل بالملف ويُبحث عنه في المذكرة، فلو عُرِّب لصعب
#: فحصه آلياً، وصار «١٣٠٧» و«1307» رقمين لا يُقارنان بأداة واحدة.
_ARABIC_INDIC = str.maketrans("0123456789", "٠١٢٣٤٥٦٧٨٩")


def _arabic(number: int) -> str:
    """يحوّل عدداً إلى أرقام عربية-هندية — للعرض وحده، ولا يُحسب به."""
    return str(number).translate(_ARABIC_INDIC)


#: أسماء الوحدات بالعربية — للعرض في `describe_rule` ورسائل الخطأ.
UNIT_LABELS: dict[Unit, str] = {
    Unit.DAYS: "يوماً",
    Unit.WEEKS: "أسبوعاً",
    Unit.MONTHS: "شهراً",
    Unit.YEARS: "سنة",
}


# ==============================================================================
# ٢. الاتفاقيات — **بيانات** لا أعراف مكتوبة في الشروط
# ==============================================================================
#
# ⚠️⚠️ **واختيار الاتفاقية قانون، لا حساب — فاقرأ هذا قبل أن تُسنِد اتفاقية
# إلى مدّة.**
#
# هذا القسم **يعرّف** العدّ ولا **يوزّعه**: لا يقول أيّ مدّة تُعدّ بأيّ اتفاقية،
# ولا يربط «إشعار» بـ «ثلاثين يوماً»، ولا «استئناف» بـ «أيام عمل». الربط نفسه
# هو الحكم القانوني، وموضعه القاعدة أو المحامي. أما هذا الملف فيكفيه أن يكون
# **قادراً على تطبيق الاتفاقية التي تُقال له**، وأن يُظهر أيّها طبّق.
#
# ⚠️ **ولهذا لا يُكتب هنا أيّ ربط بين مدّة واتفاقية** — ولا جدول يعيّن لكلّ
# مدّة عدّها. وهذا ليس نقصاً في الملف بل حدُّه: الاتفاقية **تُقال** له من
# القاعدة، فإن لم تُقل فالسؤال سؤال المحامي لا سؤال الحاسبة، ومن أجاب عنه من
# عنده فقد أنشأ حكماً في موضع الحساب.
#
# ⚠️ **وحقول الاتفاقية أربعة قرارات، وكلّها للقاعدة:**
#
#   ١. ``include_start`` — أيوم البداية يومٌ من أيام المدّة أم نقطة قياس؟
#   ٢. ``include_end``   — أيوم النهاية يومٌ محسوب أم حدٌّ لا يُحسب؟
#   ٣. ``unit_basis``    — أتُعدّ المدّة بالتقويم أم بأيام العمل؟
#   ٤. ومعها ``unit`` في القاعدة نفسها — أيومٌ أم أشهر؟
#
# والقرارات الأربعة **تُغيّر الرقم**، وكلّها تُذكر في الحصيلة لا تُفترض. ومن
# أخذ رقماً بلا سؤال «بأيّ اتفاقية؟» فقد أخذ حساباً بلا قاعدة.


@dataclass(frozen=True)
class Convention:
    """
    اتفاقية عدّ — **قرارات القاعدة مكتوبةً في بيانات**، فلا تُفترض في الشروط.

    Attributes:
        key:           معرّف آلي ثابت — هو ما يُنسب إلى الحصيلة
                       (`Period.convention_key`)، وما يُسأل به في `convention_for`.
        label:         الاسم بالعربية كما يُعرض على المحامي.
        include_start: هل يُحسب يوم البداية؟ (ولبسه مشروح في ترويسة الملف:
                       يوم البداية أوّل أيام الفراغ، فالحقل يُعلن القرار ولا
                       يزيد العدد — ومن استبعد يوم البداية أيضاً أنتج ١٣٠٦،
                       وهو رقم لا يوافق العدّ المعتمد ولا طلب المحامي.)
        include_end:   هل يُحسب يوم النهاية؟ **وهو الحقل الذي ينقل ١٣٠٧ إلى
                       ١٣٠٨**، فالفرق بين العدّين يومٌ واحد لا أكثر.
        unit_basis:    أساس العدّ — تقويميّ أم أيام عمل.
        note:          سطر عربي واحد: **متى تكون هذه الاتفاقية هي الصحيحة**.
                       وهو للعرض، وليس حكماً على واقعة: من قرأه قرأ الاقتراح،
                       والقرار للقاعدة.
    """

    key: str
    label: str
    include_start: bool
    include_end: bool
    unit_basis: DayCount
    note: str

    def __post_init__(self) -> None:
        # ولا حرس على ``include_start``/``include_end``: كلّ تركيبة منهما عدّ
        # صحيح لاتفاقية ما، والخطأ ليس في التركيبة بل في أنها لم تُعلن.
        if not self.key.strip():
            raise ValueError(
                "مفتاح الاتفاقية فارغ — والاتفاقية بلا مفتاح لا تُطلب بالاسم."
            )
        if not isinstance(self.unit_basis, DayCount):
            raise ValueError(
                f"أساس عدّ غير معروف: {self.unit_basis!r}. "
                f"والأساس من `DayCount` وحدها، فلا يُدخل نصٌّ حرّ في العدّ."
            )


#: ⚠️ **الاتفاقيات المعرَّفة في هذا المشروع — وهي بيانات لا قانون.**
#:
#: كلّ واحدة منها **قرار** أخذناه لنستطيع أن نحسب، وليس حكماً بأنّ مدّةً ما
#: تُعدّ بها. والحكم في ذلك للقاعدة التي يستند إليها الطلب. والنصّ العربي
#: المذكور في ``note`` هو **متى تصلح**، لا **ما تُطبَّق عليه**.
#:
#: وترتيبها مقصود لا أبجدي: العدّ التقويمي بحدّ عنده، ثم العدّ التقويمي بيوم
#: نهايته — وهما العدّان اللذان يفترقان بيوم واحد في الواقعة التاريخية — ثم
#: العدّ بأيام العمل، ثم العدّ بالأشهر الكاملة.
CONVENTIONS: tuple[Convention, ...] = (
    # ── الاتفاقية ١: النهاية حدٌّ لا يُحسب ──────────────────────────────────
    #
    # ⚠️ **وهذه هي الاتفاقية التي تُعطي ١٣٠٧ في الواقعة التاريخية** — من
    # ٢٠٢٣-٠٢-٠١ إلى ٢٠٢٦-٠٨-٣١. وهي **ليست** نتيجة «لا يُحسب أيّ طرف» حرفياً:
    # لو استُبعد يوم البداية أيضاً لصار العدد ١٣٠٦، وهو رقم لا يوافق العدّ
    # المعتمد في `labour_rules`، ولا الرقم الذي طلبه المحامي. فالمعنى الدقيق:
    # النهاية حدٌّ، والبداية أوّل أيام الفراغ.
    #
    # ⚠️ **ولماذا يُسمّى الحدّ ولا يُسمّى اليوم؟** لأن النهاية تُعطي واقعةً
    # («انتهت العلاقة في ٣١ أغسطس») لا يوماً معمولاً («عُمل في ٣١ أغسطس»).
    # ومن عنده الثاني نادى الاتفاقية التالية صريحاً.
    Convention(
        key="calendar_exclusive",
        label="العدّ التقويمي — ويوم النهاية حدٌّ لا يُحسب",
        include_start=False,
        include_end=False,
        unit_basis=DayCount.CALENDAR,
        note=(
            "حين تكون النهاية حدّاً لا يوماً معمولاً — وهو العدّ الذي يثبّت "
            "١٣٠٧ أيام في المدّة من ٢٠٢٣-٠٢-٠١ إلى ٢٠٢٦-٠٨-٣١."
        ),
    ),
    # ── الاتفاقية ٢: يوم النهاية يُحسب ──────────────────────────────────────
    #
    # ⚠️ **وهما اتفاقيتان لا واحدة، والفرق بينهما يومٌ واحد — وسكوتٌ عن
    # الفرق يجعله خطأً صامتاً.**
    #
    # ⚠️ **ولماذا توجد هذه أصلاً؟** لأن **العرف العمالي يعدّ آخر يوم عمل من
    # المدّة**: العامل الذي عمل يوم ٣١ أغسطس عمل يوماً يُحسب له، فالحدّ
    # («انتهت العلاقة في ٣١ أغسطس») و**اليوم المعمول** («عُمل في ٣١ أغسطس»)
    # واقعتان مختلفتان في اليوم نفسه، ولكلٍّ منهما عدّ. فالمذكرة التي قالت
    # ١٢٧٨ أخطأت في العدّ، ومن يعدّ ١٣٠٨ لا يخالف ١٣٠٧ — **بل يطبّق اتفاقية
    # أخرى، والقاعدة هي التي تختار.**
    #
    # ⚠️ **وهذا الحقل هو موضع درس الملف كله:** اتفاقيتان، والرقم نفسه،
    # والاختيار **خاصية في القاعدة** لا عرف عام. ولذلك لا يُجمع بينهما في
    # دالّة واحدة «ذكيّة» تختار للمحامي.
    Convention(
        key="calendar_inclusive_end",
        label="العدّ التقويمي — ويوم النهاية محسوب",
        include_start=False,
        include_end=True,
        unit_basis=DayCount.CALENDAR,
        note=(
            "حين يُحسب آخر يوم معمول من المدّة — وهو العرف العمالي في آخر "
            "يوم عمل، فيزيد يوماً واحداً على العدّ ذي الحدّ (١٣٠٧ ← ١٣٠٨)."
        ),
    ),
    # ── الاتفاقية ٣: أيام العمل ─────────────────────────────────────────────
    #
    # ⚠️ **وهذه اتفاقية لا تُستعمل بلا تقويم عطلات مورَّد** — و`period_between`
    # **ترفض** العدّ بها بلا تقويم بدل أن تحسبه على عطلات فارغة: التقويم
    # الفارغ يعدّ العطلة الرسمية يوم عمل، فيُنتج **موعداً متأخّراً** عن الموعد
    # الحقيقي، ولا يظهر النقص في الورقة. والامتناع هنا أهون من موعد مُخترَع.
    #
    # ⚠️ **ويوم النهاية محسوب فيها**، لأن الحدّين في مدّة «أيام عمل» يوماً
    # عملٍ فعلاً: المدّة تُعدّ من أوّل يوم عمل إلى آخر يوم عمل. فمن أراد عدّ
    # «الأيام التي تخلّلت الفترة» فليست هذه اتفاقيته، وليكتب اتفاقيته هو.
    Convention(
        key="working_days",
        label="أيام العمل — بلا عطلات نهاية الأسبوع والعطلات المورَّدة",
        include_start=True,
        include_end=True,
        unit_basis=DayCount.WORKING,
        note=(
            "حين تكون المدّة أيام عمل لا أيام تقويم (مهلة إجراء) — وتلزمها "
            "عطلات مورَّدة، فبلا تقويم عطلات تُعدّ العطلة الرسمية يوم عمل."
        ),
    ),
    # ── الاتفاقية ٤: الأشهر الكاملة ─────────────────────────────────────────
    #
    # ⚠️ **وهذه اتفاقية الأشهر لا الأيام** — تُستعمل مع `add_period` حين تكون
    # المدّة منصوصاً عليها بالأشهر («شهر إشعار»، «سنة إيجار»). والشهر فيها
    # **تقويميّ** لا ثلاثين يوماً: شهر من ١ يناير إلى ٣١ يناير = ٣١ يوماً،
    # وشهر من ١ فبراير ٢٠٢٦ = ٢٨ يوماً. فمن ضرب الأشهر في ثلاثين أنتج موعداً
    # يخالف التقويم الذي كتبته القاعدة.
    #
    # ⚠️ وحدّها المعلن: هي **للعدّ** لا لتقدير الأجر اليومي — فالأجر اليومي في
    # `labour_rules.py` على ثلاثين يوماً بحكم العرف المالي، وهما معياران
    # **مقصودان** لسؤالين مختلفين: أجر يوم، وموعد شهر.
    Convention(
        key="months_whole",
        label="أشهر تقويمية كاملة — لا ثلاثين يوماً",
        include_start=True,
        include_end=True,
        unit_basis=DayCount.CALENDAR,
        note=(
            "حين تكون المدّة معبَّراً عنها بالأشهر (شهر إشعار، سنة إيجار) — "
            "فتُعدّ الأشهر تقويمية كاملة، والشهر فيها ٢٨ إلى ٣١ يوماً."
        ),
    ),
)


def convention_for(
    key: str,
    conventions: Sequence[Convention] = CONVENTIONS,
) -> Optional[Convention]:
    """
    يعيد الاتفاقية بمفتاحها، أو ``None`` إن لم تكن معرَّفة.

    و``None`` هنا **جواب مقصود لا فشل** — على نمط `rule_for` في
    `labour_rules.py`: معناه أنّ هذه الاتفاقية **غير معرَّفة في هذا المشروع**،
    وهو ما يجب أن يُقال صراحةً بدل أن يُطبَّق عدٌّ افتراضي لم تقرّه القاعدة.
    ولو أعادت الدالّة اتفاقيةً افتراضية لصارت كلّ مدّة مجهولة الأسانيد معدودةً
    بعدٍّ لم يُطلب — وهو العيب نفسه في ثوب جديد.

    >>> convention_for("calendar_exclusive").include_end
    False
    >>> convention_for("لا-وجود") is None
    True
    """
    for convention in conventions:
        if convention.key == key:
            return convention
    return None


def _declared(key: str) -> Convention:
    """
    الاتفاقية بمفتاحها من الجدول المعرَّف في هذا الملف — **وتُشتقّ منه لا تُكرَّر**.

    ⚠️ **والاشتقاق مقصود:** لو كُتبت الثوابت أدناه تعريفاً ثانياً لاتفاقيات
    الجدول، لأمكن تعديل اتفاقيةٍ في الجدول وبقاء الثابت على القديم — فيُطبَّق
    على مدّة عدٌّ غير الذي في الجدول، وهو العيب نفسه (معياران لشيء واحد).
    فإن غاب المفتاح **سقط الاستيراد** بصوت عالٍ بدل أن يصمت.
    """
    convention = convention_for(key)
    if convention is None:
        raise ValueError(
            f"الاتفاقية «{key}» مطلوبة بالاسم وغير معرَّفة في `CONVENTIONS` — "
            f"فالجدول والثوابت تفترقان، ولا يُصلَح ذلك بعدٍّ افتراضي."
        )
    return convention


#: أسماء مختصرة للاتفاقيات المعرَّفة — للنداء بها بلا تصفّح الجدول.
#: وكلّها **مشتقّة** من `CONVENTIONS`، فمصدرها واحد.
CALENDAR_EXCLUSIVE: Convention = _declared("calendar_exclusive")
CALENDAR_INCLUSIVE_END: Convention = _declared("calendar_inclusive_end")
WORKING_DAYS: Convention = _declared("working_days")
MONTHS_WHOLE: Convention = _declared("months_whole")


# ==============================================================================
# ٣. العطلات — **بيانات مورَّدة**، ولا تقويم في هذا الملف
# ==============================================================================
#
# ⚠️⚠️ **ولا تُدرَج عطلة واحدة في هذا الملف — لا تاريخاً ولا اسماً.**
#
# والسند في ذلك عملي لا نظري: **العطلات الرسمية تُعلَن كلّ سنة وتُعدَّل**،
# فالتقويم المحفوظ في الكود يصير خطأً في السنة التالية بلا أن يُبلّغ أحد،
# ويُنتج **موعداً متأخّراً** عن الموعد الحقيقي — والموعد المتأخّر يُسقط
# استحقاقاً. ثم إن العطلات تختلف بحسب الجهة والنظام الذي تُحسب عليه المدّة،
# فلا تقويم واحد يصلح لكلّ قاعدة. فالعطلات **تُمرَّر** إلى الدالّة، ولا تُقرأ
# من الملف. واختبار في `tests/test_deadlines.py` يفحص نصّ هذا الملف بالتحليل
# النحوي (``ast``) فلا يمرّ فيه تاريخٌ حرفيّ واحد.

#: نهاية الأسبوع الافتراضية: **الجمعة والسبت** — ``date.weekday()`` هما ٤ و٥.
#:
#: ⚠️ **وهذا عرفٌ لا حقيقة كونية.** نهاية الأسبوع تختلف بين جهة وأخرى، وفي
#: بعضها يومٌ واحد. فوُضع هنا **افتراضاً معلناً** يمكن تبديله في ``HolidaySet``،
#: لا حقيقةً مفروضة: من أراد الجمعة وحدها مرّر ``frozenset({4})``، ومن أراد
#: غير ذلك مرّره صريحاً. والقاعدة هي التي تقول أيّهما يُعتمد.
DEFAULT_WEEKEND: frozenset[int] = frozenset({4, 5})


@dataclass(frozen=True)
class HolidaySet:
    """
    تقويم العطلات **كما وُرِّد** — لا كما يُخمَّن.

    Attributes:
        days:   أيام العطلات الرسمية المورَّدة. **ولا يُدرج الملف منها شيئاً**؛
                تُملأ من التقويم المعلَن للسنة المعنيّة.
        weekend: أيام نهاية الأسبوع بقيم ``date.weekday()`` (الاثنين = ٠).
                والافتراض ``DEFAULT_WEEKEND`` = الجمعة والسبت.
        label:  وصف قصير للتقويم وللمصدر — يُكتب في الحصيلة حتى يُعرف **أيّ
                تقويم** عُدّ به، فالتقويم نفسه مُدخل قابل للخطأ.

    ⚠️ **والتقويم الفارغ (``days=frozenset()``) ليس «لا عطلات» في الواقع**،
    بل هو إعلان بأنه لم تُورَّد عطلة. ولذلك هو **يُمرَّر صريحاً** ولا يُفترض:
    من نادى عدّاً بأيام العمل بلا تقويم رفضته الحاسبة (``_require_holidays``).
    """

    days: frozenset[date]
    weekend: frozenset[int] = DEFAULT_WEEKEND
    label: str = ""

    def __post_init__(self) -> None:
        for weekday in self.weekend:
            if weekday < 0 or weekday > 6:
                raise ValueError(
                    f"قيمة يوم في نهاية الأسبوع خارج المدى: {weekday}. "
                    f"والمدخل من `date.weekday()` أي ٠ إلى ٦."
                )
        if len(self.weekend) >= 7:
            # ولا حرس على حلقة لا تنتهي: لو كان كل يوم عطلة لما وُجد يوم عمل
            # واحد، فلانتظرت `add_period` أبداً. والرفض هنا يمنع ذلك.
            raise ValueError(
                "كل أيام الأسبوع عطل — فلا يوم عمل تُقاس به المدّة."
            )

    def is_working_day(self, day: date) -> bool:
        """
        هل هذا اليوم يوم عمل بهذا التقويم؟

        >>> HolidaySet(frozenset()).is_working_day(date(2026, 6, 5))
        False
        >>> HolidaySet(frozenset()).is_working_day(date(2026, 6, 1))
        True
        """
        return day not in self.days and day.weekday() not in self.weekend


def _require_holidays(
    convention: Convention,
    holidays: Optional[HolidaySet],
) -> HolidaySet:
    """
    يفرض وجود تقويم عطلات في العدّ بأيام العمل، ولا يفترض تقويمًا فارغًا.

    ⚠️ **ورفض الحساب هنا مقصود، وهو أحد مواضع الامتناع في الملف:** التقويم
    الفارغ يعدّ كلّ عطلة رسمية يوم عمل، فيُنتج عدداً أكبر فيمدّ الموعد — والمدّ
    الزائد **لا يظهر في الورقة**: يُكتب «٣٠ يوم عمل» ويُقرأ سليماً، ثم يفوّت
    الموعد. والامتناع يُرى، والموعد المُخترَع لا يُرى.
    """
    if holidays is None:
        raise ValueError(
            f"الاتفاقية «{convention.label}» تُعدّ بأيام العمل، ولا تقويم "
            f"عطلات مورَّد. وبلا تقويم تُعدّ العطلة الرسمية يوم عمل فيطول "
            f"الموعد بلا أن يظهر. مرِّر `HolidaySet` — وإن أردت العدّ بلا "
            f"عطلات فقل ذلك صريحاً بتقويم فارغ مسمّى."
        )
    return holidays


