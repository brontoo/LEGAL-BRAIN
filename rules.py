# ٣. الجدول المشحون — **قواعد هذا المشروع على نفسه، وبلا حكم موضوعي واحد**
# ==============================================================================
#
# ⚠️⚠️ **اقرأ هذا قبل أن تضيف سطراً إلى الجدول.**
#
# الجدول أدناه **ليس بياناً بالقانون**، ولا يزعم أنه استقصى أحكام الإمارات.
# هو **قواعد هذا المشروع على نفسه**: ما يلزم أن يصحّ في كل مذكرة ينتجها،
# بصرف النظر عن التشريع الذي يحكمها. ولذلك:
#
# ١. **لا حكم موضوعي واحد فيه** — ولا يُضاف. الحكم الموضوعي يحمل تاريخاً لأنه
#    يتبدّل، وهذا الجدول **لا يُراجَع بتبدّل التشريع**، فلا يجوز أن يحمل ما
#    يتبدّل. ومن احتاجه فليبنِ `RuleSet` خاصّاً به، وليكتب فيه المصدر
#    والتاريخ، وليقرأ `must_review` قبل الاعتماد.
# ٢. **ولا رقم مادة واحد فيه**، ولا إحالة إلى نصّ. والسبب أن رقم المادة
#    **يُوهم بعين المرجع**: من قرأ «المادة كذا» في الكود ظنّ أنّ الرقم محقَّق
#    في المشروع، وليس كذلك — وهو أسوأ من غيابه، لأن الغياب يوقف الكاتب
#    والرقم المخمَّن **يمضي به إلى المذكرة**. ثم إن `citations.py` يرفض رقم
#    مادة لم يظهر في المقاطع المسترجعة، فيصطدم التخمين هنا بالفحص هناك.
#    واختبار في `tests/test_rules.py` يقرأ نصّ هذا الملف ويُسقط عليه فحص
#    أرقام المواد، فلا يمرّ رقم واحد.
# ٣. **وكل سطر يحمل مصدره** — اسم الوحدة أو الفحص الذي ينفّذه. والفحص بلا
#    مصدر **رأيٌ يتنكّر في هيئة قاعدة**، ولا يُقبل ولو كان صحيحاً في الظاهر.
#
# **وحدّ هذه القواعد المعلن:** هي **صفات مطلوبة في المسودّة** — «لا تُقبل
# مذكرة كذا» — وليست أحكاماً على الواقعة. فهي تُنتج **سؤالاً** («أين سند هذا
# الاقتباس؟») لا **نتيجة** («الدعوى مقبولة»). ومن طلب من هذا الملف حكماً
# فقد طلبه من غير موضعه.
#
# **ولماذا ست قواعد لا أكثر؟** لأن الوصف حدّدها، ولأن التوسّع في «الفحص»
# يُفسد الغرض نفسه: إذا صار كل شيء فحصاً لم يبقَ فرقٌ بين ما يتبدّل وما لا
# يتبدّل — وهو الخلط الذي جاء الملف لمنعه. فالمضاف إلى هذا الجدول يُضاف
# **بمصدره وسببه**، لا لأنّه يبدو مفيداً.

#: ⚠️ **وقواعد التحقّق مشحونة هنا، والأحكام الموضوعية لا.**
#:
#: **وكل سطر أدناه يمرّ السؤال نفسه:** «هل يتبدّل هذا إذا تبدّل التشريع؟»
#: والجواب في الستة: **لا.** ولذلك لا تاريخ نفاذ على واحد منها:
#:
#: * أن يُسند الاقتباس إلى مقطع مسترجع — **شرط على الوثيقة** لا على القانون.
#:   لا تشريع يقول «يجوز أن تنقل بلا سند».
#: * أن يكون الاقتباس نصّ المادة المنسوب إليها — **شرط على النقل**.
#: * أن تحمل الواقعة مصدرها ودرجتها — **شرط على الإثبات الداخلي للملف**.
#: * أن يُظهر الحساب أساسه ومدخلاته — **شرط على المحاسبة**، وقد وقع خلاف
