def _fold(text: str) -> str:
    """
    يطوي رسم النصّ للمطابقة — **بلا استعمال `citations.normalize` عن قصد.**

    ⚠️ **والسبب موضع دقّة لا عناد:** `citations.normalize` تُبدّل كل ترقيم
    بفراغ، **فتُذيب نهايات الجمل**. وحدود الجملة هي التي يقوم عليها الفحص
    هنا (ذكر الطرفين في جملة واحدة ≠ ذكرهما في جملتين)، فلو طبّعنا بها لصار
    النصّ كتلة واحدة **والتقط الفحص كل شيء** — وهو أوسع خطأ يمكن أن يقع في
    هذا القسم.

    ⚠️ **ولا يُخترع تطبيع ثانٍ للمشروع:** الفحص هنا على **حدود الجملة**،
    فطيّ الألف والتاء والكشيدة وحدها هي كل ما يلزمه، وهو ما تفعله
    `citations.normalize` من هذه الجهة. وأما أرقام المواد فتُفحص بـ`citations`
    نفسه، فلا يفترق الفحصان.

    >>> _fold("المــادة (مائتان) من قانون المُعاملات")
    'الماده (مائتان) من قانون المعاملات'
    """
    text = _DIACRITICS.sub("", text)
    text = text.translate(_ARABIC_DIGITS).translate(_LETTER_FORMS)
    return text.lower()


def _sentences(text: str) -> tuple[str, ...]:
    """
    جمل النصّ **بعد طيّ الرسم** — وحدود الجملة تُحفظ ولا تُذاب.

    ⚠️ والطيّ جزء من الدالّة لا خطوة منفصلة، لأن كل مستهلك لهذه الجمل
    يقارن ألفاظاً مطويّة. ومن أراد النصّ كما كُتب قرأ النصّ لا ناتجها.

    >>> _sentences("أولاً. ثانياً! ثالثاً؟")
    ('اولا', 'ثانيا', 'ثالثا')
    """
    return tuple(
        part.strip()
        for part in _SENTENCE_BREAK.split(_fold(text))
        if part.strip()
    )


def _clauses(sentence: str) -> tuple[str, ...]:
    """
    مقاطع الجملة الواحدة — عليها يجري فحص «النفي والإقرار معاً».

    ⚠️ **والفحص على المقاطع لا على الجملة في الفرق الثالث،** لأن النفي
    والإقرار قد يقعان في جملة واحدة طويلة يفصلها «،» — والجملة قد تبلغ
    سطرين في المسودّة العربية.
    """
    return tuple(part.strip() for part in _CLAUSE_BREAK.split(sentence) if part.strip())


def _at(text: str, marker: str) -> Optional[tuple[int, int]]:
    """
    موضع العلامة في النصّ — بدايةً ونهايةً — أو ``None`` إن لم تكن فيه.

    ⚠️ **ووُجدت دالّةً لأن علامةً غائبة ليست موضعاً صفراً:** أوّل محرف في
    النصّ ليس علامةً واقعة فيه، والخلط بين الغياب والصفر هو الذي يُنتج
    «وجدتُها» على نصّ لا يذكرها — وهو أسوأ ما يقع في فحصٍ يُبنى عليه إنذار.

    >>> _at("نص فيه كلمة", "كلمة")
    (7, 11)
    >>> _at("نص", "غائبة") is None
    True
    """
    position = text.find(marker)
    if position == _NOT_FOUND:
        return None
    return position, position + len(marker)


def _span(text: str, markers: Iterable[str]) -> Optional[tuple[int, int, str]]:
    """
    **أوّل** علامة موجودة في النصّ، بموضعها ولفظها — أو ``None``.

    ⚠️ **وتُعيد الموضع لا ``True``،** لأن القرب شرط: علامتان في فقرة واحدة
    لكن متباعدتين لا تُعدّان قولاً واحداً. والموضع هو ما يُمكّن من قياس
    المسافة بينهما (``_adjacent``).

    ⚠️ **وأوّل علامة لا أقصرها ولا أطولها:** الترتيب هو ترتيب القائمة،
    والقائمة مرتَّبة بالأشيع أولاً. والغرض من الإعادة **الدليل** لا التمييز
    الدقيق: الملاحظة تقول أيّ لفظ أطلقها ليستطيع القارئ أن يردّ عليها.
    """
    for marker in markers:
        where = _at(text, marker)
        if where is not None:
            return where[_POS_START], where[_POS_END], marker.strip()
    return None


def _adjacent(
    text: str,
    first_markers: Iterable[str],
    second_markers: Iterable[str],
) -> Optional[tuple[str, str]]:
    """
    علامتان من مجموعتين، **متجاورتان في النصّ** — أو ``None``.

    ⚠️ **والقرب هو الشرط الذي يفرّق بين «ذُكرا» و«قُرّرا قولاً واحداً»:**
    ورودُ اللفظين في موضعين **متباعدين** من المذكرة لا يُعدّ قولاً واحداً،
    وإنما هو ذكرٌ لهما — والتباعد شاهد على عدم الخلط. وأما وقوعهما
    **متجاورين** في نَفَس واحد، فهو الذي يُقرأ قولاً واحداً، وذلك موضع
    النظر. فالفرق بين الحالين **قربٌ في النصّ**، لا وجودٌ فيه.

    ⚠️ **والمسافة تُقاس على النصّ المطويّ** (بعد `_fold`)، فالأرقام العربية
    والهندية بطول واحد، ولا يغيّر الطيّ مسافةً تغيّر الحكم.

    ⚠️ **والتقاطع مقبول ما دام الطول في النافذة:** العلامة الثانية قد تبدأ
    قبل نهاية الأولى في ألفاظ متراكبة — والقول واحد على كل حال.

    ⚠️ **وأما الخلط فهو أن يُقال، في نَفَس واحد:** «آخر يوم عمل للمدعي هو
    أول مارس، وينتهي العقد في اليوم نفسه». فالجملة تقول إنهما يوم واحد، وهذا
    هو العيب. وفي المقابل، تباعدٌ يزيد على النافذة **لا يُعدّ قولاً واحداً**.

    >>> text = _fold("آخر يوم عمل للمدعي هو أول مارس، وينتهي العقد في اليوم نفسه")
    >>> _adjacent(text, _ATTENDANCE_MARKERS, _END_MARKERS) == ("اخر يوم عمل", "ينتهي العقد")
    True
    >>> _adjacent("لا شيء هنا", _ATTENDANCE_MARKERS, _END_MARKERS) is None
    True
    >>> far = "آخر يوم عمل للمدعي. " + "حشو " * 80 + "انتهاء العقد"
    >>> _adjacent(_fold(far), _ATTENDANCE_MARKERS, _END_MARKERS) is None
    True
    """
    left = _span(text, first_markers)
    right = _span(text, second_markers)
    if left is None or right is None:
        return None
    start = min(left[_POS_START], right[_POS_START])
    end = max(left[_POS_END], right[_POS_END])
    if end - start > _PROXIMITY_CHARS:
        return None
    return left[_POS_MARKER], right[_POS_MARKER]


def _is_separated(text: str) -> bool:
    """
    هل يفصل النصّ بين الطرفين صراحةً؟ — وإن فصل، **لا ملاحظة**.

    ⚠️ **وهذه أهّم دالّة في القسم: بها لا يعاقب الفحص من أحسن.** فالصياغة
    التي تذكر «آخر يوم عمل» و«انتهاء العقد» لتقول إنهما مختلفان هي **جواب
    العيب**، لا العيب. ولو أُطلقت الملاحظة عليها لصار التقرير يُنذر على
    الصواب، **وأداةٌ تُنذر دائماً لا تُنذر أبداً.**

    ⚠️ **وحدّها:** هي فحص ألفاظ، فقد يفصل النصّ بعبارة ليست في القائمة —
    فتُرفع الملاحظة على صياغة سليمة. وهذا **الحدّ المعلن** للفحص كله، وموضعه
    في الترويسة أعلاه: الناتج **دعوة إلى النظر** لا حكم.

    ⚠️ **وعلامة الفصل لا تُسقط الفحص إلا داخل الوحدة نفسها.** فمن فصل في
    جملة، ثم خَلَط في الجملة التالية، **يُمسَك في التالية**. وهذا هو
    الصواب: الفصل في موضع لا يُبرّئ موضعاً آخر.
    """
    return any(marker in text for marker in _SEPARATORS)


#: خطة الفحص: لكل فرق، علامتاه، ونطاقه، وصياغة سببه.
#:
#: ⚠️ **والنطاق (``scope``) قرار لكل فرق لا لكل الفحوص:**
#:
#: * ``"sentence"`` — للفرقين الأول والثاني. فيهما **الصياغة المحرَّرة تستعمل
#:   الألفاظ نفسها** («آخر يوم حضور … وأما انتهاء العقد فـ…»)، فلو فُحص
#:   الملف كله لَما نجا نصّ سليم. فالفحص على الجملة، والفصل معتبر.
#: * ``"clause"`` — للفرق الثالث، لأن النفي والإقرار قد يفترقان بفاصلة.
#: * ``"sentence"`` أيضاً — للفرق الرابع، لأن وصف حكمٍ بالدوام وذكر النصّ
#:   يقعان في الجملة نفسها في أكثر الصياغات. ولا خطر في ذلك لأن علاماته
#:   («قاعدة ثابتة») **لا ترد في الصياغة المحرَّرة أصلاً**: من كتبها فقد
#:   وصف حكماً متبدّلاً بالدوام، وهذا هو العيب بعينه. **والنطاق كان في
#:   نسخة أولى من هذا الملف «الملف كله»، فأُضيق إلى الجملة** لأن الفحص على
#:   الملف كان يُطلق ملاحظة على شرح هذا الملف نفسه حين يذكر مفردتَي
#:   العلامتين في فقرتين متباعدتين — وهو إنذار كاذب من الأداة على نفسها.
_SPECIFICATIONS: tuple[tuple[DistinctionKind, tuple[str, ...], tuple[str, ...], str, str], ...] = (
    (
        DistinctionKind.ATTENDANCE_VS_END,
        _ATTENDANCE_MARKERS,
        _END_MARKERS,
        "sentence",
        "ذكر «آخر يوم حضور» و«تاريخ انتهاء العقد» في عبارة واحدة بلا فاصل "
        "بينهما — وهما مختلفان: العقد يبقى قائماً مدّة الإشعار وإن أُعفي "
        "العامل من الحضور، والفرق يغيّر ما هو واجب.",
    ),
    (
        DistinctionKind.LEAVE_DURING_VS_BALANCE,
        _LEAVE_WAGE_MARKERS,
        _BALANCE_MARKERS,
        "sentence",
        "ذكر أجر الإجازة والرصيد المتراكم في عبارة واحدة بلا فاصل — والأول "
        "أجر عن مدّة والثاني صرف رصيد، فالأساس مختلف والحساب مختلف، وجمعهما "
        "أنتج رقماً خاطئاً.",
    ),
    (
        DistinctionKind.ENTITLEMENT_VS_QUANTUM,
        _DENY_MARKERS,
        _QUANTUM_MARKERS,
        "clause",
        "نفيُ الاستحقاق والنزاعُ في المقدار في العبارة نفسها بلا فصل — "
        "فالاستحقاق مسألة والمقدار مسألة، ومن دمجها قرأ الإقرار نزاعاً "
        "والنزاع إنكاراً.",
    ),
    (
        DistinctionKind.VERIFICATION_VS_SUBSTANTIVE,
        _FIXED_MARKERS,
        _SUBSTANTIVE_MARKERS,
        "sentence",
        "وصفُ نصّ تشريعي بما يفيد أنه لا يتبدّل — وهو حكم موضوعي يتبدّل "
        "بتغيّر التشريع، فلا يجوز أن يُوصف بالدوام. وهذا بعينه ما أنتج "
        "الثمانية والعشرين في المئة: حكم ملغى قُرئ فحصاً دائماً.",
    ),
)


def _units(text: str, scope: str) -> tuple[str, ...]:
    """
    **وحدات الفحص** — الجمل أو المقاطع، بحسب نطاق الفرق.

    ⚠️ **ووُجدت لتكون الوحدة الواحدة معلنة في موضع واحد:** `check_distinctions`
    هي التي تحكم، وهذه الدالّة هي التي تُظهر **على أيّ شيء حكمت** — فيمكن
    فحص النطاق في اختبار بلا تكرار منطقه.

    >>> _units("أولاً. ثانياً!", "sentence")
    ('اولا', 'ثانيا')
    >>> _units("نفي الاستحقاق؛ والنزاع في مقدار المطالبة", "clause")
    ('نفي الاستحقاق', 'والنزاع في مقدار المطالبه')
    """
    if scope == "clause":
        return tuple(
            clause for sentence in _sentences(text) for clause in _clauses(sentence)
        )
    return _sentences(text)


def check_distinctions(text: str) -> tuple[DistinctionFinding, ...]:
    """
    يفحص نصّاً ويرصد **الصيغ** التي تخلط فروقاً أربعة وُجد هذا الملف لفصلها.

    ⚠️⚠️ **وهو قائمة تحقّق لا رأي قانوني — وهذا حدّه، لا نقص في تنفيذه.**
    يمسك **الصيغة** التي أنتجت العيب في هذا المشروع: ذكر الطرفين في مقطع
    واحد بلا فصل، أو نفيٌ وإقرار معاً، أو وصفُ حكمٍ متبدّل بالدوام. **ولا
    يمسك العيب الذي يقع بلا هذه الألفاظ** — بحسابٍ يجري على أساس خاطئ بلا
    كلام، أو بترتيب مذكرة كاملة، أو بحذف واقعة كانت تفصل بين المفهومين.
    فسكوته **ليس شهادة سلامة**، ولا يُغني عن قراءة المحامي.

    ⚠️ **ولا يُطلق على الصياغة التي تفصل** — وهذا مصرَّح به في اختبار:
    «آخر يوم حضور ليس تاريخ انتهاء العقد» لا تُنتج ملاحظة، مع أنها تذكر
    الطرفين، لأن **ذكرَهما للفصل هو الصواب** لا الخلط.

    ⚠️ **والناتج بترتيب ورود العبارات**، وبلا تكرار للعبارة الواحدة في
    الفرق الواحد: التكرار يُشوّش التقرير حتى لا يُقرأ — وهو الدرس المكتوب
    في `language_audit.py`.

    >>> len(check_distinctions("آخر يوم حضور ليس تاريخ انتهاء العقد"))
    0

    Args:
        text: نصّ المسودّة، عربيةً أو إنجليزية.

    Returns:
        الملاحظات بترتيب ورودها في النصّ.
    """
    if text is None:
        return ()
    if not _fold(text).strip():
        return ()

    findings: list[DistinctionFinding] = []
    seen: set[tuple[DistinctionKind, str]] = set()

    for kind, first, second, scope, why in _SPECIFICATIONS:
        for unit in _units(text, scope):
            if _is_separated(unit):
                continue
            adjacent = _adjacent(unit, first, second)
            if adjacent is None:
                continue
            left, right = adjacent
            marker = (kind, unit)
            if marker in seen:
                continue
            seen.add(marker)
            findings.append(
                DistinctionFinding(
                    kind=kind,
                    quote=unit.strip(),
                    why=f"{why} (العلامتان: «{left}» و«{right}»)",
                )
            )
    return tuple(findings)


# ==============================================================================
# ٧. الحصيلة — JSON-safe، والأخطاء مفصولة عن الملاحظات
# ==============================================================================
#
# ⚠️ **والفصل هنا ليس ترتيباً في العرض بل حكمٌ على الأثر:**
#
#   * **خطأ** — ما يجعل السجلّ نفسه غير صالح للاعتماد: حكمٌ موضوعي بلا مصدر،
#     أو قاعدة فحص تحمل تاريخاً. وهذا **عيب في البيانات**، ولا يصلحه القارئ.
#   * **ملاحظة** — ما يجب أن يراه المحامي ولا يُبطل السجلّ: تعارضٌ بين
#     قاعدتين، أو بحثٌ عن مفتاح غير موجود، أو صيغةٌ تخلط فرقاً.
#
# وخلط الاثنين يُفقد التقرير معناه: إذا صار التعارض «خطأً» تعطّل الاعتماد على
# قاعدتين تحتملان النظر، وإذا صار الحكم بلا مصدر «ملاحظة» مضى إلى المذكرة.
# وهو نفس الفصل بين ``error`` و``notice`` في `language_audit.py` و`review.py`.


def summarize(
    rule_set: Optional[RuleSet] = None,
    findings: Sequence[DistinctionFinding] = (),
) -> dict:
    """
    الحصيلة كاملة في قاموس **صالح للبثّ كـ JSON**.

    ⚠️ **وكلّ ما فيه قابل للتسلسل:** لا كائن ``Enum`` ولا ``Rule`` يُبَثّ
    بنفسه، لأن ``json.dumps`` لا تُسلسل ``str, Enum`` تسلسلاً واحداً في كل
    إصدارات بايثون. فالحصيلة تحمل ``.value`` صريحةً، على ما فُعل في
    `case_file.CaseFile.summary`.

    ⚠️ **و``clean`` يعني: لا خطأ.** والملاحظات لا تُفسد النقاء — وهذا هو
    معنى ``clean`` في `language_audit.LanguageReport` بعينه، فالمصطلح واحد
    في المشروع لا مصطلحان.

    Args:
        rule_set: السجلّ، أو ``None`` للجدول المشحون.
        findings: ملاحظات `check_distinctions`، إن وُجدت.

    Returns:
        قاموس صالح للبثّ، وفيه: الأعداد بالعائلة، والتعارضات، وقائمة
        المراجعة، وخريطة المفاتيح، وتفصيل كل قاعدة وكل ملاحظة.
    """
    registry = _registry(rule_set)
    rules = registry.rules

    review = must_review(registry)
    overlapping = conflicts(registry)

    errors: list[dict] = []
    notices: list[dict] = []

    for rule in rules:
        if rule.is_verification and rule.in_force_from.strip():
            errors.append(
                {
                    "code": "verification_rule_dated",
                    "key": rule.key,
                    "detail": (
                        "قاعدة فحص تحمل تاريخ نفاذ — والفحص لا يتبدّل إذا "
                        "تبدّل التشريع، فالتاريخ عليه يوهم بأنه سيُراجَع."
                    ),
                }
            )
        if rule.family is RuleFamily.SUBSTANTIVE and not rule.source.strip():
            errors.append(
                {
                    "code": "substantive_rule_without_source",
                    "key": rule.key,
                    "detail": (
                        "حكم موضوعي بلا مصدر — لا يستطيع المحامي أن يتحقّق "
                        "منه، فيصير رأياً يتنكّر في هيئة مرجع."
                    ),
                }
            )

    for first, second in overlapping:
        notices.append(
            {
                "code": "conflict",
                "keys": [first, second],
                "detail": (
                    "قاعدتان في العائلة نفسها وعلى الموضوع نفسه تتقاطعان في "
                    "النطاق وتختلفان في النصّ. والتقرير يُبلّغ ولا يحلّ: "
                    "الحكم بينهما للمحامي."
                ),
            }
        )

    for finding in findings:
        notices.append(
            {
                "code": "distinction",
                "kind": finding.kind.value,
                "label": finding.label,
                "quote": finding.quote,
                "why": finding.why,
            }
        )

    clean = not errors
    return {
        "clean": clean,
        "summary": clean_message() if clean else f"{len(errors)} خطأ في السجلّ يمنع الاعتماد عليه.",
        "rule_count": len(rules),
        "family_counts": {
            RuleFamily.VERIFICATION.value: len(registry.by_family(RuleFamily.VERIFICATION)),
            RuleFamily.SUBSTANTIVE.value: len(registry.by_family(RuleFamily.SUBSTANTIVE)),
        },
        "review_count": len(review),
        "review": [
            {
                "key": rule.key,
                "family": rule.family.value,
                "reason": (
                    "بلا مصدر"
                    if rule.family is RuleFamily.SUBSTANTIVE and not rule.source.strip()
                    else "حُلّ محلّها"
                ),
                "statement": rule.statement,
                "source": rule.source,
                "in_force_from": rule.in_force_from,
            }
            for rule in review
        ],
        "conflicts": [[first, second] for first, second in overlapping],
        "rules": [
            {
                "key": rule.key,
                "family": rule.family.value,
                "family_label": rule.family_label,
                "subject": rule.scope_key,
                "statement": rule.statement,
                "source": rule.source,
                "in_force_from": rule.in_force_from,
                "applies_to": [item.value for item in rule.applies_to],
                "stages": [item.value for item in rule.stages],
                "supersedes": list(rule.supersedes),
                "note": rule.note,
            }
            for rule in rules
        ],
        "findings": [finding.kind.value for finding in findings],
        "errors": errors,
        "notices": notices,
    }


def clean_message() -> str:
    """
    السطر العربي الذي يُقال حين لا خطأ في السجلّ.

    ⚠️ وُجد لأن **«نظيف» بالعربية لا بالإنجليزية**: هذه المنظومة عربية
    الأولى، والتقرير الذي لا عيب فيه يجب أن **يقول ذلك** لا أن يُترك خالياً.
    والفراغ غير المفسَّر يُقرأ عطباً في الأداة، فيُهمَل التقرير كله — وهو
    الدرس نفسه الذي دُفع ثمنه في مطابقة الإمارات الصامتة في `case_file.py`.

    >>> clean_message()
    'السجلّ سليم: لا خطأ، ولا تعارض، ولا قاعدة تحتاج مراجعة قبل الاعتماد.'
    """
    return "السجلّ سليم: لا خطأ، ولا تعارض، ولا قاعدة تحتاج مراجعة قبل الاعتماد."


