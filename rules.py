# ==============================================================================
# ٤. السجلّ — وعاء القواعد، ولا شيء غيره
# ==============================================================================


@dataclass(frozen=True)
class RuleSet:
    """
    مجموعة قواعد **مجمَّدة** — فلا تتبدّل أثناء تشغيل بين قارئٍ وكاتب.

    Attributes:
        rules: القواعد بترتيبها المقصود. **والترتيب ليس تفصيلاً:** هو ترتيب
               العرض على المحامي في `must_review`، فالقاعدة المشحونة أولاً
               تُقرأ أولاً.

    ⚠️ **ولا حالة ولا فهرس مخبَّأ في هذا الصنف.** والفهرسة تجري في
    `for_key` بالمرور على القواعد، وهي قائمة من عشرة أسطر لا عشرة آلاف:
    فالفهرس المحفوظ **حالة**، والحالة تُخالف محتواها إن عُدّل الجدول يوماً
    — وهو عين العيب الذي جاء هذا الملف لمنعه (معياران لشيء واحد).
    """

    rules: tuple[Rule, ...] = ()

    @property
    def keys(self) -> tuple[str, ...]:
        """
        مفاتيح القواعد بترتيبها — للفحص والعرض.

        >>> RuleSet((VERIFICATION_RULES[0],)).keys
        ('cite.traceable',)
        """
        return tuple(rule.key for rule in self.rules)

    def by_family(self, family: RuleFamily) -> tuple[Rule, ...]:
        """
        قواعد عائلة واحدة **بترتيب الجدول** — ويُنادى من موضع واحد.

        >>> RuleSet(VERIFICATION_RULES).by_family(RuleFamily.SUBSTANTIVE)
        ()
        """
        return tuple(rule for rule in self.rules if rule.family is family)


#: ⚠️ **والسجلّ المشحون بلا حكم موضوعي واحد — وهذا حدّه لا نقصه.**
#:
#: فلا يُمتحن هنا «هل النصّ الفلاني سارٍ؟» — ذلك سؤال المحامي بمرجعه. وهنا
#: يُمتحن «هل الصياغة تحمل سندها وحسابها ونصّها المثبت؟».
SHIPPED: RuleSet = RuleSet(rules=VERIFICATION_RULES)


def _registry(rule_set: Optional[RuleSet] = None) -> RuleSet:
    """
    يعيد السجلّ المعطى، أو السجلّ المشحون.

    ⚠️ ووُجدت لتُنادى من كل دالّة استعلام، فلا يُكتب `if rule_set is None`
    في خمسة مواضع — ولو كُتب لاحتمل أحد المواضع خطأً عند أوّل تعديل، فتقرأ
    دالّةٌ سجلّاً وتقرأ أخرى غيره.
    """
    return SHIPPED if rule_set is None else rule_set


# ==============================================================================
# ٥. الاستعلام — يُجيب حيث يمكن الجواب، ويرفض حيث لا يمكن
# ==============================================================================


def applicable(
    rule_set: Optional[RuleSet],
    dispute_type: DisputeType,
    stage: CaseStage,
    on_date: str = "",
) -> tuple[Rule, ...]:
    """
    القواعد السارية على نزاع بعينه، في مرحلة بعينه، بتاريخ وقائع بعينه.

    ⚠️ **والترشيح على ثلاثة، ولكلٍّ معناه:**

    ١. **نوع النزاع**: قاعدة ``applies_to`` فارغة **لا تخصّ نوعاً بعينه**،
       فتسري على كل الأنواع. والفراغ هنا **ليس «لا شيء»** — وهذا فرق لا
       يُطوى: قاعدة لا تسري على شيء وجودها عبث، وأما قاعدة تسري على الكل
       فهي الأصل في قواعد الفحص.
    ٢. **المرحلة**: ``stages`` فارغة تعني كل المراحل، بالمنطق نفسه.
    ٣. **التاريخ**: **ولا يُرشَّح بالتاريخ إلا ما حمل تاريخاً.** فالقاعدة
       التي لا تاريخ لها تسري دائماً؛ والتي لها تاريخ تُشترط بألّا يكون
       تاريخ الوقائع قبل نفاذها. و``on_date`` الفارغ **لا يُطابق** المؤرَّخة
       — فالجهل بالتاريخ يُقلّل الساري ولا يزيد، وضدّ ذلك إدخالُ حكمٍ بلا
       سؤال «هل كان نافذاً؟».

    ⚠️ **والدالّة لا تُرتّب:** الترتيب هو ترتيب الجدول، فلا يفترق ترتيب
    العرض عن ترتيب التحرير.

    >>> len(applicable(None, DisputeType.LABOUR, CaseStage.FIRST_INSTANCE)) == len(VERIFICATION_RULES)
    True

    Args:
        rule_set: السجلّ، أو ``None`` للجدول المشحون.
        dispute_type: نوع النزاع من `case_file.DisputeType`.
        stage: المرحلة من `case_file.CaseStage`.
        on_date: تاريخ الوقائع بصيغة ISO، أو ``""`` إن لم يُعطَ.

    Returns:
        القواعد السارية، بترتيب الجدول.
    """
    return tuple(
        rule
        for rule in _registry(rule_set).rules
        if (not rule.applies_to or dispute_type in rule.applies_to)
        and (not rule.stages or stage in rule.stages)
        and rule.applies_on(on_date)
    )


def for_key(rule_set: Optional[RuleSet], key: str) -> Optional[Rule]:
    """
    يعيد القاعدة بمفتاحها، أو ``None`` إن لم تكن في السجلّ.

    ⚠️⚠️ **و``None`` هنا جواب مقصود لا فشل، وهو الدرس المكتوب في
    `deadlines.convention_for` و`labour_rules.rule_for` — فاقرأه قبل أن
    تُضيف «مطابقة قريبة» أو مفتاحاً افتراضياً.**

    المفتاح المجهول **خطأ مستدعٍ**: نُودي بمفتاح ليس في الجدول. وأخطر ردود
    الفعل عليه ثلاثة، وكلّها وقعت في هذا المشروع أو كادت:

    ١. **إرجاع أقرب مفتاح.** «لا يوجد `calc.basis`، فليكن
       `calc.basis_and_inputs`» — فيُطبَّق فحصٌ لم يُطلب، ويظنّ المستدعي أنه
       نال ما طلب.
    ٢. **إرجاع قاعدة افتراضية.** فيُقرأ «سندٌ معلوم» حيث لا سند، وهو أسوأ
       ما يمكن: **الجهل يتنكّر في هيئة علم**.
    ٣. **إرجاع أول قاعدة في الجدول.** فيُرجع فحصٌ لا علاقة له بالسؤال،
       ولا يظهر الخطأ لأن الناتج كائن صالح.

    فواحد من هذه الثلاثة كان سيُنتج في المذكرة ما أنتجه الخلط بين الفحص
    والحكم الموضوعي: **قاعدة تُقرأ حيث لا تنطبق**. والجواب الصحيح أن يُقال
    «لا أعرف هذا المفتاح» — والفراغ يُرى، والردّ المخترع لا يُرى.

    >>> for_key(None, "cite.traceable").key
    'cite.traceable'
    >>> for_key(None, "لا-وجود-له") is None
    True
    """
    for rule in _registry(rule_set).rules:
        if rule.key == key:
            return rule
    return None


def _shares_scope(first: Rule, second: Rule) -> bool:
    """
    هل تتقاطع قاعدتان في النطاق؟ — والفراغ يعني «الكل».

    ⚠️ **والتقاطع يُبنى على التصريح لا على الفراغ:** قاعدتان لم تُصرّحا
    بنوع نزاع ولا بمرحلة **لا يُقال إنهما تتقاطعان** لأن كلتيهما تسري على
    الكل. والسبب عمليّ: بهذا الشرط لا يصير كل سطرين في الجدول «متعارضين»
    لمجرد أن كليهما عامّ، **وتقريرٌ يُنذر دائماً لا يُنذر أبداً** — وهو
    الدرس الذي دُفع ثمنه في `language_audit.py`.

    ⚠️ **والتصريح في أحد البُعدين يكفي للتقاطع:** قاعدةٌ صرّحت بنوع نزاعٍ
    ولم تصرّح بمرحلة، وأخرى صرّحت بمرحلةٍ ولم تصرّح بنوع، **تتقاطعان** —
    لأن كلًّا منهما تسري على كل ما لم تصرّح به. وهذا هو معنى الفراغ في
    `applicable` نفسه، فلا يفترق الفحصان. **والشرط الوحيد: أن يكون في
    القاعدتين تصريحٌ ما** — فالقاعدتان الغامضتان لا يُبنى تعارضهما على
    غموضهما.

    >>> first = Rule(key="a", family=RuleFamily.VERIFICATION, statement="س",
    ...              applies_to=(DisputeType.LABOUR,))
    >>> second = Rule(key="b", family=RuleFamily.VERIFICATION, statement="ع",
    ...               applies_to=(DisputeType.LEASE,))
    >>> _shares_scope(first, second)
    False
    >>> _shares_scope(first, Rule(key="c", family=RuleFamily.VERIFICATION,
    ...                            statement="ص", stages=(CaseStage.APPEAL,)))
    True
    >>> _shares_scope(first, Rule(key="d", family=RuleFamily.VERIFICATION,
    ...                           statement="ق"))
    True
    """
    if not (first.applies_to or first.stages or second.applies_to or second.stages):
        return False
    if first.applies_to and second.applies_to:
        if not set(first.applies_to) & set(second.applies_to):
            return False
    if first.stages and second.stages:
        if not set(first.stages) & set(second.stages):
            return False
    return True


def conflicts(rule_set: Optional[RuleSet] = None) -> tuple[tuple[str, str], ...]:
    """
    قاعدتان **على الموضوع نفسه**، في العائلة نفسها، تتقاطعان في النطاق
    وتختلفان في النصّ.

    ⚠️⚠️ **والدالّة تُبلّغ ولا تحلّ — وهذا حدّها لا نقصها.**
    لا تختار أيّ القاعدتين أصحّ، ولا تحذف إحداهما، ولا تُعدّل نصّاً. والسبب
    أن **الحكم بين قاعدتين حكمٌ قانوني**: قد تكون إحداهما أخصّ فتُقدَّم، وقد
    تكون الأخرى أحدث، وقد تكون إحداهما خطأً في التحرير. وهذا كلّه للقارئ،
    وأما هذه الدالّة فتُخرج **موضع النظر** ليراه. وقاعدةٌ «تُصلح» نفسها
    بصمت **تُخفي الخلاف** بدل أن تُظهره — وهو أسوأ من التعارض نفسه.

    ⚠️ **وثلاثة شروط قبل الإبلاغ، وكلّها تمنع إنذاراً كاذباً:**

    ١. **العائلة نفسها.** قاعدة فحص وقاعدة موضوعية قد تقولان المعنى نفسه
       بصيغتين، **ولا تعارض بينهما أصلاً**، لأن إحداهما تُفحص والأخرى
       تُطبَّق. ولو قِيس التعارض بالنصّ وحده لامتلأ التقرير بمزاعم كاذبة.
    ٢. **الموضوع نفسه** (``subject``). «الاقتباس يُتبَّع إلى مقطع» و«الواقعة
       تحمل مصدرها» قاعدتان **مختلفتان ولا تتعارضان** — جمعهما أنهما في
       الجدول نفسه، لا أنهما تتنازعان. فلا يُبلَّغ عنهما.
    ٣. **التقاطع المُصرَّح به في النطاق.** قاعدتان لنوعَي نزاع مختلفين لا
       تتعارضان. والقاعدتان العامّتان اللتان لم تُصرّحا بنطاق **لا يُبنى
       تعارضهما على عمومهما**، وإلا صار كل سطرين «متعارضين».

    ⚠️ **وحدّ الدالّة يُقال:** هي تقارن **نصّين**، فلا تعرف أن نصّين
    مختلفَي اللفظ يقولان الحكم نفسه، ولا أنهما يتناقضان تحت موضوعين مختلفين.
    فسكوتها **ليس شهادة اتفاق**، وهي **دعوة إلى النظر** لا حكمٌ بتعارض.

    ⚠️ **والناتج مرتَّب بالمفاتيح**، فالسجلّ نفسه يُعطي القائمة نفسها دائماً
    — والفحص يقارن نصّاً لا ترتيباً عارضاً.

    >>> conflicts(SHIPPED)
    ()

    Args:
        rule_set: السجلّ، أو ``None`` للجدول المشحون.

    Returns:
        أزواج المفاتيح المتعارضة ``(أ، ب)``، مرتَّبة، وبلا تكرار.
    """
    rules = _registry(rule_set).rules
    found: set[tuple[str, str]] = set()
    # ⚠️ **والزوجان يُعدّان بـ``combinations`` لا بفهرسين،** فـ``[index + 1:]``
    # رقمٌ في سطر شرط لا يُعرف سببه، و«واحد» فيه تعني «التالي» — والمعنى
    # مكتوب في اسم الدالّة خيراً من رقم. ثم إن ``combinations`` **لا تُنتج
    # الزوج مع نفسه** ولا تكرّر الزوج مرّتين، فيسقط حرسان من الجدول.
    for first, second in combinations(rules, _PAIR):
        if first.key == second.key:
            continue
        if first.family is not second.family:
            continue
        if first.scope_key != second.scope_key:
            continue
        if not _shares_scope(first, second):
            continue
        if first.statement.strip() == second.statement.strip():
            continue
        low, high = sorted((first.key, second.key))
        found.add((low, high))
    return tuple(sorted(found))


def must_review(rule_set: Optional[RuleSet] = None, as_of: str = "") -> tuple[Rule, ...]:
    """
    ما يجب أن ينظر فيه المحامي **قبل الاعتماد** — لا ما هو خاطئ بالضرورة.

    ⚠️ **وقائمتان، وسببهما مختلف:**

    ١. **حكم موضوعي بلا مصدر** — لا يستطيع المحامي أن يتحقّق منه، فيصير
       **رأياً يتنكّر في هيئة مرجع**. والعائلة الموضوعية هي التي توجب المصدر
       للأسباب المكتوبة فوق ``VERIFICATION_RULES``.
    ٢. **قاعدة حلّ محلّها غيرُها** — وهي التي **انتهت نافذتها**. وموضع
       الدلالة حقل ``supersedes``: التاريخ الذي نثق به هو **تاريخ نفاذ
       اللاحق** لا تاريخ موت السابق، فلا نكتب تاريخ انتهاء لا نعرفه. فإن
       أُعطي ``as_of`` اشترطنا أن يكون اللاحق **نافذاً في ذلك التاريخ**؛
       وإن لم يُعطَ كفى أن اللاحق في السجلّ. والخلط بين «حُلّ محلّه» و«لم
       يُحلّ» هو بعينه الخطأ الذي أنتج الثمانية والعشرين في المئة: **قاعدة
       ملغاة تُقرأ سارية لأن لا شيء وسمها**.

    ⚠️ **والناتج بترتيب الجدول**، فلا يفترق ترتيب المراجعة عن ترتيب التحرير.

    ⚠️ **و``as_of`` الفارغ يعني «الآن»** — وهذا هو الموضع الوحيد في الملف
    الذي تُقرأ فيه ساعة النظام، لأن السؤال «ما أراجعه قبل الاعتماد
    **اليوم**؟» لا معنى له بلا تاريخ. وهو **قراءة لا كتابة**: لا يُحفظ ولا
    يُبَثّ.

    ⚠️ **وأسباب المراجعة تُشتقّ هنا ولا تُخزَّن في القاعدة**، لأن السبب لو
    خُزّن لأمكن أن يكذب عليها بعد تعديل الحقل الذي بُني عليه.

    >>> [rule.key for rule in must_review(SHIPPED) if rule.is_verification]
    []

    Args:
        rule_set: السجلّ، أو ``None`` للجدول المشحون.
        as_of: تاريخ النظر بصيغة ISO، أو ``""`` ليُقرأ من الساعة.

    Returns:
        القواعد الواجب مراجعتها، بترتيب الجدول.
    """
    rules = _registry(rule_set).rules
    when = _iso(as_of) if as_of.strip() else date.today()
    live = {
        rule.key
        for rule in rules
        if rule.in_force_from.strip() and _iso(rule.in_force_from) <= when
    }

    review: list[Rule] = []
    for rule in rules:
        no_source = rule.family is RuleFamily.SUBSTANTIVE and not rule.source.strip()
        superseded = any(key in live for key in rule.supersedes if key != rule.key)
        if no_source or superseded:
            review.append(rule)
    return tuple(review)


# ==============================================================================
# ٦. الفروق الأربعة — **قائمة تحقّق على الصياغة، لا رأي قانوني**
# ==============================================================================
#
# ⚠️⚠️ **اقرأ هذا قبل أن تعتمد نتيجة `check_distinctions` أو تنقل منها.**
#
# ما يفعله هذا القسم **مطابقة أنماط** على ألفاظ عربية وإنجليزية معلنة. وهو:
#
#   ✅ **قائمة تحقّق** تُسمّي **الصيغة** التي أنتجت العيب في هذا المشروع،
#      ليراها المحامي في موضعها.
#   ❌ **وليس رأياً قانونياً**، ولا يقول إنّ في المذكرة عيباً قانونياً.
#   ❌ **ولا يستقصي كل صور العيب** — وليس هذا عجزاً في التنفيذ بل حدّ في
#      الطريقة: العيب الذي يقع بلا هذه الألفاظ **لا يُمسَك هنا**، ولا يُدّعى
#      أنه أُمسك.
#
# **والتفريق مقصود:** «وجدنا هذه العبارة» شيء، و«هذه المذكرة تخلط الاستحقاق
# بالمقدار» شيء آخر. الأول يُقاس، والثاني حكم. فالناتج يُقرأ **دعوةً إلى
# النظر** لا نتيجة.
#
# ⚠️ **والصيغ التي يُمسكها الملف ثلاث حالات فقط، لا كل حالات الخلط:**
#
#   ١. **ذكرُ الطرفين في مقطع واحد بلا فاصل يفصلهما** — فالصياغة التي
#      تذكر «آخر يوم عمل» و«انتهاء العقد» معاً ولا تقول إنهما مختلفان
#      تُقرأ كأنهما شيء واحد.
#   ٢. **نفيٌ وإقرار معاً** — كأن يُنفى الاستحقاق ويُنازَع في المقدار في
#      العبارة نفسها، فهما في الصياغة قولٌ واحد.
#   ٣. **وصفُ حكمٍ متغيّر بلفظ الدوام** — كأن يُدّعى أن نصّاً تشريعياً لا
#      يتبدّل.
#
# **وما لا يُمسَك — ويُقال صراحةً حتى لا يُطمئن التقرير كذباً:** الخلط الذي
# يقع **بلا هذه الألفاظ** (بترتيب مذكرة كاملة، أو بحسابٍ يجري على أساس خاطئ
# بلا كلام، أو بحذف واقعة تفصل بين المفهومين). وهذه أوسع من الأنماط، ولذلك
# **لا يُغني الفحص عن قراءة المحامي**، ولا يجوز أن يُقرأ سكوته سلامةً.
#
# ⚠️ **والرصيد الأهمّ في هذا القسم هو ما لا يُطلقه:** الصياغة التي **تفصل**
# الطرفين — وهي الصياغة المطلوبة — لا تُنتج ملاحظة. ولذلك لكل فحص **علامات
# فصل** تُسقطه: «ليس»، «لا يُعدّ»، «بمعزل عن»، «أما»، «بينما»، «في مقابل»،
# «بخلاف»، «الفرق بين». وبها يمرّ النصّ الذي يقول «آخر يوم حضور ليس تاريخ
# انتهاء العقد» بلا ملاحظة، مع أنه يذكر الطرفين — لأن ذكرهما هنا **هو
# الفصل**، لا الخلط. واختبار يُثبّت ذلك على صيغ محرَّرة عديدة.
#
# ⚠️ **والثاني: القربُ شرط، لا مجرّد الورود.** فالعلامتان لا بدّ أن تقعا
# **متجاورتين** (في نافذة ``_PROXIMITY_CHARS``) — لأن ذكر الطرفين في صفحتين
# متباعدتين ليس خلطاً، والقول بأنه خلط يملأ التقرير بما ليس فيه. وهذا القرب
# هو **البيان** في اللغة: من نطق بالطرفين في نَفَس واحد وبلا فاصل بينهما،
# فقد قرّرهما قولاً واحداً.
#
# ⚠️ **ونطاق الفحص هو «الجملة المنطقية»: من فاصل نقطة إلى فاصل نقطة.** وأما
# الفاصلة والنقطة والفاصلة المنقوطة **فليست نهايات جملة**، بل مواضع تنفّس
# داخل الجملة — ولو قُطعت الجملة عندها لضاع الخلط في أشيَع صورة له: «آخر يوم
# عمل للمدعي هو كذا، وينتهي العقد في التاريخ نفسه»، وهي جملة واحدة في
# العربية وإن كُتبت فيها فاصلة.


class DistinctionKind(str, Enum):
    """
    الفروق الأربعة التي وُجد هذا الملف لفصلها.

    ⚠️ **وهي أربعة لا أكثر، لا لأن غيرها لا يقع، بل لأن هذه هي التي رصدتها
    المراجعات الثلاث على هذا المشروع.** ومن رصد خلطاً خامساً فليُضِفه
    بقاعدته وعلاماته، ولا يوسّع علامات قائمة حتى تفقد معناها.
    """

    #: آخر يوم حضور ≠ تاريخ انتهاء العقد.
    ATTENDANCE_VS_END = "attendance_vs_end"
    #: أجر الإجازة عن مدّة ≠ صرف رصيد الإجازة عند الانتهاء.
    LEAVE_DURING_VS_BALANCE = "leave_during_vs_balance"
    #: هل العمولة مستحقّة ≠ كم مقدارها.
    ENTITLEMENT_VS_QUANTUM = "entitlement_vs_quantum"
    #: قاعدة فحص عامّة ≠ حكم موضوعي يتبدّل بتغيّر التشريع.
    VERIFICATION_VS_SUBSTANTIVE = "verification_vs_substantive"


#: أسماء الفروق بالعربية — للعرض في التقرير.
DISTINCTION_LABELS: dict[DistinctionKind, str] = {
    DistinctionKind.ATTENDANCE_VS_END: "آخر يوم حضور ≠ تاريخ انتهاء العقد",
    DistinctionKind.LEAVE_DURING_VS_BALANCE: "أجر الإجازة عن مدّة ≠ صرف رصيد",
    DistinctionKind.ENTITLEMENT_VS_QUANTUM: "الاستحقاق ≠ المقدار",
    DistinctionKind.VERIFICATION_VS_SUBSTANTIVE: "فحصٌ عامّ ≠ حكم موضوعي",
}


@dataclass(frozen=True)
class DistinctionFinding:
    """
    ملاحظة واحدة على الصياغة: موضعٌ قد يكون فيه خلط، مع **الدليل المنقول**.

    Attributes:
        kind:   أيّ الفروق الأربعة. ومنه يُعرف **ما يُسأل عنه** النصّ.
        quote: **العبارة كما كُتبت** (بعد طيّ رسم الحروف) — بلا تحسين ولا
               اختصار يوهم. ووجودها شرط: ملاحظة بلا دليل منقول **لا
               تُراجَع**، لأن المحامي لا يعرف إلى أيّ عبارة أُشير.
        why:    لماذا أُطلقت الملاحظة — أيّ العلامتين التقت بأيّهما. وهو
               الحقل الذي يجعل الملاحظة **قابلة للردّ**: من رأى الخطأ في
               الفحص عرف أيّ علامة أزالت الصواب.

    ⚠️ **والملاحظة ليست حكماً:** هي «هذه العبارة تجمع الطرفين بلا فصل»،
    لا «هذه المذكرة خاطئة». والصياغة السليمة قد تجمع الطرفين وتفصلهما
    بعبارة لم تُدرَج في العلامات — فتُرفع الملاحظة ويُردّ عليها، وهذا
    مقصود: **قائمة التحقّق تُنتج نظراً، والنظر يُنتج ردّاً.**
    """

    kind: DistinctionKind
    quote: str
    why: str

    @property
    def label(self) -> str:
        """اسم الفرق بالعربية — للعرض."""
        return DISTINCTION_LABELS.get(self.kind, self.kind.value)


