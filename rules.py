# ٢. سطر القاعدة — والفحص في بنائه لا في انتباه قارئه
# ==============================================================================


@dataclass(frozen=True)
class Rule:
    """
    قاعدة واحدة: ما تحكمه، وفي أيّ نطاق، وما سندها، ومن أيّ تاريخ.

    Attributes:
        key:           معرّف آلي ثابت — هو ما يُنسب إلى الحصيلة، وما يُسأل به
                       في `for_key`، وما يُذكر في ``supersedes``.
        family:        العائلة من ``RuleFamily``. **وهي التي تُقرّر حكم
                       ``__post_init__`` على التاريخ.**
        subject:       **الموضوع الذي تحكمه القاعدة** — موضوع ``conflicts``.
                       والفراغ يُشتقّ من المفتاح (ما قبل أوّل نقطة)، فالمفتاح
                       ``leave.basis`` موضوعه ``leave``. ولماذا حقل صريح؟
                       لأن التعارض **لا يُدّعى إلا بين قاعدتين على الموضوع
                       نفسه**: «الاقتباس يُتبَّع» و«الواقعة تحمل مصدرها»
                       قاعدتان مختلفتان ولا تتعارضان، ولو قيل إنهما تتعارضان
                       لامتلأ التقرير بمزاعم كاذبة.
        applies_to:    أنواع النزاع التي تخصّها القاعدة. **والفراغ يعني: لا
                       تخصّ نوعاً بعينه**، فتسري على كل الأنواع — ولا يعني
                       «لا تسري على شيء».
        stages:        مراحل التقاضي التي تسري فيها. **والفراغ يعني: كل
                       المراحل.**
        statement:     نصّ القاعدة، سطر أو سطران بالعربية — وهو ما يُعرض على
                       المحامي، وما يقارنه `conflicts`.
        source:        مصدر القاعدة: **اسم الوحدة أو الفحص الذي ينفّذها** في
                       قواعد الفحص، و**سند الحكم** في الأحكام الموضوعية.
                       و``""`` **مسموح للفحص وممنوع للموضوعي** — والفراغ في
                       الموضوعي **يُدرَج في قائمة المراجعة** (`must_review`)
                       ولا يمرّ صامتاً.
        in_force_from: تاريخ بدء النفاذ بصيغة ``DATE_FORMAT``. **ممنوع على
                       قواعد الفحص، ولازم للأحكام الموضوعية.** والفراغ يعني
                       «لا تاريخ له، فيسري دائماً» — وهو معنى الفحص وحده.
        supersedes:    مفاتيح قواعد حلّت هذه القاعدة محلّها. **وهو ما يجعل
                       «انتهت نافذتها» قابلاً للاستنتاج** في `must_review`
                       بلا أن نكتب تاريخ انتهاء لا نعرفه: التاريخ الذي نثق به
                       هو تاريخ **نفاذ اللاحق**، لا تاريخ موت السابق.
        note:          ملاحظة تحريرية للمحامي — ليست نصّ القاعدة.

    ⚠️ **والحقوق ثابتة (``frozen``):** القاعدة لا تُعدَّل بعد إنشائها، فلا
    تتبدّل قاعدة **أثناء تشغيل** بين مسار يقرأها ومسار يعتمد عليها. وهذا هو
    نفس الدرس المكتوب في `Rule` في `labour_rules.py`: الخطأ الذي يعيش في
    الذاكرة لا يُراجَع، والذي في الجدول يُراجَع.
    """

    key: str
    family: RuleFamily
    subject: str = ""
    applies_to: tuple[DisputeType, ...] = ()
    stages: tuple[CaseStage, ...] = ()
    statement: str = ""
    source: str = ""
    in_force_from: str = ""
    supersedes: tuple[str, ...] = ()
    note: str = ""

    def __post_init__(self) -> None:
        """
        ⚠️ **حرسان، وكلّها ترفع استثناءً في البناء لا في القراءة.**

        وموضع الحرس **هنا** مقصود: قاعدةٌ فاسدة **لا تُبنى أصلاً**، فلا تصل
        إلى جدول، ولا إلى حصيلة، ولا إلى مذكورة. أما حرسٌ يُنادى عند العرض
        فيترك القاعدة الفاسدة تعيش في المنظومة إلى أن يقرأها أحد.

        Raises:
            ValueError: إن كان المفتاح أو النصّ فارغاً، أو العائلة غير
                معروفة، أو كان تاريخ النفاذ بصيغة غير ISO، أو **خالف وجودُ
                التاريخ عائلةَ القاعدة**.
        """
        if not self.key.strip():
            raise ValueError(
                "مفتاح القاعدة فارغ — والقاعدة بلا مفتاح لا تُسأل بالاسم، ولا "
                "تُذكر في `supersedes`، ولا يظهر تعارضها."
            )
        if not self.statement.strip():
            raise ValueError(
                f"نصّ القاعدة «{self.key}» فارغ — والقاعدة بلا نصّ سطرٌ لا يُقرأ."
            )
        if not isinstance(self.family, RuleFamily):
            raise ValueError(
                f"عائلة غير معروفة: {self.family!r}. والعائلة من `RuleFamily` "
                f"وحدها، فلا تُوصف قاعدة بنصّ حرّ."
            )

        # ⚠️⚠️ **وهذا هو الحرس الذي يقوم عليه الملف كله — فاقرأه قبل أن
        # تُخفّفه، فهو موضع الثمانية والعشرين في المئة.**
        #
        # قاعدة الفحص **لا تحمل تاريخ نفاذ**، لأن التاريخ المكتوب عليها
        # **يدعو قارئها إلى الظنّ بأنها ستُراجَع**: من رأى «سارية من ٢٠٢٤-٠١-٠١»
        # على فحصٍ يتفهّم أنه صار قديماً — وهو لا يتبدّل أصلاً، فلا معنى
        # للتاريخ ولا لانتظار المراجعة. والفحص المؤرَّخ أسوأ من الفحص المطلق:
        # يبدو مؤقّتاً فيُهمَل، أو يبدو مُراجَعاً فيُعتمد.
        #
        # والحكم الموضوعي **لا يوجد بلا تاريخ نفاذ**، لأن الحكم الذي لا تاريخ
        # له **يصير قانوناً ملغى يبدو سارياً**. وهذا بعينه ما أنتج الخطأ:
        # صيغة ملغاة بقيت في السجلّ بلا سؤال «من أيّ تاريخ تسري؟» — فحُسبت
        # على أنها النافذة، ونقصت المكافأة نحو الثمانية والعشرين في المئة.
        #
        # فالحرس واحد على الشرطين لا حرسان: القاعدة **إمّا فحص بلا تاريخ،
        # وإمّا حكم بتاريخ**، ولا ثالث بينهما. وهذا هو ما يجعل الخلط مستحيلاً
        # في البناء لا موكولاً إلى انتباه الكاتب.
        has_date = bool(self.in_force_from.strip())
        if has_date != (self.family is RuleFamily.SUBSTANTIVE):
            if has_date:
                raise ValueError(
                    f"قاعدة فحص بتاريخ نفاذ: «{self.key}». والفحص لا يتبدّل "
                    f"إذا تبدّل التشريع، فالتاريخ عليه يوهم بأنه سيُراجَع — "
                    f"إمّا فيُهمَل لأنه يبدو مؤقّتاً، وإمّا يُعتمد لأنه يبدو "
                    f"مُراجَعاً. انزع `in_force_from`، أو اجعل العائلة "
                    f"`SUBSTANTIVE` إن كان حكماً يتبدّل."
                )
            raise ValueError(
                f"حكم موضوعي بلا تاريخ نفاذ: «{self.key}». والحكم الذي لا "
                f"تاريخ له **يصير قانوناً ملغى يبدو سارياً** — وهذا أصل الخطأ "
                f"الذي بلغ ثمانية وعشرين في المئة في احتساب المكافأة. فإمّا "
                f"تاريخ نفاذ بصيغة {DATE_FORMAT}، وإمّا تصنيفه فحصاً إن كان "
                f"لا يتبدّل إذا تبدّل التشريع."
            )

        if has_date:
            self._require_iso_date()

    def _require_iso_date(self) -> None:
        """
        التاريخ بصيغة ISO — وإلا رُفض في البناء.

        ⚠️ **والرفض هنا مقصود وإن بدا صرامةً شكلية:** تاريخ النفاذ هو الحقل
        الذي **تُقارَن به الوقائع** في `applicable`. ولو قُبل نصّاً حرّاً
        («مارس ٢٠٢٤»، «٢٠٢٤/٣/١») لصار الحقل الذي يقوم عليه الفصل **غير قابل
        للمقارنة**، فتمرّ قاعدة ملغاة لأن تاريخها لم يُفهَم — وهو العيب نفسه
        بثوب آخر.

        Raises:
            ValueError: إن لم يكن النصّ تاريخاً بصيغة ISO صحيحة.
        """
        try:
            date.fromisoformat(self.in_force_from.strip())
        except (TypeError, ValueError) as exc:
            raise ValueError(
                f"تاريخ نفاذ غير صالح في «{self.key}»: {self.in_force_from!r}. "
                f"والصيغة المعتمدة {DATE_FORMAT}، لأن هذا الحقل يُقارَن "
                f"بالوقائع ولا يُقرأ للعرض وحده."
            ) from exc

    @property
    def family_label(self) -> str:
        """
        اسم العائلة بالعربية — للعرض في الحصيلة والتقرير.

        >>> RuleFamily.VERIFICATION.value
        'verification'
        """
        return FAMILY_LABELS.get(self.family, self.family.value)

    @property
    def is_verification(self) -> bool:
        """
        هل هي قاعدة فحص؟ — السؤال يُسأل في موضع واحد.

        >>> VERIFICATION_RULES[0].is_verification
        True
        """
        return self.family is RuleFamily.VERIFICATION

    @property
    def scope_key(self) -> str:
        """
        الموضوع الذي يُقارَن به — الحقل الصريح، أو ما قبل أوّل نقطة من المفتاح.

        ⚠️ **والاشتقاق لا يُخزَّن في الحقل**، فلا يفترق ما في ``subject`` عمّا
        في ``key`` بعد تعديل أحدهما.

        >>> Rule(key="leave.basis", family=RuleFamily.VERIFICATION, statement="س").scope_key
        'leave'
        """
        return self.subject.strip() or _namespace(self.key)

    def applies_on(self, on_date: str = "") -> bool:
        """
        هل تسري هذه القاعدة على تاريخ الوقائع المعطى؟

        ⚠️ **والقاعدة التي لا تاريخ لها تسري دائماً** — وهذا معنى قواعد
        الفحص. وأما التي لها تاريخ فلا تسري قبل نفاذه.

        ⚠️ **و``on_date`` الفارغ يعني «لم يُعطَ تاريخ»**، فلا تسري القاعدة
        المؤرَّخة. وهذا **قرار مقصود**: مطابقة قاعدة لم يُعرف تاريخ نفاذها
        بالوقائع **تُدخل حكماً بلا سؤال «هل كان سارياً؟»**، وهو الخلط نفسه
        الذي جاء الملف لمنعه. فالجهل بالتاريخ **يُقلّل** ما يسري، ولا يزيد.

        >>> VERIFICATION_RULES[0].applies_on()
        True
        """
        if not self.in_force_from.strip():
            return True
        if not on_date.strip():
            return False
        return _iso(on_date) >= _iso(self.in_force_from)


def _iso(value: str) -> date:
    """
    يقرأ تاريخاً بصيغة ISO — والخطأ هنا **خطأ مستدعٍ** لا قاعدة فاسدة.

    ⚠️ والفرق بين الحالين مقصود: تاريخ القاعدة فُحص في البناء، فأي خطأ فيه
    عطب في الجدول. وأما تاريخ **الاستعلام** فيأتي من مسار آخر، فرفضه برسالة
    صريحة أهون من مقارنة نصّية صامتة تُنتج ترتيباً خاطئاً.

    Raises:
        ValueError: إن لم يكن النصّ تاريخاً بصيغة ISO.
    """
    try:
        return date.fromisoformat(value.strip())
    except (TypeError, ValueError) as exc:
        raise ValueError(
            f"تاريخ غير صالح: {value!r}. والصيغة المعتمدة {DATE_FORMAT} — "
            f"والمقارنة تجري على تواريخ لا على نصوص."
        ) from exc


