"""
سجلّ القواعد المتخصّصة — **قاعدتان لا تُخلطان: ما يُفحص، وما يتغيّر بتغيّر التشريع.**
================================================================================

المشكلة التي يحلّها
------------------
ثلاث مراجعات قانونية مستقلّة لمذكرات هذا المشروع رصدت أن الصياغة **تخلط أربعة
أزواج** من الأشياء التي تختلف قانوناً، وطلبت إحدى المراجعات فصلها صراحةً:

١. **آخر يوم حضور** ≠ **تاريخ انتهاء العقد.** يفترقان حين يُعفى العامل من
   الحضور خلال مدّة الإشعار، والفرق **يغيّر ما هو واجب**: العقد يبقى قائماً
   مدّةً قد لا يعمل فيها العامل.

٢. **أجر الإجازة خلال الخدمة** ≠ **الرصيد المتراكم المدفوع عند الانتهاء.**
   الأوّل **أجر عن مدّة**، والثاني **صرف رصيد**. فالأساس مختلف والحساب
   مختلف، وجمعهما في حساب واحد أنتج **رقماً خاطئاً**.
٣. **هل العمولة مستحقّة** ≠ **كم مقدارها**. وقد عبّرت إحدى المراجعات عن ذلك
   بدقّة: صياغة هذا المشروع **دمجت الاستحقاق بالمقدار** — فسقط الدفع الجزئي
   في الوسط: من ينازع في المقدار يبدو كأنه ينكر الاستحقاق، ومن يقرّ
   بالاستحقاق يبدو كأنه سلّم بالمقدار. **والبابان بابان.**

٤. **قاعدة فحص عامّة** ≠ **حكم موضوعي يتغيّر بتغيّر التشريع.** الأولى موضعها
   الفحوص ولا يُشترط لها تاريخ، والثاني **يجب أن يحمل تاريخاً ومصدراً**، ولا
   يجوز أن يُكتب في الكود حيث لا يُراجَع، فهما **مستقلّان**.
   **والثاني والثالث مفهومان، لا يُقاس أحدهما بالآخر.**

والهدف يقولها في سطر واحد: **لا تُثبَّت القواعد كلها في مطلب واحد طويل؛ افصل
قواعد التحقّق العامّة عن الأحكام الموضوعية التي تتغيّر بتغيّر التشريع.**

⚠️ **والعيب الذي دُفع ثمنه — وهو سبب وجود هذا الملف**
----------------------------------------------------
خطأ في احتساب مكافأة نهاية الخدمة بلغ **ثمانية وعشرين في المئة**، وأصله أن
قاعدةً **موضوعية ملغاة** بقيت في موضع تُقرأ فيه كأنها **فحصٌ لا يُراجَع**:
صيغة القانون القديم كُتبت حيث لا يُسأل «هل ما زالت سارية؟». والخطأ لم يكن في
المعرفة بل في **المكان**: حكمٌ متغيّر وُضع في طبقة ثابتة، فلا شيء في المنظومة
كان يُبلّغ بتغيّره.

فالعلاج بنيويّ لا أخلاقي: **الفصل بين العائلتين في النوع نفسه**، حتى يصير
الخلط **مستحيلاً في البناء** لا موكولاً إلى انتباه الكاتب.

المبدأ التصميمي — على نمط `citations.py` و`labour_rules.py` و`deadlines.py`
--------------------------------------------------------------------------
> **النموذج يروي، والخادم يُقرّر.** وكل ما يمكن فحصه بقاعدة ثابتة لا يُترك
> لنموذج يفحص.

فالملف **بيانات وفحص**، لا حكم:

* **العائلتان مغلقتان** (`RuleFamily`): قيمة ``VERIFICATION`` لا تحمل تاريخ
  نفاذ، وقيمة ``SUBSTANTIVE`` لا تُبنى بلا تاريخ. والخلط **يرفع استثناءً عند
  البناء**.
* **الجدول المشحون فحوصٌ وحدها** (`VERIFICATION_RULES`): ولا حكم موضوعي واحد
  فيه، ولا رقم مادة واحد — والاختبار يفحص الأمرين على النصّ لا على النوايا.
* **الاستعلام دوالّ نقية** (`applicable`، `for_key`، `conflicts`،
  `must_review`): بلا حالة، وبلا إدخال/إخراج، وبلا شبكة، وبلا طبع.
* **الفحص النصّي قائمة تحقّق** (`check_distinctions`): يُسمّي **الصيغة** التي
  أنتجت العيب، لا العيب نفسه — والفرق بينهما مكتوب في موضعه أدناه.

⚠️ **وحدّان صريحان، وهما أهمّ ما في الملف**
------------------------------------------
**الأول: هذا السجلّ ليس بياناً بالقانون، ولا يزعم أنه استقصى أحكام الإمارات.**
والجدول **فارغ من الأحكام الموضوعية عن قصد**: لا تُكتب هنا قاعدةٌ تتغيّر، لأن
القاعدة المكتوبة في الكود **تصير خطأً في اللحظة التي يتغيّر فيها النصّ، ولا
شيء في المنظومة يُبلّغ بذلك** — تُعدَّل المادة، ويبقى السجلّ يقول القديم،
فيُمضى به إلى المذكرة **بثقة**، والثقة أسوأ من الجهل لأن الجهل يوقف الكاتب.

**والثاني: الحكم الموضوعي يُدخله المحامي بمصدره وتاريخه، ولا يُخترع هنا.**
فما يُشحن اليوم هو **قواعد هذا المشروع على نفسه** — أن يُسند كل اقتباس إلى
مقطع مسترجع، وأن تحمل كل واقعة مصدرها ودرجتها، وأن يُظهر كل حساب أساسه
ومدخلاته. وهذه **لا تسقط إذا تبدّل التشريع**، فهي العائلة الثابتة، وهي
وحدها المشحونة.

الملف بلا تبعية خارجية: مكتبة بايثون القياسية وحدها (`dataclasses`، `enum`،
`datetime`، `re`، `typing`)، ومعها وحدتان من هذا المشروع: `case_file`
**لأن ``DisputeType`` و``CaseStage`` تُعاد استعمالاً ولا تُكرَّر** — ونسخة
ثانية منهما تنحرف عن الأولى بصمت عند أوّل تعديل عليها؛ و`citations`
**لأن أرقام المواد موضع واحد في المشروع**، وفحصها هنا بفحصٍ آخر يُنتج حكمين
لنصّ واحد.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from datetime import date
from enum import Enum
from itertools import combinations
from typing import Iterable, Optional, Sequence

# ⚠️ **والاستيرادان مقصودان، وليسا تبعية جديدة.**
