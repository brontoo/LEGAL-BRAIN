class RuleFamily(str, Enum):
    """
    عائلة القاعدة — **وهي أوّل سؤال يُسأل عن كل سطر في السجلّ.**

    ⚠️ **والسؤال ليس تنظيمياً بل عمليّ:** «هل تتبدّل هذه القاعدة إذا تبدّل
    التشريع؟» فإن كانت لا تتبدّل فهي **فحص**، موضعها طبقة الفحوص ولا تاريخ
    لها؛ وإن كانت تتبدّل فهي **حكم موضوعي**، ولا يجوز أن توجد بلا مصدر
    وتاريخ نفاذ.

    ولماذا `Enum` لا نصّ؟ لأن العيب الذي جاء هذا الملف لمنعه كان **وضع حكم
    متغيّر في موضع فحص**. ولو كان الوصف نصّاً حرّاً لما أمكن فحصه، ولا اكتشف
    أحد أن حكماً موضوعياً سُجّل على أنه فحص. أما كونه قيمةً من مغلقتين فيصير
    الخلط **قابلاً للرفض في البناء**، على نفس ما فُعل بـ ``WAGE_BASIS_*`` في
    `labour_rules.py` و``DayCount`` في `deadlines.py`.
    """

    #: قواعد فحص ثابتة — لا تتغيّر بتغيّر التشريع.
    VERIFICATION = "verification"
    #: أحكام موضوعية — تتغيّر، ولكلٍّ مصدره وتاريخه.
    SUBSTANTIVE = "substantive"


#: أسماء العائلتين بالعربية — للعرض على المحامي، ولا يُحسب بها.
FAMILY_LABELS: dict[RuleFamily, str] = {
    RuleFamily.VERIFICATION: "فحصٌ عامّ على الوثيقة",
    RuleFamily.SUBSTANTIVE: "حكمٌ موضوعي يتغيّر بتغيّر التشريع",
}

#: صيغة التاريخ المعتمدة: **ISO** (``YYYY-MM-DD``).
#:
#: ⚠️ وصيغة واحدة لا صيغتان، لأن تاريخ النفاذ يُقارَن ويُفرز ويُطبَع، والنصّ
#: الحرّ («مارس ٢٠٢٤»، «١/٣/٢٠٢٤») لا يُقارَن بأداة. ومن كتب تاريخاً بصيغة
#: أخرى **يرفع استثناءً عند البناء** ولا يمرّ صامتاً.
DATE_FORMAT = "ISO-8601 (YYYY-MM-DD)"

#: ⚠️ **وثلاثة أرقام مسمّاة، لأن الرقم في سطر شرط سقفٌ لا يُعرف سببه.**
#:
#: * ``_NAMESPACE_SEPARATOR`` و``_FIRST``: فضاء المفتاح هو ما قبل أوّل نقطة —
#:   وهو **الموضوع الضمني** لقاعدة لم تُصرّح بموضوعها (``scope_key``).
#: * ``_PAIR``: عدد أطراف الزوج في `conflicts`. وهو **مطلوب في بايثون 3.14**
#:   ولا افتراض له، وسمّيته لأن «٢» عائمةً في سطر نداء لا يُعرف معناها.
_NAMESPACE_SEPARATOR = "."
_FIRST = 0
_PAIR = 2


def _namespace(key: str) -> str:
    """
    فضاء المفتاح: ما قبل أوّل نقطة — وهو **الموضوع الضمني** للقاعدة.

    ⚠️ **والمفتاح بلا نقطة فضاءُه نفسه**، لأنه موضوعٌ قائم بذاته (``leave``
    موضوع، لا بادئةً لموضوع). والفراغ يبقى فراغاً، فلا يُخترع له موضوع.

    >>> _namespace("leave.basis")
    'leave'
    >>> _namespace("leave")
    'leave'
    >>> _namespace("")
    ''
    """
    return key.split(_NAMESPACE_SEPARATOR)[_FIRST].strip()


