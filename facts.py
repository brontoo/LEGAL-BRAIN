@dataclass(frozen=True)
class Fact:
    """
    واقعة واحدة **مسجَّلة**: نصّها، ودرجتها، ومصدرها، والنصّ الذي تستند إليه.

    Attributes:
        key:      معرّف آلي ثابت. ⚠️ **وهو ليس تسمية للعرض**: به تُنادى
                  الواقعة (`of_key`) وبه تُقارَن المقارنة الرخيصة في
                  `check_fidelity`. فمفتاحٌ يتغيّر بتغيّر الصياغة يُفقد
                  المقارنة أساسها.
        statement: الواقعة بالعربية — جملةً واحدة، بلا حشو ولا مقدّمة.
        source:   اسم المستند الذي جاءت منه.
        locus:    الموضع: صفحة أو بند أو فقرة.
        date:     تاريخ الواقعة، أو ``""`` إن لم يكن لها تاريخ.
        asserted_by: من يتمسّك بها (الموكّل، الخصم، شاهد، مستند).
        standing: درجتها من ``Standing``.
        quote:    **النصّ الذي تستند إليه، حرفياً**، أو ``""`` إن لم تستند إلى
                  نصّ. ⚠️ وحضوره هو الفرق بين واقعة تُقارَن بواقعة تُصدَّق:
                  نصٌّ حرفيّ يمكن أن يُقابَل بالمستند، والمعنى المنقول لا
                  يُقابَل بشيء. ولذلك يعدّ `unquoted()` ما لا نصّ له.
        subject:  **موضوع الواقعة** — ما تُسأل عنه، مثل «مصير المخالصة». وبه
                  تُقرَن الوقائع المتناقضة في `conflicts()`. وإن لم يُذكر فمن
                  المفتاح يُستنبط (ما قبل الفاصلة ``.``).
        version:  نسخة المستند إن كان لواقعةٍ أكثر من نسخة (توقيع، تاريخ،
                  ختم). ويُستعمل في `version_conflicts()`.

    ⚠️ **والواقعة المجرّدة من نصّها ودرجتها ليست واقعة في هذا الملف.** فالحقول
    ليست زينة: `source` و`locus` يجعلان المراجعة ممكنة، و`standing` يمنع
    الادعاء من أن يُقرأ ثابتاً، و`quote` يجعل المقارنة ممكنة. وهذا هو الفرق
    بين سجلّ وقائع ونصّ عابر.
    """

    key: str
    statement: str
    source: str
    locus: str
    date: str
    asserted_by: str
    standing: Standing
    quote: str = ""
    subject: str = ""
    version: str = ""

    @property
    def effective_subject(self) -> str:
        """
        الموضوع الذي تُقرَن به الواقعة: المعلن، أو ما قبل الفاصلة في المفتاح.

        والاستنباط **يقع على المفتاح المطبَّع**، لأن المفاتيح تكتب
        ``release.refused`` و``Release-Refused``، ولو قارنّاها على الرسم
        لصارت موضوعين.

        >>> _the_release_fact().effective_subject
        'release'
        """
        if self.subject.strip():
            return normalize(self.subject)
        return _subject_of(self.key)

    @property
    def is_quoted(self) -> bool:
        """هل تستند الواقعة إلى نصّ حرفي؟"""
        return bool(self.quote.strip())

    @property
    def standing_label(self) -> str:
        """اسم الدرجة بالعربية — للعرض."""
        return STANDING_LABELS.get(self.standing.value, self.standing.value)


@dataclass(frozen=True)
class FactVersion:
    """
    نسخةٌ من مستندٍ يُوجد منه أكثر من نسخة — والخلاف ليس في النصّ بل **أيّها
    المعمول به**.

    Attributes:
        document:  اسم المستند.
        version:   رمز النسخة أو وصفها (``"مسودة"``، ``"موقّعة"``، ``"2"``).
        date:      تاريخها، أو ``""``.
        signed:    ``True`` موقّعة / ``False`` غير موقّعة / ``None`` **غير معروف**.
        implied:   هل يُستنتج من المسافات بين النسخ أن نسخةً قد تكون مفقودة.
        note:      ملاحظة عن هذه النسخة.

    ⚠️ **ولماذا حقل ``signed`` ثلاثيّ القيم؟** لأن ``False`` تقول «علمنا أنها
    غير موقّعة»، و``None`` تقول «لم يُنظر في التوقيع». والخلط بينهما يجعل
    تقرير المحامي **صحيحاً في الملف خاطئاً في الواقع**: نسخةٌ لم تُفحص تُعرض
    غير موقّعة، فيُبنى على ذلك ما لا يُبنى. والفرق بين «لا» و«لا أعرف» هو
    الفرق الذي يقوم عليه هذا الملف كله.
    """

    document: str
    version: str
    date: str = ""
    signed: bool | None = None
    implied: bool = False
    note: str = ""

    @property
    def signed_label(self) -> str:
        """
        التوقيع بالعربية: موقّعة / غير موقّعة / **لم يُفحص**.

        >>> FactVersion("مخالصة", "1").signed_label
        'التوقيع: لم يُفحص'
        """
        if self.signed is True:
            return "موقّعة"
        if self.signed is False:
            return "غير موقّعة"
        return "لم يُفحص"


@dataclass(frozen=True)
class VersionConflict:
    """
    مجموعة نسخٍ لمستند واحد — **ولا يُكتفى بذكر تعدّدها**.

    Attributes:
        document: اسم المستند.
        versions: النسخ كما سُجّلت.
        note:     سطر عربي يسمّي **النسخة المقترحة للعمل** وتاريخها وحال
                  توقيعها، أو يقول صريحاً ما الذي ينقص تحديده. ووُجد هذا
                  الحقل لأن تعدّد النسخ وحده **لا يفيد المحامي بشيء**: «للمخالصة
                  نسختان» معلومة تُقرأ ويُمضى. أما «النسخة الموقّعة المؤرّخة
                  كذا هي المعمول بها، ويُحتاج تحديد توقيع الأخرى» فسؤال يُجاب.
    """

    document: str
    versions: tuple[FactVersion, ...]
    note: str


@dataclass(frozen=True)
class FactShift:
    """
    موضعٌ **افترقت فيه المسودّة عن السجل** — وهو مخرَج الفحص الحاسم.

    Attributes:
        fact_key:  مفتاح الواقعة التي افترقت.
        kind:      ``"missing"`` (لم تُذكر) · ``"reworded"`` (أُعيدت بصياغة
                   تُغيّر المعنى) · ``"contradicted"`` (نُقضت).
        draft_text: النصّ الذي قابلناه من المسودّة (أو ``""`` إن لم يوجد).
        fact_statement: نصّ الواقعة من السجل — **يُعرض دائماً**، لأن الافتراق
                   لا يُفهم بلا الطرفين: «لم تُذكر» بلا نصّها لا تُراجَع.
        note:      سبب الافتراق بالأرقام: أيّ واجهة، وأيّ نسبة رموز، وعند أيّ
                   عتبة. ⚠️ والأرقام تُكتب لأن العتبات **عتبات**، والمحامي
                   يستحقّ أن يعرف هل الافتراق قريب من الحدّ أم بعيد عنه.
    """

    fact_key: str
    kind: str
    draft_text: str
    fact_statement: str
    note: str


