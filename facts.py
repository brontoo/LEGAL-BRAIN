#: **عتبة قبول إعادة الصياغة**: أدنى نسبة من رموز الواقعة تظهر في المسودّة.
#:
#: وهي معيار **غير متماثل عن قصد**: البسط رموز الواقعة الموجودة في نصّ
#: المسودّة، والمقام رموز الواقعة كلها. والسؤال الذي تجيب عنه: **«كم من
#: الواقعة وصل إلى المسودّة؟»** — وهو السؤال الصحيح هنا، لأن **الحذف** هو
#: العيب الأكثر وقوعاً: كلمة ``تنازلاً`` تسقط، أو ``التوقيع`` تُستبدل، فيبقى
#: من الواقعة نصفها ويكفي.
#:
#: ⚠️ **وعتبة ٠٫٢٠ أي خُمس رموز الواقعة** — والقيمة مضبوطة على **قياس
#: الواقعة التاريخية بالرموز لا على تقدير**: رموز واقعة ``release.refused``
#: سبعة، والمسودّة المعطوبة («رفض استلام المبلغ») تُبقي منها رمزين ⇒ تغطية
#: **٠٫٢٨٦**، وهي فوق العتبة فتُقرأ **إعادةَ صياغة** لا حذفاً. ورفعها فوق
#: ٠٫٢٨٦ كان يجعل العيب التاريخي يُوسم ``missing`` — والوسم لا يمنع الكشف،
#: لكنه **يُخفي أن الواقعة حاضرة محرّفة**، وهو الفرق الذي يقوم عليه هذا الملف:
#: الواقعة لم تسقط، بل قُلب **مَن عليه الخطأ**.
#:
#: ⚠️ ولا يُنزل بها كثيراً: الواقعة التي لا تشترك مع المسودّة في شيء تُعطي
#: **٠٫٠٠** فتبقى ``missing``. والعتبة تفصل «لم تُذكر أصلاً» من «ذُكرت أخرى
#: مكانها» — وهو الفصل الذي يجب أن يراه المحامي.
FIDELITY_ACCEPT_COVERAGE = 0.20

#: **عتبة التشابه الكامل**: فوقها، النصّان يقولا الشيء نفسه بالحرف تقريباً.
#:
#: وهي محسوبة بـ``|التقاطع| ÷ |الاتّحاد|`` (معامل جاكار). وهي **متماثلة** —
#: لا اتجاه فيها — لأنها تجيب سؤالاً آخر: «هل النصّان هما النصّ نفسه؟».
#: وتُستعمل **بعد** قبول التغطية، للتمييز بين **إعادة صياغة** و**استبدال**.
#:
#: ⚠️ **وهذا هو الموضع الذي تُنتج فيه المقارنة إنذارات كاذبة، وهو معروف
#: ومسجَّل هنا لا مخفيّ.** والقيمة ٠٫٧٥ مضبوطة على **قياسين مأخوذين من
#: الواقعة نفسها** لا على ذوق:
#:
#:   • المسودّة المعطوبة («رفض استلام المبلغ وقد أُرفق محضر الجلسة…»): تغطية
#:     **٠٫٢٨٦** ونسبة **٠٫١٢١** ⇒ دون ٠٫٧٥ ⇒ ``reworded``. ✔ **يُكشف.**
#:   • ومسودّة **أمينة** تحمل نصّ الواقعة كما هو مع زيادة مشروعة («وحيث إن …
#:     فلا يصحّ الاحتجاج عليه …»): تغطية **١٫٠٠** ونسبة **٠٫٣٨٩** ⇒ فوق
#:     ٠٫٧٥؟ **لا — دونها**، فتقع ``reworded``. ⚠️ وهذا هو **الإنذار الكاذب
#:     المعلن**: إضافة كلام حول الواقعة تُبعد النسبة، ولو كان النصّ أميناً
#:     حرفياً. ولا علاج له بلا نموذج يقيس المعنى — وهو مرفوض عن قصد لأن
#:     `check_fidelity` يجب أن يبقى حتمياً وبلا شبكة ليُختبر في كل تشغيل.
#:
#: فالخيار المعلن: أن يُنذر على الصياغة المشروعة، ولا يُمرّر تغيير **مادّي**
#: في رمز واحد. وإنذارٌ يُقرأ ويُتجاهَل أهون من واقعة مقلوبة تُسلَّم إلى
#: المحكمة. وموضع هذا الحدّ في التقارير: اختبار
#: ``test_a_faithful_restatement_is_not_a_contradiction`` يثبّت أن الأمين
#: **لا يُقرأ نقضاً** — وهو أخطر الأوسمة الثلاثة.
FIDELITY_REWORD_MAX_RATIO = 0.75

#: عدد الجمل المتلاصقة التي تُدمج في نافذة مقارنة واحدة.
#:
#: ⚠️ **و٢ لأن الدمج مضادّ**: يفيد حين يُقسم نصّ الواقعة على جملتين، ويضرّ
#: حين يقع في النافذة كلامٌ لا علاقة له بالواقعة (فتنخفض النسبة). والضرر
#: محدود لأن الدالّة تأخذ **أعلى** نسبة على الجمل المفردة والنوافذ المدمجة
#: معاً — فالجملة المفردة الجيدة تنجو ولو أوقع الدمج النافذة في كلام آخر.
#: ولو رُفع الرقم لصار الدمج نفسه مصدر إنذارات كاذبة.
FIDELITY_WINDOW = 2

