"""
سِجلّ الوقائع — الضمانة التي تجعل **تغيير واقعة** قابلاً للكشف.
=============================================================================

المشكلة التي يحلّها — وهي أخطر ما رُصد في هذا المشروع
---------------------------------------------------
واقعة واحدة **غُيِّرت**، فانقلب مَن عليه الخطأ:

    الموظف **رفض التوقيع على مخالصة متضمّنة تنازلاً**.
    فصارت في المذكرة: **رفض استلام المبلغ**.

والفرق ليس في الصياغة بل في **مَن عليه الخطأ**: الأول يمتنع عن تنازل،
والثاني يمتنع عن قبض حقّه. والواقعة الأولى تُبني عليها دعوى العامل، والثانية
تُهدَم بها. ⚠️ **وتكرّر العيب في ثلاث مسودّات متعاقبة** — أي أنه لم يكن سهواً
عابراً، بل نتيجة بنيوية.

وأصل العيب البنيوي
------------------
**الوقائع كانت تمرّ في المنظومة نثراً غير متمايز.** لا يُسجَّل لواقعة:
* من أين جاءت (`source`)،
* وفي أيّ موضع (`locus`)،
* وعلى أيّ نصّ تستند (`quote`)،
* **وهل هي متّفق عليها أم مجرّد ادعاء** (`standing`).

فلا شيء يستطيع أن يكتشف التغيير: المذكرة تقول «رفض استلام المبلغ»، والوقائع
لم تكن قد سُجّلت في صورةٍ تُقارَن بها، بل في نصّ يُقرأ من جديد في كل تشغيل.

الحلّ
-----
**واقعةٌ لم تُسجَّل بدرجتها ومصدرها ونصّها ليست واقعةً يمكن الدفاع عنها.**
فهذا الملف يُعطي الواقعة **هويّة** (`key`) و**درجة إثبات** (`standing`)
و**مصدراً** (`source`) و**نصّاً تستند إليه** (`quote`)، ثم يُقارن المسودّة
بالسجل مقارنةً حتمية (`check_fidelity`) تُعلن كل افتراق قبل التسليم.

المبدأ التصميمي — على نمط `citations.py` و`labour_rules.py`
-----------------------------------------------------------
> **النموذج يروي، والخادم يُقرّر.**

فـ`check_fidelity` **لا يستعمل نموذجاً ولا شبكة ولا قرصاً**: مقارنة رموز
حتمية. والسبب عملي لا أكاديمي: **الضمانة التي تعتمد على نداء نموذج لا يمكن
اختبارها**، وما لا يُختبر لا يُعوَّل عليه. ولو كان فحص الوقائع نفسه نموذجاً،
لكان الفحص عرضةً للعيب الذي يمنعه.

⚠️ **وحدّ هذا الفحص، وهو حدّ حقيقي لا يُخفى**
------------------------------------------
مقارنة الرموز **تُنتج إنذارات كاذبة على إعادة الصياغة**. «رفض التوقيع على
مخالصة متضمّنة تنازلاً» و«امتنع عن التوقيع على إقرار فيه تنازل» واقعةٌ واحدة
ورموزها مختلفة اختلافاً كبيراً. فالعتبات في هذا الملف (`FIDELITY_*`) هي
**أقلّ الشرور**: تُنذر على الصياغة المشروعة أحياناً، ولا تمرّر تغييراً
**مادّياً** أبداً. والإنذار الكاذب يُقرأ ويُتجاهل، أما الواقعة المقلوبة فتصل
إلى المحكمة. فالخطأ في الاتّجاه الآمن مقصود. وتفصيله في `check_fidelity`.

⚠️ **وقاعدة ثالثة، وهي التي تمنع العيب من أصله:** `CLIENT_STATEMENT_IS_NOT_PROOF`
و`OPPONENT_PLEADING_IS_NOT_EVIDENCE` — رواية الموكّل وادعاء الخصم تُسجَّلان
`CLAIMED` ولا تصيران `AGREED` أبداً. والسبب أن رواية الموكّل **صحيحة في نظر
صاحبها**، فإن مرّت `AGREED` فقد صارت في المذكرة حقيقةً مسلَّمة — وهي صورة
أخرى من العيب الأول: أن يُغيَّر **وزن** الواقعة لا نصّها.
"""

