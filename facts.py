def check_fidelity(draft: str, ledger: FactLedger) -> tuple[FactShift, ...]:
    """
    يواجه المسودّة بسجلّ الوقائع، ويُعيد كل **موضع افتراق** — حتمياً وبلا نموذج.

    والأنواع الثلاثة، ولكلٍّ شرطه المعلن:

    ``missing``
        لم يصل من الواقعة إلى المسودّة ما يكفي: أعلى تغطية دون
        ``FIDELITY_ACCEPT_COVERAGE``. أي أن الواقعة **لم تُذكر** — وهي أخطر
        الحالات، لأن الغياب لا يُقرأ: لا يرى المحامي في المسودّة ما يشير إلى
        أن شيئاً سقط منها.

    ``contradicted``
        النصّ المقابل **ينقض** الواقعة: نفيٌ في أحدهما دون الآخر، أو استبدالٌ
        مادّي في الموضع نفسه. والعيب التاريخي من هذا الباب: «رضي بالتوقيع» في
        مقابل «رفض التوقيع» — رمز واحد يقلب مَن عليه الخطأ.

    ``reworded``
        الواقعة **وصلت** (تغطية ≥ العتبة) لكنها أُعيدت صياغتها بما يُبعدها عن
        نصّها: نسبة التشابه دون ``FIDELITY_REWORD_MAX_RATIO``. وهذه الحالة هي
        التي تُنتج الإنذارات الكاذبة على الصياغة المشروعة — انظر شرح العتبات
        أعلاه، ففيه تصريح بالحدّ لا إخفاء له.

    ⚠️ **ولا يُستعمل نموذج ولا شبكة ولا قرص — وهذا شرط لا تحسين.** الفحص
    الذي يحتاج نداءً لا يُشغَّل في الاختبار، وما لا يُشغَّل لا يُعوَّل عليه.
    وقد دفع هذا المشروع ثمن «ضمانة» لا تُختبر: العيب نفسه تكرّر في ثلاث
    مسودّات، لأن لا شيء كان يفحصه.

    ⚠️ **وحدّان لا يُدَّعى خلافهما:**
      ١. التغطية والنسبة **تقريبٌ لا فهم**. النصّ الذي يُغيّر المعنى بمفردتين
         مترادفتين ظاهرياً («التوقيع» / «الاستلام») هو ما نبحث عنه، والنصّ
         الذي يُغيّر المعنى بإعادة صياغة كاملة يقع في ``missing`` أو
         ``reworded`` — وكلاهما **يُعرَض**، فالعيب لا يمرّ؛ وإنما يختلف وسمه.
      ٢. وهذا الفحص **ليس حكماً على صواب المسودّة القانوني**: هو يقول «هذا
         النصّ لا يقابل ذلك السجلّ»، لا «هذا النصّ خطأ». والحكم الثاني
         للمحامي.

    >>> shifts = check_fidelity(_flawed_draft(), _the_ledger())
    >>> [(s.fact_key, s.kind) for s in shifts]
    [('release.refused', 'reworded')]
    """
    shifts: list[FactShift] = []
    sentences = _sentences(draft)

    # نوافذ المقارنة: الجمل المفردة، والجمل المتلاصقة بعدد `FIDELITY_WINDOW`.
    windows: list[tuple[str, str]] = []
    for index in range(len(sentences)):
        windows.append((sentences[index], sentences[index]))
        upper = min(index + FIDELITY_WINDOW, len(sentences))
        if upper > index + 1:
            merged = " ".join(sentences[index:upper])
            windows.append((merged, sentences[index]))

    for fact in ledger.facts:
        fact_tokens = _fact_tokens(fact)
        if len(fact_tokens) < _MIN_STATEMENT_TOKENS:
            # واقعة من رمز واحد: المقارنة عليها عبث — تُترك للمحامي ولا تُوسم.
            continue

        best_coverage = 0.0
        best_ratio = 1.0
        best_span = ""
        best_shared = 0
        for window, report_span in windows:
            shared, coverage, ratio = _against(window, fact_tokens)
            if coverage > best_coverage or (
                coverage == best_coverage and ratio < best_ratio
            ):
                best_coverage, best_ratio = coverage, ratio
                best_span, best_shared = report_span, shared

        if best_coverage < FIDELITY_ACCEPT_COVERAGE:
            shifts.append(
                FactShift(
                    fact_key=fact.key,
                    kind="missing",
                    draft_text="",
                    fact_statement=fact.statement,
                    note=(
                        f"الواقعة لم تُذكر في المسودّة: أعلى تغطية "
                        f"{best_coverage:.3f} دون العتبة "
                        f"{FIDELITY_ACCEPT_COVERAGE:.2f} "
                        f"({best_shared} رمزاً مشتركاً من "
                        f"{len(fact_tokens)})."
                    ),
                )
            )
            continue

        # الواقعة وصلت. فالسؤال: هل وصلت محرَّفة؟
        draft_negated = _has_negation(best_span)
        fact_negated = _has_negation(fact.statement)
        if draft_negated != fact_negated:
            shifts.append(
                FactShift(
                    fact_key=fact.key,
                    kind="contradicted",
                    draft_text=best_span,
                    fact_statement=fact.statement,
                    note=(
                        "المسودّة تنقض الواقعة: النفي في أحدهما دون الآخر "
                        f"(تغطية {best_coverage:.3f} · نسبة {best_ratio:.3f}). "
                        "⚠️ وهذا موضع انقلاب المعنى: رمز نفي واحد يغيّر مَن "
                        "عليه الخطأ."
                    ),
                )
            )
            continue

        if best_ratio < FIDELITY_REWORD_MAX_RATIO:
            shifts.append(
                FactShift(
                    fact_key=fact.key,
                    kind="reworded",
                    draft_text=best_span,
                    fact_statement=fact.statement,
                    note=(
                        f"الواقعة أُعيدت صياغتها: نسبة {best_ratio:.3f} دون "
                        f"{FIDELITY_REWORD_MAX_RATIO:.2f} مع تغطية "
                        f"{best_coverage:.3f}. فالرموز المشتركة {best_shared} "
                        "والرموز التي تبدّلت هي موضع المراجعة — وقد تكون إعادة "
                        "صياغة مشروعة، فالوسم إنذار لا حكم."
                    ),
                )
            )

    return tuple(shifts)


