class FactLedger:
    """
    سجلّ وقائع القضية — **مجموعة لا حالة**.

    ⚠️ **ولماذا صنفٌ لا قائمة وقائع وحدها؟** لأن الأسئلة التي تُسأل عن الوقائع
    أسئلة متكرّرة (ما المتناقض؟ ما غير المحقَّق؟ ما بلا نصّ؟)، ولكلٍّ منها
    ترتيبٌ مقصود. ولو تُركت للاستدعاء المباشر لَتُكرّرت في كل مسار بنسخة،
    فتفترق النسخ عند أول تعديل — وهو التناقض الداخلي نفسه الذي رُصد في
    `labour_rules.py`.

    ⚠️ **والسجلّ لا يُرتّب وقائعه ولا يُصفّيها.** الترتيب ترتيب الإدخال، لأن
    الإدخال يجري على ترتيب قراءة المستندات، **وموضع الواقعة في السجلّ يهمّ**:
    الدوال التي تُرتّب (`needs_verification`) تُرتّب نتيجتها وحدها، ولا
    تُعيد ترتيب السجلّ نفسه. وهو الفرق بين عرضٍ مرتّب وبيانات مُشوَّشة.

    Args:
        facts: الوقائع، **بلا تكرار مفتاح**.
        versions: نسخ المستندات — للوثائق التي عُرفت لها أكثر من نسخة.

    Raises:
        ValueError: إن تكرّر مفتاح، أو كانت واقعة بلا مفتاح أو بلا نصّ
            مدّعى. ⚠️ والرفع مقصود: مفتاح مكرّر يعني أن وقعتين تتنازعان
            هويّةً واحدة، فيُسأل `of_key` عن أيّهما؟ ولا جواب. والسماح به
            يُنتج **سجلّاً يفترق عن نفسه**، وهو أسوأ من التوقّف.
    """

    def __init__(
        self,
        facts: tuple[Fact, ...] = (),
        versions: tuple[FactVersion, ...] = (),
    ) -> None:
        seen: set[str] = set()
        for fact in facts:
            if not fact.key.strip():
                raise ValueError("واقعة بلا مفتاح — لا تُعرَف ولا تُطالَب.")
            if fact.key in seen:
                raise ValueError(
                    f"مفتاح مكرّر في السجلّ: {fact.key!r} — وقائعتان بهويّة واحدة."
                )
            if not fact.statement.strip():
                raise ValueError(f"واقعة بلا نصّ: {fact.key!r}.")
            seen.add(fact.key)
        self._facts: tuple[Fact, ...] = tuple(facts)
        self._versions: tuple[FactVersion, ...] = tuple(versions)

    # --------------------------------------------------------------------------
    # ٣.١ القراءة
    # --------------------------------------------------------------------------

    @property
    def facts(self) -> tuple[Fact, ...]:
        """الوقائع بترتيب الإدخال — نسخةٌ لا تُعدَّل."""
        return self._facts

    @property
    def versions(self) -> tuple[FactVersion, ...]:
        """نسخ المستندات بترتيب الإدخال."""
        return self._versions

    def of_key(self, key: str) -> Fact | None:
        """
        الواقعة بمفتاحها، أو ``None``.

        و``None`` **جواب مقصود لا فشل**، على قاعدة ``rule_for`` في
        `labour_rules.py`: معناه «لا واقعة بهذا المفتاح في السجلّ» — وهو ما
        يجب أن يُقال صراحةً. ولو أعادت الدالّة واقعةً فارغة لأمكن أن يُبنى
        عليها كما يُبنى على المسجَّلة.

        >>> FactLedger((_the_release_fact(),)).of_key("release.refused").standing.value
        'claimed'
        >>> FactLedger((_the_release_fact(),)).of_key("nope") is None
        True
        """
        for fact in self._facts:
            if fact.key == key:
                return fact
        return None

    def by_standing(self, standing: Standing | str) -> tuple[Fact, ...]:
        """
        وقائع بدرجة واحدة — والدرجة تُقبل قيمةً أو نصّاً آلياً.

        وقبول النصّ الآلي مقصود لمسار البثّ: الواجهة تُرسل ``"claimed"`` لا
        كائناً. والقيمة الغريبة لا تُطابق شيئاً فتُعيد فراغاً — ولا تُخمَّن
        لها درجة.

        >>> len(FactLedger((_the_release_fact(),)).by_standing(Standing.CLAIMED))
        1
        >>> FactLedger((_the_release_fact(),)).by_standing("agreed")
        ()
        """
        wanted = standing.value if isinstance(standing, Standing) else str(standing)
        return tuple(fact for fact in self._facts if fact.standing.value == wanted)

    def keys(self) -> tuple[str, ...]:
        """المفاتيح بترتيب الإدخال — تُستعمل في العرض والمقارنة."""
        return tuple(fact.key for fact in self._facts)

    # --------------------------------------------------------------------------
    # ٣.٢ التناقض
    # --------------------------------------------------------------------------

    def conflicts(self) -> tuple[tuple[Fact, Fact], ...]:
        """
        أزواج الوقائع المتناقضة — **مقرونةً بموضوعها**.

        والقرن على `subject` لا على التشابه النصّي وحده، والسبب تجريبي: هذا
        السجلّ يحمل وقائع عن مصير المخالصة، وأخرى عن تاريخ انتهاء العلاقة،
        وأخرى عن مبلغ التسوية. ولو قرنّا بحسب التشابه النصّي لظهرت «تناقضات»
        بين وقائع لا علاقة بينها — «تأخّر عن السداد» و«تأخّر عن التوقيع» —
        وهي أبعد ما يكون عن التناقض. أما الموضوع فهو **ما تُسأل عنه الواقعة**،
        ولا يتناقض إلا ما اتّفق موضوعه.

        ⚠️ **والتناقض هنا لا يعني أن إحداهما كاذبة** — بل أن **إحداهما لا
        تصحّ مع الأخرى**. وقد يكون سببه أن إحداهما ادعاء الخصم والأخرى رواية
        الموكّل، وهذا **ليس عيباً بل صورة النزاع**: يُعرَض على المحامي ليعرف
        أنّ عليه أن يحسمه بدليل، لا ليعرف أنّ في السجلّ خطأً.

        ⚠️ **وشرط الدرجة الواحدة:** لا يُقرن `AGREED` بـ`INFERRED` ولا
        `CLAIMED` بـ`UNCERTAIN`، لأن اختلافهما ليس تناقضاً بل **اختلافاً في
        مصدر الواقعة** — وذانك بابان مختلفان. وشرطٌ زائد مقصود: التوسّع في
        التناقض يُنتج جداراً من الأزواج التي لا معنى لها، فيغرق التناقض
        الحقيقي فيه — وهو بعينه ما وقع في `language_audit.py`.

        >>> pairs = FactLedger(_conflicting_facts()).conflicts()
        >>> [(a.key, b.key) for a, b in pairs]
        [('release.signed', 'release.refused')]
        >>> FactLedger(_unrelated_facts()).conflicts()
        ()
        """
        by_subject: dict[str, list[Fact]] = {}
        for fact in self._facts:
            by_subject.setdefault(fact.effective_subject, []).append(fact)

        pairs: list[tuple[Fact, Fact]] = []
        for subject in by_subject:  # ترتيب الظهور محفوظ في بايثون
            group = by_subject[subject]
            for index, first in enumerate(group):
                for second in group[index + 1 :]:
                    if first.standing != second.standing:
                        continue
                    if _contradict(first, second):
                        pairs.append((first, second))
        return tuple(pairs)

    def version_conflicts(self) -> tuple[VersionConflict, ...]:
        """
        المستندات التي لها أكثر من نسخة — **مع تسمية النسخة المقترحة للعمل**.

        ⚠️ **ولماذا لا تُكتفى بذكر التعدّد؟** لأن «للمخالصة ثلاث نسخ» جملة
        تُقرأ ويُمضى. والمطلوب هو: **أيّها المعمول به؟ وتاريخها؟ وهل هي
        موقّعة؟** — فإن لم يُستطع تحديدها، قيل ذلك صراحةً، وحينها يعرف
        المحامي أن هذا **موضع يجب أن يُحسم قبل الكتابة** لا بعدها.

        والمقترح **ليس حكماً قانونياً**: هو أرجح النسخ من بين ما سُجّل (الموقّعة
        ثم الأحدث)، ويُعرض مع ما ينقصه (`signed is None` أو بلا تاريخ). فالترجيح
        يقع على **ما في السجلّ**، لا على القانون.

        ⚠️ **والتعدّد وحده لا يكفي، ولا يُذكر مستند بنسخة واحدة.** ولو ذُكر
        لصار التقرير ضجيجاً، والضجيج يُفقد التقرير قيمته.

        >>> notes = FactLedger(versions=_two_versions()).version_conflicts()
        >>> notes[0].document, notes[0].versions[1].signed
        ('مخالصة', True)
        """
        by_document: dict[str, list[FactVersion]] = {}
        for version in self._versions:
            by_document.setdefault(version.document, []).append(version)

        found: list[VersionConflict] = []
        for document, versions in by_document.items():
            if len(versions) < 2:
                continue
            found.append(
                VersionConflict(
                    document=document,
                    versions=tuple(versions),
                    note=_version_conflict_note(document, versions),
                )
            )
        return tuple(found)

    # --------------------------------------------------------------------------
    # ٣.٣ ما يجب أن يُراجَع
    # --------------------------------------------------------------------------

    def needs_verification(self) -> tuple[Fact, ...]:
        """
        الوقائع غير المحقَّقة — **والأسماء والأرقام والتواريخ والتوقيعات أولاً**.

        ⚠️ **ولماذا هذا الترتيب بالتحديد؟** لأن القراءة الآلية (OCR) تُخطئ في
        هذه الأربعة **خطأً قريباً من الصواب**: «أحمد» تُقرأ «أحمد» و«أحمد» في
        سياق آخر، و«٤٩٠» تُقرأ «٤٩٠» و«٤٩٠٠» بغياب صفر، و«٢٠٢٤» تُقرأ «٢٠٢٤»
        و«٢٠٢١» بذيل الرقم، والتوقيع **لا يُقرأ أصلاً** بل يُخمَّن وجوده.

        وهذا هو الفرق بين خطأ يُكشف وخطأ يمرّ: الخطأ في **معنى الجملة** يُقرأ
        فيُستغرب، والخطأ في **رقم أو اسم** يُقرأ فيُقبل — لأن الرقم لا يبدو
        خطأً في ذاته. فالمطالبة بالتحقّق تُقدَّم حيث لا يكشف الخطأ نفسه.

        ⚠️ **والترتيب على الإشارة في النصّ لا على نوع الحقل:** لا حقل «اسم» في
        ``Fact``، والقاعدة قائمة على ظهور ما يشير إليه (رقم، أو اسم علم، أو
        تاريخ، أو لفظ توقيع). وهذا **أوسع من اللازم عن قصد**: وسم واقعةٍ بأنها
        «تحتاج تحقّقاً» ليس خطأً يُخشى، بخلاف **إغفال** رقمٍ لم يُتحقَّق منه.

        >>> [f.key for f in FactLedger(_uncertain_facts()).needs_verification()]
        ['signature.status', 'note.text', 'end.date', 'salary.amount']
        """
        uncertain = [
            fact
            for fact in self._facts
            if fact.standing in (Standing.UNCERTAIN, Standing.DISPUTED)
        ]
        # الفرز مستقرّ، والمعيار الأول وسمُ الأولوية ثم رتبة إشارته، فما تساوت
        # رتبته بقي على ترتيب الإدخال. والوسم لا يُظهر الواقعة المؤكَّدة أولاً
        # — بل **يُقدّم موضع الخطر في غير المؤكَّدة**.
        return tuple(
            fact
            for _, fact in sorted(
                ((_verification_rank(fact), fact) for fact in uncertain),
                key=lambda item: (item[0][0], item[0][1], item[0][2]),
            )
        )

    def unquoted(self) -> tuple[Fact, ...]:
        """
        الوقائع التي **لا نصّ لها** — أي أُسندت بلا نصّ.

        ⚠️ وهذا ليس عيباً في كل حال: واقعةٌ مثل «تأخّر المستأجر عن السداد عن
        ثلاثة أشهر» قد تُستخلص من الحساب لا من عبارة. لكن **فحص**
        `citations.py` يقوم على اقتباس حرفي، والواقعة التي لا نصّ لها **لا
        تصلح أساساً لاقتباس**، فيُقال ذلك للمحامي قبل أن يُطلب منه اقتباس ما
        لا يوجد — وهو الطلب الذي يُنتج اقتباساً **مؤلَّفاً**، وهو أخطر من
        غياب الواقعة.

        >>> [f.key for f in FactLedger(_the_ledger_facts()).unquoted()]
        ['payment.refused']
        """
        return tuple(fact for fact in self._facts if not fact.is_quoted)


