def assert_system_does_not_agree(facts: tuple[Fact, ...]) -> None:
    """
    يرفع استثناءً إن أنشأ **النظام** واقعةً `AGREED`.

    ⚠️ **والفحص لا يفرّق بين مسار ومسار** (لا وسيط مصدر): لانّ الوسيط يُمرَّر
    خطأً، أولاً. والذي يُفرَّق به هو **الدرجة نفسها**: ما جاء من مسار آلي لا
    يُوسم `AGREED`، وما جاء من المحامي يوسمه هو في السجلّ اليدوي. فالحارس
    يمنع الحالة المستحيلة، ولا يدّعي أنه يعرف المصدر.

    Raises:
        SystemOverclaimError: إن وُجدت واقعة `AGREED` في ما أُدخل آلياً.

    >>> assert_system_does_not_agree((_the_release_fact(),))
    >>> from facts import Fact as _F
    >>> try:
    ...     assert_system_does_not_agree(
    ...         (_F("k", "ن", "م", "١", "", "المسار", Standing.AGREED),))
    ...     print("لم يرفع")
    ... except SystemOverclaimError:
    ...     print("رفع")
    رفع
    """
    for fact in facts:
        if fact.standing == Standing.AGREED:
            raise SystemOverclaimError(
                f"واقعة بدرجة `AGREED` في مسار آلي: {fact.key!r}. "
                + CLIENT_STATEMENT_IS_NOT_PROOF
            )


def stale_settlement_figure(fact: Fact) -> bool:
    """
    هل هذه الواقعة **مبلغ منقول عن تسوية سابقة** يُخشى أن يُقرأ احتساباً؟

    ⚠️ **وهذا العيب الرابع الذي رصدته المراجعات:** مسودّة قرّرت مبلغاً
    (١٢٥٠٠) وجاء من تسوية سابقة، لا من احتساب. وحدّ هذا الفحص معلن: هو
    **وسمٌ على الواقعة** لا على المسودّة، لأن المسودّة قد تنقل المبلغ نقلاً
    صحيحاً مشروعاً — والذي يجب أن يُمنع أن يُقرأ **محتسباً**.

    >>> stale_settlement_figure(_the_release_fact())
    False
    """
    haystack = normalize(f"{fact.statement} {fact.source} {fact.key}")
    return bool({"تسويه", "تسوية", "settlement", "settled"} & set(haystack.split()))


