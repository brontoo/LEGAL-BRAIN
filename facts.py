class Standing(str, Enum):
    """
    **درجة الواقعة**: على أيّ شيء تستند، وما وزنها في المذكرة.

    وهي الحقل الذي بحضوره يصير **تغيير وزن الواقعة** قابلاً للكشف، لا تغيير
    نصّها فقط. وترتيب القيم أدناه هو ترتيب **قوّة الإثبات** تنازلياً، وهو
    ترتيب العرض أيضاً.

    ⚠️ **والدرجات ليست تدرّجاً في الثقة، بل أنواع مختلفة من الحكم:**
    «متفق عليها» حكمٌ على موقف الخصم، و«استنتاج» حكمٌ على **مصدر الواقعة**
    (أنها من صنع المنظومة لا من نصّ)، و«غير محقّقة» حكمٌ على **القراءة**.
    فلا يُقاس بعضها إلى بعض («هل `INFERRED` أقوى من `DISPUTED`؟») — وهذا
    سؤال لا معنى له، ومن سأله فقد ظنّها سلّماً واحداً.
    """

    #: متفق عليها — لا ينازع فيها الخصم. ⚠️ ولا ينشئها النظام بنفسه: انظر
    #: `assert_system_does_not_agree`.
    AGREED = "agreed"
    #: ادعاء — يقوله طرف ولم يثبت. ورواية الموكّل وادعاء الخصم كلاهما هنا.
    CLAIMED = "claimed"
    #: متنازع عليها — الطرفان على قولين متعارضين في الأمر نفسه.
    DISPUTED = "disputed"
    #: استنتاج — استنتاج المنظومة نفسها، لا نصّ في مستند. ⚠️ ويُبنى عليه
    #: الاستدلالُ القانوني، فلا يصحّ أن يُقرأ حقيقةً.
    INFERRED = "inferred"
    #: غير محقّقة — قراءة آلية (OCR مثلاً) أو صورة غير واضحة. ⚠️ وهذه أخطر
    #: المواضع على الأرقام والأسماء والتواريخ والتوقيعات، لأن القراءة الآلية
    #: تُخطئ فيها خطأً **قريباً من الصواب**: «٤٩» تُقرأ «٤٩» و«٤٩٠» في سياق
    #: آخر، ولا يميّزها إلا من يقرأ الصورة.
    UNCERTAIN = "uncertain"


#: أسماء الدرجات بالعربية — للعرض على المحامي، مع فصل المفتاح اللاتيني
#: عن النصّ العربي كما في `WAGE_BASIS_LABELS` في `labour_rules.py`.
STANDING_LABELS: dict[str, str] = {
    Standing.AGREED.value: "متفق عليها",
    Standing.CLAIMED.value: "ادعاء لم يثبت",
    Standing.DISPUTED.value: "متنازع عليها",
    Standing.INFERRED.value: "استنتاج المنظومة",
    Standing.UNCERTAIN.value: "غير محقّقة",
}


#: ⚠️⚠️ **رواية الموكّل ليست دليلاً — وهي أهمّ قاعدة في هذا الملف.**
#:
#: رواية الموكّل **صحيحة في نظره**: هو يروي ما وقع كما رآه، وقد يكون صادقاً
#: تماماً. لكن **صدقه ليس إثباتاً**: الذي يُنسب إلى المذكرة على أنه متّفق عليه
#: أو ثابت هو ما يُسنده مستند أو إقرار من الخصم. ولو مرّت الرواية `AGREED`
#: لصارت في المذكرة حقيقةً مسلَّمة، فبُنيت عليها طلبات، فواجه المحامي خصماً
#: يُنكر ما كتبه وكيله على أنه ثابت.
#:
#: ⚠️ **وهذا يقع عملياً لا نظرياً:** الموكّل يقول «اتفقنا على كذا»، فيُكتب
#: «اتفق الطرفان على كذا» — والاتّفاق لم يثبت، وإنما رواه طرفه. والمحامي يقرأ
#: «اتفق الطرفان» فيصدّقها لأنها من ملفّه، والخصم ينكرها، فيسقط الطلب.
#:
#: فالقاعدة في **المنظومة** لا في الحوار — على درس `labour_rules.py`: التصحيح
#: الذي يعيش في محادثة لا يصل إلى المسار.
CLIENT_STATEMENT_IS_NOT_PROOF = (
    "رواية الموكّل ليست دليلاً: تُسجَّل `CLAIMED` أو `DISPUTED`، ولا تصير "
    "`AGREED` أبداً. والواقعة لا تُنسب إلى المتفق عليه إلا بمستند يُسندها أو "
    "بإقرار من الخصم — فإن نُسبت إلى المتفق عليه وهي مجرّد رواية، فقد صُنع "
    "دليل من لا دليل."
)

#: ⚠️ **وادعاء الخصم ليس دليلاً على ما يدّعيه.**
#:
#: وهذا مقلوب القاعدة الأولى، وموضعه صحيفة الدعوى أو المذكرة أو الإنذار:
#: فيها ما يقوله الخصم، لا ما ثبت. فلو مرّت `CLAIMED` في مذكرة الخصم ثم
#: أُعيدت في مسودّتنا بلا وسم، صار **ادعاء الخصم حجّة على موكّلنا** — وهو
#: أسوأ من غياب الواقعة، لأن الواقعة الغائبة تُطلب، وهذه تُقرأ ثابتة.
#:
#: ⚠️ **والفرق بين القاعدتين عملي:** الأولى تمنع **تضخيم** موقفنا من كلام
#: موكّلنا، والثانية تمنع **تصديق** موقف الخصم من كلامه. وكلتاهما تُنتج
#: المذكرة نفسها: أن يُكتب في الملف ما لم يثبت على أنه ثابت.
OPPONENT_PLEADING_IS_NOT_EVIDENCE = (
    "ادعاء الخصم في صحيفة دعواه أو إنذاره ليس دليلاً على ما يدّعيه: يُسجَّل "
    "`CLAIMED` ولا يُقرأ ثابتاً. وإن أُعيد في مسودّتنا بلا وسم، صار ادعاؤه "
    "حجّة على موكّلنا."
)

#: الدرجة الوحيدة التي **لا ينشئها النظام بنفسه**.
#:
#: وُضعت هنا كي يُستدعى `assert_system_does_not_agree` في أي مسار يُدخل
#: وقائع آلياً، فيكون منع الترقية **فحصاً في الكود** لا نصيحةً في تعليق.
SYSTEM_RECORDED_STANDINGS: tuple[Standing, ...] = (
    Standing.CLAIMED,
    Standing.DISPUTED,
    Standing.INFERRED,
    Standing.UNCERTAIN,
)


class SystemOverclaimError(ValueError):
    """
    المنظومة أنشأت واقعة `AGREED` بنفسها — وهذا خطأ يجب أن يوقف المسار.

    ولماذا استثناء لا تحذير؟ لأن التحذير يُطبع ويُمضى، والواقعة **المصنوعة**
    تمضي إلى المذكرة مع التحذير. والاستثناء يُوقف المسار عند أول واقعة مصنوعة،
    وهو الموضع الوحيد الذي يمكن فيه إصلاحها.
    """


