def summarize(
    ledger: FactLedger,
    shifts: tuple[FactShift, ...] = (),
) -> dict:
    """
    السجلّ ونتيجة الفحص في قاموس **صالح للبثّ كـ JSON**.

    ⚠️ **وفي هذا القاموس تُعرَض القاعدتان صريحتين** — لا في تعليق في الكود:
    ``client_statement_is_not_proof`` و``opponent_pleading_is_not_evidence``.
    والسبب أن القاعدة التي تعيش في تعليق **لا تُقرأ مع التقرير**، والذي يقرأ
    التقرير هو من يحتاجها.

    ووُجدت ``needs_verification`` و``unquoted`` **بالأسماء** لا بالأعداد:
    العدد يقول «ثمّ ثلاث وقائع»، والاسم يقول **أيّها**، والثانية هي التي
    يُراجَع عليها.

    >>> payload = summarize(_the_ledger())
    >>> payload["has_conflicts"], payload["statement"] .startswith("وقائع")
    (False, True)
    """
    shifts = tuple(shifts)
    conflicts = ledger.conflicts()
    version_conflicts = ledger.version_conflicts()
    uncertain = ledger.needs_verification()
    unquoted = ledger.unquoted()

    return {
        "summary": _summary_line(ledger, conflicts, version_conflicts, shifts),
        "fact_count": len(ledger.facts),
        "by_standing": {
            standing.value: len(ledger.by_standing(standing))
            for standing in Standing
        },
        "conflict_count": len(conflicts),
        "conflicts": [
            {
                "subject": first.effective_subject,
                "first": _fact_payload(first),
                "second": _fact_payload(second),
            }
            for first, second in conflicts
        ],
        "version_conflict_count": len(version_conflicts),
        "version_conflicts": [
            {
                "document": conflict.document,
                "note": conflict.note,
                "versions": [
                    {
                        "version": version.version,
                        "date": version.date,
                        "signed": version.signed,
                        "implied": version.implied,
                        "note": version.note,
                    }
                    for version in conflict.versions
                ],
            }
            for conflict in version_conflicts
        ],
        "needs_verification": [_fact_payload(fact) for fact in uncertain],
        "unquoted": [fact.key for fact in unquoted],
        "shifts": [
            {
                "fact_key": shift.fact_key,
                "kind": shift.kind,
                "draft_text": shift.draft_text,
                "fact_statement": shift.fact_statement,
                "note": shift.note,
            }
            for shift in shifts
        ],
        "rules": {
            "client_statement_is_not_proof": CLIENT_STATEMENT_IS_NOT_PROOF,
            "opponent_pleading_is_not_evidence": OPPONENT_PLEADING_IS_NOT_EVIDENCE,
        },
    }


def shifts_summary(shifts: tuple[FactShift, ...]) -> list[dict]:
    """
    الافتراقات وحدها في صورة صالحة للبثّ — للواجهة التي تعرض الفحص وحده.

    ووُجدت منفصلة عن `summarize` لأن المسار قد يحتاج الفحص لا السجلّ:
    فحصُ مسودّةٍ في نهاية التشغيل لا يحتاج إعادة إرسال الوقائع كلها.
    """
    return [
        {
            "fact_key": shift.fact_key,
            "kind": shift.kind,
            "draft_text": shift.draft_text,
            "fact_statement": shift.fact_statement,
            "note": shift.note,
        }
        for shift in shifts
    ]


def _fact_payload(fact: Fact) -> dict:
    """الواقعة في صورة صالحة للبثّ — بدرجتها ومصدرها ونصّها."""
    return {
        "key": fact.key,
        "statement": fact.statement,
        "source": fact.source,
        "locus": fact.locus,
        "date": fact.date,
        "asserted_by": fact.asserted_by,
        "standing": fact.standing.value,
        "standing_label": fact.standing_label,
        "quote": fact.quote,
        "subject": fact.effective_subject,
        "version": fact.version,
    }


def _summary_line(
    ledger: FactLedger,
    conflicts: tuple[tuple[Fact, Fact], ...],
    version_conflicts: tuple[VersionConflict, ...],
    shifts: tuple[FactShift, ...],
) -> str:
    """
    سطر عربي موجز — ويُبنى من **الوقائع لا من الأعداد وحدها**.

    ⚠️ وذكر ``unquoted`` في السطر مقصود: وقائع بلا نصّ تعني أن مسار
    `citations.py` **لا يستطيع أن يقتبس لها شيئاً**، فالمذكرة ستُبنى على
    معنى منقول لا على نصّ. والمحامي يستحقّ أن يعرف ذلك من السطر الأول لا أن
    يكتشفه حين يُرفض اقتباسه.
    """
    parts = [f"وقائع: {len(ledger.facts)}"]
    if conflicts:
        parts.append(f"متناقضات: {len(conflicts)}")
    if version_conflicts:
        parts.append(f"مستندات بنسخ متعدّدة: {len(version_conflicts)}")
    uncertain = ledger.needs_verification()
    if uncertain:
        parts.append(f"تحتاج تحقّقاً: {len(uncertain)}")
    unquoted = ledger.unquoted()
    if unquoted:
        parts.append(f"بلا نصّ: {len(unquoted)}")
    if shifts:
        parts.append(f"افتراقات المسودّة: {len(shifts)}")
    return " · ".join(parts) + "."


def _version_conflict_note(document: str, versions: list[FactVersion]) -> str:
    """
    يسمّي **النسخة المقترحة للعمل** أو يقول صريحاً ما الذي ينقص تحديده.

    والترجيح على ما في السجلّ: الموقّعة أولاً، ثم الأحدث تاريخاً، ثم الأخيرة
    رقماً. ⚠️ **والترجيح ليس حكماً قانونياً** — هو عرضٌ لِما سُجّل، فمن كانت
    نسخته الموقّعة متأخّرة عن غيرها فالسجلّ يقول ذلك صريحاً.
    """
    signed = [version for version in versions if version.signed is True]
    dated = [version for version in versions if version.date.strip()]
    candidates = signed or dated or list(versions)

    # الأحدث تاريخاً: المقارنة على النصّ (ISO أو ما يشبهه)، ولا تُحوَّل إلى
    # `date` — فالنصّ قد يكون هجرياً أو حرّاً، والتحويل هنا تقريب صامت.
    chosen = max(candidates, key=lambda version: (version.date.strip(), version.version))

    missing: list[str] = []
    if not chosen.date.strip():
        missing.append("تاريخها")
    if chosen.signed is None:
        missing.append("حال توقيعها")

    note = (
        f"للمستند «{document}» {len(versions)} نسخ. والمرجَّح للعمل: "
        f"«{chosen.version}» — تاريخها: {chosen.date.strip() or 'غير محدَّد'} · "
        f"التوقيع: {chosen.signed_label}."
    )
    if missing:
        note += " ⚠️ ويجب تحديد " + " و".join(missing) + " قبل الاعتماد عليها."
    if any(version.implied for version in versions):
        note += (
            " ⚠️ ويُستنتج من المسافات بين النسخ وجود نسخة أخرى غير مسجَّلة — "
            "فيُطلب استكمال النسخ قبل الكتابة."
        )
    return note


