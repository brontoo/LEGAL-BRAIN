#: ترتيب الإشارات في `needs_verification`: الأسماء والأرقام والتواريخ
#: والتوقيعات أولاً — **وهو ترتيب ترقيم لا ترتيب أهمّية قانونية**.
_VERIFICATION_SIGNAL_ORDER: tuple[str, ...] = (
    "name",
    "number",
    "date",
    "signature",
)

#: ما يُكتب في ``note`` حين لا تكون للواقعة إشارة خاصة.
_VERIFICATION_SIGNAL_LABELS: dict[str, str] = {
    "name": "اسم",
    "number": "رقم",
    "date": "تاريخ",
    "signature": "توقيع",
}

#: فاصل الموضوع في المفتاح — تجريبي لا إلزامي.
_SUBJECT_SEPARATORS = (".", "/", ":", "|")

#: الفواصل التي تُقطع عندها الجملة: الترقيم العربي واللاتيني، وسطر جديد.
#:
#: ⚠️ **ولا يُقطع على الواو** ولو كانت عاطفةً، لأن قطع النصّ العربي عليها
#: يُنتج جملاً ناقصة تُفقد المقارنة معناها («وقد رفض التوقيع» جملة بلا فعل
#: مفهوم). ويُقطع على ``؛`` و``،``؟ لا: الفاصلة العربية لا تقطع جملة، والقطع
#: عليها يجعل نصف الجملة نافذةً مستقلة — وهو ما يُنتج إنذارات كاذبة.
_SENTENCE_BREAK = re.compile(r"[.!?؟!\n\r\u06d4]+")

#: صور الأرقام — والتحقّق بـ``isdecimal`` لا ``isdigit``.
#:
#: ⚠️ والفرق ليس تجميلياً: ``isdigit`` تُصدّق محارف **ليست أرقاماً** مثل
#: ``²`` (الأس المربّع)، فتوسم واقعةً بأنها «فيها رقم» وهي ليست فيه. أما
#: ``isdecimal`` فلا تُصدّق إلا الأرقام العشرية — وهي الأصل في هذا الموضع.
#: ⚠️ **وهذا السطر كان يمنع الوحدة من الاستيراد إطلاقاً.**
#:
#: كان مكتوباً بمصدرٍ من **عشرين محرفاً** (عربية ١٠ + فارسية ١٠) وهدفٍ من
#: **عشرة** — فترفع ``ValueError`` عند الاستيراد:
#:     the first two maketrans arguments must have equal length
#:
#: **فلم تكن الوحدة تعمل، ولم يكن يعلم أحد.** لا مسار يستوردها ولا اختبار،
#: **فلا شيء يفشل — والسويت كان أخضر.**
#:
#: ⚠️ **والدرس أن ``ast.parse`` لا يكشف هذا**: النصّ نحويّاً سليم تماماً،
#: **ولا يظهر إلا بالتنفيذ.** ولذلك وُلد ``tests/test_module_health.py``.
_DIGIT_TRANSLATION = str.maketrans(
    "٠١٢٣٤٥٦٧٨٩۰۱۲۳۴۵۶۷۸۹",
    "01234567890123456789",
)


def _subject_of(key: str) -> str:
    """
    الموضوع المستنبَط من المفتاح: ما قبل أول فاصل.

    >>> _subject_of("release.refused")
    'release'
    >>> _subject_of("end_date")
    'end date'
    """
    normalized = normalize(key)
    for separator in _SUBJECT_SEPARATORS:
        if separator in key:
            return normalize(key.split(separator, 1)[0])
    # ولا فاصل: المفتاح نفسه موضوعاً، مطبَّعاً (فـ«end_date» و«end-date»
    # موضوع واحد — وهو ما يمنع تناقضاً كاذباً بسبب شرطة).
    return normalized


def _content_tokens(text: str) -> list[str]:
    """
    رموز المقارنة: الكلمات ذات المعنى، بلا تكرار، وبعد التطبيع العربي.

    والتطبيع **يُستدعى من `citations.normalize`** ولا يُعاد كتابته: تطبيعان
    في مشروع واحد يفترقان عند أول تعديل، فتقبل دالّةٌ نصّاً وترفضه أخرى —
    وهو نفس العيب الذي قيل في `review.py` عند استيراد `MIN_QUOTE_CHARS`.

    >>> _content_tokens("رفض الموظف التوقيع على مخالصة")
    ['رفض', 'الموظف', 'التوقيع', 'مخالصه']
    """
    normalized = normalize(text)
    if not normalized:
        return []
    seen: dict[str, None] = {}
    for token in normalized.split():
        if len(token) < _MIN_TOKEN_CHARS:
            continue
        seen.setdefault(token, None)
    return list(seen)


def _fact_tokens(fact: Fact) -> list[str]:
    """
    رموز الواقعة للمقارنة: **نصّها**، وإن لم يكن لها نصّ فمفتاحها ومصدرها.

    ⚠️ **ولماذا يُدخَل المفتاح والمصدر؟** لأن الواقعة التي لا نصّ لها
    (`unquoted`) لا رموز لها أصلاً، فلا تُقارَن بشيء فتُوسم ``missing`` دائماً
    — وهو إنذار كاذب **دائم** لكل واقعة بلا نصّ. فالمفتاح يمثّلها: هو أضعف
    أساس، لكنه **أفضل من لا أساس**، ومع ذلك يبقى النقص مُعلَناً في
    `unquoted()` لا مسكوتاً عنه.
    """
    tokens = _content_tokens(fact.statement)
    if tokens:
        return tokens
    return _content_tokens(f"{fact.key} {fact.source}")


def _sentences(text: str) -> list[str]:
    """
    جمل النصّ — وبها يُقاس «أيّ نصّ في المسودّة يقابل الواقعة».

    ⚠️ **ولا يُقارَن المتن كلّه بالواقعة**: لو قارنّاه لكلّة لَنجحت كل واقعة
    في كل مسودّة، لأن رمزاً واحداً أو رمزين منها يظهران في أي متن طويل — فتصير
    الدالّة صامتة دائماً، وهي **أداة تُنذر دائماً لا تُنذر أبداً** بعكسها.
    """
    return [part.strip() for part in _SENTENCE_BREAK.split(text or "") if part.strip()]


def _against(candidate: str, fact_tokens: list[str]) -> tuple[int, float, float]:
    """
    يقيس نصّاً من المسودّة في مقابل رموز الواقعة: (مشترك, تغطية, نسبة).

    * **التغطية** = ``المشترك ÷ رموز الواقعة`` — «كم من الواقعة وصل؟»
    * **النسبة**   = ``المشترك ÷ الاتّحاد`` — «هل النصّان هما النصّ نفسه؟»

    ⚠️ والمقياسان **معاً**، ولا يكفي أحدهما: التغطية وحدها تُصدّق نصّاً يشمل
    الواقعة وزيادةً تُغيّر معناها («رفض التوقيع لأنه لا يعرف القراءة»)،
    والنسبة وحدها تُسقط نصّاً استُبدل فيه رمز واحد.
    """
    candidate_tokens = set(_content_tokens(candidate))
    fact_set = set(fact_tokens)
    if not candidate_tokens or not fact_set:
        return 0, 0.0, 0.0
    shared = fact_set & candidate_tokens
    union = fact_set | candidate_tokens
    return len(shared), len(shared) / len(fact_set), len(shared) / len(union)


def _has_negation(text: str) -> bool:
    """
    هل في النصّ نفيٌ أو صورة من صور الامتناع؟

    ⚠️ **وهذا هو الفحص الحاسم في العيب التاريخي:** «رضي بالتوقيع» و«رفض
    التوقيع» رمزاهما شبه متطابقين، والفرق **حرف نفي واحد** يقلب المعنى رأساً
    على عقب. فالنفي يُفحص **قبل** النسبة، لأنه لا يُقاس بالنسبة.

    ⚠️ **وحدّه: النفي يُقرأ على **ظهور الصورة** لا على إعرابها.** فـ«لم»
    تُطابق «لم» في «الم»؟ لا — لأن المطابقة على **الرمز كاملاً** أو على
    **بادئته في رمز أطول منه بحرفين على الأقل**، فلا تُطابق ``لماذا`` ولا
    ``لغة``. وهذا احتياط مقصود: نفيٌ كاذب يُنتج ``contradicted`` على واقعة
    سليمة، وسمة «نُقضت» أخطر من سمة «أُعيدت صياغتها».

    >>> _has_negation("رفض الموظف التوقيع على المخالصة")
    True
    >>> _has_negation("لماذا يمتنع؟")
    True
    >>> _has_negation("وقّع الموظف المخالصة")
    False
    """
    for token in normalize(text).split():
        for prefix in _NEGATION_PREFIXES:
            if token == prefix or (
                token.startswith(prefix) and len(token) - len(prefix) >= 2
            ):
                return True
    return False


def _subject_of_key_is_compared(first: Fact, second: Fact) -> bool:
    """
    هل تقع الواقعتان على **الأمر نفسه بعينه** — لا على الموضوع نفسه؟

    ⚠️ **ولماذا لا يكفي اتّفاق الموضوع؟** لأن الموضوع واسع: وقائعتان عن
    «مصير المخالصة» إحداهما تقول «وُقّعت» والأخرى تقول «طُبع منها ثلاث نسخ»
    — وهما لا تتناقضان. فالتناقض يقتضي أن تتناولا **التفصيل نفسه**، وهذا ما
    تقيسه هذه الدالّة: تغطية عالية في الاتجاهين مع نسبة منخفضة = **استبدال
    في الموضع نفسه**.
    """
    first_tokens = _content_tokens(first.statement)
    second_tokens = _content_tokens(second.statement)
    if not first_tokens or not second_tokens:
        return False
    first_set, second_set = set(first_tokens), set(second_tokens)
    shared = first_set & second_set
    coverage_first = len(shared) / len(first_set)
    coverage_second = len(shared) / len(second_set)
    ratio = len(shared) / len(first_set | second_set)
    return (
        coverage_first >= _CONTRADICTION_COVERAGE
        and coverage_second >= _CONTRADICTION_COVERAGE
        and ratio < _CONTRADICTION_MAX_RATIO
    )


#: أقلّ تغطية متبادلة بين واقعتين لتُقرأ إحداهما استبدالاً للأخرى.
_CONTRADICTION_COVERAGE = 0.60

#: وأعلى نسبة تشابه بينهما: فوقها النصّان يقولا الشيء نفسه فلا تناقض.
_CONTRADICTION_MAX_RATIO = 0.75


def _contradict(first: Fact, second: Fact) -> bool:
    """
    هل تتناقض الواقعتان؟ — الحكم الواحد في هذا الملف.

    ⚠️ **والحكم عامٌّ لأي زوج لا لهذا الملف**: نفيٌ في إحداهما دون الأخرى =
    تناقض، لأن النصّين عندئذٍ يقولان نقيضين. ويُقيَّد بأن يكون النصّان
    متقاربين فعلاً (``_subject_of_key_is_compared``) وإلا لتناقضت كل واقعة
    مثبتة مع كل واقعة منفية في الملف كله.

    ⚠️ **وحدّ مسجَّل:** «تأخّر عن السداد» و«لم يتأخّر عن السداد» — الأولى بلا
    صورة نفي، والثانية فيها ``لم`` — تُقرأ تناقضاً. وهذا هو المطلوب هنا. أما
    «رفض التوقيع» و«وقّع» فلا تُقرأ تناقضاً، لأن ``رفض`` ليست في صور النفي
    إلا بادئةً على الرمز — وهي كذلك: ``رفض`` رمزٌ كامل في القائمة، فيُطابق.
    والفرق بين الحالتين يُثبّته الاختبار لا هذا التعليق.
    """
    negated_first = _has_negation(first.statement)
    negated_second = _has_negation(second.statement)
    if negated_first == negated_second:
        # النفي نفسه في الاثنتين (أو غائب عنهما): لا نقيض. ويبقى احتمال
        # الاستبدال المادّي — «تأخّر ثلاثة أشهر» في مقابل «أربعة أشهر» —
        # وهو بابٌ منفصل يُقاس بالتغطية والنسبة.
        return _subject_of_key_is_compared(first, second)
    return _subject_of_key_is_compared(first, second)


def _has_number(text: str) -> bool:
    """
    هل في النصّ رقم؟ — والتحقّق على الرقم العشري لا على ``isdigit``.

    ⚠️ والأرقام تُحوَّل أولاً إلى اللاتينية، لأن ``٤٩٠`` و``490`` الرقم نفسه
    برسمين — والفرق بينهما لا يهمّ المحامي.
    """
    return any(char.isdecimal() for char in normalize(text).translate(_DIGIT_TRANSLATION))


def _has_name(text: str) -> bool:
    """
    هل في النصّ ما يشير إلى **اسم علم**؟

    ⚠️ **وحدّ هذا الفحص معلن:** لا يعرف هذا الملف أسماء الأعلام، ولا يحاول.
    الذي يقرأه: بادئة «ام» أو «م» على رمز تالٍ (``ام احمد``، ``مريم``) — وهو
    وسْمُ الاسم في المستندات العربية، ولو كان تقريبياً. والتقريب هنا مقبول
    لأن نتيجته **طلبُ تحقّق زائد**، لا إسقاطُ واقعة.
    """
    tokens = normalize(text).split()
    for index, token in enumerate(tokens):
        for prefix in _NAME_PREFIXES:
            if token == prefix and index + 1 < len(tokens):
                return True
            if token.startswith(prefix) and len(token) - len(prefix) >= 3:
                # «مريم»: «م» + ثلاثة أحرف على الأقل — فلا تُطابق «معه».
                return True
    return False


def _has_date(text: str) -> bool:
    """هل في النصّ تاريخ؟ — برقم فيه، أو بلفظ من ألفاظ التاريخ."""
    if _has_number(text):
        return True
    tokens = set(normalize(text).split())
    return bool(tokens & set(_DATE_WORDS))


def _has_signature(text: str) -> bool:
    """هل في النصّ ما يتعلّق بالتوقيع أو الختم؟"""
    tokens = set(normalize(text).split())
    return bool(tokens & set(_SIGNATURE_WORDS))


def _verification_rank(fact: Fact) -> tuple[bool, int, int]:
    """
    رتبة العرض في `needs_verification`: (هل الإشارة مؤكَّدة؟, رتبة الإشارة).

    ⚠️ **و`has_number` تجمع مع `has_date`** — والترتيب يحسم: الرقم قبل
    التاريخ لأن كل تاريخ فيه رقم، ولأن **الرقم المجرّد** (مبلغ، نسبة، عدد
    أيام) أخطر ما تُخطئ فيه القراءة الآلية ويبدو سليماً.
    """
    haystack = " ".join(
        (fact.statement, fact.quote, fact.source, fact.locus, fact.date, fact.key)
    )
    signals = (
        _has_name(haystack),
        _has_number(haystack),
        _has_date(haystack),
        _has_signature(haystack),
    )
    for index, present in enumerate(signals):
        if present:
            return (False, index, 0)
    # لا إشارة خاصة: يبقى الطلب — «غير محقَّقة» تُراجَع كلها — لكنها في الآخر.
    return (True, len(_VERIFICATION_SIGNAL_ORDER), 0)


