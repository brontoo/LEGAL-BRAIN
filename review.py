#: ترتيب الفرز: الأخطاء قبل الملاحظات، ثم الأنواع بترتيب `KINDS`.
_SEVERITY_RANK = {severity: index for index, severity in enumerate(SEVERITIES)}
_KIND_RANK = {kind: index for index, kind in enumerate(KINDS)}

#: بداية أي مصفوفة JSON. نبحث عنها لا عن الوسم، لأن النموذج يحيط جوابه
#: بالنثر والسياج في أغلب الأحيان رغم المنع.
_ARRAY_OPEN = "["


def _text(value: object) -> str:
    """
    يحوّل قيمة إلى نصّ نظيف، وغير النصّ إلى فراغ.

    ولا نحوّل الأرقام إلى نصوص: اعتراض `quote` فيه رقم مجرّد ليس اقتباساً من
    المسودّة، وسند `basis` فيه `5` ليس سنداً. و`str(value)` هنا كان سيصنع
    اقتباساً من لا شيء ثم يُرفض لاحقاً بلا سبب مفهوم.
    """
    return value.strip() if isinstance(value, str) else ""


def _label(value: object, allowed: Sequence[str], default: str) -> str:
    """يقرأ تصنيفاً من مخرج النموذج، ويعيد الافتراضي لكل ما لا يُعرف."""
    if isinstance(value, str):
        candidate = value.strip().lower()
        if candidate in allowed:
            return candidate
    return default


def _first_json_array(raw: str) -> list:
    """
    يستخرج **أول** مصفوفة JSON من النصّ، ويتجاهل ما حولها.

    ولماذا `raw_decode` على كل `[` بدل البحث عن أول `[` وآخر `]`؟ لأن
    النموذج قد يكتب شرحاً فيه قوس، أو يجعل الجواب كائناً قبل المصفوفة، أو
    يقصّ المصفوفة في المنتصف. والمحاولة على كل موضع تُنجينا من كل ذلك، وتفشل
    فشلاً واضحاً حين لا توجد مصفوفة أصلاً.

    Raises:
        ReviewParseError: إن لم توجد مصفوفة JSON في النصّ كلّه.
    """
    if not isinstance(raw, str) or not raw:
        raise ReviewParseError("مخرج المراجع فارغ — لا شيء يُقرأ.")

    decoder = json.JSONDecoder()
    start = raw.find(_ARRAY_OPEN)
    while start != -1:
        try:
            value, _end = decoder.raw_decode(raw, start)
        except ValueError:
            value = None
        if isinstance(value, list):
            return value
        start = raw.find(_ARRAY_OPEN, start + 1)

    raise ReviewParseError("لم يُعثر على مصفوفة JSON في مخرج المراجع.")


def _is_verified(quote: str, basis: str, draft: str, brief: str, evidence: str) -> bool:
    """
    الفحص الحاسم: أيُعتمد الاعتراض أم يُسقَط؟

    ثلاثة شروط، وكلّها تمرّ بـ `quote_in_text`، فلا حكم في هذا الملف على
    النصّ العربي بنفسه — الحكم كلّه لدالّة واحدة في `citations.py`:

    1. الاقتباس موجود حرفياً في **المسودّة**. ودالّة الفحص ترفضه أيضاً إن كان
       أقصر من `MIN_QUOTE_CHARS`، فالسطر القصير يوجد في كل مسودّة بالمصادفة.
    2. السند فارغ — وهذا مقبول ومقصود: اعتراض يقع على المسودّة وحدها (تناقض
       داخلي مثلاً) لا سند له في الموجز.
    3. أو السند موجود حرفياً في **الموجز** أو في **المقتطفات**.

    ⚠️ وقرار مقصود: السند يمرّ بالعتبة نفسها التي يمرّ بها الاقتباس.
    لو تحقّقنا من وجوده وحده لأمكن للمراجع أن «يسند» كل اعتراض بكلمتين
    شائعتين («المادة»، «الأجرة») توجد في أي مقتطف، فيمرّ الاعتراض المؤلَّف
    بلا سند حقيقي. فتكون الحماية باباً بلا قفل. والسند الأقصر من اقتباس
    معتبر ليس سنداً.
    """
    if not quote_in_text(quote, draft):
        return False
    if not basis:
        return True
    return quote_in_text(basis, brief) or quote_in_text(basis, evidence)


def parse_review(
    raw: str,
    draft: str,
    brief: str,
    evidence: str,
) -> ReviewOutcome:
    """
    يقرأ مخرج المراجع، ويتحقّق من كل اعتراض، ويعيد ما ثبت فقط.

    الترتيب مقصود: نتحقّق قبل أن نُصنّف. فالتصنيف يستهلك الانتباه (عتبات
    الترقية والفرز)، والاعتراض الذي لا نصّ له لا يستحقّ أيّ انتباه.

    وكل ما أُسقط يُعدّ ولا يُسقَط صامتاً، على قاعدة `parse_citations` في
    `citations.py` («سطر مشوّه يعني سنداً ضائعاً»): مراجع أنتج خمسة اعتراضات
    ولم يثبت منها واحد معلومة تهمّ المحامي — تعني أن النداء يعمل والمسودّة
    سليمة في نظر المراجع، أو أن الصياغة لا تُقرأ. والصمت عن الفرق يُخفي
    عيباً في الموجّه.

    >>> out = parse_review(
    ...     '[{"kind": "fact", "severity": "error", "message": "خ",'
    ...     ' "quote": "تأخّر المستأجر عن سداد الأجرة", "basis": ""}]',
    ...     "تأخّر المستأجر عن سداد الأجرة عن أربعة أشهر", "", "")
    >>> out.findings[0].severity, out.dropped
    ('error', 0)
    """
    elements = _first_json_array(raw)

    findings: list[ReviewFinding] = []
    dropped = 0
    # مفتاح التكرار: (النوع، الاقتباس **بعد التطبيع**).
    #
    # والتطبيع مقصود، على نمط `_group_matches` في `language_audit.py`: تكرار
    # الاعتراض بصيغة إملائية أخرى هو الاعتراض نفسه، وإسقاطه على الرسم وحده
    # يُنتج جداراً من الاعتراضات المتشابهة — وهو ما يُغرِق العيب الحقيقي.
    seen: set[tuple[str, str]] = set()

    for element in elements:
        # عنصر ليس كائناً = النموذج لم يفهم الشكل أصلاً. يُسقَط ويُحسب، لأن
        # ظهوره عيب في الموجّه يجب أن يُرى لا أن يمرّ.
        if not isinstance(element, dict):
            dropped += 1
            continue

        message = _text(element.get("message"))
        if not message:
            # اعتراض بلا كلام ليس اعتراضاً: لا شيء يعرضه المحامي.
            dropped += 1
            continue

        quote = _text(element.get("quote"))
        basis = _text(element.get("basis"))
        if not _is_verified(quote, basis, draft, brief, evidence):
            dropped += 1
            continue

        kind = _label(element.get("kind"), KINDS, DEFAULT_KIND)
        severity = _label(element.get("severity"), SEVERITIES, DEFAULT_SEVERITY)

        key = (kind, normalize(quote))
        if key in seen:
            # التكرار يُطوى ولا يُعدّ في `dropped`: العدّاد يُعرَض على المحامي
            # بمعنى «لم يثبت نصّه»، والتكرار ثبت نصّه ولم يُضِف شيئاً.
            continue
        seen.add(key)

        findings.append(
            ReviewFinding(
                kind=kind,
                severity=severity,
                message=message,
                quote=quote,
                basis=basis,
            )
        )

    # الأخطاء أولاً (تمنع التسليم)، ثم الأنواع بترتيب `KINDS`، ثم ترتيب الورود
    # — فالفرز في بايثون مستقرّ، وما تساوت رتبته يبقى كما كتبه المراجع.
    findings.sort(key=lambda item: (_SEVERITY_RANK[item.severity], _KIND_RANK[item.kind]))
    return ReviewOutcome(findings=findings, dropped=dropped)


