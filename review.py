def _summary_line(findings: Sequence[ReviewFinding], dropped: int) -> str:
    """
    سطر عربي واحد يصلح للعرض في الواجهة أو السجل.

    وذكر المُسقَط في السطر ليس تفصيلاً: مسودّة أُسقطت فيها كل الاعتراضات
    تخرج `clean` — وهذا صحيح، إذ لم يثبت عيب. لكنها ليست كمسودّة لم يُعترض
    عليها أصلاً، والمحامي يستحقّ أن يعرف الفرق: هل سكت المراجع لأنه رضي، أم
    لأنه اتّهم ولم يُثبت؟
    """
    errors = [item for item in findings if item.severity == "error"]
    notices = [item for item in findings if item.severity == "notice"]

    if not errors and not notices:
        line = "لا اعتراض — لم يجد المراجع الثاني ما يستحقّ الاعتراض."
    elif not errors:
        line = f"لا مانع من التسليم · {len(notices)} اعتراض للعلم."
    else:
        line = f"{len(errors)} اعتراض يمنع التسليم"
        if notices:
            line += f" · {len(notices)} اعتراض للعلم"
        line += "."

    if dropped:
        line += f" وأُسقط {dropped} اعتراضاً لم يثبت نصّه في المسودّة أو الموجز."
    return line


def summarize(findings: Sequence[ReviewFinding], dropped: int = 0) -> dict:
    """
    يحوّل الحصيلة إلى قاموس صالح للبثّ كـ JSON إلى الواجهة.

    ``clean`` تُحسب من الأخطاء وحدها: الاعتراض الذي لا يمنع التسليم لا يجوز
    أن يمنعه، وهذا هو الحدّ الذي تعلّمه `language_audit.py` من تشغيل حقيقي —
    وسمُ أحد عشر سلوكاً صحيحاً كأخطاء كان سيُفقد التقرير كلّه.

    >>> payload = summarize([], 0)
    >>> payload["clean"], payload["error_count"]
    (True, 0)
    """
    errors = [item for item in findings if item.severity == "error"]
    notices = [item for item in findings if item.severity == "notice"]

    return {
        "summary": _summary_line(findings, dropped),
        "clean": not errors,
        "error_count": len(errors),
        "notice_count": len(notices),
        "dropped": dropped,
        "findings": [
            {
                "kind": item.kind,
                "severity": item.severity,
                "message": item.message,
                "quote": item.quote,
                "basis": item.basis,
            }
            for item in findings
        ],
    }

