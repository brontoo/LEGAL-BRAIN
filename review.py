"""
المراجع الثاني — عين الخصم على المسودّة قبل تسليمها.
=============================================================================

المشكلة التي يحلّها
------------------
`citations.py` يتحقّق أن كل سند في المسودّة موجود حرفياً في الأرشيف، وهذا
يمنع **التأليف**. لكنه لا يمنع شيئاً آخر: مسودّة قد تكون **كل أسانيدها صحيحة**
ومع ذلك تخالف الموجز، أو تُغفل واقعة جوهرية، أو تبني دفعاً لا تسنده النصوص
المسترجَعة. والاستشهاد السليم لا يُنقذ حجّة فاسدة.

الحلّ
-----
نداء ثانٍ لنموذج يقرأ المسودّة **خصماً** لا كاتباً: يواجه المسودّة بالموجز
وبما استُرجِع من الأرشيف، ويُعدّد ما يُؤخذ به الكاتب. ثم يقرأ المحامي
الاعتراضات قبل أن يُسلّم المستند.

⚠️ الشرط الذي يقوم عليه الملف كله: **لا يُصدَّق المراجع**.
------------------------------------------------------------------
مراجع يستطيع أن **يختلق** الاقتباس أو السند أسوأ من عدم وجود مراجع أصلاً.
لماذا؟ لأن المحامي سيتعلّم بعد أسبوعين ألّا يقرأ تقرير الاعتراضات — فحين يظهر
العيب الحقيقي لا يقرؤه أحد. وكذلك مراجع يختلق اعتراضات ليُظهر أنه عمل:
**أداة تُنذر دائماً لا تُنذر أبداً.**

فالقاعدة هنا صريحة، وهي مبدأ `citations.py` نفسه:

> **النموذج يروي، والخادم يُقرّر.**

كل اعتراض يجب أن يُرفق **اقتباساً حرفياً من المسودّة**، و**سنداً حرفياً من
الموجز أو المقتطفات** (أو سنداً فارغاً إن لم يوجد). و`quote_in_text` هو
الحكم: اقتباس لا يوجد في المسودّة يُسقَط، وسند لا يوجد في الموجز ولا في
المقتطفات يُسقَط، **ويُعدّان معاً في عدّاد `dropped`** لأن المحامي يجب أن
يعرف أن المراجع حاول ولم يثبت.

حدّان صريحان
------------
**١) اجتياز الفحص ليس صواباً قانونياً.** المراجع الذي يمرّ نصّه قد يكون
استنتاجه خاطئاً: الاقتباس موجود، والسند موجود، والحكم الذي بناه عليهما غير
صحيح. وهذا حكم قانوني لا يحسمه كود، ولا يدّعيه هذا الملف. الاعتراض **سؤال
يُعرَض على المحامي**، لا نتيجة.

**٢) وحدّ في المطابقة نفسها:** `normalize` يمحو الترقيم، فاقتباس بلا فاصلة
يجتاز الفحص على نصّ فيه فاصلة — وقد تفرق الفاصلة بين معنيين («لا، يفسخ» ≠
«لا يفسخ»). ولذلك الموجّه يُلزِم المراجع **بالقراءة**، والفحص يمنع التأليف
فقط. ومحلّ هذا التفصيل: اختبار `TestQuoteInTextBehaviour`.

لماذا `ReviewOutcome` بدل `last_dropped()`
------------------------------------------
البديل المطروح كان دالة `last_dropped()` تُخزّن عدّاداً في حالة الوحدة. ورُفض
لسبب مبدأي ولسبب عملي:

* `citations.py` يعلن في صدره أن الوحدات **بلا حالة وبلا إدخال/إخراج**، وهو
  ما يجعلها قابلة للاختبار مباشرة. والدالة التي تقرأ «عدد ما أُسقط في آخر
  نداء» تعتمد على **ترتيب النداءات** لا على مدخلاتها.
* وعملياً: لو نادى مسارٌ النداء ثم نادى آخر قبل قراءة العدّاد، لقُرئ الرقم من
  النداء الخطأ — ويبقى الجواب صحيحاً في الاختبار المفرد خاطئاً في الخدمة.

فالحصيلة تُعاد كاملةً في `ReviewOutcome`، على نمط `VerificationOutcome` في
`citations.py`: `parse_review(...)` تُعيد الحصيلة، ومنها
`outcome.findings` و`outcome.dropped`. فلا حالة، ولا اعتماد على ترتيب.
(والاختبار `test_repeated_calls_do_not_share_state` يُثبّت هذا الضمان.)
"""

