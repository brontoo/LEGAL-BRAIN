@dataclass(frozen=True)
class ReviewFinding:
    """
    اعتراض واحد من المراجع الثاني، **بعد أن ثبت نصّه**.

    Attributes:
        kind:     `fact` أو `omission` أو `unsupported` أو `arithmetic` أو
                  `strength`. وكل تصنيف مجهول صار `unsupported` قبل الوصول
                  إلى هنا — فالقراءة بعد التطبيع لا تُنتج قيمة غريبة.
        severity: `error` يمنع التسليم، أو `notice` للعلم.
        message:  الاعتراض بالعربية، في جملة أو جملتين.
        quote:    النصّ كما نقله المراجع من المسودّة. وقد يخالف رسمَ المسودّة
                  في التشكيل والترقيم، لأن الفحص يجري على النصّ المطبَّع —
                  وهو الفرق نفسه الذي يقوم عليه `quote_in_text`.
        basis:    النصّ الذي يسند الاعتراض من الموجز أو المقتطفات، أو ``""``.
                  ووجود اعتراض بسند فارغ مشروع: الاقتباس من المسودّة وحده قد
                  يكفي، كأن تخالف المسودّة نفسها.
    """

    kind: str
    severity: str
    message: str
    quote: str
    basis: str = ""


@dataclass
class ReviewOutcome:
    """
    حصيلة نداء المراجع الثاني كاملة.

    Attributes:
        findings: ما ثبت من اعتراضات، مرتّبة (الأخطاء أولاً).
        dropped:  عدد الاعتراضات التي أُسقطت لأن نصّها لم يثبت — لا غير.
                  و«لا غير» مهمّة: التكرار المطويّ ليس إسقاطاً، وإدخاله في
                  العدّاد يجعل الرقم المعروض على المحامي («أُسقط كذا اعتراضاً
                  لم يثبت نصّه») **كاذباً**. والتكرار ضجيج لا تزوير.
    """

    findings: list[ReviewFinding] = field(default_factory=list)
    dropped: int = 0

    @property
    def errors(self) -> list[ReviewFinding]:
        """الاعتراضات التي تمنع التسليم."""
        return [item for item in self.findings if item.severity == "error"]

    @property
    def notices(self) -> list[ReviewFinding]:
        """الاعتراضات التي تُعرَض ولا تمنع."""
        return [item for item in self.findings if item.severity == "notice"]

    @property
    def clean(self) -> bool:
        """هل خرجت المسودّة بلا اعتراض مانع؟"""
        return not self.errors

    def summary(self) -> str:
        """سطر عربي موجز — يُبنى من نفس دالّة `summarize` فلا يفترقان."""
        return _summary_line(self.findings, self.dropped)


