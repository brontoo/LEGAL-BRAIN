import os
from dotenv import load_dotenv
from swarmmy import run_sync, create_provider, Config

# تحميل مفاتيح API من ملف .env
load_dotenv()

# 1. تحديد شخصيات فريق العمل الصارمة (تم إضافة تعليمة "اكتب العقد فقط بدون ثرثرة")
legal_team_roles = [
    "أنت 'مُسْوَدَّة أفندي' (وكيل الصياغة). مهمتك استلام طلب المستخدم وكتابة المسودة الأولية. لا تقم بالثرثرة ولا تشرح من أنت. اكتب محتوى الإنذار القانوني مباشرة.",
    "أنت 'المفتش ثُغرة' (المدقق القانوني). راجع المسودة بصرامة وتصيد الثغرات. قم بإعادة كتابة الإنذار كاملاً بعد سد الثغرات القانونية وفق قوانين دبي. لا تشرح من أنت ولا تكتب مقدمات.",
    "أنت 'سيبويه المُكشّر' (المدقق اللغوي). مهمتك ضبط الصياغة لتكون فخمة جداً. قم بإعادة كتابة الإنذار كاملاً بلغة قانونية رصينة بدون أي مقدمات أو تعليقات جانبية."
]

# 2. إعداد مكتب المحاماة 
config = Config(
    agents=3,
    rounds=1,
    roles=legal_team_roles,
    concurrency=1,    # ترتيب الدخول لمنع غضب الخادم
    max_retries=3,    # إعادة المحاولة عند الفشل
    max_tokens=2048   # 👈 زيادة الحد الأقصى للنصوص لتجنب قطع العقد في المنتصف
)

# 3. ربط مدير المكتب (Gemini)
backend = create_provider(
    "gemini", 
    model="gemini-2.5-flash", # استخدم أحدث نموذج لضمان سعة أكبر
    api_key=os.environ.get("GOOGLE_API_KEY")
)

print("\n🏢 تم افتتاح مكتب العقل القانوني... الموظفون يأخذون أماكنهم.\n")

task = "صغ إنذاراً قانونياً قصيراً جداً ومباشراً لمستأجر متأخر عن سداد الإيجار لمدة 3 أشهر في دبي، وطالبه بالسداد أو الإخلاء."

# 4. تشغيل الفريق
result = run_sync(
    task,
    backend=backend,
    config=config,
    live=True 
)

print("\n====================================================================")
print("🎯 النتيجة النهائية (تم الاعتماد والختم من 'المعلم أبو الختم'):")
print("====================================================================\n")
print(result.answer)

print(f"\n📊 إحصائيات المهمة: استغرقت {result.elapsed_seconds:.2f} ثانية | إجمالي الطلبات: {result.calls}")