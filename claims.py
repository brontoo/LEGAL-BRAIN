def _marker_hits(text: str, markers: tuple[str, ...]) -> tuple[str, ...]:
    """
    الألفاظ الموجودة في النصّ — **بعد التطبيع**، بترتيب ``markers``.

    ⚠️ **وإعادة الألفاظ لا زينة:** الحكم بلا الألفاظ التي أوقعته **يُقرأ
    اعتباطاً فلا يُراجَع**؛ وبها يرى المحامي أن الأداة أُخذت بلفظ «تقدير»
    ومراده شيء آخر — فيتجاهل الإنذار الكاذب ويقرأ ما بعدها. وهذا هو الأصل
    المعلن في `facts.py`: الإنذار الكاذب يُعرض ليُقرأ، ولا يُخفى.
    """
    haystack = normalize(text)
    if not haystack:
        return ()
    return tuple(marker for marker in markers if normalize(marker) in haystack)


def stage_constraints(stage: Stage) -> tuple[str, ...]:
    """
    ما تقبله المرحلة وما تمنعه — **جمل عربية جاهزة للعرض**.

    ⚠️ والجمل **بيانات** لا نثراً في دالّة: ``STAGE_ACCEPTS`` و``STAGE_PROHIBITS``
    يُقرآن معاً، ويُفحص في الاختبار أن لكلتا المجموعتين **المفاتيح نفسها** —
    فمرحلةٌ لها ما تقبله بلا ما تمنعه تُنتج قيداً **نصفَه غائب**، وهو أسوأ من
    غيابه كله لأن نصفه يُقرأ كمالاً.

    >>> len(stage_constraints(Stage.CASSATION)) >= 4
    True
    >>> any("تقدير الدليل" in line for line in stage_constraints(Stage.CASSATION))
    True

    Args:
        stage: المرحلة.

    Returns:
        الجمل: المقبول أولاً ثم الممنوع، بلا تكرار.
    """
    label = STAGE_LABELS.get(stage.value, stage.value)
    lines = [f"المرحلة: {label}."]
    lines.extend(STAGE_ACCEPTS.get(stage, ()))
    lines.extend(STAGE_PROHIBITS.get(stage, ()))
    return tuple(lines)


def validate_for_stage(item: MatrixItem, stage: Stage) -> tuple[StageViolation, ...]:
    """
    أوجهٌ **لا تقبلها المرحلة** — مطابقة أنماط حتمية على ألفاظ معلنة.

    ⚠️⚠️ **وهذه قائمة تحقّق، لا رأي قانوني، ولا حكم على وجه.**

    ما تفعله هذه الدالّة بالضبط: تنظر هل في نصّ العنصر لفظٌ من ألفاظ معلنة
    (``_MARKERS_*``) ينتمي إلى صنفٍ **لا تقبله المرحلة** في الجدول أعلاه، فإن
    وُجد أُنذر. وهي:

    * **لا تفهم وجهاً لم تُعلَّم ألفاظه.** الوجه الصحيح الصياغة الذي لا يرد
      فيه لفظ من الألفاظ المعلنة **يمرّ بلا إنذار** — وهذا موضع **خطأ سالب**
      معلن، لا يمكن إصلاحه بلا فهم المعنى، وفهم المعنى خارج حدود هذا الملف
      (المبدأ: الخادم يُقرّر، ونقاء الدالّة شرط قابلية اختبارها).
    * **ولا تفرّق بين الوجه وبين الكلام عنه.** فمن كتب «هذا الطعن لا يتعرّض
      لتقدير الدليل» فقد ردّ فيه لفظ «تقدير الدليل» — **فيُنذر عليه**.
    * **وتُعطي درجة واحدة للأنواع كلها** (``error``)، وهذا اختيار: القاعدة
      المعلنة عند ``validate_for_stage`` **قيد على الشكل** لا تقدير قوّة،
      ومن جعل بعضها ملاحظةً **قوّم وجهاً قانونياً بحقل نصّيّ** — وهو أسوأ من
      الإنذار الزائد.

    والأسباب الثلاثة أعلاه **مواضع الإنذار الكاذب في هذا الملف**، وهي مفصّلة
    هنا لأن إخفاءها يجعل الإنذار يُقرأ حكماً، **والإنذار الذي يُقرأ حكماً
    كاذباً يُفقد الثقة في الإنذار الصادق**.

    Args:
        item: الطلب أو الدفع.
        stage: المرحلة المنظور فيها.

    Returns:
        الوجوه المخالفة، بترتيب القواعد، ولكلٍّ سببُه وألفاظُه.

    >>> [v.rule for v in validate_for_stage(_cassation_evidence_ground(), Stage.CASSATION)]
    ['attacks_evidence_weighing']
    >>> validate_for_stage(_cassation_evidence_ground(), Stage.APPEAL)
    ()
    """
    text = item.label + " " + item.response
    kind = _kind_of(item)
    found: list[StageViolation] = []

    def add(rule: str, message: str, markers: tuple[str, ...]) -> None:
        hits = _marker_hits(text, markers)
        if not hits:
            return
        found.append(
            StageViolation(
                item_key=item.key,
                kind=kind,
                stage=stage.value,
                rule=rule,
                message=message,
                note=(
                    "الألفاظ التي أوقعت المطابقة: "
                    + " · ".join(hits)
                    + " — ⚠️ والأداة تُطابق اللفظ لا المعنى: راجع الوجه، "
                    "فالمراد قد يكون غير ما طابقته الألفاظ."
                ),
            )
        )

    if stage is Stage.CASSATION:
        add(
            RULE_EVIDENCE_WEIGHING,
            "⚠️ وجهٌ يمسّ **تقدير الدليل أو وزن الوقائع**، والتمييز محكمة "
            "قانون لا محكمة وقائع: ما جرى استخلاصه من الدليل لا يُعاد. "
            "والمقبول في هذه المرحلة: خطأ في تطبيق القانون أو في الإجراء.",
            _MARKERS_EVIDENCE_WEIGHING,
        )
        add(
            RULE_NEW_CLAIM,
            "⚠️ **طلبٌ جديد**، والطلب الجديد لا يُقبل في التمييز: الخصومة "
            "تتحدّد في المرحلتين السابقتين، والتمييز لا يُنشئ طلباً.",
            _MARKERS_NEW_CLAIM,
        )
    elif stage is Stage.APPEAL:
        add(
            RULE_NEW_FACTS,
            "⚠️ وجهٌ **يعيد جدال الوقائع**، والاستئناف مراجعةٌ للحكم لا خصومةٌ "
            "جديدة: يُبيَّن الخطأ الذي وقع فيه الحكم، لا يُعاد سرد الوقائع "
            "وطلبُ وزنٍ آخر لها.",
            _MARKERS_NEW_FACTS,
        )
        add(
            RULE_NEW_CLAIM,
            "⚠️ **طلبٌ جديد**، ولا يُضاف في الاستئناف طلبٌ لم يكن في الدعوى "
            "الابتدائية.",
            _MARKERS_NEW_CLAIM,
        )
    elif stage is Stage.RECONSIDERATION:
        add(
            RULE_NEW_CLAIM,
            "⚠️ **طلبٌ جديد**، والمرحلة أضيق من الاستئناف: المقبول فيها تعذّرُ "
            "إبداء دفعٍ أو تقديم بيانٍ لم يكن مقدوراً عليه.",
            _MARKERS_NEW_CLAIM,
        )
    elif stage is Stage.EXECUTION:
        add(
            RULE_EXECUTION_NOT_THE_RIGHT,
            "⚠️ وجهٌ **يخوض في أصل الحقّ المحكوم به**، ومحلّ نزاع التنفيذ "
            "إجراءُ التنفيذ لا الحقّ الذي أثبته الحكم.",
            _MARKERS_UNDERLYING_RIGHT,
        )
    elif stage is Stage.ARBITRATION:
        add(
            RULE_ARBITRATION_JURISDICTION,
            "⚠️ **الاختصاص ونطاق شرط التحكيم يُنظران أولاً**، ولا يُخاض في "
            "الموضوع قبل استقرارهما: المحكّم لا ينظر بغير سندٍ من الاتّفاق.",
            _MARKERS_JURISDICTION,
        )
        add(
            RULE_ARBITRATION_SCOPE,
            "⚠️ وجهٌ **خارج نطاق ما أحاله الشرط**: التحكيم ينظر ما اتّفق عليه "
            "الطرفان لا كلّ ما له صلة بالنزاع.",
            _MARKERS_OUTSIDE_SCOPE,
        )
    # ⚠️ **والابتدائي لا قاعدة له في الجدول**: الموضوع مفتوح فيه، فلا وجه
    # يُمنع **لذاته**. وهذا ليس إغفالاً: أُعلن في ``STAGE_PROHIBITS`` نصّاً
    # بدل أن تُترك المرحلة بلا قيد، وكي لا تُقرأ المرحلة الغائبة من الجدول
    # «مرحلةً لم تُفحص».

    return tuple(found)


# ==============================================================================
# ٩. الدفوع المتداولة — **اقتراحٌ يُوسَم، لا دفعٌ يُضاف**
# ==============================================================================
# ⚠️⚠️ **ولماذا اقتراحٌ لا إضافة — وهذا هو العيب الثالث بعينه:**
#
# الدفوع المتداولة (التقادم، الإسقاط، عدم الاختصاص، المخالصة) تُقال في كل
# قضية تقريباً، **فتُرفع لأنها «تُقال» لا لأن في الملف ما يسندها**. والدفع
# الذي لا تسنده واقعة **يُسقطه الخصم أول مرة**، ويترتّب على إسقاطه أثرٌ أخطر
# من إسقاطه: **يُفقد الدفوع السليمة وزنها معه**، لأن المحامي الذي رفع دفعاً
# بلا سند عُرف بأنه يرمي ولا يصوّب، فيُقرأ دفعه الصحيح بعين الشك نفسه.
#
# ⚠️ **والأخطر أن الدفع الجاهز يُخفي ما يجب أن يُسأل:** إذا كان الجدول يُضيف
# الدفوع تلقائياً، **لم يبقَ موضع يسأل** «هل ينطبق التقادم على هذه الدعوى؟»
# — لأن الجواب صار مُدرجاً. فالسؤال يضيع بإدراج الجواب.
#
# فالقرار في هذا الملف: **لا يُضاف دفعٌ واحد**. ويُعرض البديل في مخرَج
# منفصل، موسومٌ بعبارة التحذير ``SUGGESTION_NOTE`` في **كل** بند منه.


def _stock_defence(
    key: str,
    label: str,
    stages: tuple[Stage, ...],
    is_procedural: bool,
    facts_required: tuple[str, ...],
    documents_required: tuple[str, ...],
) -> dict:
    """
    بناء بند اقتراح **خام** — ليبقى الجدول أدناه جدول بيانات لا كوداً.

    ⚠️ ووُجدت منفصلة لأن الجدول يُبنى بـ``_stock_defence`` **مرّة واحدة في
    القراءة لا في كل نداء**، فلا يُنسخ البند ولا يُعاد بناؤه في كل اقتراح.

    Args:
        key: رمز البند.
        label: اسم الدفع.
        stages: المراحل التي يُستحضر فيها.
        is_procedural: هل هو إجرائي؟
        facts_required: الوقائع التي **يلزم وجودها** في الملف لصلاحيته.
        documents_required: ما يلزم لإثباته.

    Returns:
        قاموس البند — و``prompt_only`` فيه ``True`` دائماً.
    """
    return {
        "key": key,
        "label": label,
        "stages": tuple(stage.value for stage in stages),
        "is_procedural": is_procedural,
        "facts_required": facts_required,
        "documents_required": documents_required,
        "prompt_only": True,
    }


