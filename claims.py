#: أسماء المواضع بالعربية — تُذكر في الرسالة، فالمحامي يقرأ **ما تمسّكنا به**
#: لا رمزاً لاتينياً.
GROUND_LABELS: dict[str, str] = {
    "setoff": "المقاصة / الخصم",
    "payment": "السداد",
    "intermediary": "نصيب الوسيط",
    "release": "المخالصة / التنازل",
}


def _grounds_in_text(text: str) -> tuple[str, ...]:
    """
    المواضع التي **يتمسّك بها نصٌّ** — بترتيب ``BURDEN_CARRYING_GROUNDS``.

    ⚠️ والمطابقة على **النصّ المطبَّع** وعلى **الجذر** («مقاصه»)، لأن أداة
    التعريف وضمير الملك تتغيّران والجذر لا يتغيّر. وهذا هو الفرق بين مطابقة
    تعمل ومطابقة تُعيد فراغاً دائماً — والفراغ يُقرأ سلامةً وهو جهل.

    ⚠️ **والمطابقة على الجذور تُنتج إنذارات كاذبة معلومة**، وهي أخفّ من
    العكس: لفظ «وسيط» يُطابق «وسيط الشحن» في نصّ لا علاقة له بنصيب الوسيط.
    فالحكم **يُعرض ليُقرأ** ولا يُسقط شيئاً، والقاعدة المعلنة في `facts.py`
    تُتبع هنا: الإنذار الكاذب يُقرأ ويُتجاهل، والعبء المقلوب يصل إلى المحكمة.

    >>> _grounds_in_text("يُخصم من المطالبة نصيب الوسيط")
    ('setoff', 'intermediary')
    >>> _grounds_in_text("لا شيء هنا")
    ()

    Args:
        text: النصّ الخام (شماله يُطبَّع).

    Returns:
        رموز المواضع التي وُجد لفظها، بلا تكرار، وبترتيب الثابت.
    """
    haystack = normalize(text)
    if not haystack:
        return ()
    found: list[str] = []
    for ground in BURDEN_CARRYING_GROUNDS:
        for marker in BURDEN_GROUND_MARKERS.get(ground, ()):
            if normalize(marker) in haystack:
                found.append(ground)
                break
    return tuple(found)


def grounds_in_item(item: MatrixItem) -> tuple[str, ...]:
    """
    المواضع المنقولة العبء التي **يتمسّك بها عنصرٌ** — من نصّه هو.

    ⚠️ **والقراءة تجري على ``label`` و``response`` معاً**، لا على واحد:
    الطلب يُصاغ في ``label`` ويُعلَّل في ``response``، و«المقاصة» قد تُذكر في
    أيّهما. ولو قُرئ أحدهما لَسقط نصف التمسّك.

    >>> grounds_in_item(_the_setoff_defence())
    ('setoff', 'intermediary')

    Args:
        item: الطلب أو الدفع.

    Returns:
        رموز المواضع، بترتيب ``BURDEN_CARRYING_GROUNDS``.
    """
    return _grounds_in_text(item.label + " " + item.response)


def burden_finding(item: MatrixItem, our_party: Party | None) -> Finding | None:
    """
    الحكم على عبء الإثبات في عنصر — **وهذا موضع العيب التاريخي**.

    القاعدة المطبَّقة:

    1. إن كان العنصر **يتمسّك بأحد المواضع الأربعة** (``BURDEN_CARRYING_GROUNDS``)
       **ولم يكن من نازع في أصله** — أي ليس على محور ``EXISTENCE`` وحده —
       فالعبء **علينا**، **سواء كنّا مدّعين أو مدّعى عليهم**. ومن قال «خصمت
       نصيب الوسيط» فهو الذي يجب أن يُثبت أنه خصمه.
    2. وإن كان التمسّك من **الخصم** (``claimed_by`` مخالف لنا)، فالعبء عليه.
    3. وإلا فالعبء على **من ادّعى**: ``claimed_by``.

    ⚠️ **والخطأ يقع في حالة واحدة، وهي العيب التاريخي بعينه:** العبء علينا في
    عنصرٍ تمسّكنا فيه بهذه المواضع و``documents_required`` **فارغ**. وحينها
    يُرفع ``CODE_OUR_GROUND_NEEDS_DOCUMENTS`` بدرجة **خطأ**، لأن الأثر ليس
    نقصاً في البيان بل **دفعٌ لا دليل له مع نقل عبئه إلى الخصم**.

    ⚠️ **ولماذا يُستثنى ``EXISTENCE`` وحده؟** لأن من **ينكر** الاستحقاق لا
    يحمل عبء إثبات الإنكار: هو لا يتمسّك بواقعة، بل ينفي واقعة ادّعاها خصمه.
    فالمقاصة المذكورة في **دفعٍ ينكر الاستحقاق** ليست تمسّكاً بواقعةٍ بل وصفٌ
    لما يقوله الخصم، ولا تُطالَب بدليل. وهذا موضع كان يمكن أن يُنتج إنذاراً
    كاذباً لو مُطابق اللفظ وحده.

    Args:
        item: الطلب أو الدفع.
        our_party: صفتنا، أو ``None`` إن لم تُعرف.

    Returns:
        ``Finding`` إن وُجد عيب، أو ``None`` — و``None`` **جوابٌ صحيح**
        (العنصر ليس من المواضع المنقولة العبء) لا فشل.

    >>> burden_finding(_the_setoff_defence(), Party.DEFENDANT) is not None
    True
    >>> burden_finding(_the_quantum_claim(), Party.CLAIMANT) is None
    True
    """
    grounds = grounds_in_item(item)
    if not grounds:
        return None

    on_one_axis = item.axes_in_dispute == (DisputeAxis.EXISTENCE,)
    if on_one_axis:
        # إنكارٌ لا تمسّكٌ بواقعة — لا عبء على المنكِر.
        return None

    names = " و".join(GROUND_LABELS.get(ground, ground) for ground in grounds)

    # ⚠️ **والتمسّك من الخصم يُقلب الحكم:** الدفع الذي يرفعه الخصم بخصمٍ
    # يُطالَب هو بدليله، لا نحن. ولو حُكم على اللفظ وحده لَحُمل عبؤه علينا
    # لمجرّد وروده في المصفوفة — وهو إنذار كاذب من الجنس الذي يُفقد التقرير.
    if our_party is not None and item.claimed_by is not our_party:
        return Finding(
            code=CODE_MISSING_DOCUMENTS,
            severity=SEVERITY_NOTICE,
            item_key=item.key,
            kind=_kind_of(item),
            message=(
                f"التمسّك بـ{names} مصدره الخصم، فعبء إثباته عليه لا علينا. "
                f"والمطلوب منّا أن نُبيّن ما ينقضه، لا أن نُثبته."
            ),
            note=f"المواضع المكتشفة: {', '.join(grounds)}",
        )

    if item.documents_required:
        return None

    return Finding(
        code=CODE_OUR_GROUND_NEEDS_DOCUMENTS,
        severity=SEVERITY_ERROR,
        item_key=item.key,
        kind=_kind_of(item),
        message=(
            f"تمسّكنا بـ{names}، والعبء في ذلك **علينا** لا على الخصم، ولم "
            f"يُذكر مستندٌ واحد يُثبته. ⚠️ ومن يتمسّك بواقعة هو المطالب "
            f"بإثباتها؛ فإن لم يكن في الملف مستندٌ يُثبتها فالتمسّك بها حجّة "
            f"لا وجود لها، والصواب أن تُسقط من المذكرة لا أن تُنقل تبعتها "
            f"إلى الخصم. المطلوب: تعبئة ``documents_required`` بمستندات "
            f"الإثبات."
        ),
        note=(
            "هذا هو العيب التاريخي: الموظف طُلب منه إثبات نصيب الوسيط، "
            "والشركة هي التي تمسّكت بالخصم."
        ),
    )


def burden_for(item: MatrixItem, our_party: Party | None = None) -> Burden:
    """
    عبء الإثبات في عنصر — القاعدة، ومنها المواضع المنقولة.

    ⚠️ **ولا تُقرأ ``item.burden`` متجاهلةً هذه الدالّة:** الحقل ما كتبه
    المستدعي، وهذه الدالّة **ما يجب** أن يكون. والافتراق بينهما هو **موضع
    السؤال**: العنصر الذي كُتب فيه ``ON_OPPONENT`` وهو من المواضع التي
    تمسّكنا فيها هو بعينه العيب التاريخي، ولا يُصلَح بصمت.

    والاشتقاق:

    1. عنصر يتمسّك بموضعٍ من ``BURDEN_CARRYING_GROUNDS`` ولم يكن على محور
       ``EXISTENCE`` وحده ⇒ ``ON_US``.
    2. ``claimed_by`` مجهول (``None``) ولا موضع منقول ⇒ ``UNKNOWN`` (ويُسأل).
    3. وإلا فعلى **من ادّعى**: ``claimed_by`` مقابل ``our_party``.
    4. و``claimed_by`` غير معروف مقابل ``our_party`` معروف ⇒ ``ON_OPPONENT``.

    >>> burden_for(_the_setoff_defence(), Party.DEFENDANT) is Burden.ON_US
    True
    >>> burden_for(_the_quantum_claim(), Party.CLAIMANT) is Burden.ON_US
    True
    >>> burden_for(_the_quantum_claim(), Party.DEFENDANT) is Burden.ON_OPPONENT
    True

    Args:
        item: الطلب أو الدفع.
        our_party: صفتنا، أو ``None``.

    Returns:
        ``Burden`` المقابل؛ و``UNKNOWN`` **مخرَج صحيح يُسأل عنه** لا فشل.
    """
    if grounds_in_item(item) and item.axes_in_dispute != (DisputeAxis.EXISTENCE,):
        return Burden.ON_US
    if item.claimed_by is None:
        return Burden.UNKNOWN
    if our_party is None:
        return Burden.UNKNOWN
    return Burden.ON_US if item.claimed_by is our_party else Burden.ON_OPPONENT


def _kind_of(item: MatrixItem) -> str:
    """نوع العنصر — ``"defence"`` أو ``"claim"``. يُقرأ بالصنف لا بحقل."""
    return "defence" if isinstance(item, Defence) else "claim"


