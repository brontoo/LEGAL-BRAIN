# ١١. تقاطع الوقائع — **الطلب الذي يستند إلى ادعاء**
# ==============================================================================
# ⚠️⚠️ **«الطلب المستند إلى واقعةٍ ادُّعيت طلبٌ لا يستند إلى شيء.»**
#
# وهذا أخطر من غياب الواقعة، لأن الواقعة الغائبة **تُطلب**، أما الواقعة
# المُدَّعاة فتُقرأ في المصفوفة **كأنها ثابتة**، فيُبنى عليها ردٌّ ثم يُنكر
# الخصم ما كُتب على أنه ثابت. وقد وقع هذا بعينه في `facts.py`:
#
#   «الموكّل يقول: اتفقنا على كذا» ⇒ «اتفق الطرفان على كذا» في المسودّة.
#
# ⚠️ **والعلاج هنا لا حذف:** العنصر يبقى في المصفوفة ويُوسَم. ولماذا؟ لأن
# **حذفه يُعيد العيب الأصلي** — يصير النقص صامتاً. أما وسمه فيجعله **سؤالاً
# يُجاب**: «هذا الطلب يستند إلى ادعاء لم يثبت بعد — فهل نطلب إثباته أم نُسقط
# الطلب؟»

#: الدرجات التي **لا تُسند** طلباً — ولا يُبنى عليها استحقاق.
#:
#: ⚠️ **و``DISPUTED`` و``UNCERTAIN`` ليستا هنا عن قصد:**
#:
#: * ``DISPUTED`` واقعةٌ **قائمة** وإن نوزع فيها، ولا يُقال إن الطلب المستند
#:   إليها «لا يستند إلى شيء» بل يُقال إنه مستندٌ إلى واقعة يُنازع فيها —
#:   وهذا حكمٌ آخر بمرتبة أخفّ. وجعلها في هذه المجموعة يُسقط طلباً له سندٌ
#:   حقيقي، وهو أشدّ من الإنذار الكاذب.
#: * ``UNCERTAIN`` عيبٌ في **القراءة** لا في الواقعة، ومحلّها
#:   ``FactLedger.needs_verification`` وقد كُفي هنا.
NO_STANDING_FOR_SUPPORT: frozenset[Standing] = frozenset(
    (Standing.CLAIMED, Standing.INFERRED)
)


def cross_check_facts(
    matrix: ClaimMatrix,
    ledger: FactLedger,
) -> tuple[Finding, ...]:
    """
    يقابل **مفاتيح وقائع المصفوفة** بسجلّ الوقائع — ويكشف ما لا سند له.

    الحكمان:

    1. مفتاح واقعة **ليس في السجلّ أصلاً** ⇒ ``CODE_FACT_UNKNOWN`` بدرجة
      ``error``: العنصر يُحيل إلى شيء لا وجود له، فلا يُتحقّق منه ولا يُقارَن
      به — وهو أسوأ من واقعة ضعيفة، لأن الضعيفة تُقوّى والمعدومة تُطلب.
    2. مفتاح واقعة **في السجلّ بدرجة لا تُسند** (``CLAIMED`` أو ``INFERRED``)
      في جانب ``supporting`` ⇒ ``CODE_FACT_ASSERTED_ONLY`` بدرجة ``error``:
      **الطلب المستند إلى ادعاء لا يستند إلى شيء.**

    ⚠️ **والجانب يُقرأ في الحكم:** الواقعة ``CLAIMED`` في جانب
    ``opposing_facts`` **ليست عيباً** بل هي الأصل في ادعاء الخصم — ووسمها
    عيباً إنذار كاذب من الجنس الذي يُفقد التقرير كلّه. وهذا هو سبب وجود
    ``FactCheck.side``.

    ⚠️ **ولا يُحذف العنصر ولا تُحذف الواقعة**، ولا يُعدَّل السجلّ: الحكم
    **عرضٌ** يُقرأ، والمصفوفة تبقى كما هي ليُقرّر المحامي.

    Args:
        matrix: المصفوفة.
        ledger: سجلّ الوقائع — يُقرأ ولا يُعدَّل.

    Returns:
        الأحكام، عنصراً عنصراً وبترتيب الإدخال.

    >>> findings = cross_check_facts(_the_matrix(), _the_ledger())
    >>> [f.item_key for f in findings]
    ['end_of_service']
    >>> claimable_total(_the_matrix(), _the_ledger())
    3
    """
    findings: list[Finding] = []
    for item in matrix.items:
        kind = _kind_of(item)
        for side, keys in (
            ("supporting", item.supporting_facts),
            ("opposing", item.opposing_facts),
        ):
            for key in keys:
                fact = ledger.of_key(key)
                if fact is None:
                    findings.append(
                        Finding(
                            code=CODE_FACT_UNKNOWN,
                            severity=SEVERITY_ERROR,
                            item_key=item.key,
                            kind=kind,
                            message=(
                                f"الواقعة «{key}» مذكورة في العنصر «{item.label}» "
                                f"وهي **ليست في سجلّ الوقائع**، فلا تُتحقّق ولا "
                                f"تُقارَن. المطلوب: تسجيلها في السجلّ بمصدرها "
                                f"ودرجتها، أو حذف الإحالة إليها."
                            ),
                            note=f"الجانب: {side} · المفاتيح المتاحة: "
                                 + (", ".join(f.key for f in ledger.facts) or "—"),
                        )
                    )
                    continue
                if (
                    side == "supporting"
                    and fact.standing in NO_STANDING_FOR_SUPPORT
                ):
                    findings.append(
                        Finding(
                            code=CODE_FACT_ASSERTED_ONLY,
                            severity=SEVERITY_ERROR,
                            item_key=item.key,
                            kind=kind,
                            message=(
                                f"الطلب «{item.label}» يستند في جانبه المؤسِّس "
                                f"إلى الواقعة «{key}» ودرجتها "
                                f"«{fact.standing_label}» — **فهو لا يستند إلى "
                                f"شيء**: الواقعة المُدَّعاة تُقرأ في المصفوفة "
                                f"كأنها ثابتة، فيُبنى عليها ردٌّ ثم يُنكر الخصم "
                                f"ما كُتب على أنه ثابت. المطلوب: مستندٌ يُسندها "
                                f"أو إقرارٌ من الخصم، وإلا فالمطالبة بلا أساس."
                            ),
                            note=(
                                f"مصدر الواقعة: {fact.source} · موضعها: {fact.locus} "
                                f"· الجانب: {side}. ⚠️ والعنصر **يبقى في "
                                f"المصفوفة** ولا يُحذف: الحذف يُعيد العيب "
                                f"صامتاً."
                            ),
                        )
                    )
    return tuple(findings)


def fact_checks(
    matrix: ClaimMatrix,
    ledger: FactLedger,
) -> tuple[FactCheck, ...]:
    """
    نتيجة المقابلة **مفصّلة لكل مفتاح** — لا الأحكام وحدها.

    ⚠️ **ووُجدت منفصلة عن ``cross_check_facts`` لا مكرّرةً لها:** الأولى
    تُنتج **أحكاماً** (خطأ/ملاحظة) تُعرض في التقرير، وهذه تُنتج **جدول
    المقابلة** كاملاً — بما فيه ما سلم. ولماذا يهمّ السالم؟ لأن **غياب
    الإنذار لا يُقرأ سلامة** بلا دليل على أن الواقعة فُحصت: «لا اعتراض»
    و«لم يُفحص» سيّان في التقرير، والفرق بينهما فرقٌ في الائتمان — وهو الدرس
    المكتوب في `attribution.py` عند ``_summary_line`` وفي `review.py` عند
    ``dropped``.

    >>> [(check.fact_key, check.standing) for check in fact_checks(_the_matrix(), _the_ledger())]
    [('service.ended', 'agreed'), ('release.refused', 'claimed'), ('service.ended', 'agreed'), ('claim.filed', 'disputed')]

    Args:
        matrix: المصفوفة.
        ledger: سجلّ الوقائع.

    Returns:
        صفوف المقابلة، بترتيب العناصر وجوانبها.
    """
    checks: list[FactCheck] = []
    for item in matrix.items:
        for side, keys in (
            ("supporting", item.supporting_facts),
            ("opposing", item.opposing_facts),
        ):
            for key in keys:
                fact = ledger.of_key(key)
                if fact is None:
                    checks.append(
                        FactCheck(
                            item_key=item.key,
                            kind=_kind_of(item),
                            fact_key=key,
                            side=side,
                            standing="",
                            note="⚠️ ليست في سجلّ الوقائع — لا تُتحقّق ولا تُقارَن.",
                        )
                    )
                    continue
                note = f"درجتها: {fact.standing_label}."
                if side == "supporting" and fact.standing in NO_STANDING_FOR_SUPPORT:
                    note += " ⚠️ ولا تُسند طلباً."
                checks.append(
                    FactCheck(
                        item_key=item.key,
                        kind=_kind_of(item),
                        fact_key=key,
                        side=side,
                        standing=fact.standing.value,
                        note=note,
                    )
                )
    return tuple(checks)


def claimable_total(matrix: ClaimMatrix, ledger: FactLedger) -> int:
    """
    عدد مفاتيح الوقائع التي **تُسند فعلاً** في المصفوفة — بعد المقابلة بالسجلّ.

    ⚠️ ووُجدت لأن العدد الكامل **يكذب**: مصفوفة بعشرة مفاتيح إسناد قد لا يكون
    في سجلّها إلا مفتاحان مسندان، والرقم الأول يُقرأ قوّةً والثاني حقيقة.
    وهذا هو الفرق بين «كم كتبنا» و«كم لنا» — وهو الفرق الذي يقوم عليه هذا
    الملف.

    >>> claimable_total(_the_matrix(), _the_ledger())
    3

    Args:
        matrix: المصفوفة.
        ledger: سجلّ الوقائع.

    Returns:
        العدد — ولا يُحتسب مفتاح غير موجود، ولا مفتاح درجته لا تُسند.
    """
    return sum(
        1
        for check in fact_checks(matrix, ledger)
        if check.standing and check.standing not in {
            standing.value for standing in NO_STANDING_FOR_SUPPORT
        }
    )


# ==============================================================================
# ١٢. أحكام المصفوفة — ما لا يمنع التسليم وما يمنعه
# ==============================================================================
# ⚠️ **والأحكام الثلاثة الوحيدة التي تُحسب من العنصر نفسه** — وهي التي طلبها
# التعريف صراحةً:
#
#   * ``outcome_sought`` فارغ ⇒ **خطأ**: الردّ بلا نتيجة مطلوبة يُقرأ في
#     المستند تسليماً أو إغفالاً، وكلاهما ليس ما أراده الكاتب.
#   * ``documents_required`` فارغ والعبء علينا ⇒ **خطأ**: يُلتقط في
#     ``burden_finding`` عند المواضع المنقولة، ويُلتقط هنا **في كل موضع** لأن
#     العبء قد يكون علينا بغير موضع منقول (طلبٌ رفعناه نحن).
#   * ولا وقائع في الجانبين ⇒ **خطأ**: العنصر الذي لا واقعة له ولا واقعة على
#     خصمه **غير قابل للتحقيق** — لا يُنفَّذ ولا يُدفع.


def _defect_findings(matrix: ClaimMatrix) -> tuple[Finding, ...]:
    """
    الأحكام المستخرجة من العناصر نفسها — بلا تدخّل المستدعي.

    ⚠️ **والدالّة خاصة (``_``) لأنها ليست من واجهة الوحدة:** الأحكام تُجمع
    في ``summarize``، ومن استدعاها منفصلةً قد يفوته بعضها فيقرأ تقريراً
    ناقصاً. والواجهة الواحدة أسلم من واجهتين تفترقان — وهو العيب المكتوب في
    ``_STAGE_OF_CASE_STAGE``.
    """
    findings: list[Finding] = []
    for item in matrix.items:
        kind = _kind_of(item)
        if not item.outcome_sought.strip():
            findings.append(
                Finding(
                    code=CODE_MISSING_OUTCOME,
                    severity=SEVERITY_ERROR,
                    item_key=item.key,
                    kind=kind,
                    message=(
                        f"العنصر «{item.label}» بلا ``outcome_sought``: الردّ بلا "
                        f"نتيجة مطلوبة يُقرأ في المستند تسليماً أو إغفالاً — "
                        f"وكلاهما ليس ما أراده الكاتب. المطلوب: كتابة النتيجة "
                        f"(رفض، عدم قبول، إلزام بمبلغ، تعديل الحكم)."
                    ),
                )
            )
        if not item.supporting_facts and not item.opposing_facts:
            findings.append(
                Finding(
                    code=CODE_NO_FACTS,
                    severity=SEVERITY_ERROR,
                    item_key=item.key,
                    kind=kind,
                    message=(
                        f"العنصر «{item.label}» بلا وقائع في الجانبين: لا واقعة "
                        f"تسنده ولا واقعة على خصمه، فهو **غير قابل للتحقيق** — "
                        f"لا يُنفَّذ ولا يُدفع. المطلوب: إسناده إلى وقائع السجلّ، "
                        f"أو إعلانه مسألةً قانونية بلا وقائع بصراحة."
                    ),
                )
            )
    return tuple(findings)


def summarize(
    matrix: ClaimMatrix,
    findings: tuple[Finding, ...] = (),
    *,
    ledger: FactLedger | None = None,
    draft: str = "",
    stage: Stage | None = None,
    suggestions: tuple[SuggestedDefence, ...] = (),
) -> dict:
    """
    المصفوفة وأحكامها في قاموس **صالح للبثّ كـ JSON**.

    ⚠️ **و``findings`` المُمرَّرة تُضمّ إلى المحسوبة، ولا تُنقصها:** من فحص
    المصفوفة بأداة أخرى (أو بنى حكماً بيده) يُمرّرها فتُعرض مع الباقي. ولو
    كان الحقل **بديلاً** لَما استُعمل التقرير إلا في صورة واحدة — وهو ما يمنع
    جمعه في مسار واحد.

    ⚠️ **و``clean`` تُحسب من الأخطاء وحدها** — على قاعدة `review.py` و
    `attribution.py`: ما لا يمنع التسليم **لا يجوز أن يمنعه**. فاقتراحُ دفعٍ
    لم يُتبنَّ وعبءٌ لم يُحدَّد **ملاحظتان**، لا خطأين: ومن جعلهما خطأً منع
    تسليم مصفوفة سليمة، فتُهمَل الأخطاء كلها معه.

    ⚠️ **وتُشغَّل الأقيسة كلها بلا استثناء**، ولا تُشغَّل إلا بشرطها: الوحدات
    الثلاث التي تحتاج سياقاً (``ledger`` و``draft`` و``stage``) لا تُشغَّل
    بلا سياق، **لأن تشغيلها بلا سياق يُنتج إنذارات كاذبة** — وهذا حدّ أعلن
    لا خطأ مُخفي.

    ⚠️ **وصفتنا تُقرأ من ``matrix.our_party``**، ولا تُمرَّر هنا مرّة ثانية:
    تمريرها في موضعين يجعل المصفوفة تقول صفتنا وهذا النداء يقول غيرها،
    فيُحكم على العبء بصفتين — وهو عين العيب الذي وُجد هذا الملف لمنعه.

    >>> payload = summarize(_the_matrix())
    >>> payload["clean"], payload["error_count"] > 0
    (False, True)
    >>> summarize(ClaimMatrix())["clean"]
    True

    Args:
        matrix: المصفوفة — ومنها صفتنا ومنها المرحلة.
        findings: أحكام إضافية من المستدعي.
        ledger: سجلّ الوقائع — يُفعِّل ``cross_check_facts``.
        draft: نصّ المسودّة — يُفعِّل ``unanswered``.
        stage: المرحلة — تُفعِّل ``validate_for_stage``.
        suggestions: اقتراحات لم تُتبنَّ — تُعرض بدرجة ``notice``.

    Returns:
        قاموس JSON-safe: عدّادات بالمحاور والعبء والدرجة، وعلم ``clean``،
        وتفصيل عنصراً عنصراً.
    """
    collected: list[Finding] = list(findings)
    collected.extend(_defect_findings(matrix))

    # ⚠️ والعبء والحكم يجريان على **كل** عنصر، والمواضع المنقولة تُلتقط فيهما.
    for item in matrix.items:
        if item.burden is Burden.UNKNOWN:
            collected.append(
                Finding(
                    code=CODE_UNKNOWN_BURDEN,
                    severity=SEVERITY_NOTICE,
                    item_key=item.key,
                    kind=_kind_of(item),
                    message=(
                        f"عبء الإثبات في «{item.label}» **لم يُحدَّد** — "
                        f"``Burden.UNKNOWN``. ولا تُقرأ ``ON_NEITHER`` مكانها: "
                        f"«لا أعرف» ليست «لا عبء». المطلوب: تحديد من يتمسّك "
                        f"بالواقعة فيه."
                    ),
                )
            )
        # ⚠️ والعنصر الذي كُتب فيه ``ON_OPPONENT`` وهو من المواضع المنقولة
        # **يُنذر هنا أيضاً**: الافتراق بين ما كُتب وما يجب هو العيب التاريخي
        # بعينه، ولا يجوز أن يمرّ بلا إعلان.
        derived = burden_for(item, matrix.our_party)
        if (
            derived is Burden.ON_US
            and item.burden is Burden.ON_OPPONENT
        ):
            collected.append(
                Finding(
                    code=CODE_OUR_GROUND_NEEDS_DOCUMENTS,
                    severity=SEVERITY_NOTICE,
                    item_key=item.key,
                    kind=_kind_of(item),
                    message=(
                        f"العنصر «{item.label}» كُتب فيه أن العبء على الخصم، "
                        f"وهو **علينا**: من يتمسّك بخصمٍ أو سدادٍ أو تنازلٍ "
                        f"يجب أن يُثبته، ولا ينتقل العبء إلى الخصم لأننا "
                        f"قلنا ذلك. المطلوب: تصحيح ``burden`` وتعبئة "
                        f"``documents_required``."
                    ),
                    note="⚠️ هذا هو العيب التاريخي: الموظف طُلب منه إثبات نصيب الوسيط.",
                )
            )
        burden_finding_for_item = burden_finding(item, matrix.our_party)
        if burden_finding_for_item is not None:
            collected.append(burden_finding_for_item)

    if ledger is not None:
        collected.extend(cross_check_facts(matrix, ledger))
    if draft:
        collected.extend(unanswered(matrix, draft))
    if stage is not None:
        for item in matrix.items:
            for violation in validate_for_stage(item, stage):
                collected.append(
                    Finding(
                        code=CODE_STAGE_GROUND,
                        severity=SEVERITY_ERROR,
                        item_key=violation.item_key,
                        kind=violation.kind,
                        message=violation.message,
                        note=f"القاعدة: {violation.rule} · {violation.note}",
                    )
                )
    for suggestion in suggestions:
        collected.append(
            Finding(
                code=CODE_SUGGESTED_NOT_ADOPTED,
                severity=SEVERITY_NOTICE,
                item_key=suggestion.key,
                kind="defence",
                message=(
                    f"دفعٌ متاح في هذه المرحلة ولم يُرفع: «{suggestion.label}». "
                    f"⚠️ وهو **دعوةٌ إلى النظر** لا دفعٌ مطلوب، ولا يُضاف إلى "
                    f"المصفوفة من هذا الملف."
                ),
                note=suggestion.note,
            )
        )

    return _summary(matrix, tuple(collected), suggestions)


def _summary(
    matrix: ClaimMatrix,
    findings: tuple[Finding, ...],
    suggestions: tuple[SuggestedDefence, ...] = (),
) -> dict:
    """
    بناء القاموس المبثوث — موضع واحد للعدّ والعرض.

    ⚠️ **والعدّادات كلها مشتقّة هنا ولا محفوظة في المصفوفة:** العدد المحفوظ
    يكذب على المصفوفة بعد أول تعديل، وهي قاعدة ``CaseFile.summary`` نصّاً:
    ``blocking_missing`` محسوب **لا محفوظ**.
    """
    axes: dict[str, int] = {axis.value: 0 for axis in DisputeAxis}
    burdens: dict[str, int] = {burden.value: 0 for burden in Burden}
    for item in matrix.items:
        for axis in item.axes_in_dispute:
            axes[axis.value] = axes.get(axis.value, 0) + 1
        burdens[item.burden.value] = burdens.get(item.burden.value, 0) + 1

    errors = [finding for finding in findings if finding.severity == SEVERITY_ERROR]
    notices = [finding for finding in findings if finding.severity == SEVERITY_NOTICE]

    return {
        "summary": _summary_line(matrix, len(errors), len(notices), len(suggestions)),
        "clean": not errors,
        "error_count": len(errors),
        "notice_count": len(notices),
        "claim_count": len(matrix.claims),
        "defence_count": len(matrix.defences),
        "stage": matrix.stage.value,
        "our_party": matrix.our_party.value if matrix.our_party else None,
        "by_axis": axes,
        "by_burden": burdens,
        "by_severity": {
            SEVERITY_ERROR: len(errors),
            SEVERITY_NOTICE: len(notices),
        },
        "order": [item.key for item in order_for_review(matrix)],
        "gates": list(review_order_labels(matrix)),
        "findings": [
            {
                "code": finding.code,
                "severity": finding.severity,
                "item_key": finding.item_key,
                "kind": finding.kind,
                "message": finding.message,
                "note": finding.note,
            }
            for finding in findings
        ],
        "claims": [_item_payload(item) for item in matrix.claims],
        "defences": [_item_payload(item) for item in matrix.defences],
        "suggested_defences": [
            {
                "key": suggestion.key,
                "label": suggestion.label,
                "stage": suggestion.stage,
                "is_procedural": suggestion.is_procedural,
                "facts_required": list(suggestion.facts_required),
                "documents_required": list(suggestion.documents_required),
                "prompt_only": suggestion.prompt_only,
                "note": suggestion.note,
            }
            for suggestion in suggestions
        ],
        "rules": {
            "suggestion_is_not_a_pleading": SUGGESTION_NOTE,
            "procedural_gates_come_first": PROCEDURAL_ORDER_RULE,
        },
    }


def _item_payload(item: MatrixItem) -> dict:
    """
    العنصر في صورة صالحة للبثّ — **بالقيم الآلية والأسماء العربية معاً**.

    ⚠️ والاسمان العربي والآلي **يُبثّان معاً** على قاعدة ``CaseFile.summary``:
    الواجهة تحتاج المفتاح لتُصفّي، والمحامي يحتاج الاسم ليقرأ. ولو بُثّ أحدهما
    لاحتاج كلٌّ منهما جدولاً عنده — فيصير للمشروع جدولان يفترقان.
    """
    payload = {
        "key": item.key,
        "kind": _kind_of(item),
        "label": item.label,
        "claimed_by": item.claimed_by.value if item.claimed_by else None,
        "elements": list(item.elements),
        "supporting_facts": list(item.supporting_facts),
        "opposing_facts": list(item.opposing_facts),
        "evidence": list(item.evidence),
        "axes_in_dispute": [
            {
                "axis": axis.value,
                "label": AXIS_LABELS.get(axis.value, axis.value),
                "question": AXIS_QUESTIONS.get(axis.value, ""),
            }
            for axis in item.axes_in_dispute
        ],
        "burden": item.burden.value,
        "burden_label": BURDEN_LABELS.get(item.burden.value, item.burden.value),
        "burden_derived": burden_for(item).value,
        "response": item.response,
        "outcome_sought": item.outcome_sought,
        "documents_required": list(item.documents_required),
        "gate": GATE_LABELS.get(_gate_of(item) or MERITS, MERITS_LABEL),
    }
    if isinstance(item, Defence):
        payload["is_procedural"] = item.is_procedural
    return payload


def _summary_line(
    matrix: ClaimMatrix,
    error_count: int,
    notice_count: int,
    suggestion_count: int,
) -> str:
    """
    سطر عربي واحد يصلح للعرض — **والفراغ فيه يُعلَن جواباً صحيحاً**.

    ⚠️ **والمصفوفة الفارغة تقول إنها فارغة ولا تُعتذر** — على قاعدة
    ``build_review_prompt`` في `review.py`: «المصفوفة الفارغة جواب صحيح
    ومتوقَّع». ولماذا يُقال صراحةً؟ لأن التقرير الفارغ **يُقرأ نقصاً في التشغيل**
    فيُملأ بما ليس منه، أو يُقرأ سلامةً وهو لم يُملأ بعد — والاثنان يُمنعان
    بالنصّ: «لا طلبات ولا دفوع في المصفوفة» و«الأداة لم تجد ما تعترض عليه»
    سيّان في الفراغ ومختلفان في المعنى.
    """
    if not matrix.items:
        line = (
            "لا طلبات ولا دفوع في المصفوفة — **وهذا جوابٌ صحيح** لا نقص: "
            "المصفوفة الفارغة تعني أنه لم يُسجَّل طلبٌ بعد، أو أن المصفوفة "
            "سليمة بلا اعتراض. ولا يُخترع طلبٌ ولا دفعٌ لتمتلئ."
        )
    else:
        line = (
            f"{len(matrix.claims)} طلباً و{len(matrix.defences)} دفعاً، "
            f"بترتيب: {' ثم '.join(review_order_labels(matrix))}."
        )
        if error_count:
            line += f" ⚠️ {error_count} خطأً يمنع التسليم."
        else:
            line += " لا خطأ يمنع التسليم."
        if notice_count:
            line += f" و{notice_count} ملاحظة للعلم."
    if suggestion_count:
        line += (
            f" ومعها {suggestion_count} دفعاً مقترحاً للنظر — "
            f"**اقتراحاً لا دفعاً مرفوعاً**."
        )
    return line


