"""
مصفوفة الطلبات والدفوع — طلباً طلباً، ودفعاً دفعاً، وبالمرحلة.
=============================================================================

المشكلة التي يحلّها
------------------
ثلاث مراجعات قانونية مستقلّة رصدت في مذكرات هذا المشروع **نمطاً واحداً**:
الصياغة تعاملت مع القضية **كتلةً واحدة**. فتكرّر أربعة عيوب بعينها:

١. **طلبات أُجيب عنها وأخرى أُغفلت.** المذكرة تردّ على بعض الطلبات وتسكت عن
   غيرها، ولا شيء يُسمّي **ما لم يُجَب** — فيُسلَّم المستند ناقصاً بلا أن يلاحظ
   أحد، لأن النقص **صمتٌ لا خطأ**.

٢. **خلط أربعة أسئلة مختلفة في سؤال واحد.** «هل الاستحقاق ثابت أصلاً؟» غير
   «وكم مقداره؟» غير «وهل صار مستحقّاً؟» غير «وهل يمكن إثباته؟». والصياغة
   كانت تُجيب عن أحدها وتُقرأ كأنها أجابت عن الأربعة. ⚠️ **وأخطر ما في الخلط
   أنّ «نسلّم بأصل الاستحقاق وننازع في المقدار» و«ننكر الاستحقاق» دفعتان
   مختلفتان تماماً**، ولكلٍّ منهما عبءٌ ونتيجة: الأولى تُسقط المطالبة إلى حدّ،
   والثانية تُسقطها كلها. فمن جمعهما في نصّ واحد كتب دفعةً لا يقولها.

٣. **دفوع جاهزة لا تسندها وقائع.** تُرفع الدفوع المتداولة (تقادم، إسقاط،
   مخالصة) لأنها «تُقال عادةً»، لا لأن في الملف ما يسندها. ⚠️ **والدفع بلا
   واقعة يُضعف الدفوع كلها**، لأن الخصم يُسقطه أولاً، فتفقد الدفوع السليمة
   معه وزنها: من رفع دفعاً لا سند له عُرف بأنه يرمي ولا يصوّب.

٤. **نقل عبء الإثبات إلى الخصم.** وقع في المسودّة أن **الشركة** تمسّكت بخصم
   نصيب وسيط من المطالبة، **وطالبَت الموظف بأن يثبت نصيب الوسيط**. وهذا قلبٌ
   للعبء: من يتمسّك بخصم أو سداد أو تنازل **هو** من يجب أن يُقدّم ما يثبته.
   ⚠️ **والتفصيل مكتوب مرّة واحدة عند `BURDEN_GROUND_MARKERS` — فاقرأه.**

ولماذا مصفوفة، لا مذكرة أفضل؟
-----------------------------
لأن العيوب الأربعة ليست في **الصياغة** بل في **التفكيك**: ما دامت القضية
تُمرَّر كتلةً نصّية واحدة، فلا موضع في المنظومة يسأل «أيّ طلب هذا؟» ولا «أيّ
الأسئلة الأربعة يُنازَع فيه؟» ولا «على مَن عبؤه؟». فالمصفوفة تُفكّك أوّلاً،
**وحينها يصير كلّ عيب قابلاً للقياس**، لأن كل عيب يصبح سؤالاً على عنصر مفرد:
هل نازعناه في مقداره أم في أصله؟ وهل عليه دليل أم لا؟

المبدأ التصميمي — على نمط `citations.py` و`case_file.py` و`facts.py`
------------------------------------------------------------------
> **النموذج يروي، والخادم يُقرّر.**

فالملف **بلا حالة وبلا إدخال/إخراج وبلا شبكة وبلا طباعة**: مكتبة بايثون
القياسية وحدها، ودوالّه نقية، **ولا يضيف دفعاً ولا يخترع واقعة**. ومن لم
يُمرّر له دفعٌ لا يجد دفعاً في المصفوفة — والاقتراح مخرَج آخر، مُوسَم.

⚠️ **وما ليس هذا الملف**
-----------------------
هو **ليس رَأياً قانونياً**، ولا يعرف قانوناً. هو:
* **الأسئلة الأربعة** مفصولةً بعضها عن بعض (``DisputeAxis``)،
* **وعبء الإثبات** موسوماً على كل عنصر (``Burden``)،
* **وما يلزم لإثبات ما تمسّكنا به** (``documents_required``)،
* **وما لا تقبله المرحلة** من أوجه (``stage_constraints``)،
* **وما أُغفل** في مسودّة (``unanswered``).

والجواب في كلّها يبقى **للمحامي**، وهذا صريح في مواضعه أدناه.

⚠️ **وإعادةُ استخدام الأنواع لا نسخُها**
--------------------------------------
``CaseFile`` و``CaseStage`` و``Party`` و``BLOCKING_FIELDS`` تُستورد من
`case_file.py`، و``Fact`` و``FactLedger`` و``Standing`` من `facts.py`. ولماذا؟
لأن النسخة الثانية **تفترق عن الأولى عند أول تعديل**، فيصير للمشروع تعريفان
لـ«عبء الإثبات» يفترقان، وهذا بعينه العيب الذي جاءت هذه الوحدات لمنعه:
**رقمان لشيء واحد.**
"""

