# ٢. المرحلة — وما تقبله من أوجه
# ==============================================================================
# ⚠️ **ولماذا ``Stage`` غير ``CaseStage``؟**
#
# لأن السؤالين مختلفان: ``CaseStage`` في `case_file.py` **حقل في ملف القضية**
# يُبنى عليه نمط المستند المطلوب. أما ``Stage`` هنا فهو **موضع العرض**:
# ترتيب البوابات، وما تقبله المرحلة من أوجه، وأيّ دفوع تُقترح فيها. فالملف
# يقول «القضية في التميز»، والمصفوفة تقول «إذن لا يُطعن بتقدير الدليل».
#
# ⚠️ **والتكرار هنا ليس نسخاً بل عرضٌ لمجموعة القيم نفسها**، والفرق بينهما
# يُمنع بفحص لا بتعليق: ``stage_of_case`` تُطابق كل قيمة، و`test_claims.py`
# يشهد على **الجولة الكاملة** بين التصنيفين. فلو أُضيفت مرحلة في `case_file.py`
# ولم تُضَف هنا، ظهر النقص في الاختبار لا في عين المراجع — وهذا هو الدرس
# المكتوب في `case_file.py` عند ``EMIRATE_ALIASES``.


class Stage(str, Enum):
    """
    مرحلة الخصومة كما تُعرض في المصفوفة — وتُشتقّ من ``CaseFile.stage``.

    ⚠️ **ولا تُشتقّ من نصّ**، بل من قيمة ``CaseStage`` عبر ``stage_of_case``،
    فالمطابقة على التصنيف المغلق لا على وصف حرّ — والعيب الذي وقع في مطابقة
    الجهة في `case_file.py` كان من مطابقة النصّ الحرّ.
    """

    FIRST_INSTANCE = "first_instance"
    APPEAL = "appeal"
    CASSATION = "cassation"
    RECONSIDERATION = "reconsideration"
    EXECUTION = "execution"
    ARBITRATION = "arbitration"


#: المرحلة المقابلة لكل قيمة في ``CaseStage`` — **والجدول كامل لا ناقص**.
#:
#: ⚠️ ووُجد ليكون النقص **ظاهراً**: من أضاف قيمة إلى ``CaseStage`` ولم يُضفها
#: هنا يرفع ``stage_of_case`` استثناءً بدل أن تُقرأ المرحلة خطأً.
_STAGE_OF_CASE_STAGE: dict[CaseStage, Stage] = {
    CaseStage.FIRST_INSTANCE: Stage.FIRST_INSTANCE,
    CaseStage.APPEAL: Stage.APPEAL,
    CaseStage.CASSATION: Stage.CASSATION,
    CaseStage.RECONSIDERATION: Stage.RECONSIDERATION,
    CaseStage.EXECUTION: Stage.EXECUTION,
    CaseStage.ARBITRATION: Stage.ARBITRATION,
}


def stage_of_case(case: CaseFile) -> Stage:
    """
    مرحلة المصفوفة — مشتقّة من ملف القضية لا مكتوبة بيد المستدعي.

    ⚠️ **ولماذا تُشتقّ ولا تُمرَّر؟** لأن تمريرها يفتح باباً لافتراق صامت:
    ملفٌّ يقول «استئناف» ومصفوفة تقول «ابتدائي»، فيُقترح في المستند ما لا
    تقبله مرحلته. والاشتقاق **يجعل الافتراق مستحيلاً** لا مُنذَراً.

    Args:
        case: ملف القضية.

    Returns:
        المرحلة المقابلة.

    Raises:
        ValueError: إن كانت مرحلة الملف غير مسجَّلة في الجدول — وهذا لا يقع
            إلا بعد تعديل ``CaseStage`` بلا تعديل الجدول، وهو **العيب المقصود
            كشفه**.

    >>> stage_of_case(_an_appeal_case()) is Stage.APPEAL
    True
    """
    stage = _STAGE_OF_CASE_STAGE.get(case.stage)
    if stage is None:
        raise ValueError(
            f"مرحلة غير مسجَّلة في جدول العرض: {case.stage!r} — أضفها إلى "
            f"_STAGE_OF_CASE_STAGE في هذا الملف. ⚠️ ولا تُقرأ خطأً: مطابقة "
            f"المرحلة تُبنى عليها الأوجه المقبولة، وخطؤها يُنتج مستنداً "
            f"صحيحاً في مرحلة وخاطئاً في التي ينظرها القضاء."
        )
    return stage


