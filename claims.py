# ١٠. ما أُغفل — الطلب الذي لا يُجاب
# ==============================================================================
# ⚠️ **والعيوب الثلاثة الأخرى في هذا الملف كلها تُصلَح بالقراءة، وهذا يُصلَح
# بالسؤال:** «ما لم يُجَب؟» لا يجيبه إلا حصرٌ. والمراجعات وجدت **طلبات أُجيب
# عنها وأخرى أُغفلت** بلا أن يُلاحظ أحد، لأن الإغفال صمتٌ لا خطأ — والصمت لا
# يُقرأ عيباً لأنه لا يقول شيئاً.


def unanswered(matrix: ClaimMatrix, draft: str) -> tuple[Finding, ...]:
    """
    عناصر المصفوفة **التي لم تخاطبها المسودّة** — الطلبات والدفوع.

    ⚠️ **والمطابقة على النصّ المطبَّع**، وعلى ``key`` و``label`` معاً:
    المسودّة تذكر الطلب بلفظه («مكافأة نهاية الخدمة») أو بمفتاحه إن كان
    المستدعي يكتب مفاتيحه في متن المسودّة. ولو طوبقت التسمية وحدها لَسقطت
    مسودّةٍ تعمل بالمفاتيح، ولو طوبق المفتاح وحده لَسقطت مسودّةٍ بلغة المحكمة.

    ⚠️⚠️ **وحدّ المطابقة معلن:** المطابقة **لفظية**، فمسودّة تعالج الطلب
    بمعناه بلا أن ترد فيه ألفاظه **تُعدّ غير مجيبة**. وهذا **خطأ سالب معلن**
    لا يمكن إصلاحه بلا نموذج يفهم المعنى — وهو مرفوض عن قصد لأن هذه الدالّة
    يجب أن تبقى حتمية. والمخرَج **يُعرض ليُقرأ** ولا يُسقط شيئاً: «لم تُجَب»
    دعوى قابلة للردّ، لا حكم.

    Args:
        matrix: المصفوفة.
        draft: نصّ المسودّة — حرّ.

    Returns:
        ``Finding`` لكل عنصر لم يُخاطَب، برمز ``CODE_UNANSWERED`` ودرجة
        ``notice`` — لأن الخطأ هنا **موضع نظرٍ للمحامي** لا حكمٌ على المسودّة.

    >>> [f.item_key for f in unanswered(_the_matrix(), "لم نخاطب شيئاً")]
    ['end_of_service', 'arbitration_clause', 'limitation']
    """
    haystack = normalize(draft)
    findings: list[Finding] = []
    for item in matrix.items:
        key = normalize(item.key)
        label = normalize(item.label)
        addressed = bool(haystack) and (
            (key and key in haystack) or (label and label in haystack)
        )
        if addressed:
            continue
        findings.append(
            Finding(
                code=CODE_UNANSWERED,
                severity=SEVERITY_NOTICE,
                item_key=item.key,
                kind=_kind_of(item),
                message=(
                    f"العنصر «{item.label}» في المصفوفة، ولا تخاطبه المسودّة. "
                    f"⚠️ والإغفال صمتٌ لا خطأ: يُقرأ على أنه لم يكن، وهو "
                    f"قائم. المطلوب: ردٌّ عليه، أو إعلانٌ صريح بأنه غير "
                    f"منازَع فيه."
                ),
                note=(
                    "المطابقة لفظية على المفتاح أو على نصّ الطلب — فإن عالجت "
                    "المسودّة العنصر بمعناه بلا ألفاظه، فهذا إنذار كاذب "
                    "معلن."
                ),
            )
        )
    return tuple(findings)


