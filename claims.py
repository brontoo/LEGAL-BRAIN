# ⚠️ **و``Claim`` و``Defence`` نوعان لا نوع واحد بحقلٍ يميّز.**
#
# لأن الفرق بينهما **ليس وصفاً بل جوهراً**: الطلب دعوى يُطالب بها، والدفع
# جوابٌ يُجاب به، ولكلٍّ منهما عبءٌ ونتيجة. ولو جُمعا في dataclass واحد بحقل
# «النوع» لجاز أن يُقرأ دفعٌ مكان طلب في الترتيب وفي العدّ، **وهما مختلفان في
# الاتّجاه**. والتكرار في الحقول مقصود ومُنذَر: الفرق الوحيد بين النوعين
# ``is_procedural``، وأي حقل يزاد في أحدهما ولا يزاد في الآخر **يُكشف**
# لأنِّي أُعلن الحقول هنا صريحة، لا أشتقّها من `field_names`.


@dataclass(frozen=True)
class Claim:
    """
    **طلب واحد** — وحدةُ حكمٍ ومطالبةٍ ودفع، كما في ``CaseFile.claims``.

    Attributes:
        key:   معرّف آلي ثابت يخاطبه التقرير والمسودّة. ⚠️ **وليس تسميةً
               للعرض**: به تُعرَف المطالبة في ``unanswered`` وفي العدّ.
               ⚠️ ويُرفض مفتاح مكرّر أو فارغ في ``ClaimMatrix``: مفتاحان
               متساويان يعنيان مطالبتين بهويّة واحدة، فلا يُعرف أيّهما أُجيب.
        label: الطلب **بصيغته** كما يُكتب في المذكرة («مكافأة نهاية الخدمة
               عن مدّة الخدمة كاملة»).
        claimed_by: من يتمسّك بالطلب، من ``Party``. ⚠️ **وهو أصل عبء الإثبات**:
               من ادّعى حمل عبء ما ادّعاه، إلا في المواضع المقلوبة المكتوبة
               عند ``BURDEN_GROUND_MARKERS``.
        elements: عناصر الاستحقاق التي يقوم عليها الطلب. ⚠️ **والعناصر ليست
               شرحاً**: كل عنصر **موضعُ دفعٍ مستقلّ**، والدفع في عنصر واحد لا
               يُسقط الطلب كلّه إلا إن كان فيه مناطه.
        supporting_facts: مفاتيح وقائع من السجلّ تُسند الطلب. ⚠️ **وهي مفاتيح
               لا نصوص**، لأن ``cross_check_facts`` يقابلها بالسجلّ ليعرف
               درجتها — ولو نُقل نصّها هنا لَما أمكن أن يُعرف أهي ``AGREED``
               أم ``CLAIMED``، ولضاع الفرق الذي يقوم عليه `facts.py`.
        opposing_facts: مفاتيح وقائع الخصم — تُذكر **لأنّ ذكرها يمنع أن يُبنى
               عليها بلا وعي بها**، لا لأنها تُقبل.
        evidence: أسماء المستندات التي بين أيدينا فعلاً.
        axes_in_dispute: ⚠️ **مجموعة لا قيمة**: الطلب الواحد يُنازَع فيه على
               أكثر من محور، وهذا هو الأصل. وخلط المحاور هو العيب الذي وُجد
               ``DisputeAxis`` لمنعه.
        burden: من عليه عبء الإثبات في هذا العنصر.
        response: الردّ القانوني — **بالنسبة لهذا الطلب وحده**، لا للقضية.
        outcome_sought: النتيجة المطلوبة لهذا الطلب. ⚠️ **وغيابه خطأ**:
               الردّ بلا نتيجة مطلوبة يُقرأ في المستند تسليماً أو إغفالاً.
        documents_required: ما يلزم لإثبات ما تمسّكنا به. ⚠️ **وهو خطأ إن كان
               فارغاً والعبء علينا** — وهذا هو **العيب التاريخي**: انظر
               ``BURDEN_GROUND_MARKERS`` و``burden_finding``.

    ⚠️ **والحقول بلا قيم افتراضية عن قصد** — على قاعدة ``CaseFile`` نفسها:
    حقلٌ بقيمة افتراضية يُبنى بلا أن يُنبَّه أحد، والافتراض الصامت أخطر من
    الخطأ الصريح لأنه يُرى ولا يُسلَّم. ومن لم يعرف المحور فليكتب
    ``(DisputeAxis.PROOF,)`` ويقصدها، لا أن تُكتب عنه.
    """

    key: str
    label: str
    claimed_by: Party
    elements: tuple[str, ...]
    supporting_facts: tuple[str, ...]
    opposing_facts: tuple[str, ...]
    evidence: tuple[str, ...]
    axes_in_dispute: tuple[DisputeAxis, ...]
    burden: Burden
    response: str
    outcome_sought: str
    documents_required: tuple[str, ...]


@dataclass(frozen=True)
class Defence:
    """
    **دفع واحد** نرفعه — بالبنية نفسها، وفرقٌ واحد: ``is_procedural``.

    Attributes:
        (كما في ``Claim`` — والفروق الثلاثة وحدها تُشرح هنا، لأن شرحها مرّة
         عند ``Claim`` ولا يُعاد: إعادة الشرح تُنتج شرحين يفترقان.)
        is_procedural: هل الدفع إجرائيّ (اختصاص، قبول، تقادم، صفة، إجراء)؟
            ⚠️ **وليس هذا وصفاً للشكل بل حكمٌ على الترتيب**: الإجرائي يُقدَّم
            لأن ما بعده لا يُبحث قبل استقراره، والموضوعي يُؤخَّر لأن الفصل فيه
            لا يُوقف الفصل في غيره. ولو كان التمييز في نصّ الدفع لاحتاج
            ``order_for_review`` إلى قراءة نصّ حرّ، وهو ما مُنع في
            `case_file.py` لأن المطابقة على النصّ الحرّ تُخطئ بلا صوت.
        elements: في الدفع، هي **أركان الدفع**: «تقادم» أركانه ميعادٌ سارٍ
            ولم يتحقّق سببٌ يقطعه. ⚠️ وتفصيلها مقصود: الدفع الذي لا تُعرَف
            أركانه لا يُعرف ما يُطلب لإثباته.
        outcome_sought: في الدفع، هي **النتيجة المطلوبة**: رفض الدعوى، أم
            عدم قبولها، أم بطلان الإجراء.

    ⚠️ **و``claimed_by`` في الدفع هو من يتمسّك به لا من يُوجَّه إليه** — وهو
    في أغلب الدفوع ``our_party``، وقد يكون الخصم إذا تمسّك بدفعٍ تبعيّ يُبنى
    على ردّه (كالدفع بعدم جواز التداعي لسبق الفصل).
    """

    key: str
    label: str
    claimed_by: Party
    elements: tuple[str, ...]
    supporting_facts: tuple[str, ...]
    opposing_facts: tuple[str, ...]
    evidence: tuple[str, ...]
    axes_in_dispute: tuple[DisputeAxis, ...]
    burden: Burden
    response: str
    outcome_sought: str
    documents_required: tuple[str, ...]
    is_procedural: bool


#: نوع أيّ من عنصري المصفوفة — يُستعمل في التوقيعات المشتركة.
#:
#: ⚠️ **واتّحادٌ لا تجريد**: لا صنف أب مشترك، لأن الصنف الأب يفتح باباً لأن
#: يُمرَّر دفعٌ إلى دالّة تنتظر طلباً. والدوال المشتركة هنا **لا تفرّق بينهما
#: أصلاً** — تعمل على الحقول المشتركة وحدها، والفرق الوحيد المهمّ
#: (``is_procedural``) يُقرأ في ``order_for_review`` بأمان عبر ``isinstance``.
MatrixItem = Claim | Defence


@dataclass(frozen=True)
class ClaimMatrix:
    """
    المصفوفة — الطلبات والدفوع **مفصولةً لا مخلوطة**.

    Attributes:
        claims:   الطلبات، بترتيب ``CaseFile.claims``.
        defences: الدفوع التي **رفعها المستدعي**. ⚠️ **ولا يُضيف هذا الملف
                  دفعاً بنفسه أبداً** — والاقتراح مخرَج آخر مُوسَم
                  (``suggested_only``). والسبب أن الدفع الذي يُضاف بلا واقعة
                  تُسنده يُقرأ دفعاً مرفوعاً، والدفع بلا واقعة **يُسقط نفسه
                  ويفقد الدفوع السليمة وزنها معه**.
        stage:    المرحلة التي تُقرأ بها المصفوفة. ولها قيمة افتراضية
                  ``FIRST_INSTANCE`` لأن **الموضوع مفتوح فيها**، والمرحلة
                  الأوسع هي أصلح افتراض حين لم تُذكر — على أن تبقى **عرضاً
                  للعرض** لا حكماً على القضية: من أراد حكماً استعمل
                  ``stage_of_case`` على ملف القضية.
        our_party: صفتنا، أو ``None`` إن لم تُعرف. ⚠️ و``None`` **لا تُقرأ
                  مدّعياً ولا مدّعى عليه**: معناها «لم يُسأل»، ويُعالَج ذلك
                  بأن يُسأل (``Burden.UNKNOWN``) لا بأن يُفترض.

    Raises:
        ValueError: إن كان مفتاح فارغاً، أو تكرّر **بين الطلبات والدفوع معاً**.
            ⚠️ والتكرار بين القائمتين مرفوض أيضاً: المفتاح هو ما يُعرَف به
            العنصر في ``unanswered`` وفي العدّ، فمفتاحٌ في القائمتين يجعل
            «أُغفل» و«أُجيب» يُقرآن عن العنصر الخطأ.
    """

    claims: tuple[Claim, ...] = ()
    defences: tuple[Defence, ...] = ()
    stage: Stage = Stage.FIRST_INSTANCE
    our_party: Party | None = None

    def __post_init__(self) -> None:
        seen: set[str] = set()
        for item in self.claims + self.defences:
            if not item.key.strip():
                raise ValueError("عنصر بلا مفتاح — لا يُعرَف ولا يُطالَب.")
            if item.key in seen:
                raise ValueError(
                    f"مفتاح مكرّر في المصفوفة: {item.key!r} — عنصران بهويّة "
                    "واحدة، فلا يُعرف أيّهما أُجيب وأيّهما أُغفل. ⚠️ والتكرار "
                    "بين الطلبات والدفوع مرفوض كذلك."
                )
            seen.add(item.key)

    @property
    def items(self) -> tuple[MatrixItem, ...]:
        """
        العنصران معاً — **بترتيب الإدخال، الطلبات أولاً**.

        ⚠️ **ولا يُعاد ترتيبها ولا تُدمج القائمتان في حقل واحد.** الترتيب
        المقصود للعمل يُنتجه ``order_for_review`` وحده، فتبقى المصفوفة
        **بيانات** ويبقى الترتيب **حكماً** — ولو خُلطا لصار تعديل قاعدة الترتيب
        تعديلاً في البيانات.
        """
        return self.claims + self.defences

    def of_key(self, key: str) -> MatrixItem | None:
        """
        العنصر بمفتاحه، أو ``None``.

        و``None`` **جواب مقصود لا فشل** — على قاعدة ``FactLedger.of_key``:
        معناه «لا عنصر بهذا المفتاح»، وهو ما يجب أن يُقال صراحةً.

        >>> _the_matrix().of_key("end_of_service") is not None
        True
        >>> _the_matrix().of_key("nope") is None
        True
        """
        for item in self.items:
            if item.key == key:
                return item
        return None


