def stock_defences(stage: Stage) -> tuple[SuggestedDefence, ...]:
    """
    الدفوع **المتاحة عادةً** في مرحلة — **دعوةٌ إلى النظر، لا دفعٌ مرفوع**.

    ⚠️⚠️ **وهذه الدالّة لا تُضيف شيئاً إلى أيّ مصفوفة، ولا يجوز أن تفعل.**
    مخرَجها **اقتراحات موسومة** بعبارة ``SUGGESTION_NOTE``، و``prompt_only``
    فيها ``True``. والسبب مكتوب مطوّلاً قبل ``_STOCK_DEFENCES``: الدفع بلا
    واقعة تُسنده يُسقط نفسه **ويُفقد الدفوع السليمة وزنها معه**.

    ⚠️ **وكل بند يذكر ما يلزمه** من وقائع ومستندات — وهذا هو الغرض الحقيقي
    من الجدول: **أن يُسأل المحامي ويجيب**، لا أن يُزوَّد بدفوع.

    >>> suggestions = stock_defences(Stage.CASSATION)
    >>> all(item.prompt_only for item in suggestions)
    True
    >>> [item.key for item in suggestions][:1]
    ['limitation']

    Args:
        stage: المرحلة.

    Returns:
        الاقتراحات المتاحة في المرحلة، موسومة، بلا تكرار.
    """
    return tuple(
        SuggestedDefence(
            key=entry["key"],
            label=entry["label"],
            stage=stage.value,
            is_procedural=entry["is_procedural"],
            facts_required=entry["facts_required"],
            documents_required=entry["documents_required"],
            prompt_only=True,
            note=SUGGESTION_NOTE,
        )
        for entry in _STOCK_DEFENCES
        if stage.value in entry["stages"]
    )


def suggested_only(matrix: ClaimMatrix, stage: Stage) -> tuple[SuggestedDefence, ...]:
    """
    الاقتراحات **منفصلةً عن المصفوفة** — لما لم يُتبنَّ من الدفوع المتاحة.

    ⚠️ **والفصل هو الغرض لا الشكل:** لو أُعيدت الاقتراحات في ``stock_defences``
    وحدها لَجاز أن تُقرأ مع المصفوفة وتُخلط بها؛ أما هذه الدالّة فتُصرّح
    **بما ليس في المصفوفة**: «هذه دفوعٌ متاحة لم ترفعها»، وهو سؤال يُعرض على
    المحامي، **ولا يُضاف إلى المدافعات عنه**.

    ⚠️ **ولا يُسقَط ما تبنّيناه:** الدفع الموجود في المصفوفة لا يُعرض اقتراحاً،
    لأن عرضه يوهم أنه لم يُرفع فيُرفع مرّتين — والتكرار يُسقط الدفع الصحيح
    لأنه يُقرأ إعادةَ كلامٍ لا دفعاً.

    >>> _suggested_keys(_the_matrix(), Stage.CASSATION)
    ['cassation_grounds', 'client_ground_without_documents']

    Args:
        matrix: المصفوفة — لمعرفة ما رُفع منها.
        stage: المرحلة.

    Returns:
        الاقتراحات غير المتبنّاة، موسومة، بترتيب ``_STOCK_DEFENCES``.
    """
    adopted = {defence.key for defence in matrix.defences}
    return tuple(
        suggestion
        for suggestion in stock_defences(stage)
        if suggestion.key not in adopted
    )


