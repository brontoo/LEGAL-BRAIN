# ٧. الترتيب — الإجراء قبل الموضوع
# ==============================================================================
# ⚠️ **والقاعدة في القسم ٣، وهذا تطبيقها — ولا تُكتب مرّتين.** ما يُعاد هنا
# سبب واحد: أن الترتيب **لا يُغيّر العناصر ولا يُسقطها**، بل يُعيدها مرتّبة.
# فما لا يُسند إلى بوابة إجرائية **يبقى في المخرَج** موضوعاً في آخره، ولا
# يُخفى ولا يُحذف — لأن العنصر المحذوف من الترتيب عنصرٌ ضائع من المصفوفة،
# والحذف هو العيب الأول الذي جاء هذا الملف لمنعه.


def _gate_of(item: MatrixItem) -> str | None:
    """
    بوّابة العنصر الإجرائية، أو ``None`` إن كان موضوعاً.

    ⚠️ **والاشتقاق على مُسندين اثنين، والأول يُقدَّم:**

    1. ``is_procedural`` — **حكم المستدعي**، وهو أرجح من المطابقة، لأنه وُضع
       عن معرفة بالدفع لا عن قراءة لفظه.
    2. ألفاظ ``GATE_MARKERS`` — **احتياط للموضوعي وحده**، حين يكون الدفع
       إجرائيّاً في جوهره ولم يُوسم كذلك في ``is_procedural``. ⚠️ وبغير هذا
       الاحتياط يقع دفع التقادم في آخر الترتيب، وهو **العيب الذي وُجد الترتيب
       لمنعه** بعينه.

    ⚠️ **والاحتياط لا يُقلب:** عنصر مُوسَم ``is_procedural=True`` لا يُقرأ
    موضوعاً لأنه لم يُطابق لفظاً. الوسم حكمٌ، والمطابقة احتمال.
    """
    if isinstance(item, Defence) and item.is_procedural:
        return _gate_from_text(item) or _UNCLASSIFIED
    return _gate_from_text(item)


def _gate_from_text(item: MatrixItem) -> str | None:
    """أوّل بوابة يطابق لفظها نصّ العنصر، أو ``None``."""
    haystack = normalize(item.label + " " + item.response)
    if not haystack:
        return None
    for gate in PROCEDURAL_GATES:
        for marker in GATE_MARKERS.get(gate, ()):
            if normalize(marker) in haystack:
                return gate
    return None


#: ترتيب الفرز: البوابات بترتيبها، ومجهول البوابة **قبل** الموضوع كما في
#: ``_UNCLASSIFIED``، ثم الموضوع في الآخر.
#:
#: ⚠️ والفرز **مستقرّ** لأنه يُبنى على ``sorted``، وهو شرط صحة لا تفصيل: عنصران
#: في البوابة نفسها يحفظان ترتيب الإدخال، فلا يفترق تقريران على مدخل واحد —
#: وهذه هي الحتمية التي يُشترط أن يراها المحامي (**الأداة التي تُعيد ترتيباً
#: مختلفاً على المدخل نفسه لا يُقارَن تقريرها بتقرير**).
_ORDER: dict[str, int] = {
    **{gate: index for index, gate in enumerate(PROCEDURAL_GATES)},
    _UNCLASSIFIED: len(PROCEDURAL_GATES),
    MERITS: len(PROCEDURAL_GATES) + 1,
}


def order_for_review(matrix: ClaimMatrix) -> tuple[MatrixItem, ...]:
    """
    العناصر **بترتيب العمل**: الاختصاص، فالقبول، فالتقادم، فالصفة، فالإجراء،
    **ثم الموضوع**.

    ⚠️⚠️ **وسبب الترتيب — وهو سبب قانوني لا تنظيمي:** كل بوابة **يترتّب على
    فواتها أثرٌ لا يُتدارك بالحكم في الموضوع**: الحكم من محكمة غير مختصّة باطل
    ولو كان صواباً، والدعوى غير المقبولة لا يُنظر في موضوعها، والمطالبة
    المتقادمة تسقط ولو ثبتت. **فالدفع في الموضوع قبل هذه البوابات دفعٌ في
    الترتيب الخطأ** — يُتعَب فيه ثم يُقال إن المحكمة لا تنظر الدعوى أصلاً، أو
    يُقال ذلك بعد أن بُني في الموضوع ما لا يُبنى.

    ⚠️ **والترتيب لا يُغيّر العناصر:** يُعاد كلّ عنصر في المخرَج، والتعريف
    في ``_gate_of`` يقرّر بابه. والعنصر المجهول البوابة **يُقدَّم على الموضوع
    ولا يُؤخَّر معه**، لأن تقديمه لا يضرّ وتأخيره قد يُبني عليه في الموضوع.

    >>> [item.key for item in order_for_review(_the_matrix())][:2]
    ['arbitration_clause', 'limitation']

    Args:
        matrix: المصفوفة.

    Returns:
        العناصر مرتّبة، بلا حذف ولا تغيير.
    """
    return tuple(
        sorted(matrix.items, key=lambda item: _ORDER.get(_gate_of(item) or MERITS, _ORDER[MERITS]))
    )


def review_order_labels(matrix: ClaimMatrix) -> tuple[str, ...]:
    """
    أسماء البوابات بالعربية **بترتيب ظهورها في المصفوفة** — للعرض.

    ⚠️ ووُجدت لأن الترتيب نفسه **يُعرض ليُفهم**: مصفوفة يقول تقريرها «الاختصاص
    ثم التقادم ثم الموضوع» أرصن من مصفوفة تُعرض عناصرها بلا أبواب، والفرق أن
    الأول يُقاس والثاني يُنسخ.

    >>> review_order_labels(_the_matrix())
    ('الاختصاص', 'التقادم', 'الموضوع')
    """
    seen: list[str] = []
    for item in order_for_review(matrix):
        gate = _gate_of(item) or MERITS
        label = GATE_LABELS.get(gate, MERITS_LABEL)
        if label not in seen:
            seen.append(label)
    return tuple(seen)


