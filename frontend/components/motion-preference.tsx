"use client";

/**
 * احترام «تقليل الحركة» — قاعدة من `motion` في دليل الأنماط، ومكانها الجذر.
 * ============================================================================
 * ⚠️ **ما القاعدة؟** نصّ الدليل في فصله الأخير (Accessibility):
 *
 *     «In most operating systems, users may opt out of motion from their
 *      accessibility settings… When implementing animations on the web, it is
 *      crucial to respect the choice of the user.»
 *
 * و«respect the choice» عنده **لا يعني حذف المكوّن ولا إلغاء حالته**، بل أن
 * ينتهي الانتقال إلى **حالته النهائية بلا رحلة**: العنصر يظهر، والخبر يصل،
 * ولا شيء يتحرّك على الشاشة.
 *
 * ⚠️ **ولماذا `MotionConfig` لا شرطٌ في كل موضع؟** لأن الحركة في هذا المشروع
 * موزّعة على أربعة مواضع (`office-scene.tsx` · `app/workspace/page.tsx`)،
 * وشرطٌ يُنسَخ في كل موضع هو **أربع فرص لأن يُنسى واحدها** — وهو عطب تكرّر في
 * هذا المشروع أكثر من غيره (نسختان تنحرفان). فالقرار واحدٌ في الجذر، وكل
 * `motion.*` تحته يطيعه بلا أن تعرف عنه شيئاً.
 *
 * ⚠️ **و`reducedMotion="user"` لا `"always"`:** القيمة تتبع **اختيار النظام**
 * لا ذوقنا. فمن لم يُعطّل الحركة في نظامه يراها كما صُمّمت، ومن عطّلها لا
 * يراها. ولو ثُبّتت `"always"` لَحُرم منها من لم يطلب حذفها.
 *
 * ⚠️ **ولا يُصلح هذا كلَّ حركة في المشروع، وهذا حدّه المعلن:**
 *   • `animate-spin` في `Loader2` (`data-notice.tsx` · `app/chat/page.tsx` ·
 *     زرّ الإرسال) **لا تتغيّر به**: هي CSS في Tailwind لا `motion`. وهي
 *     **مؤشّر انتظار** لا زينة — الدليل نفسه يعدّها Tier C مشروعة، وإزالتها
 *     تُبقي المحامي أمام شاشة ساكنة لا يقول له شيء. فلا تُمسّ هنا.
 *   • و`transition-colors` (وهي ~٥٠ موضعاً) **خارج حكمه أيضاً**: CSS لا
 *     `motion`، ومدّتها الافتراضية 150ms داخل حدّ الدليل (100–500ms).
 *
 * ⚠️ **والاتجاه:** هذه القاعدة **لا اتجاه لها** — لا يسار ولا يمين، بل تفضيلٌ
 * في نظام التشغيل. فهي تنتقل إلى العربية كما هي، ولا شيء فيها يُصحَّح لـRTL.
 * (وهو فرقها عن قواعد المواضع في الدليل: `side="top"` و`align="start"` في
 * التلميح والمنبثق هي التي تنقلب، لا هذه.)
 */

import { MotionConfig } from "motion/react";
import type { ReactNode } from "react";

export function MotionPreference({ children }: { children: ReactNode }) {
  return (
    /*
     * ⚠️ ولا `transition` افتراضيّ هنا: الدليل يحدّد المدّة في موضع كل حالة
     * (100ms لصغير، 200–300ms لما يدخل ويخرج)، ففرضُ مدّة واحدة على المنصة
     * كلها يُخالف ما يقول. فالمدّة تُكتب عند كل `motion.*` بحسب حجم التغيير،
     * وهذا المكوّن لا يحمل إلا **تفضيل المستخدم**.
     */
    <MotionConfig reducedMotion="user">{children}</MotionConfig>
  );
}
